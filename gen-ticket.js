// hud-manager/gen-ticket.js
//
// Чей это запрос генерации: ответ персонажа в чат ролевой или чужой.
//
// Инструкцию HUD index.js дописывает, перехватывая сетевой запрос генерации.
// Раньше чужим считался только запрос, о котором перехватчик Таверны
// (generate_interceptor) сообщил «quiet» или «impersonate». Но перехватчик
// зовётся лишь из Generate — обычной генерации Таверны. Запросы в обход неё
// он не видит вовсе:
//   • generateRaw — «сырой» режим саммари Таверны, TunnelVision (лорбуки) и
//     другие расширения;
//   • прямой fetch — ExtBlocks (внешние блоки) шлёт свой запрос сам.
// Такой запрос приходил без типа и получал всю инструкцию HUD.
//
// Теперь наоборот: инструкцию получает только запрос, на который Таверна
// выдала «билет». Generate сначала зовёт перехватчик (тип генерации), затем
// сообщает GENERATE_AFTER_DATA — данные запроса готовы — и сразу отправляет
// его. На это событие выдаём билет с типом; запрос генерации его забирает.
// Без билета запрос чужой — его не трогаем. Вложенная генерация (расширение
// посреди ответа зовёт тихую) — стек: её тип снимается раньше.

const СРОК_ТИПА = 120e3;   // перехватчик без данных (генерацию прервали)
const СРОК_БИЛЕТА = 10e3;  // данные готовы, а запроса так и не было (запрос уходит сразу)

export function создатьБилеты({ сейчас = () => Date.now() } = {}) {
  const стек = [];
  const билеты = [];
  // Событие GENERATE_AFTER_DATA есть не во всякой Таверне. Без него билетов
  // не бывает, и index.js решает по-старому — по типу из перехватчика.
  let событиеЕсть = false;
  return {
    подключено() { событиеЕсть = true; },
    // generate_interceptor: тип генерации (normal, swipe, continue, quiet…).
    перехватчик(тип) {
      стек.push({ тип: тип ?? null, at: сейчас() });
      if (стек.length > 20) стек.splice(0, стек.length - 20);
    },
    // GENERATE_AFTER_DATA: Generate собрал запрос и сейчас его отправит.
    данныеГотовы(dryRun) {
      if (dryRun) return;
      const t = сейчас();
      while (стек.length && t - стек[0].at > СРОК_ТИПА) стек.shift();
      const з = стек.pop();
      билеты.push({ тип: з ? з.тип : null, at: t });
      if (билеты.length > 10) билеты.shift();
    },
    // Генерация закончилась или остановлена: неиспользованный билет — не
    // для следующего чужого запроса.
    сбросить() { билеты.length = 0; },
    /** Для очередного запроса генерации текста: { чей: 'таверна', тип } —
     *  запрос Generate этого типа; { чей: 'чужой' } — в обход Generate;
     *  { чей: 'неизвестно' } — Таверна без события, решать по-старому. */
    забрать() {
      if (!событиеЕсть) return { чей: 'неизвестно' };
      const t = сейчас();
      while (билеты.length && t - билеты[0].at > СРОК_БИЛЕТА) билеты.shift();
      const б = билеты.shift();
      return б ? { чей: 'таверна', тип: б.тип } : { чей: 'чужой' };
    },
  };
}
