// hud-manager/era.js
//
// Эпоха сеттинга (настройка «Эпоха»). Четыре значения:
//   modern            — современность: телефон и перехваты;
//   fantasy-modern    — современное фэнтези: тот же телефон, магия рядом с техникой;
//   medieval          — средневековье: шкатулка и подслушанное;
//   fantasy-medieval  — средневековое фэнтези: та же шкатулка, но с магией.
//
// Эпоха отвечает за пару блоков (телефон или шкатулка) и за время событий.
// У фэнтези есть второй выбор — уровень магии (settings.fantasyMagic):
//   high      — явная магия: руны, круги, зачарованные вещи, ларец чародея,
//               письма с вороном и камнем-посыльным;
//   grounded  — приземлённое: способности врождённые (стихии), духи есть, но
//               ни заклинаний, ни порталов, ни зачарованных вещей; письма носят
//               гонцы и ястребы, быт обычный.
//
// Почти всё в HUD спрашивает одно: есть ли телефоны. Для этого — старина():
// средневековое фэнтези во всём, что не про вид, ведёт себя как средневековье.
// фэнтези() и магия() — только про оформление и подсказки модели.
//
// Три независимые оси мира (Настройки → Блоки HUD → Эпоха):
//   · эпоха — современность или средневековье: телефон или шкатулка (база());
//   · технологии (settings.techLevel) — auto (из карточки и лорбука),
//     primitive, preindustrial, industrial, modern, future: только подсказка
//     модели, пару блоков выбирает эпоха;
//   · магия в мире (settings.magicPresence) — none, hidden (скрыта от
//     общества: мир с виду обычный), open (общедоступна) — и её вид
//     (settings.fantasyMagic): high — заклинания, grounded — врождённые силы.
// Общедоступная магия — это и есть эпохи фэнтези: settings.era хранит
// 'fantasy-…' ровно тогда, когда магия open, поэтому обличье блоков (свечи,
// кристаллы, руны) и всё, что смотрит на фэнтези(), остаётся как было.
// Скрытая магия облика не меняет, но модель и блоки сил о ней знают:
// для промта и сил — магияВМире(), заклинанияВМире(), дарыВМире().
// Старые настройки без magicPresence переносятся сами: фэнтези → open.
//
// И отдельно — глубокая настройка «Связь в современности» (settings.modernComms):
// мир современный, но люди пишут друг другу письма (письма вместо телефона или
// вместе с ним).

import { settings } from './settings.js?v=23.89.33';

export const ЭПОХИ = ['modern', 'fantasy-modern', 'medieval', 'fantasy-medieval'];
export const МАГИЯ = ['high', 'grounded'];
export const СВЯЗЬ = ['phone', 'letters', 'both'];
export const ПРИСУТСТВИЕ = ['none', 'hidden', 'open'];
export const ТЕХНОЛОГИИ = ['auto', 'primitive', 'preindustrial', 'industrial', 'modern', 'future'];

/** Значение настройки, приведённое к одному из четырёх. */
export const эпоха = (э = settings.era) => (ЭПОХИ.includes(э) ? э : 'modern');
/** Телефонов нет: средневековье или средневековое фэнтези. */
export const старина = (э = settings.era) => э === 'medieval' || э === 'fantasy-medieval';
/** В мире есть магия: любое из двух фэнтези. */
export const фэнтези = (э = settings.era) => э === 'fantasy-modern' || э === 'fantasy-medieval';
/** Пара блоков эпохи: 'medieval' (шкатулка) или 'modern' (телефон). */
export const основаЭпохи = (э = settings.era) => (старина(э) ? 'medieval' : 'modern');
/** Уровень магии: 'high' | 'grounded' в фэнтези, '' вне фэнтези. */
export const магия = (э = settings.era, м = settings.fantasyMagic) => (фэнтези(э) ? (МАГИЯ.includes(м) ? м : 'high') : '');
/** База эпохи без магии: 'modern' | 'medieval'. */
export const база = (э = settings.era) => (старина(э) ? 'medieval' : 'modern');
/** Магия в мире: 'none' | 'hidden' | 'open'. Эпоха фэнтези — всегда open. */
export const присутствиеМагии = (э = settings.era, п = settings.magicPresence) => (фэнтези(э) ? 'open' : п === 'hidden' ? 'hidden' : 'none');
/** В мире есть магия — скрытая или общедоступная: промт и блоки сил. */
export const магияВМире = (э = settings.era) => присутствиеМагии(э) !== 'none';
/** Вид магии в мире: 'high' (заклинания) | 'grounded' (врождённые силы) | ''. */
export const видМагииВМире = (э = settings.era, м = settings.fantasyMagic) => (магияВМире(э) ? (МАГИЯ.includes(м) ? м : 'high') : '');
export const заклинанияВМире = (э = settings.era) => видМагииВМире(э) === 'high';
export const дарыВМире = (э = settings.era) => видМагииВМире(э) === 'grounded';
/** Магия скрыта от общества: мир с виду обычный. */
export const магияСкрыта = (э = settings.era) => присутствиеМагии(э) === 'hidden';
/** Уровень технологий: auto — из карточки и лорбука. */
export const технологии = (т = settings.techLevel) => (ТЕХНОЛОГИИ.includes(т) ? т : 'auto');
/** Значение settings.era по базе и присутствию магии: open → 'fantasy-…'. */
export const собратьЭпоху = (б, п) => (п === 'open' ? 'fantasy-' : '') + (б === 'medieval' ? 'medieval' : 'modern');
/** Явная магия: руны, круги, зачарованные вещи. */
export const явнаяМагия = (э = settings.era) => магия(э) === 'high';
/** Приземлённое фэнтези: врождённые силы и духи, без заклинаний и порталов. */
export const приземлённое = (э = settings.era) => магия(э) === 'grounded';
/** Связь в современности: 'phone' | 'letters' | 'both' (в старине — всегда письма). */
export const связь = (э = settings.era, с = settings.modernComms) => (старина(э) ? 'letters' : (СВЯЗЬ.includes(с) ? с : 'phone'));
/** Современный мир, где пишут письма (вместо телефона или вместе с ним). */
export const письмаВСовременности = (э = settings.era) => !старина(э) && связь(э) !== 'phone';
/** Телефон в этом мире есть: современность без «только письма». */
export const естьТелефоны = (э = settings.era) => !старина(э) && связь(э) !== 'letters';

