/** Блок оставлен в современном виде (Кастомизация → Обличье эпохи). */
export const современныйВид = (ключ) => !!(settings.eraModern && settings.eraModern[ключ]);

/** Эпоха и магия — атрибутами на корне страницы: стили фэнтези выбираются по ним. */
export function отметитьЭпоху(root = typeof document !== 'undefined' ? document.documentElement : null) {
  if (!root || !root.dataset) return;
  root.dataset.hudEra = эпоха();
  const м = магия();
  if (м) root.dataset.hudMagic = м; else delete root.dataset.hudMagic;
}
