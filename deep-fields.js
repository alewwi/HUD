// Все пути каталога — для проверки и для «включить всё».
export const ВСЕ_ПУТИ = КАТАЛОГ.flatMap(р => р.группы.flatMap(г => г.поля.flatMap(([к, , под]) => { const код = г.код || р.код; return [код + '.' + к, ...(под || []).map(([пк]) => код + '.' + к + '.' + пк)]; })));
const ИЗВЕСТНЫЕ = new Set(ВСЕ_ПУТИ);

/** Выключенные пути из настроек — только известные каталогу. */
export function списокВыключенного(s) {
  const сырой = s && Array.isArray(s.fieldsOff) ? s.fieldsOff : [];
  return [...new Set(сырой.filter(x => typeof x === 'string' && ИЗВЕСТНЫЕ.has(x)))];
}

const объект = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const экран = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// --- Разобранный HUD -------------------------------------------------------
// Метка внутри строки: «eng: 80 бодра; awk: 60» → без «eng: …». Пункты
// разделены «;», группы болезней — «|».
export function безМетки(строка, метка) {
  const s = String(строка);
  const re = new RegExp(`(^|;\\s*|\\|\\s*)${экран(метка)}\\s*:[^;|]*?(?=\\s*(?:[;|]|$))`, 'gi');
  if (!re.test(s)) return s;
  // Убранный пункт забирает «; » перед собой; у начала группы «| » остаётся.
  return s.replace(re, (всё, перед) => (перед.startsWith('|') ? перед : ''))
    .replace(/\|\s*;\s*/g, '| ').replace(/^\s*;\s*/, '').replace(/\s*\|\s*(?=\||$)/g, '').replace(/^\s*\|\s*/, '').trim();
}

function убратьВУзле(узел, путь) {
  if (Array.isArray(узел)) { узел.forEach(x => убратьВУзле(x, путь)); return; }
  if (!объект(узел) || !путь.length) return;
  const [ключ, ...дальше] = путь;
  if (!(ключ in узел)) return;
  if (!дальше.length) { delete узел[ключ]; return; }
  const v = узел[ключ];
  if (typeof v === 'string') {
    узел[ключ] = дальше.length === 1 ? безМетки(v, дальше[0]) : v;
  } else убратьВУзле(v, дальше);
}

/**
 * Убирает выключенное из HUD в кодах промта (сырой ответ модели или снимок).
 * Меняет объект на месте и его же возвращает.
 */
export function убратьВыключенное(корень, выключено) {
  if (!объект(корень) || !выключено || !выключено.length) return корень;
  for (const путь of выключено) {
    const [раздел, ...дальше] = путь.split('.');
    if (раздел in корень) убратьВУзле(корень[раздел], дальше);
  }
  return корень;
}

// --- Промт -----------------------------------------------------------------
// Схема в промте — JSON-подобный текст, по полю на строку. Раздел — строка
// ` "cs": [` до первой строки с той же единичной отступкой ` ]` / ` }`.
// Поле в разделе — строка `"Код": …` с наименьшим отступом раздела; если она
// открывает скобку, поле тянется до её закрытия. Объекты в одну строку
// (спутники, малыши) правятся внутри строки.

function конецБлока(строки, i) {
  const отступ = строки[i].match(/^\s*/)[0].length;
  if (!/[[{]\s*,?\s*$/.test(строки[i])) return i;
  for (let j = i + 1; j < строки.length; j++) {
    const т = строки[j];
    if (т.trim() && т.match(/^\s*/)[0].length <= отступ && /^\s*[\]}]/.test(т)) return j;
  }
  return i;
}

function границыРаздела(строки, код) {
  const начало = строки.findIndex(т => new RegExp(`^ "${экран(код)}": [\\[{]`).test(т));
  if (начало < 0) return null;
  const конец = конецБлока(строки, начало);
  return конец > начало ? [начало + 1, конец] : null;
}

// Значение-строка поля в строке схемы: "Код": "[…]".
const ЗНАЧЕНИЕ = (код) => new RegExp(`"${экран(код)}"\\s*:\\s*"((?:[^"\\\\]|\\\\.)*)"`);

// Метка внутри описания поля: '... eng: energy; awk: alertness; ...' или
// голым списком 'nm; sg; rc'. Апостроф внутри слова (baby's, night's) — не
// конец списка: конец — кавычка, за которой не буква. «;» внутри описания
// метки (en: «…(a pregnancy risk); what happened right after») — тоже её
// текст: пункт кончается только на «; » перед следующей меткой «код:».
function безМеткиВОписании(описание, метка) {
  const re = new RegExp(`(^|['\\s(;])${экран(метка)}(?:: (?:(?!;\\s*[a-z][a-z0-9]{0,3}:\\s)[^']|'(?=[a-zA-Z]))*?)?(;\\s*(?=[a-z][a-z0-9]{0,3}[:;']|$)|(?='(?![a-zA-Z])))`);
  const м = описание.match(re);
  if (!м) return описание;
  const до = описание.slice(0, м.index + м[1].length);
  const после = описание.slice(м.index + м[0].length);
  // Последний пункт перед кавычкой — убираем и «; » перед ним.
  return м[2] ? до + после : до.replace(/;\s*$/, '') + после;
}

function вырезатьПоле(строки, [от, до], путь) {
  const [ключ, ...дальше] = путь;
  const кандидаты = [];
  for (let i = от; i < до; i++) if (new RegExp(`^\\s*"${экран(ключ)}"\\s*:`).test(строки[i])) кандидаты.push(i);
  if (кандидаты.length) {
    const мин = Math.min(...кандидаты.map(i => строки[i].match(/^\s*/)[0].length));
    const i = кандидаты.find(к => строки[к].match(/^\s*/)[0].length === мин);
    const j = конецБлока(строки, i);
    if (!дальше.length) {
      // Пояснения к полю строками «  - …» сразу под ним — тоже его.
      let к = j;
      while (к + 1 < до && /^\s*- /.test(строки[к + 1])) к++;
      // Убрали последнее поле объекта — висящую запятую у предыдущего тоже.
      const следующая = строки.slice(к + 1).find(т => т.trim());
      строки.splice(i, к - i + 1);
      if (следующая && /^\s*[\]}]/.test(следующая) && i > 0) строки[i - 1] = строки[i - 1].replace(/,\s*$/, '');
      return true;
    }
    if (j > i) return вырезатьПоле(строки, [i + 1, j], дальше);
    if (дальше.length === 1) { строки[i] = строки[i].replace(ЗНАЧЕНИЕ(ключ), (всё, опис) => всё.replace(опис, безМеткиВОписании(опис, дальше[0]))); return true; }
    return false;
  }
  // Поле внутри объекта в одну строку: {"n": "…", "sp": "…"}.
  for (let i = от; i < до; i++) {
    const м = строки[i].match(ЗНАЧЕНИЕ(ключ));
    if (!м) continue;
    if (!дальше.length) {
      строки[i] = строки[i].replace(new RegExp(`,\\s*${экран(м[0])}|${экран(м[0])},?\\s*`), '');
    } else if (дальше.length === 1) {
      строки[i] = строки[i].replace(м[0], м[0].replace(м[1], безМеткиВОписании(м[1], дальше[0])));
    }
    return true;
  }
  return false;
}

/** Схема промта без выключенного. */
export function вырезатьИзПромпта(текст, выключено) {
  if (!выключено || !выключено.length) return текст;
  const строки = String(текст).split('\n');
  // Сначала метки, потом поля: иначе метка искала бы уже вырезанное поле.
  const порядок = [...выключено].sort((a, b) => b.split('.').length - a.split('.').length);
  for (const путь of порядок) {
    const [раздел, ...дальше] = путь.split('.');
    const г = границыРаздела(строки, раздел);
    if (г) вырезатьПоле(строки, г, дальше);
  }
  return строки.join('\n');
}

/** Правило для модели: что пользователь выключил. Пусто — нечего говорить. */
export function правилоВыключенного(выключено) {
  if (!выключено || !выключено.length) return '';
  const поля = [], метки = new Map();
  for (const путь of выключено) {
    const ч = путь.split('.');
    if (ч.length === 2) поля.push(ч.join('.'));
    else { const к = ч.slice(0, 2).join('.'); метки.set(к, [...(метки.get(к) || []), ч[2]]); }
  }
  const части = [];
  if (поля.length) части.push(`fields ${поля.join(', ')}`);
  if (метки.size) части.push(`inside fields, the labels ${[...метки].map(([к, м]) => `${к} → ${м.join(', ')}`).join('; ')}`);
  return `\n- 🚫 SWITCHED OFF by the user — never write ${части.join('; and ')} (section.field codes). Leave them out entirely, even if older HUDs in the story still have them.`;
}
