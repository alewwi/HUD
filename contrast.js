// hud-manager/contrast.js
//
// Контраст по WCAG и подбор читаемого цвета текста — чистые функции, без DOM.
// Нужны в трёх местах: applyThemeColors (index.js) пишет --hud-accent-text,
// окно кастомизации показывает значок у цветовых полей, тест прогоняет темы.
//
// Подбор не меняет выбранный цвет: он двигает только светлоту в oklch —
// тон и насыщенность остаются, поэтому подправленный акцент узнаётся как
// «тот же, только темнее». Сдвиг ограничен: цвет не превращается в чёрный
// или белый. Если и предела мало — отдаём лучшее, что получилось, а значок
// честно показывает, что 4,5 не достигнуто.

export const НОРМА_ТЕКСТА = 4.5;   // WCAG 1.4.3 — обычный текст
export const НОРМА_ЛИНИЙ = 3;      // WCAG 1.4.11 — рамки, значки, флажки

/** '#rgb' | '#rrggbb' | '#rrggbbaa' | 'rgb(…)' | 'rgba(…)' → {r,g,b,a} (0…255, a 0…1) или null. */
export function разобратьЦвет(цвет) {
  const s = String(цвет ?? '').trim().toLowerCase();
  let m = s.match(/^#([0-9a-f]{3,8})$/);
  if (m) {
    let h = m[1];
    if (h.length === 3 || h.length === 4) h = [...h].map(c => c + c).join('');
    if (h.length !== 6 && h.length !== 8) return null;
    const n = (i) => parseInt(h.slice(i, i + 2), 16);
    return { r: n(0), g: n(2), b: n(4), a: h.length === 8 ? n(6) / 255 : 1 };
  }
  m = s.match(/^rgba?\(\s*([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)(?:[\s,/]+([\d.]+%?))?\s*\)$/);
  if (m) {
    const a = m[4] == null ? 1 : (m[4].endsWith('%') ? parseFloat(m[4]) / 100 : parseFloat(m[4]));
    return { r: +m[1], g: +m[2], b: +m[3], a: Math.max(0, Math.min(1, a)) };
  }
  return null;
}

const hex2 = (n) => Math.round(Math.max(0, Math.min(255, n))).toString(16).padStart(2, '0');
export const вHex = ({ r, g, b }) => '#' + hex2(r) + hex2(g) + hex2(b);

/** Цвет с прозрачностью поверх подложки → непрозрачный цвет. */
export function наложить(верх, низ) {
  const a = верх.a ?? 1;
  return { r: верх.r * a + низ.r * (1 - a), g: верх.g * a + низ.g * (1 - a), b: верх.b * a + низ.b * (1 - a), a: 1 };
}

const линейно = (c) => { c /= 255; return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
const гамма = (c) => 255 * (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);

/** Относительная яркость WCAG, 0…1. */
export function яркость(цвет) {
  const c = typeof цвет === 'string' ? разобратьЦвет(цвет) : цвет;
  if (!c) return NaN;
  return 0.2126 * линейно(c.r) + 0.7152 * линейно(c.g) + 0.0722 * линейно(c.b);
}

/** Отношение контраста двух непрозрачных цветов, 1…21. */
export function контраст(а, б) {
  const A = яркость(а), B = яркость(б);
  if (!Number.isFinite(A) || !Number.isFinite(B)) return NaN;
  return (Math.max(A, B) + 0.05) / (Math.min(A, B) + 0.05);
}

// sRGB ↔ oklch (Björn Ottosson). Только для подбора светлоты.
function вOklch({ r, g, b }) {
  const R = линейно(r), G = линейно(g), B = линейно(b);
  const l = Math.cbrt(0.4122214708 * R + 0.5363325363 * G + 0.0514459929 * B);
  const m = Math.cbrt(0.2119034982 * R + 0.6806995451 * G + 0.1073969566 * B);
  const s = Math.cbrt(0.0883024619 * R + 0.2817188376 * G + 0.6299787005 * B);
  const L = 0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s;
  const a = 1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s;
  const bb = 0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s;
  return { L, C: Math.hypot(a, bb), h: Math.atan2(bb, a) };
}
function изOklchЛинейно({ L, C, h }) {
  const a = C * Math.cos(h), b = C * Math.sin(h);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3;
  return [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s];
}
// Вне охвата sRGB уменьшаем насыщенность, а не обрезаем каналы: так тон не плывёт.
function изOklch(o) {
  const в = (v) => v >= -1e-4 && v <= 1 + 1e-4;
  let lo = 0, hi = o.C, лин = изOklchЛинейно(o);
  if (!лин.every(в)) {
    for (let i = 0; i < 20; i++) { const mid = (lo + hi) / 2; if (изOklchЛинейно({ ...o, C: mid }).every(в)) lo = mid; else hi = mid; }
    лин = изOklchЛинейно({ ...o, C: lo });
  }
  const [r, g, b] = лин.map(v => гамма(Math.max(0, Math.min(1, v))));
  return { r, g, b, a: 1 };
}

// Предел сдвига светлоты: не темнее и не светлее этого (oklch L).
const L_МИН = 0.18, L_МАКС = 0.96;

/**
 * Цвет текста, читаемый на фоне: сам цвет, если контраст ≥ нормы, иначе
 * ближайший по светлоте (тот же тон) с контрастом ≥ нормы.
 * → { цвет: '#rrggbb', было, стало, подправлен, достигнут }
 */
export function подобратьТекст(цвет, фон, норма = НОРМА_ТЕКСТА) {
  const c = typeof цвет === 'string' ? разобратьЦвет(цвет) : цвет;
  const f = typeof фон === 'string' ? разобратьЦвет(фон) : фон;
  if (!c || !f) return { цвет: typeof цвет === 'string' ? цвет : '', было: NaN, стало: NaN, подправлен: false, достигнут: false };
  const исх = c.a < 1 ? наложить(c, f) : c;
  const было = контраст(исх, f);
  if (было >= норма) return { цвет: вHex(исх), было, стало: было, подправлен: false, достигнут: true };
  const o = вOklch(исх);
  // Темнее на светлом фоне, светлее на тёмном. Если в «правильную» сторону
  // предела не хватает — пробуем и другую, берём ту, что ближе к норме.
  // Ищем с запасом в сотые: после округления до #rrggbb норма не теряется.
  const цель = норма + 0.03;
  const вариант = (вниз) => {
    const край = вниз ? L_МИН : L_МАКС;
    const крайний = изOklch({ ...o, L: край });
    if (контраст(крайний, f) < цель) return { цвет: крайний, к: контраст(крайний, f), сдвиг: Math.abs(край - o.L), достигнут: false };
    let a = o.L, b = край;
    for (let i = 0; i < 24; i++) { const mid = (a + b) / 2; if (контраст(изOklch({ ...o, L: mid }), f) >= цель) b = mid; else a = mid; }
    const итог = изOklch({ ...o, L: b });
    return { цвет: итог, к: контраст(итог, f), сдвиг: Math.abs(b - o.L), достигнут: true };
  };
  const вниз = яркость(f) > 0.18;
  const основной = вариант(вниз);
  let лучший = основной;
  if (!основной.достигнут) { const другой = вариант(!вниз); if (другой.достигнут || другой.к > основной.к) лучший = другой; }
  // Округление до #rrggbb может опустить контраст на сотую — проверяем по hex.
  const hex = вHex(лучший.цвет);
  const стало = контраст(hex, f);
  return { цвет: hex, было, стало, подправлен: true, достигнут: стало >= норма - 1e-9 };
}

// ST по умолчанию тёмный; если его цвет подложки неизвестен, считаем так.
export const ПОДЛОЖКА_ТЁМНАЯ = '#171717';
export const ПОДЛОЖКА_СВЕТЛАЯ = '#f2f2f2';

/**
 * Реальный фон карточки: оба конца градиента с их прозрачностью поверх
 * подложки чата. Возвращает худший (ближе к цвету текста) — по нему и
 * проверяем, иначе на «удачном» конце градиента текст пропадёт.
 */
export function фоныКарточки({ cardBgStart, cardBgEnd, cardBgAlpha } = {}, подложка = ПОДЛОЖКА_ТЁМНАЯ) {
  const низ = разобратьЦвет(подложка) || разобратьЦвет(ПОДЛОЖКА_ТЁМНАЯ);
  const альфа = Math.max(0, Math.min(100, Number(cardBgAlpha ?? 100))) / 100;
  return [cardBgStart, cardBgEnd].map(разобратьЦвет).filter(Boolean).map(c => вHex(наложить({ ...c, a: c.a * альфа }, низ)));
}

/** Худший контраст цвета к любому из фонов. */
export function худшийКонтраст(цвет, фоны) {
  const к = (фоны || []).map(ф => контраст(цвет, ф)).filter(Number.isFinite);
  return к.length ? Math.min(...к) : NaN;
}

/**
 * Подбор к нескольким фонам сразу (концы градиента): цвет двигаем, пока он
 * не станет читаем на худшем из них.
 */
export function подобратьКФонам(цвет, фоны, норма = НОРМА_ТЕКСТА) {
  const список = (фоны || []).filter(ф => разобратьЦвет(ф));
  if (!список.length || !разобратьЦвет(цвет)) return { цвет, было: NaN, стало: NaN, подправлен: false, достигнут: false };
  const было = худшийКонтраст(цвет, список);
  if (было >= норма) return { цвет, было, стало: было, подправлен: false, достигнут: true };
  // Худший фон задаёт направление; проверяем итог на всех.
  const худший = список.reduce((а, ф) => (контраст(цвет, ф) < контраст(цвет, а) ? ф : а), список[0]);
  const р = подобратьТекст(цвет, худший, норма);
  const стало = худшийКонтраст(р.цвет, список);
  return { ...р, было, стало, достигнут: стало >= норма - 1e-9 };
}

/** «4,8» — по-русски, с запятой. */
export const числоКонтраста = (к) => Number.isFinite(к) ? (Math.floor(к * 10) / 10).toFixed(1).replace('.', ',') : '—';

/**
 * Значок у цветового поля: состояние и текст. Не только цвет — знак и
 * число, чтобы значок читался и без различения цветов.
 */
export function значокКонтраста(к, { норма = НОРМА_ТЕКСТА, подправлено = null } = {}) {
  if (!Number.isFinite(к)) return { состояние: 'na', текст: '—', подсказка: 'Контраст не определён: цвет фона наследуется от Таверны' };
  const ч = числоКонтраста(к);
  if (к >= норма) return { состояние: 'ok', текст: `AA ${ч} ✓`, подсказка: `Контраст ${ч}:1 — достаточно для текста` };
  const под = подправлено && Number.isFinite(подправлено.стало)
    ? ` Для текста HUD использует ${числоКонтраста(подправлено.стало)}:1 (цвет чуть ${подправлено.темнее ? 'темнее' : 'светлее'}); выбранный цвет не меняется.` : '';
  if (к >= НОРМА_ЛИНИЙ) return { состояние: 'warn', текст: `${ч} !`, подсказка: `Контраст ${ч}:1 — хватает для рамок и значков, мало для текста (нужно ${числоКонтраста(норма)}).${под}` };
  return { состояние: 'bad', текст: `${ч} ✗`, подсказка: `Контраст ${ч}:1 — мало и для текста, и для рамок.${под}` };
}

/**
 * Подложка чата Таверны: её цвет размытия (--SmartThemeBlurTintColor) поверх
 * тёмного. Без DOM или без темы Таверны — тёмная по умолчанию.
 */
export function подложкаЧата() {
  try {
    const v = getComputedStyle(document.body).getPropertyValue('--SmartThemeBlurTintColor').trim();
    const c = разобратьЦвет(v);
    if (c) return вHex(наложить(c, разобратьЦвет(ПОДЛОЖКА_ТЁМНАЯ)));
  } catch (_) { /* не браузер */ }
  return ПОДЛОЖКА_ТЁМНАЯ;
}

const кэш = new Map();
/** Подбор для пары «цвет ↔ фон карточки из настроек»; кэш по паре. */
export function текстНаКарточке(цвет, s, подложка = подложкаЧата()) {
  const ключ = [цвет, s.cardBgStart, s.cardBgEnd, s.cardBgAlpha, подложка].join('|');
  if (кэш.has(ключ)) return кэш.get(ключ);
  const р = подобратьКФонам(цвет, фоныКарточки(s, подложка));
  р.темнее = р.подправлен && яркость(р.цвет) < яркость(цвет);
  if (кэш.size > 200) кэш.clear();
  кэш.set(ключ, р);
  return р;
}
