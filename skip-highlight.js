// hud-manager/skip-highlight.js
//
// Таверна раскрашивает каждый блок кода в сообщении, а HUD приходит как
// [HUD] ```json … ``` [/HUD], и через секунды этот блок сменяется карточкой.
// Раскраска ответа в 80 000 знаков — тысячи узлов, а наблюдатель клавиатуры
// Таверны обходит каждый новый узел. Замер на чате в 300 ходов: 60 000 узлов и
// 9 секунд при открытии чата ради текста, которого никто не видит.
// Поэтому блок HUD не раскрашиваем. Разбор читает его и без раскраски, а
// остальной код в сообщениях раскрашивается как обычно.

const ОТКРЫТИЕ = /\[HUD\]\s*$/i;

/** Блок кода в сообщении, стоящий сразу за [HUD]. */
export function блокHUD(код) {
  const блок = код && код.parentElement;
  if (!блок || блок.tagName !== 'PRE' || !код.closest('.mes_text')) return false;
  const перед = блок.previousElementSibling;
  return !!перед && ОТКРЫТИЕ.test(перед.textContent || '');
}

export function подключитьПропускПодсветки(подсветка = window.hljs) {
  if (!подсветка || typeof подсветка.highlightElement !== 'function' || подсветка.__hudПропуск) return;
  const родная = подсветка.highlightElement;
  подсветка.__hudПропуск = true;
  подсветка.highlightElement = function (код, ...прочее) {
    let свой = false;
    try { свой = блокHUD(код); } catch (_) { /* раскрасит как обычно */ }
    return свой ? undefined : родная.call(this, код, ...прочее);
  };
}
