/** Пункт выключен в настройках: в сводку не идёт, в списке приглушён. */
export function пунктВыключен(s, путь) {
  if (!s) return false;
  const [раздел, поле] = String(путь).split('.');
  if (БЛОК_ВЫКЛ[раздел] && БЛОК_ВЫКЛ[раздел](s)) return true;
  if (раздел === 'bd' && s.nsfwPrompt === 'never') return true;
  if (['cs', 'us', 'bb'].includes(раздел) && ПОЛЕ_ВЫКЛ[поле] && ПОЛЕ_ВЫКЛ[поле](s)) return true;
  if (раздел === 'cs' || раздел === 'us') {
    if (s.nsfwPrompt === 'never' && БЛИЗОСТЬ.has(поле)) return true;
    if (s.enableIntimacyExtras === false && ДЕТАЛИ_БЛИЗОСТИ.has(поле)) return true;
  }
  if (раздел === 'us' && s.userAllFields !== true && !ИГРОКУ_ВСЕГДА.has(поле)) return true;
  return false;
}

// Люди раздела: [{ имя, данные }].
function людиРаздела(коды, раздел, о) {
  if (раздел === 'us') return объект(коды.us) ? [{ имя: о.имяИгрока || 'User', данные: коды.us }] : [];
  const ключИмени = раздел === 'pet' ? 'n' : 'N';
  return (Array.isArray(коды[раздел]) ? коды[раздел] : []).filter(объект)
    .map(д => ({ имя: о.имя(String(д[ключИмени] ?? '').trim()), данные: д })).filter(ч => ч.имя);
}

// Значение одного пункта — строкой без метки ('' — нечего сказать).
function значениеПункта(путь, коды, о) {
  const [раздел, поле] = путь.split('.');
  const длинное = ДЛИННЫЕ.test(путь);
  const предел = длинное ? ПРЕДЕЛ_ДЛИННОГО : ПРЕДЕЛ;
  const список = (пункты, n = предел) => { const п2 = пункты.map(чисто).filter(есть); return п2.length ? обрезать(п2.join('; '), n) : ''; };

  if (['cs', 'us', 'bb', 'pet'].includes(раздел)) {
    const кто = людиРаздела(коды, раздел, о).map(ч => {
      const сырое = ч.данные[поле];
      const т = поле === 'Ill' && typeof сырое === 'string' ? болезниКоротко(сырое) : чисто(строкой(сырое));
      return есть(т) ? `${ч.имя}: ${обрезать(безТочкиЗапятой(т), длинное ? ПРЕДЕЛ_ДЛИННОГО : ПРЕДЕЛ_ЧЕЛОВЕКА)}` : '';
    }).filter(Boolean);
    return кто.join('; ');
  }
  if (раздел === 'sc') {
    const v = объект(коды.sc) ? коды.sc[поле] : undefined;
    if (поле === 'Tw' && объект(v)) return список([[v.ttl, v.hap].filter(есть).join(' — ')]);
    if (поле === 'Tw' && typeof v === 'string') {
      const м = (к) => (v.match(new RegExp(`(?:^|;\\s*)${к}:\\s*([^;]*)`)) || [])[1] || '';
      const кратко = [м('ttl'), м('hap')].filter(есть).join(' — ');
      return список([кратко || v]);
    }
    return список([строкой(v)]);
  }
  if (раздел === 'me') {
    const me = объект(коды.me) ? коды.me : {};
    const v = me[поле];
    if (поле === 'md' && объект(v)) {
      return список([[о.имяИгрока, v.us], [о.имяПерсонажа, v.chr]].map(([имя, x]) => (объект(x) && есть(x.nw) ? `${имя || '—'}: ${строкой(x.nw)}` : '')));
    }
    if (поле === 'rt' && объект(v)) {
      return список([[о.имяИгрока, v.us], [о.имяПерсонажа, v.chr]].map(([имя, x]) => { const с = строки(x); return с.length ? `${имя || '—'}: ${с[с.length - 1]}` : ''; }));
    }
    if (поле === 'sec') return список((Array.isArray(v) ? v : []).filter(объект).map(с => (есть(с.f) ? `${строкой(с.f)}${есть(с.stt) ? ` (${строкой(с.stt)})` : ''}` : '')));
    // Последняя строка журнала — это «Событие» основы: второй раз её не пишем.
    if (поле === 'lg' && о.выбор && о.выбор.has('x.ev')) { const с = строки(v); return список(с.slice(0, -1)); }
    if (поле === 'gun') return список(строки(v).map(g => { const ст = колонка(g, 2); return колонка(g, 0) + (есть(ст) ? ` (${ст})` : ''); }));
    return список(строки(v).length ? строки(v) : [строкой(v)]);
  }
  if (раздел === 'dy' || раздел === 'bd') {
    const ключ = поле === 'ab' ? 'ab' : 'tx';
    return список((Array.isArray(коды[раздел]) ? коды[раздел] : []).filter(объект).map(з => (есть(з[ключ]) ? `${о.имя(строкой(з.au)) || '—'}: ${строкой(з[ключ])}` : '')));
  }
  if (раздел === 'dr') return список((Array.isArray(коды.dr) ? коды.dr : []).filter(объект).map(с => строкой(с.tx)));
  if (раздел === 'mw') return список((Array.isArray(коды.mw) ? коды.mw : []).filter(объект).map(з => (есть(з.tx) ? `${о.имя(строкой(з.N)) || '—'}${есть(з.at) ? ` (${строкой(з.at)})` : ''}: ${строкой(з.tx)}` : '')));
  if (раздел === 'cm') {
    // Переписка — последней строкой: кто кому что, без времени и статуса.
    const чаты = объект(коды.cm) ? Object.entries(коды.cm) : [];
    return список(чаты.map(([имя, ч]) => { const с = строки(объект(ч) ? ч.ms : ч); return с.length ? `${имя}: ${колонка(с[с.length - 1], 0)}` : ''; }));
  }
  if (раздел === 'tp') {
    return список((Array.isArray(коды.tp) ? коды.tp : []).filter(объект).map(ч => { const с = строки(ч.ms); return с.length ? `${строкой(ч.cn) || строкой(ч.tg)}: ${колонка(с[с.length - 1], 0)}` : ''; }));
  }
  if (раздел === 'lt') {
    return список((Array.isArray(коды.lt) ? коды.lt : []).filter(объект).map(л => [`${строкой(л.fr) || '?'} → ${строкой(л.to) || '?'}`, строкой(л.st)].filter(есть).join(', ')));
  }
  if (раздел === 'ov') {
    return список((Array.isArray(коды.ov) ? коды.ov : []).filter(объект).map(з => { const с = строки(з.ms); return [строкой(з.wh), с[0] || ''].filter(есть).join(': '); }));
  }
  if (раздел === 'phn' || раздел === 'sm') {
    const v = объект(коды[раздел]) ? коды[раздел][поле] : undefined;
    const вещи = Array.isArray(v) ? v.filter(объект) : [];
    if (поле === 'ct') return список(вещи.map(к => строкой(к.n)));
    if (поле === 'gl' || поле === 'nb' || поле === 'kp') return список(вещи.map(к => строкой(к.ti)));
    if (поле === 'mp') return список(вещи.map(к => строкой(к.pl)));
    if (поле === 'cl') return список(вещи.map(к => [строкой(к.dt), строкой(к.ti), есть(к.st) ? `(${строкой(к.st)})` : ''].filter(есть).join(' ')));
    if (поле === 'doc') return список(вещи.map(к => [строкой(к.ti), есть(к.st) ? `(${строкой(к.st)})` : ''].filter(есть).join(' ')));
    // Часы: сон, шаги, пульс — словами, а не кодами.
    if (поле === 'hl' && объект(v)) {
      const части = [[о.т('сон'), v.sl], [о.т('шагов'), v.st], [о.т('пульс'), v.hr]].filter(([, x]) => есть(строкой(x)));
      return список([части.map(([к, x]) => `${к} ${строкой(x)}`).join(', ')]);
    }
    if (поле === 'wl' && объект(v)) {
      const траты = (Array.isArray(v.trx) ? v.trx : []).filter(объект).map(т => [строкой(т.ti), строкой(т.am)].filter(есть).join(' '));
      return список([[строкой(v.bl), строкой(v.cu)].filter(есть).join(' '), ...траты]);
    }
    return список([строкой(v)]);
  }
  if (раздел === 'wd') {
    const v = объект(коды.wd) ? коды.wd[поле] : undefined;
    if (поле === 'nws') return список(строки(v).map(с => колонка(с, 0)));
    return список(строки(v));
  }
  if (раздел === 'ep' || раздел === 'cb') {
    const v = объект(коды[раздел]) ? коды[раздел][поле] : undefined;
    return список(строки(v).length ? строки(v) : [строкой(v)]);
  }
  return '';
}

/**
 * Дополнительные части сводки (всё, кроме основы), в порядке каталога.
 * коды — HUD в кодах промта; о: { s, имяИгрока, имяПерсонажа, имя(n), т(строка),
 * безОдежды } — безОдежды, когда одежду уже дописала основа (тихие запросы).
 */
export function дополнительныеЧасти(коды, выбор, о = {}) {
  if (!объект(коды) || !выбор || !естьДополнительное(выбор)) return [];
  const s = о.s || {};
  const опции = { имя: (n) => n, т: (x) => x, ...о, выбор };
  // Выключенное глубокой настройкой — как и на карточке, в сводку не идёт.
  // Коды лежат в кэше: копируем только разделы, где есть что вырезать (весь
  // большой HUD копировался бы на каждую сводку каждого запроса).
  const выкл = выключеноВОтвете(s);
  let чистые = коды;
  if (выкл.length) {
    чистые = { ...коды };
    for (const р of new Set(выкл.map(п => п.split('.')[0]))) if (р in коды) чистые[р] = JSON.parse(JSON.stringify(коды[р]));
    убратьВыключенное(чистые, выкл);
  }
  const части = [];
  for (const путь of ПУТИ_СВОДКИ) {
    if (ОСНОВА_СВОДКИ.includes(путь) || !выбор.has(путь)) continue;
    if (опции.безОдежды && (путь === 'cs.C' || путь === 'us.C')) continue;
    if (пунктВыключен(s, путь)) continue;
    let т = '';
    try { т = значениеПункта(путь, чистые, опции); } catch (_) { т = ''; }
    if (!есть(т)) continue;
    // Одна метка — одна часть: одежда персонажей и игрока, настроение людей и
    // спутников идут вместе, как в прежней «Одежде».
    const метка = меткаПункта(путь, опции.т);
    const была = части.find(ч => ч.метка === метка);
    if (была) была.т += '; ' + т; else части.push({ метка, т });
  }
  return части.map(ч => `${ч.метка}: ${ч.т}`);
}

/**
 * Все метки пунктов — по-русски и каждым переводчиком (язык интерфейса и
 * язык модели): карточке сводки, чтобы узнать их.
 */
export function меткиСводки(...переводчики) {
  const м = new Set();
  for (const путь of ПУТИ_СВОДКИ) for (const т of [(x) => x, ...переводчики]) м.add(String(меткаПункта(путь, т)).toLowerCase());
  return м;
}
