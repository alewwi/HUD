// --- Значения --------------------------------------------------------------------
const объект = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
// «nc» — модель не переписала неизменное: в сводке хода это ничего не говорит.
const ЗАГЛУШКА = /^(?:|empty|none|null|undefined|n\/a|nc|no change|нет|пусто|-|—|\[\]|\{\})$/i;
const есть = (v) => v !== undefined && v !== null && !ЗАГЛУШКА.test(String(v).trim());

export function обрезать(s, n) {
  const t = String(s).replace(/\s+/g, ' ').trim();
  if (t.length <= n) return t;
  const срез = t.slice(0, n);
  const пробел = срез.lastIndexOf(' ');
  return (пробел > n * 0.6 ? срез.slice(0, пробел) : срез).replace(/[\s,.;:—-]+$/, '') + '…';
}
// Значение любой формы — строкой: списки через «; », объекты «ключ: значение».
function строкой(v, глубина = 0) {
  if (v === undefined || v === null || глубина > 4) return '';
  if (Array.isArray(v)) return v.map(x => строкой(x, глубина + 1)).filter(есть).join('; ');
  if (объект(v)) return Object.entries(v).map(([k, x]) => { const т = строкой(x, глубина + 1); return есть(т) ? `${k}: ${т}` : ''; }).filter(Boolean).join('; ');
  const т = String(v).trim();
  return есть(т) ? т : '';
}
// Внутри части: «|» рвал бы сводку на части, скобки — метки разгрузки.
const чисто = (s) => String(s).replace(/\s*\|\s*/g, ' / ').replace(/[[\]]/g, '').replace(/\s+/g, ' ').trim();
// Значение человека в списке «Имя: …; Имя: …» — его «;» становятся « · »:
// запятые внутри пунктов («муж, любит, но боится») слепили бы их.
const безТочкиЗапятой = (s) => s.split(';').map(x => x.trim()).filter(Boolean).join(' · ');
const строки = (v) => (Array.isArray(v) ? v : (есть(v) ? String(v).split(/\n+/) : [])).map(x => строкой(x)).filter(есть);
// Первая колонка строки «a | b | c» и её статус (n-я колонка).
const колонка = (строка, i) => String(строка).split('|').map(x => x.trim())[i] || '';

// Метка «код: значение» внутри строки ('' — нет такой).
const метка = (строка, код) => ((String(строка).match(new RegExp(`(?:^|;)\\s*${код}\\s*:\\s*([^;]*)`, 'i')) || [])[1] || '').trim();
// Болезни: «nm: грипп; sg: stable; rc: 60 | nm: …» → «грипп — stable, 60%; …»
// (в сводке — « · » между болезнями, как у остальных значений человека).
function болезниКоротко(v) {
  return String(v).split('|').map(г => {
    const имя = метка(г, 'nm');
    if (!есть(имя)) return чисто(г);
    const где = метка(г, 'zn'), стадия = метка(г, 'sg'), рц = метка(г, 'rc');
    const как = [есть(стадия) ? стадия : '', есть(рц) ? рц.replace(/\s*%?$/, '%') : ''].filter(Boolean).join(', ');
    return чисто(`${имя}${есть(где) ? ` (${где})` : ''}${как ? ` — ${как}` : ''}`);
  }).filter(есть).join('; ');
}

