import { возрастПерсонажа } from './render/babies.js?v=23.90.10';

const объект = (v) => !!v && typeof v === 'object' && !Array.isArray(v);
const имя = (о) => String((о && о.N) || '').trim();

/**
 * Дети последнего HUD: { малыши, выросли, безВозраста } — имена.
 * помнит — Map(имя в нижнем регистре → день рождения, мс): HUD считает возраст
 * от него, а не от каждого нового числа модели.
 */
export function детиСнимка(снимок, порогДней, сценаMs = null, помнит = new Map()) {
  const out = { малыши: [], выросли: [], безВозраста: [] };
  const возраст = (о) => {
    const д = помнит.get(имя(о).toLowerCase());
    if (Number.isFinite(д) && сценаMs !== null && сценаMs >= д) return Math.round((сценаMs - д) / 864e5);
    return возрастПерсонажа(о.A, сценаMs);
  };
  for (const о of Array.isArray(снимок?.bb) ? снимок.bb : []) {
    if (!объект(о) || !имя(о)) continue;
    const д = возраст(о);
    (д === null ? out.безВозраста : д < порогДней ? out.малыши : out.выросли).push(имя(о));
  }
  for (const о of Array.isArray(снимок?.cs) ? снимок.cs : []) {
    if (!объект(о) || !имя(о)) continue;
    const д = возраст(о);
    if (д !== null && д < порогДней && !out.малыши.includes(имя(о))) out.малыши.push(имя(о));
  }
  return out;
}

/* --- По тексту: карточка, персона, последние сообщения ------------------------- */

const НЕ = '(?<![\\p{L}\\p{N}])';
const КОНЕЦ = '(?![\\p{L}\\p{N}])';
// «Спит как младенец», «like a newborn» — сравнение, а не ребёнок.
const СРАВНЕНИЕ = '(?<!(?:как|словно|будто|точно|like|as)\\s(?:(?:a|an|the)\\s)?)';
const МЛАДЕНЕЦ = new RegExp(`${НЕ}${СРАВНЕНИЕ}(?:новорожд[её]нн(?:ый|ая|ого|ой|ому|ую|ым|ые|ых)|младен(?:ец|ца|цу|цем|цы|цев)|груднич(?:ок|ка|ку|ком|ки|ков)|newborns?|infants?|toddlers?)${КОНЕЦ}`, 'iu');
const РЕБЁНОК = '(?:сын|доч|дет(?:и|ей|ям|ьми)|реб[её]н|малыш|кроха|мальчик|девочк|брат|сестр|племянни|близнец|двойняш|двойн|son|daughter|child|kid|baby|boy|girl|brother|sister|nephew|niece|toddler|twin|triplet)';
const СЛОВАМИ = [['полуторагодовал', 1.5], ['годовал', 1], ['двухлетн', 2], ['тр[её]хлетн', 3], ['четыр[её]хлетн', 4], ['пятилетн', 5], ['шестилетн', 6], ['семилетн', 7], ['восьмилетн', 8], ['девятилетн', 9], ['десятилетн', 10],
  ['one-year-old', 1], ['two-year-old', 2], ['three-year-old', 3], ['four-year-old', 4], ['five-year-old', 5]];
const ДО_СЛОВА = '(?:[\\s,-]+[\\p{L}-]+){0,2}?[\\s,-]+';
const ПРИЛАГАТЕЛЬНЫЕ = СЛОВАМИ.map(([к, лет]) => [new RegExp(`${НЕ}${к}\\p{L}*${ДО_СЛОВА}${РЕБЁНОК}`, 'iu'), лет]);
const ЧИСЛОМ = new RegExp(`${НЕ}(\\d{1,2})[-\\s]?(летн\\p{L}*|year[-\\s]old|месячн\\p{L}*|month[-\\s]old)${ДО_СЛОВА}${РЕБЁНОК}`, 'giu');
// «Дочери 8 месяцев», «сыну два года»; «сын 2 года назад уехал» — нет.
const ПОСЛЕ = new RegExp(`${НЕ}(?:сын|доч|реб[её]н|малыш)\\p{L}*[^.!?\\n]{0,20}?(?<![\\d.,])(\\d{1,2}|полтора|два|три)\\s*(мес\\p{L}*|год(?:а|ик\\p{L}*)?|months?|years?)${КОНЕЦ}(?!\\s*(?:назад|ago))`, 'giu');
const ЧИСЛО_СЛОВОМ = { полтора: 1.5, два: 2, три: 3 };

/** Назван ли в тексте ребёнок младше порога (в годах). */
export function ребёнокВТексте(текст, порогЛет) {
  const s = String(текст || '');
  if (!s.trim()) return false;
  if (МЛАДЕНЕЦ.test(s)) return true;
  for (const [rx, лет] of ПРИЛАГАТЕЛЬНЫЕ) if (лет < порогЛет && rx.test(s)) return true;
  for (const m of s.matchAll(ЧИСЛОМ)) if ((/^(?:мес|month)/i.test(m[2]) ? +m[1] / 12 : +m[1]) < порогЛет) return true;
  for (const m of s.matchAll(ПОСЛЕ)) {
    const n = ЧИСЛО_СЛОВОМ[m[1].toLowerCase()] ?? +m[1];
    if ((/^(?:мес|month)/i.test(m[2]) ? n / 12 : n) < порогЛет) return true;
  }
  return false;
}
