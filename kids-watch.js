// Есть ли в истории малыш, о чьих родах HUD не знает: он родился до начала
// сюжета, его усыновили, или роды никто не отметил. Раньше «Детская» просилась
// у модели только после записанных родов, и такому ребёнку её не доставалось.
//
// Чистые функции: снимок последнего HUD (в кодах), дата сцены и тексты — на
// входе, ответ «кто это» — на выходе. Решает prompt.js.
