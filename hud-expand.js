// hud-manager/hud-expand.js
//
// Короткий HUD → полный. Чтобы модель писала меньше, ей разрешено (prompt.js,
// настройки hudNoChange, hudWorldDaily, hudMemoryDelta):
//   • «nc» (no change) вместо внешности, одежды, кинков, фетишей, «никогда» и
//     последнего секса, здоровья, статуса, инвентаря, следов и болезней, если
//     с прошлого HUD в них ничего не изменилось (ПОЛЯ_NC — только постоянные:
//     у них прежнее значение ищется глубже, остальные берутся из последнего хода);
//   • мир дня (новости, слухи, прогноз, курсы, афиша, город, объявления,
//     гороскоп) — только раз в сюжетный день, комментарии — каждый ход;
//   • в памяти (факты, ружья, секреты, журнал) — только новое и изменённое.
// Сразу после ответа HUD разворачивает это обратно в полный HUD и кладёт его
// в сообщение (index.js). Карточка, архив, летопись и снимок для следующего
// хода видят полный HUD, как раньше, — экономятся только токены ответа.
//
// Чистые функции: на вход — HUD этого хода и прошлые HUD (новые первыми), всё
// в кодах (hud-snapshot.js, HUDвКодах).
// TavernOS HUD © 2026 alewwi — https://github.com/alewwi/HUD — GNU AGPL-3.0, see LICENSE and NOTICE.md.

import { namesLikelySame } from './names.js?v=23.89.21';

export const NC = /^\s*(?:nc|n\/c|no change|unchanged)\s*\.?\s*$/i;
export const ПОЛЯ_NC = ['Ap', 'C', 'Kn', 'Ft', 'NG', 'SxL'];
export const МИР_ДНЯ = ['nws', 'rm', 'fc', 'zd', 'fate', 'eco', 'afs', 'cty', 'ad'];
export const ПАМЯТЬ_ОБНОВЛЕНИЯМИ = ['fct', 'prm', 'gun', 'sec', 'lg'];

// Сколько держим в развёрнутом списке: модель пишет только новое, и без
// предела список рос бы с каждым ходом — а с ним снимок для модели.
const ПРЕДЕЛ = { fct: 25, prm: 20, gun: 20, sec: 25, lg: 5 };

const объект = (v) => !!v && typeof v === 'object' && !Array.isArray(v);
const ПУСТО = /^\s*(?:empty|none|null|нет|пусто)?\s*$/i;
const пусто = (v) => v === undefined || v === null || (typeof v === 'string' && ПУСТО.test(v)) || (Array.isArray(v) && !v.length);
const копия = (v) => (v === undefined ? v : JSON.parse(JSON.stringify(v)));
const люди = (h) => (h && Array.isArray(h.cs) ? h.cs : h && объект(h.cs) ? [h.cs] : []);

// --- nc -------------------------------------------------------------------------

// «nc» и список из одного «nc».
const этоNC = (v) => (typeof v === 'string' && NC.test(v)) || (Array.isArray(v) && v.length === 1 && typeof v[0] === 'string' && NC.test(v[0]));
const запись = (h, кто) => (кто === null ? (h && h.us) : люди(h).find(c => объект(c) && c.N && namesLikelySame(String(c.N), кто)));

// Прежнее значение поля. Постоянные (внешность, кинки) ищем назад до первого
// непустого. Остальные — только в последнем ходе, где человек был: «Ill: nc»
// после «Ill: empty» значит «по-прежнему нет», а не болезнь полугодовой давности.
function прежнее(узлы, поле, постоянное) {
  for (const з of узлы) {
    if (!объект(з)) continue;
    const v = з[поле];
    if (этоNC(v)) continue;
    if (постоянное) { if (пусто(v)) continue; return v; }
    return пусто(v) ? undefined : v;
  }
  return undefined;
}

// Модель пишет «nc» не только в разрешённых полях, а видит HUD игрок: любое
// поле, в любой глубине объекта, берёт значение с того же места прошлого хода.
function развернутьУзел(узел, прошлые, { постоянные = null, мимо = null } = {}) {
  let было = false;
  for (const поле of Object.keys(узел)) {
    if (мимо && мимо.includes(поле)) continue;
    const v = узел[поле];
    if (этоNC(v)) {
      const старое = прежнее(прошлые, поле, !!постоянные && постоянные.includes(поле));
      // Прежнего нет — пусто, а не «nc» на карточке.
      if (старое === undefined) delete узел[поле]; else узел[поле] = копия(старое);
      было = true;
    } else if (объект(v) && развернутьУзел(v, прошлые.map(з => (объект(з) ? з[поле] : undefined)))) было = true;
  }
  return было;
}

function развернутьNC(з, прошлые, кто) {
  return развернутьУзел(з, прошлые.map(h => запись(h, кто)), { постоянные: ПОЛЯ_NC, мимо: ['N'] });
}

// --- Мир дня ----------------------------------------------------------------------

function развернутьМир(hud, прошлые, ключи) {
  let было = false;
  for (const к of ключи) {
    const v = объект(hud.wd) ? hud.wd[к] : undefined;
    if (v !== undefined && !(typeof v === 'string' && NC.test(v))) continue;
    const откуда = прошлые.find(h => h && объект(h.wd) && !пусто(h.wd[к]));
    if (!откуда) { if (v !== undefined) { delete hud.wd[к]; было = true; } continue; }
    if (!объект(hud.wd)) hud.wd = {};
    hud.wd[к] = копия(откуда.wd[к]);
    было = true;
  }
  return было;
}

// --- Память обновлениями ---------------------------------------------------------

const нормаТекста = (s) => String(s ?? '').toLowerCase().replace(/ё/g, 'е').replace(/[«»"'`.,;:!?()\[\]—–-]/g, ' ').replace(/\s+/g, ' ').trim();
// «Начинается теми же словами»: те же первые слова (до пяти, не меньше трёх).
export function тотЖеПункт(а, б) {
  const А = нормаТекста(а), Б = нормаТекста(б);
  if (!А || !Б) return false;
  if (А === Б) return true;
  const ка = А.split(' '), кб = Б.split(' ');
  const n = Math.min(5, ка.length, кб.length);
  return n >= 3 && ка.slice(0, n).join(' ') === кб.slice(0, n).join(' ');
}
const УБРАТЬ = /^\s*[-−–]\s+/;
const текстПункта = (поле, x) => поле === 'sec' ? (объект(x) ? String(x.f ?? '') : String(x ?? '')) : поле === 'gun' ? String(x ?? '').split('|')[0] : поле === 'prm' ? String(x ?? '').split('|').slice(0, 2).join(' ') : String(x ?? '');
const безМинуса = (поле, x) => {
  if (поле === 'sec' && объект(x)) return { ...x, f: String(x.f ?? '').replace(УБРАТЬ, '') };
  return typeof x === 'string' ? x.replace(УБРАТЬ, '') : x;
};
// Пункт из одного статуса или прочерка: «fired», «kept», «-». Это не запись,
// а сокращение модели «[g1] fired» — пометить запись, а не заменить её словом.
export const ТОЛЬКО_СТАТУС = /^\s*(?:[-−–—]|fired|open|building|kept|broken|done|сработал[оа]?|выстрелил[оа]?|открыт[оа]?|исполнен[оа]?|сдержан[оа]?|нарушен[оа]?)?\s*$/i;
const МЕСТО_СТАТУСА = { gun: 2, prm: 3 };
/** Записи-обломки «fired» / «-» без текста — не пункты списка. */
export const безОбломков = (список) => Array.isArray(список) ? список.filter(x => typeof x !== 'string' || !ТОЛЬКО_СТАТУС.test(x)) : список;
function сНовымСтатусом(поле, старый, статус) {
  const место = МЕСТО_СТАТУСА[поле];
  if (место === undefined || typeof старый !== 'string') return старый;
  const части = старый.split('|');
  while (части.length <= место) части.push(' ');
  части[место] = ' ' + статус + (место < части.length - 1 ? ' ' : '');
  return части.join('|');
}
const сработало = (x) => /^\s*(?:fired|сработал[оа]?|выстрелил[оа]?)\b/i.test(String(x ?? '').split('|')[2] || '');
// Обещание исполнено или нарушено — видно один ход, как сработавшее ружьё.
/** Статус обещания: 'kept', 'broken' или 'open'. «Не сдержано» — нарушено, поэтому сперва нарушенное. */
export function статусОбещания(текст) {
  const s = String(текст ?? '').trim().toLowerCase();
  if (/^(?:broken|failed|not kept|нарушен|сорван|не сдержан|не выполнен|провален)/.test(s)) return 'broken';
  if (/^(?:kept|fulfilled|done|completed|исполнен|сдержан|выполнен|сделан)/.test(s)) return 'kept';
  return 'open';
}
const решено = (x) => статусОбещания(String(x ?? '').split('|')[3] || '') !== 'open';
const время = (x) => { const m = String(x ?? '').match(/(\d{1,2}):(\d{2})/); return m ? +m[1] * 60 + +m[2] : -1; };
const списком = (v) => (Array.isArray(v) ? v.filter(x => !пусто(x)) : пусто(v) ? [] : [v]);
const деньСцены = (h) => нормаТекста(h && объект(h.sc) ? (h.sc.Dt ?? '') : '');

// --- Номера записей ([f3 · 5 days ago], memory-age.js) ---------------------------
// В снимке у фактов, ружей и секретов стоят номер и давность. Номер — позиция
// в прошлом HUD: «[f3] новый текст» меняет третий факт, «- [f3]» убирает его.
// Пометки в сообщение не идут: если модель их переписала, они снимаются.
export const МЕТКА_ЗАПИСИ = /^\s*\[\s*([fgsp]\d{1,3})?\s*(?:·\s*)?(?:today|yesterday|a year ago|\d+ (?:days?|weeks?|months?|years?) ago)?\s*\]\s*/i;
const ДАВНОСТЬ_ЭПИЗОДА = /(^|;\s*)\[(?:today|yesterday|a year ago|\d+ (?:days?|weeks?|months?|years?) ago)\]\s*/gi;
export const безМетки = (s) => typeof s === 'string' ? s.replace(МЕТКА_ЗАПИСИ, '') : s;
export const безДавности = (s) => typeof s === 'string' ? s.replace(ДАВНОСТЬ_ЭПИЗОДА, '$1') : s;
/** «[f3] …», «- [f3]», секрет с "id": "s3" → индекс 2 в прошлом списке; иначе -1. */
function индексПоНомеру(поле, x) {
  const буква = поле === 'fct' ? 'f' : поле === 'gun' ? 'g' : поле === 'sec' ? 's' : поле === 'prm' ? 'p' : '';
  if (!буква) return -1;
  const с = поле === 'sec' && объект(x) ? String(x.id ?? '') + ' ' + String(x.f ?? '') : String(x ?? '');
  const м = с.match(new RegExp(`(?:^|\\[)\\s*${буква}(\\d{1,3})\\b`, 'i'));
  return м ? +м[1] - 1 : -1;
}
function чистыйПункт(поле, x) {
  if (поле === 'sec' && объект(x)) { const { id, age, ...прочее } = x; return { ...прочее, f: безМетки(String(прочее.f ?? '')) }; }
  return безМетки(x);
}
// Модель переписала пометки и без «памяти обновлениями» — снимаем везде.
function снятьПометки(hud) {
  let было = false;
  const me = объект(hud.me) ? hud.me : null;
  if (me) for (const к of ['fct', 'prm', 'gun', 'sec']) {
    if (!Array.isArray(me[к])) continue;
    // «- [f3]» без прошлого списка (первый ход, память не обновлениями)
    // убирать нечего — пустая команда, а не пункт.
    const чисто = me[к].filter(x => !/^\s*[-−–]\s*\[\s*[fgsp]\d{1,3}[^\]]*\]\s*$/i.test(к === 'sec' && объект(x) ? String(x.f ?? '') : String(x ?? ''))).map(x => чистыйПункт(к, x));
    if (JSON.stringify(чисто) !== JSON.stringify(me[к])) { me[к] = чисто; было = true; }
  }
  for (const c of люди(hud)) if (объект(c) && typeof c.Mm === 'string') { const м = безДавности(c.Mm); if (м !== c.Mm) { c.Mm = м; было = true; } }
  return было;
}

function развернутьПоле(поле, новое, старое, { новыйДень }) {
  const итог = (поле === 'lg' && новыйДень) ? [] : безОбломков(списком(старое)).map(копия);
  // Номера — по прошлому списку, каким его видела модель; до правок этого хода.
  const поНомеру = итог.slice();
  const тронуто = new Set();
  for (const сырой of списком(новое)) {
    const номер = индексПоНомеру(поле, сырой);
    const текст = текстПункта(поле, сырой).replace(МЕТКА_ЗАПИСИ, '');
    const убрать = УБРАТЬ.test(текстПункта(поле, сырой)) || УБРАТЬ.test(текст) || (поле === 'sec' && объект(сырой) && номер >= 0 && !String(сырой.f ?? '').replace(МЕТКА_ЗАПИСИ, '').replace(УБРАТЬ, '').trim());
    const пункт = чистыйПункт(поле, безМинуса(поле, сырой));
    const поИд = номер >= 0 && поНомеру[номер] !== undefined ? итог.indexOf(поНомеру[номер]) : -1;
    const i = поИд >= 0 ? поИд : итог.findIndex(x => тотЖеПункт(текстПункта(поле, x), текстПункта(поле, пункт)));
    if (убрать) { if (i >= 0) итог.splice(i, 1); continue; }
    // «[g1] fired», «[p2] kept», «[f3] -»: по номеру пришёл только статус или прочерк.
    if (typeof пункт === 'string' && ТОЛЬКО_СТАТУС.test(пункт)) {
      const статус = пункт.trim();
      if (поИд < 0) continue;
      if (!статус || /^[-−–—]$/.test(статус)) { итог.splice(поИд, 1); continue; }
      if (МЕСТО_СТАТУСА[поле] !== undefined) { итог[поИд] = сНовымСтатусом(поле, итог[поИд], статус); тронуто.add(итог[поИд]); }
      continue;
    }
    if (i >= 0) { итог[i] = копия(пункт); тронуто.add(итог[i]); }
    else { const к = копия(пункт); итог.push(к); тронуто.add(к); }
  }
  // Сработавшее ружьё живёт один ход, как и раньше: в следующем его уже нет.
  let out = поле === 'gun' ? итог.filter(x => тронуто.has(x) || !сработало(x)) : поле === 'prm' ? итог.filter(x => тронуто.has(x) || !решено(x)) : итог;
  if (поле === 'lg') out = out.map((x, i) => [x, i]).sort((а, б) => (время(а[0]) - время(б[0])) || (а[1] - б[1])).map(([x]) => x);
  return out.slice(-ПРЕДЕЛ[поле]);
}

function развернутьПамять(hud, прошлые, ключи) {
  const прошлый = прошлые.find(h => h && объект(h.me));
  if (!прошлый) return false;
  const новыйДень = !!деньСцены(hud) && !!деньСцены(прошлый) && деньСцены(hud) !== деньСцены(прошлый);
  let было = false;
  for (const к of ключи) {
    const новое = объект(hud.me) ? hud.me[к] : undefined;
    const старое = прошлый.me[к];
    if (новое === undefined && старое === undefined) continue;
    const итог = развернутьПоле(к, новое, старое, { новыйДень });
    if (JSON.stringify(итог) === JSON.stringify(списком(новое))) continue;
    if (!объект(hud.me)) hud.me = {};
    hud.me[к] = итог;
    было = true;
  }
  return было;
}

