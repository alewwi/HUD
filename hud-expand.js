import { namesLikelySame } from './names.js?v=23.90.4';
import { блокКакБыл } from './hud-block.js?v=23.90.4';
import { людиHUD, безЛюдей } from './faction-groups.js?v=23.90.4';

export const NC = /^\s*(?:nc|n\/c|no change|unchanged)\s*\.?\s*$/i;
export const ПОЛЯ_NC = ['Ap', 'C', 'Kn', 'Ft', 'NG', 'SxL'];
// Где модели разрешено «nc» (prompt.js) — у персонажей, игрока и малышей.
// Медленные поля — роль, цели, отношения, воспоминания, доверие, страхи,
// конфликт, характерные реплики, открытые нити — меняются редко, а весят
// больше всего; их прежнее значение берётся из последнего хода.
export const ПОЛЯ_NC_МОДЕЛИ = ['Ap', 'C', 'Kn', 'Ft', 'NG', 'SxL', 'H', 'St', 'I', 'Mrk', 'Ill', 'R', 'G', 'Rl', 'Mm', 'Tr', 'Fr', 'X', 'Ln', 'Fl'];
// Репутация (wd.rep) — не «мир дня», а обновления: см. развернутьРепутацию.
export const МИР_ДНЯ = ['nws', 'rm', 'fc', 'zd', 'fate', 'eco', 'afs', 'cty', 'ad'];
export const ПАМЯТЬ_ОБНОВЛЕНИЯМИ = ['fct', 'prm', 'gun', 'sec', 'lg'];

// Сколько держим в развёрнутом списке: модель пишет только новое, и без
// предела список рос бы с каждым ходом — а с ним снимок для модели.
const ПРЕДЕЛ = { fct: 25, prm: 20, gun: 20, sec: 25, lg: 5 };

const объект = (v) => !!v && typeof v === 'object' && !Array.isArray(v);
const ПУСТО = /^\s*(?:empty|none|null|нет|пусто)?\s*$/i;
const пусто = (v) => v === undefined || v === null || (typeof v === 'string' && ПУСТО.test(v)) || (Array.isArray(v) && !v.length);
const копия = (v) => (v === undefined ? v : JSON.parse(JSON.stringify(v)));
const люди = (h) => (h && Array.isArray(h.cs) ? h.cs : h && объект(h.cs) ? [h.cs] : []);

// --- nc -------------------------------------------------------------------------

// «nc» и список из одного «nc».
const этоNC = (v) => (typeof v === 'string' && NC.test(v)) || (Array.isArray(v) && v.length === 1 && typeof v[0] === 'string' && NC.test(v[0]));
const запись = (h, кто) => (кто === null ? (h && h.us) : люди(h).find(c => объект(c) && c.N && namesLikelySame(String(c.N), кто)));

// Прежнее значение поля. Постоянные (внешность, кинки) ищем назад до первого
// непустого. Остальные — только в последнем ходе, где человек был: «Ill: nc»
// после «Ill: empty» значит «по-прежнему нет», а не болезнь полугодовой давности.
// Кто был вне сцены, записан коротко (hud-snapshot.js, ВНЕ_СЦЕНЫ_БЕЗ): вещей,
// воспоминаний, отметин и страхов там нет вовсе. Нет — не значит «пусто»: в
// снимке модель видит прежнюю карточку целиком и вправе написать «nc».
const НЕТ_ВНЕ_СЦЕНЫ = ['I', 'Mm', 'Ln', 'Fr', 'Mrk', 'Eo'];
const записанКоротко = (з) => !!з.N && пусто(з.Ap) && пусто(з.C);
let прошёлКороткие = false;
function прежнее(узлы, поле, постоянное) {
  прошёлКороткие = false;
  for (const з of узлы) {
    if (!объект(з)) continue;
    const v = з[поле];
    if (этоNC(v)) continue;
    if (v === undefined && НЕТ_ВНЕ_СЦЕНЫ.includes(поле) && записанКоротко(з)) { прошёлКороткие = true; continue; }
    if (постоянное) { if (пусто(v)) continue; return v; }
    return пусто(v) ? undefined : v;
  }
  return undefined;
}

// Списки с именами (спутники pet, контакты и т. п.): пункт этого хода ищем в
// прошлых по имени, а не по номеру — порядок модель меняет.
const КЛЮЧИ_ИМЕНИ = ['N', 'n', 'nm'];
// У спутников описание (вид, возраст, глаза, лакомство, хозяин, навыки) —
// постоянное: необязательные поля модель пишет не каждый ход, и прежнее
// ищется глубже первой пустоты.
const ПОСТОЯННЫЕ_В_СПИСКАХ = [...ПОЛЯ_NC, 'sp', 'ag', 'eye', 'trt', 'ow', 'skl', 'scr'];

// «nc» у одной части поля с метками: цели «nw: …; sn: …; lt: nc» — дальняя
// цель та же. Прежнее значение части — из последнего хода, где у этого поля
// была та же метка не «nc» (подряд «lt: nc» бывает десятки ходов).
const ЧАСТЬ = /^(\s*)([^:;]{1,24}?)(\s*:\s*)([\s\S]*?)\s*$/;
const ЕСТЬ_ЧАСТЬ_NC = /(?:^|;)\s*[^:;]{1,24}:\s*(?:nc|n\/c|no change|unchanged)\s*\.?\s*(?:;|$)/i;
export const ОСТАЛАСЬ_ЧАСТЬ_NC = /(?:"|;)\s*[^":;\\]{1,24}:\s*(?:nc|n\/c|no change|unchanged)\s*\.?\s*(?:;|")/i;
const меткаЧасти = (ч) => { const m = String(ч).match(ЧАСТЬ); return m ? { м: m, метка: m[2].trim().toLowerCase(), значение: m[4] } : null; };
// Не нашли прежнего: false — оставить «nc» до поиска глубже, true — убрать часть.
let частиУбирать = true;
let нужноГлубже = false;
function развернутьЧасти(s, прошлые) {
  let было = false;
  const итог = [];
  for (const ч of String(s).split(';')) {
    const п = меткаЧасти(ч);
    if (!п || !NC.test(п.значение)) { итог.push(ч); continue; }
    let найдено, нашли = false;
    for (const pv of прошлые) {
      if (typeof pv !== 'string') continue;
      const прош = pv.split(';').map(меткаЧасти).find(x => x && x.метка === п.метка && !NC.test(x.значение));
      if (прош) { найдено = пусто(прош.значение) ? undefined : прош.значение.trim(); нашли = true; break; }
    }
    if (нашли) { if (найдено !== undefined) итог.push(п.м[1] + п.м[2] + п.м[3] + найдено); было = true; }
    else if (частиУбирать) было = true;
    else итог.push(ч);
  }
  return было ? { значение: итог.join(';').replace(/^\s*;\s*/, '') } : null;
}

// Модель пишет «nc» не только в разрешённых полях, а видит HUD игрок: любое
// поле, в любой глубине объекта и в списках с именами, берёт значение с того
// же места прошлого хода.
// части — «nc» у части поля («lt: nc»): только в полях самих людей. В телефоне,
// памяти и мире «Макс: nc» может быть настоящим текстом.
function развернутьУзел(узел, прошлые, { постоянные = null, мимо = null, части = false } = {}) {
  let было = false;
  for (const поле of Object.keys(узел)) {
    if (мимо && мимо.includes(поле)) continue;
    const v = узел[поле];
    if (этоNC(v)) {
      const старое = прежнее(прошлые, поле, !!постоянные && постоянные.includes(поле));
      if (старое === undefined && прошёлКороткие && !частиУбирать) { нужноГлубже = true; continue; }
      // Прежнего нет — пусто, а не «nc» на карточке.
      if (старое === undefined) delete узел[поле]; else узел[поле] = копия(старое);
      было = true;
    } else if (части && typeof v === 'string' && ЕСТЬ_ЧАСТЬ_NC.test(v)) {
      const р = развернутьЧасти(v, прошлые.map(з => (объект(з) ? з[поле] : undefined)));
      if (р) { if (р.значение.trim()) узел[поле] = р.значение; else delete узел[поле]; было = true; }
    } else if (объект(v)) {
      if (развернутьУзел(v, прошлые.map(з => (объект(з) ? з[поле] : undefined)))) было = true;
    } else if (Array.isArray(v) && v.some(объект)) {
      const списки = прошлые.map(з => (объект(з) && Array.isArray(з[поле]) ? з[поле] : null));
      for (const пункт of v) {
        if (!объект(пункт)) continue;
        const ключ = КЛЮЧИ_ИМЕНИ.find(к => typeof пункт[к] === 'string' && пункт[к].trim());
        if (!ключ) continue;
        const имя = пункт[ключ];
        const пары = списки.map(с => (с ? с.find(x => объект(x) && typeof x[ключ] === 'string' && namesLikelySame(x[ключ], имя)) : undefined));
        if (развернутьУзел(пункт, пары, { постоянные: ПОСТОЯННЫЕ_В_СПИСКАХ, мимо: [ключ] })) было = true;
      }
    }
  }
  return было;
}

function развернутьNC(з, прошлые, кто) {
  return развернутьУзел(з, прошлые.map(h => запись(h, кто)), { постоянные: ПОЛЯ_NC, мимо: ['N'], части: true });
}

// Малыши (bb) — список, как cs: прежнее значение — у ребёнка с тем же именем.
const малыши = (h) => (h && Array.isArray(h.bb) ? h.bb : []);
function развернутьМалыша(м, прошлые) {
  const имя = String(м.N);
  return развернутьУзел(м, прошлые.map(h => малыши(h).find(c => объект(c) && c.N && namesLikelySame(String(c.N), имя))), { постоянные: ПОЛЯ_NC, мимо: ['N'], части: true });
}

// --- Мир дня ----------------------------------------------------------------------

function развернутьМир(hud, прошлые, ключи) {
  let было = false;
  for (const к of ключи) {
    const v = объект(hud.wd) ? hud.wd[к] : undefined;
    if (v !== undefined && !(typeof v === 'string' && NC.test(v))) continue;
    const откуда = прошлые.find(h => h && объект(h.wd) && !пусто(h.wd[к]));
    if (!откуда) { if (v !== undefined) { delete hud.wd[к]; было = true; } continue; }
    if (!объект(hud.wd)) hud.wd = {};
    hud.wd[к] = копия(откуда.wd[к]);
    было = true;
  }
  return было;
}

// --- Репутация обновлениями ---------------------------------------------------------
// Модель пишет в wd.rep только группы, чьё отношение сдвинулось в этом ходу,
// и новые; ничего не сдвинулось — []. Остальные строки — из последнего хода,
// где репутация была: свежая строка встаёт на место прежней той же группы
// к тому же человеку («Гильдия | Лилиан | …»), новая — в конец.
const ПРЕДЕЛ_РЕПУТАЦИИ = 24;
const частиРепутации = (s) => String(s ?? '').split('|').map(x => x.trim());
const ключГруппы = (s) => нормаТекста(частиРепутации(s)[0]);
const тотЖеАдресат = (а, б) => { const x = частиРепутации(а)[1] || '', y = частиРепутации(б)[1] || ''; return (!x && !y) || (!!x && !!y && (нормаТекста(x) === нормаТекста(y) || namesLikelySame(x, y))); };
const строкиРепутации = (v) => (этоNC(v) ? [] : списком(v).filter(s => typeof s === 'string' && ключГруппы(s)));
// замки — { применить(строки), держит(строка) }: группы, зафиксированные игроком
// (render/faction-locks.js), — со строкой замка, и предел списка их не режет.
// люди — имена из HUD (faction-groups.js): строка про персонажа — не фракция, убираем
// и из ответа, и из прежних.
export function развернутьРепутацию(hud, прошлые, замки = null, люди = []) {
  const v = объект(hud.wd) ? hud.wd.rep : undefined;
  const свежие = безЛюдей(строкиРепутации(v), люди);
  const подЗамки = (строки) => (замки && typeof замки.применить === 'function' ? замки.применить(строки) : строки);
  const откуда = прошлые.find(h => h && объект(h.wd) && строкиРепутации(h.wd.rep).length);
  if (!откуда) {
    if (этоNC(v)) { hud.wd.rep = []; return true; }
    const держим = Array.isArray(v) ? безЛюдей(подЗамки(безЛюдей(v, люди)), люди) : v;
    if (держим === v) return false;
    hud.wd.rep = держим;
    return true;
  }
  const итог = безЛюдей(строкиРепутации(откуда.wd.rep), люди).slice();
  for (const s of свежие) {
    const i = итог.findIndex(x => ключГруппы(x) === ключГруппы(s) && тотЖеАдресат(x, s));
    if (i >= 0) итог[i] = s; else итог.push(s);
  }
  let лишних = итог.length - ПРЕДЕЛ_РЕПУТАЦИИ;
  const новое = безЛюдей(подЗамки(итог.filter(s => !(лишних > 0 && !(замки && замки.держит && замки.держит(s)) && лишних--))), люди);
  if (Array.isArray(v) && JSON.stringify(v) === JSON.stringify(новое)) return false;
  if (!объект(hud.wd)) hud.wd = {};
  hud.wd.rep = новое;
  return true;
}

// --- Жизнь эпохи (render/medieval-life.js) ------------------------------------------
// Часть «ep», которую модель не написала вовсе, — прежняя: честь, суд или
// запасы не исчезают оттого, что ход о них промолчал. [] — явное «ничего».
function развернутьЭпоху(hud, прошлые, ключи) {
  let было = false;
  for (const к of ключи) {
    if (объект(hud.ep) && hud.ep[к] !== undefined) continue;
    const откуда = прошлые.find(h => h && объект(h.ep) && Array.isArray(h.ep[к]) && h.ep[к].length && !этоNC(h.ep[к]));
    if (!откуда) continue;
    if (!объект(hud.ep)) hud.ep = {};
    hud.ep[к] = копия(откуда.ep[к]);
    было = true;
  }
  return было;
}

// --- Память обновлениями ---------------------------------------------------------

const нормаТекста = (s) => String(s ?? '').toLowerCase().replace(/ё/g, 'е').replace(/[«»"'`.,;:!?()\[\]—–-]/g, ' ').replace(/\s+/g, ' ').trim();
// Без номера совпасть должен весь текст записи. Регистр, «ё», кавычки и точка
// в конце не в счёт: модель переписывает их как попало, и запись двоилась бы.
export function тотЖеПункт(а, б) {
  const А = нормаТекста(а);
  return !!А && А === нормаТекста(б);
}
// --- Пересказ уже записанного -----------------------------------------------------
// Модель просят писать только новое, а она нередко выписывает журнал дня заново,
// другими словами и с другими деталями. Случившееся не переписывается: строка,
// записанная в свой ход, главнее пересказа. Дописанная подробность — не пересказ:
// слова прежней строки на месте и по порядку, и добавились новые.
const кориСобытия = (s) => new Set(нормаТекста(String(s ?? '').replace(/^\s*\[?\s*(?:\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?[,\s]+)?\d{1,2}:\d{2}\s*\]?/, '')).split(' ').filter(w => w.length > 3).map(w => w.slice(0, 5)));
/** Насколько строки журнала об одном: доля общих корней меньшей из них, 0…1. */
function схожесть(А, Б) {
  if (!А.size || !Б.size) return 0;
  let общих = 0;
  for (const w of А) if (Б.has(w)) общих++;
  return общих / Math.min(А.size, Б.size);
}
/**
 * Строка журнала — пересказ одной из записанных в прошлых ходах? Индекс записи
 * или -1. Та же минута обязательна; у минуты раньше последней записанной
 * похожести нужно меньше: новых событий там уже не бывает.
 */
function пересказСобытия(строка, старые) {
  const минута = время(строка);
  if (минута < 0) return -1;
  const порог = минута < Math.max(...старые.map(время)) ? .5 : .8;
  const Б = кориСобытия(строка);
  let лучший = -1, доля = 0;
  старые.forEach((x, i) => {
    if (время(x) !== минута) return;
    const д = схожесть(кориСобытия(x), Б);
    if (д >= порог && д > доля) { лучший = i; доля = д; }
  });
  return лучший;
}
/** Запись та же, только короче или с дописанным: слова одной идут по порядку в другой. */
function подряд(короче, длиннее) {
  const а = нормаТекста(короче).split(' '), б = нормаТекста(длиннее).split(' ');
  if (а.length < 3 || а.length >= б.length) return false;
  let i = 0;
  for (const w of б) if (w === а[i]) i++;
  return i === а.length;
}
const УБРАТЬ = /^\s*[-−–]\s+/;
const текстПункта = (поле, x) => поле === 'sec' ? (объект(x) ? String(x.f ?? '') : String(x ?? '')) : поле === 'gun' ? String(x ?? '').split('|')[0] : поле === 'prm' ? String(x ?? '').split('|').slice(0, 2).join(' ') : String(x ?? '');
const безМинуса = (поле, x) => {
  if (поле === 'sec' && объект(x)) return { ...x, f: String(x.f ?? '').replace(УБРАТЬ, '') };
  return typeof x === 'string' ? x.replace(УБРАТЬ, '') : x;
};
// Пункт из одного статуса или прочерка: «fired», «kept», «-». Это не запись,
// а сокращение модели «[g1] fired» — пометить запись, а не заменить её словом.
export const ТОЛЬКО_СТАТУС = /^\s*(?:[-−–—]|fired|open|building|kept|broken|done|сработал[оа]?|выстрелил[оа]?|открыт[оа]?|исполнен[оа]?|сдержан[оа]?|нарушен[оа]?)?\s*$/i;
const МЕСТО_СТАТУСА = { gun: 2, prm: 3 };
/** Записи-обломки «fired» / «-» без текста — не пункты списка. */
export const безОбломков = (список) => Array.isArray(список) ? список.filter(x => typeof x !== 'string' || !ТОЛЬКО_СТАТУС.test(x)) : список;
function сНовымСтатусом(поле, старый, статус) {
  const место = МЕСТО_СТАТУСА[поле];
  if (место === undefined || typeof старый !== 'string') return старый;
  const части = старый.split('|');
  while (части.length <= место) части.push(' ');
  части[место] = ' ' + статус + (место < части.length - 1 ? ' ' : '');
  return части.join('|');
}
const сработало = (x) => /^\s*(?:fired|сработал[оа]?|выстрелил[оа]?)\b/i.test(String(x ?? '').split('|')[2] || '');
// Обещание исполнено или нарушено — видно один ход, как сработавшее ружьё.
/** Статус обещания: 'kept', 'broken' или 'open'. «Не сдержано» — нарушено, поэтому сперва нарушенное. */
export function статусОбещания(текст) {
  const s = String(текст ?? '').trim().toLowerCase();
  if (/^(?:broken|failed|not kept|нарушен|сорван|не сдержан|не выполнен|провален)/.test(s)) return 'broken';
  if (/^(?:kept|fulfilled|done|completed|исполнен|сдержан|выполнен|сделан)/.test(s)) return 'kept';
  return 'open';
}
const решено = (x) => статусОбещания(String(x ?? '').split('|')[3] || '') !== 'open';
const время = (x) => { const m = String(x ?? '').match(/(\d{1,2}):(\d{2})/); return m ? +m[1] * 60 + +m[2] : -1; };
const списком = (v) => (Array.isArray(v) ? v.filter(x => !пусто(x)) : пусто(v) ? [] : [v]);
const деньСцены = (h) => нормаТекста(h && объект(h.sc) ? (h.sc.Dt ?? '') : '');

// --- Номера записей ([f3 · 5 days ago], memory-age.js) ---------------------------
// В снимке у фактов, ружей и секретов стоят номер и давность. Номер — позиция
// в прошлом HUD: «[f3] новый текст» меняет третий факт, «- [f3]» убирает его.
// Пометки в сообщение не идут: если модель их переписала, они снимаются.
export const МЕТКА_ЗАПИСИ = /^\s*\[\s*([fgsp]\d{1,3})?\s*(?:·\s*)?(?:today|yesterday|a year ago|\d+ (?:days?|weeks?|months?|years?) ago)?\s*\]\s*/i;
const ДАВНОСТЬ_ЭПИЗОДА = /(^|;\s*)\[(?:today|yesterday|a year ago|\d+ (?:days?|weeks?|months?|years?) ago)\]\s*/gi;
export const безМетки = (s) => typeof s === 'string' ? s.replace(МЕТКА_ЗАПИСИ, '') : s;
export const безДавности = (s) => typeof s === 'string' ? s.replace(ДАВНОСТЬ_ЭПИЗОДА, '$1') : s;
/** «[f3] …», «- [f3]», секрет с "id": "s3" → индекс 2 в прошлом списке; иначе -1. */
function индексПоНомеру(поле, x) {
  const буква = поле === 'fct' ? 'f' : поле === 'gun' ? 'g' : поле === 'sec' ? 's' : поле === 'prm' ? 'p' : '';
  if (!буква) return -1;
  const с = поле === 'sec' && объект(x) ? String(x.id ?? '') + ' ' + String(x.f ?? '') : String(x ?? '');
  const м = с.match(new RegExp(`(?:^|\\[)\\s*${буква}(\\d{1,3})\\b`, 'i'));
  return м ? +м[1] - 1 : -1;
}
function чистыйПункт(поле, x) {
  if (поле === 'sec' && объект(x)) { const { id, age, ...прочее } = x; return { ...прочее, f: безМетки(String(прочее.f ?? '')) }; }
  return безМетки(x);
}
// Модель переписала пометки и без «памяти обновлениями» — снимаем везде.
function снятьПометки(hud) {
  let было = false;
  const me = объект(hud.me) ? hud.me : null;
  if (me) for (const к of ['fct', 'prm', 'gun', 'sec']) {
    if (!Array.isArray(me[к])) continue;
    // «- [f3]» без прошлого списка (первый ход, память не обновлениями)
    // убирать нечего — пустая команда, а не пункт.
    const чисто = me[к].filter(x => !/^\s*[-−–]\s*\[\s*[fgsp]\d{1,3}[^\]]*\]\s*$/i.test(к === 'sec' && объект(x) ? String(x.f ?? '') : String(x ?? ''))).map(x => чистыйПункт(к, x));
    if (JSON.stringify(чисто) !== JSON.stringify(me[к])) { me[к] = чисто; было = true; }
  }
  for (const c of люди(hud)) if (объект(c) && typeof c.Mm === 'string') { const м = безДавности(c.Mm); if (м !== c.Mm) { c.Mm = м; было = true; } }
  return было;
}

function развернутьПоле(поле, новое, старое, { новыйДень }) {
  const итог = (поле === 'lg' && новыйДень) ? [] : безОбломков(списком(старое)).map(копия);
  // Номера — по прошлому списку, каким его видела модель; до правок этого хода.
  const поНомеру = итог.slice();
  const тронуто = new Set();
  for (const сырой of списком(новое)) {
    const номер = индексПоНомеру(поле, сырой);
    const текст = текстПункта(поле, сырой).replace(МЕТКА_ЗАПИСИ, '');
    const убрать = УБРАТЬ.test(текстПункта(поле, сырой)) || УБРАТЬ.test(текст) || (поле === 'sec' && объект(сырой) && номер >= 0 && !String(сырой.f ?? '').replace(МЕТКА_ЗАПИСИ, '').replace(УБРАТЬ, '').trim());
    const пункт = чистыйПункт(поле, безМинуса(поле, сырой));
    const поИд = номер >= 0 && поНомеру[номер] !== undefined ? итог.indexOf(поНомеру[номер]) : -1;
    const i = поИд >= 0 ? поИд : итог.findIndex(x => тотЖеПункт(текстПункта(поле, x), текстПункта(поле, пункт)));
    if (убрать) { if (i >= 0) итог.splice(i, 1); continue; }
    // «[g1] fired», «[p2] kept», «[f3] -»: по номеру пришёл только статус или прочерк.
    if (typeof пункт === 'string' && ТОЛЬКО_СТАТУС.test(пункт)) {
      const статус = пункт.trim();
      if (поИд < 0) continue;
      if (!статус || /^[-−–—]$/.test(статус)) { итог.splice(поИд, 1); continue; }
      if (МЕСТО_СТАТУСА[поле] !== undefined) { итог[поИд] = сНовымСтатусом(поле, итог[поИд], статус); тронуто.add(итог[поИд]); }
      continue;
    }
    if (i < 0 && поле === 'lg' && поНомеру.length) {
      const п = пересказСобытия(пункт, поНомеру);
      if (п >= 0) {
        const где = итог.indexOf(поНомеру[п]);
        if (где >= 0 && подряд(поНомеру[п], пункт)) итог[где] = копия(пункт);
        continue;
      }
    }
    if (i < 0 && поле === 'fct' && typeof пункт === 'string') {
      if (поНомеру.some(x => typeof x === 'string' && итог.includes(x) && подряд(пункт, x))) continue;
      const где = итог.findIndex(x => typeof x === 'string' && поНомеру.includes(x) && подряд(x, пункт));
      if (где >= 0) { итог[где] = пункт; continue; }
    }
    if (i >= 0) { итог[i] = копия(пункт); тронуто.add(итог[i]); }
    else { const к = копия(пункт); итог.push(к); тронуто.add(к); }
  }
  // Сработавшее ружьё живёт один ход, как и раньше: в следующем его уже нет.
  let out = поле === 'gun' ? итог.filter(x => тронуто.has(x) || !сработало(x)) : поле === 'prm' ? итог.filter(x => тронуто.has(x) || !решено(x)) : итог;
  if (поле === 'lg') out = out.map((x, i) => [x, i]).sort((а, б) => (время(а[0]) - время(б[0])) || (а[1] - б[1])).map(([x]) => x);
  return out.slice(-ПРЕДЕЛ[поле]);
}

function развернутьПамять(hud, прошлые, ключи) {
  const прошлый = прошлые.find(h => h && объект(h.me));
  if (!прошлый) return false;
  const новыйДень = !!деньСцены(hud) && !!деньСцены(прошлый) && деньСцены(hud) !== деньСцены(прошлый);
  let было = false;
  for (const к of ключи) {
    const новое = объект(hud.me) ? hud.me[к] : undefined;
    const старое = прошлый.me[к];
    if (новое === undefined && старое === undefined) continue;
    const итог = развернутьПоле(к, новое, старое, { новыйДень });
    if (JSON.stringify(итог) === JSON.stringify(списком(новое))) continue;
    if (!объект(hud.me)) hud.me = {};
    hud.me[к] = итог;
    было = true;
  }
  return было;
}

