/**
 * Разворачивает короткий HUD на месте. прошлые — HUD прошлых ходов, новые первыми.
 * мир / память — какие ключи разворачивать (то, что включено в настройках и
 * просили писать коротко); репутация — дополнять wd.rep прежними строками;
 * nc разворачивается всегда. true — что-то поменялось.
 */
export function развернутьКраткое(hud, прошлые, { мир = [], память = [], эпоха = [], репутация = false, замкиРепутации = null, игрок = '', глубже = null } = {}) {
  if (!объект(hud)) return false;
  let было = false;
  const nc = (до) => {
    for (const c of люди(hud)) if (объект(c) && c.N && развернутьNC(c, до, String(c.N))) было = true;
    if (объект(hud.us) && развернутьNC(hud.us, до, null)) было = true;
    for (const м of малыши(hud)) if (объект(м) && м.N && развернутьМалыша(м, до)) было = true;
    // Остальные разделы — сцена, мир, телефон, память: по тем же путям.
    if (развернутьУзел(hud, до, { мимо: ['cs', 'us', 'bb'] })) было = true;
  };
  const до = Array.isArray(прошлые) ? прошлые.filter(объект) : [];
  // «lt: nc» без прежнего в ближних ходах — ищем в дальних (глубже() дорогая:
  // разбирает старые HUD), потом убираем часть, а не оставляем «nc».
  try {
    частиУбирать = typeof глубже !== 'function';
    нужноГлубже = false;
    nc(до);
    if (!частиУбирать && (нужноГлубже || ОСТАЛАСЬ_ЧАСТЬ_NC.test(JSON.stringify([hud.cs, hud.us, hud.bb])))) {
      частиУбирать = true;
      const ещё = глубже();
      nc(Array.isArray(ещё) ? ещё.filter(объект) : до);
    }
  } finally { частиУбирать = true; }
  if (мир.length && развернутьМир(hud, до, мир)) было = true;
  if (репутация && развернутьРепутацию(hud, до, замкиРепутации, людиHUD([hud, ...до], [игрок]))) было = true;
  if (память.length && развернутьПамять(hud, до, память)) было = true;
  if (эпоха.length && развернутьЭпоху(hud, до, эпоха)) было = true;
  if (снятьПометки(hud)) было = true;
  return было;
}

