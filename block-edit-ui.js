// Эмоция листа дневника: плашки тем (цвет — как у листа), выбранная отмечена.
// Тема пишется словом, которое HUD узнаёт; «своё слово» — если ни одна не подходит.
const ЭМОЦИИ_ТЕЛА = [['desire', 'желание'], ['shame', 'стыд'], ['tenderness', 'нежность'], ['emptiness', 'опустошение'], ['triumph', 'триумф'], ['anxiety', 'тревога']];
function частьНастроение(значение, ф) {
  const сейчас = безПустого(значение).trim();
  const узел = эл('div', 'hud-be-group is-mood');
  const темы = ф.набор === 'bd'
    ? ЭМОЦИИ_ТЕЛА.map(([к, имя]) => ({ ключ: к, имя, слово: к }))
    : Object.entries(ТЕМЫ_ДНЕВНИКА).map(([к, т]) => ({ ключ: к, имя: т.имя, слово: normalizeDiaryMood(к) === к ? к : т.пример }));
  const выбрано = ф.набор === 'bd' ? (темы.find(т => т.ключ === сейчас.toLowerCase()) || {}).ключ : (сейчас ? normalizeDiaryMood(сейчас) : '');
  const своё = поле(сейчас, { подсказка: 'Или своё слово' });
  const ряд = эл('div', 'hud-be-pills hud-be-moods');
  const плашки = темы.map(т => {
    const к = кнопка(т.имя, `hud-be-pill hud-diary-mood-${т.ключ}`, () => {
      плашки.forEach(x => x.setAttribute('aria-checked', String(x === к)));
      своё.value = т.слово;
    });
    к.setAttribute('role', 'radio');
    к.setAttribute('aria-checked', String(т.ключ === выбрано));
    return к;
  });
  ряд.append(...плашки);
  своё.addEventListener('input', () => {
    const к = ф.набор === 'bd' ? своё.value.trim().toLowerCase() : normalizeDiaryMood(своё.value);
    плашки.forEach((x, i) => x.setAttribute('aria-checked', String(темы[i].ключ === к)));
  });
  узел.append(ряд, строкаПоля(ф.набор === 'bd' ? 'Слово эмоции' : 'Слово эмоции (оформление листа подберётся по нему)', своё));
  return { узел, взять: () => (своё.value.trim() || 'empty') };
}

function частьСообщения(значение, путь) {
  const узел = эл('div', 'hud-be-group is-msgs');
  const список = эл('div', 'hud-be-list');
  const ряды = [];
  const кратко = (s) => { const р = разобратьСообщениеПравки(s); return `${р.от || '—'}: ${р.текст || ВИДЫ_СООБЩЕНИЯ.find(в => в[0] === р.вид)?.[1] || ''}`.slice(0, 80); };
  const добавить = (s, открыт = false) => {
    const ряд = эл('details', 'hud-be-msgrow');
    ряд.open = открыт;
    const итог = эл('summary', '', кратко(s));
    const ч = частьСообщение(s);
    ряд.append(итог, ч.узел, кнопка('Удалить сообщение', 'hud-be-del is-wide', () => { ряд.remove(); ряды.splice(ряды.indexOf(ч), 1); }));
    ряды.push(ч);
    список.append(ряд);
  };
  (Array.isArray(значение) ? значение : []).forEach(s => добавить(String(s ?? '')));
  узел.append(список, кнопка('+ сообщение', 'hud-be-add', () => добавить('', true)));
  return { узел, взять: () => ряды.map(ч => ч.взять()).filter(s => !/^\s*(?:[^:]*:)?\s*$/.test(s)) };
}

function частьОбъект(значение, путь) {
  const узел = эл('div', 'hud-be-group is-object');
  const части = Object.entries(значение || {}).map(([к, v]) => {
    const ч = часть([...путь, к], v);
    const р = эл('div', 'hud-be-sub');
    р.append(эл('span', 'hud-be-label', т(подписьКлюча([...путь, к]))), ч.узел);
    узел.append(р);
    return [к, ч];
  });
  return { узел, взять: () => Object.fromEntries(части.map(([к, ч]) => [к, ч.взять()])) };
}

function частьЗаписи(значение, путь) {
  const узел = эл('div', 'hud-be-group is-records');
  const список = эл('div', 'hud-be-list');
  const ряды = [];
  const образец = (Array.isArray(значение) ? значение : []).find(объект) || {};
  const добавить = (з, i) => {
    const ряд = эл('fieldset', 'hud-be-record');
    ряд.append(эл('legend', '', `№${i + 1}`));
    // Строка среди записей (секрет без полей) — правится строкой, не теряется.
    const ч = объект(з) ? частьОбъект(з, [...путь, i]) : частьТекст(з, { длинный: true });
    ряд.append(ч.узел, кнопка('Удалить запись', 'hud-be-del is-wide', () => { ряд.remove(); ряды.splice(ряды.indexOf(ч), 1); }));
    ряды.push(ч);
    список.append(ряд);
  };
  (Array.isArray(значение) ? значение : []).forEach((з, i) => { if (з !== null && з !== undefined) добавить(з, i); });
  узел.append(список, кнопка('+ запись', 'hud-be-add', () => добавить(Object.fromEntries(Object.keys(образец).map(к => [к, typeof образец[к] === 'string' ? '' : Array.isArray(образец[к]) ? [] : {}])), ряды.length)));
  return { узел, взять: () => ряды.map(ч => ч.взять()).filter(v => v !== 'empty') };
}

/** Часть формы для значения по пути: { узел, взять() }. */
export function часть(путь, значение) {
  const ф = формаЗначения(путь, значение);
  switch (ф.вид) {
    case 'метки': return частьМетки(значение, ф);
    case 'настроение': return частьНастроение(значение, ф);
    case 'части': return частьЧасти(значение, ф);
    case 'доверие': return частьДоверие(значение);
    case 'список': return частьСписок(значение, ф, путь);
    case 'сообщение': return частьСообщение(значение);
    case 'сообщения': return частьСообщения(значение, путь);
    case 'объект': return частьОбъект(значение, путь);
    case 'записи': return частьЗаписи(значение, путь);
    default: return частьТекст(значение, ф);
  }
}

/* --- Окно ---------------------------------------------------------------------- */

let открытое = null;
export const окноПравкиОткрыто = () => !!открытое;

/**
 * заголовок — плашка сверху; путь и значение — что правим; соседи —
 * [{ путь, подпись }] для переключателя; можноВернуть — есть ли что вернуть.
 * сохранить(новое) и вернуть() — промисы; бросают ошибку — окно остаётся.
 * Своя форма: форма = { узел, взять }.
 */
export function открытьОкноПравки({ заголовок, пояснение = '', путь, значение, форма = null, создатьФорму = null, соседи = [], можноВернуть = false, сохранить, вернуть = null, сменить = null, закрыто = null, текстОтмены = 'Отмена' }) {
  открытое?.закрыть();
  const фон = эл('div', 'hud-be-overlay');
  фон.setAttribute('role', 'dialog');
  фон.setAttribute('aria-modal', 'true');
  const окно = эл('div', 'hud-be-box');
  const шапка = эл('div', 'hud-be-head');
  const плашка = эл('span', 'hud-be-plate', заголовок);
  шапка.append(плашка);
  if (соседи.length > 1 && сменить) {
    const выбор = эл('select', 'hud-be-switch');
    выбор.setAttribute('aria-label', т('Другое поле этого блока'));
    for (const с of соседи) {
      const о = эл('option', '', т(с.подпись));
      о.value = JSON.stringify(с.путь);
      о.selected = JSON.stringify(с.путь) === JSON.stringify(путь);
      выбор.append(о);
    }
    выбор.addEventListener('change', () => {
      const новый = JSON.parse(выбор.value);
      if (изменено() && !window.confirm(т('Изменения в этом поле не сохранены. Перейти к другому?'))) { выбор.value = JSON.stringify(путь); return; }
      закрыть();
      сменить(новый);
    });
    шапка.append(выбор);
  }
  const тело = эл('div', 'hud-be-body');
  if (пояснение) тело.append(эл('p', 'hud-be-note', т(пояснение)));
  // Форма собирается заново для «Вернуть как было»: поля — как в миг открытия окна.
  const сделать = () => (создатьФорму ? создатьФорму() : форма || часть(путь, значение));
  let ч = сделать();
  тело.append(ч.узел);
  const итог = эл('div', 'hud-be-error');
  итог.hidden = true;
  const низ = эл('div', 'hud-be-foot');
  const отмена = кнопка(текстОтмены, 'hud-be-btn', () => закрыть());
  // «Вернуть как было»: есть несохранённое в окне — поля как в миг открытия;
  // окно не трогали, а блок раньше правили и сохранили — в HUD снова то, что
  // написала модель.
  const можноСбросить = !!создатьФорму || !форма;
  const назад = кнопка('Вернуть как было', 'hud-be-btn', async () => {
    if (можноСбросить && изменено()) {
      const новая = сделать();
      ч.узел.replaceWith(новая.узел);
      ч = новая;
      итог.hidden = true;
      обновить();
      return;
    }
    if (!можноВернуть || !вернуть) return;
    занято(true);
    try { await вернуть(); закрыть(); } catch (err) { ошибка(err); }
  });
  const сохранитьК = кнопка('Сохранить', 'hud-be-btn is-main', async () => {
    занято(true);
    try { await сохранить(ч.взять()); закрыть(); } catch (err) { ошибка(err); }
  });
  низ.append(отмена, назад, сохранитьК);
  окно.append(шапка, тело, итог, низ);
  фон.append(окно);

  const начало = JSON.stringify(безОшибок(() => ч.взять()));
  function безОшибок(f) { try { return f(); } catch (_) { return null; } }
  function изменено() { return JSON.stringify(безОшибок(() => ч.взять())) !== начало; }
  function обновить() {
    const окноМенялось = можноСбросить && изменено();
    назад.disabled = !окноМенялось && !(можноВернуть && вернуть);
    назад.title = т(окноМенялось ? 'Вернуть поля к тому, что было, когда окно открылось' : 'Вернуть в HUD то, что написала модель, — до ваших сохранённых правок');
  }
  function занято(да) { низ.querySelectorAll('button').forEach(к => { к.disabled = да; }); if (!да) обновить(); }
  function ошибка(err) { итог.hidden = false; итог.textContent = String((err && err.message) || err); занято(false); }
  function закрыть() {
    if (!фон.isConnected) return;
    фон.remove();
    document.removeEventListener('keydown', клавиши, true);
    if (открытое && открытое.фон === фон) открытое = null;
    try { закрыто?.(); } catch (_) { /* окно уже закрыто */ }
  }
  function клавиши(e) {
    if (e.key === 'Escape') { e.preventDefault(); e.stopPropagation(); закрыть(); }
    else if (e.key === 'Enter' && (e.ctrlKey || e.metaKey)) { e.preventDefault(); сохранитьК.click(); }
  }
  // Нажатие мимо окна — как «Отмена», но несохранённое спросит.
  фон.addEventListener('mousedown', (e) => { if (e.target === фон && (!изменено() || window.confirm(т('Закрыть без сохранения?')))) закрыть(); });
  // Клики внутри окна не должны долетать до карточки и Таверны.
  фон.addEventListener('click', (e) => e.stopPropagation());
  document.addEventListener('keydown', клавиши, true);
  // «Вернуть как было» доступна, только когда в окне что-то поменяли.
  тело.addEventListener('input', обновить);
  // В захвате: кнопки формы (плашки, «+ пункт») гасят всплытие.
  тело.addEventListener('click', () => setTimeout(обновить, 0), true);
  обновить();
  document.body.append(фон);
  открытое = { фон, закрыть };
  requestAnimationFrame(() => окно.querySelector('input, textarea')?.focus({ preventScroll: true }));
  return { закрыть };
}

/** Выбор, что править, когда по нажатию блок не узнать: пункты — [{ подпись, действие }]. */
export function открытьВыбор({ заголовок, пояснение = '', пункты = [] }) {
  const форма = { узел: эл('div', 'hud-be-pick'), взять: () => undefined };
  let окно = null;
  for (const п of пункты) форма.узел.append(кнопка(п.подпись, 'hud-be-pickbtn', () => { окно?.закрыть(); п.действие(); }));
  окно = открытьОкноПравки({ заголовок, пояснение, путь: [], значение: null, форма, сохранить: async () => {} });
  const фон = открытое && открытое.фон;
  фон?.classList.add('is-pick');
  return окно;
}
