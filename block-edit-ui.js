const объект = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const эл = (тег, класс = '', текст = '') => {
  const у = document.createElement(тег);
  if (класс) у.className = класс;
  if (текст) у.textContent = текст;
  return у;
};
const безПустого = (v) => (пусто(v) ? '' : String(v ?? ''));

function поле(значение, { длинный = false, подсказка = '' } = {}) {
  const у = длинный ? эл('textarea', 'hud-be-input') : эл('input', 'hud-be-input');
  if (!длинный) у.type = 'text';
  у.value = безПустого(значение);
  if (подсказка) у.placeholder = т(подсказка);
  if (длинный) {
    // В скрытом блоке (вид сообщения не выбран) высоты нет — подгоняем, когда покажут.
    const подогнать = () => { if (!у.isConnected || !у.offsetParent) return; у.style.height = 'auto'; у.style.height = Math.min(320, у.scrollHeight + 2) + 'px'; };
    у.__подогнать = подогнать;
    у.rows = Math.min(8, Math.max(2, Math.ceil(у.value.length / 60)));
    у.addEventListener('input', подогнать);
    requestAnimationFrame(подогнать);
  }
  return у;
}
function строкаПоля(подпись, узел, класс = '') {
  const р = эл('label', 'hud-be-field' + (класс ? ' ' + класс : ''));
  р.append(эл('span', 'hud-be-label', т(подпись)), узел);
  return р;
}
const кнопка = (текст, класс, действие) => {
  const к = эл('button', класс, т(текст));
  к.type = 'button';
  к.addEventListener('click', (e) => { e.preventDefault(); e.stopPropagation(); действие(e); });
  return к;
};
const длинноеЛи = (v) => String(v ?? '').length > 60 || /\n/.test(String(v ?? ''));

