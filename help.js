export function normalizeTerm(текст) {
  return String(текст || '')
    .replace(/[\u{1F000}-\u{1FAFF}\u{2190}-\u{2BFF}\u{FE0F}\u{200D}]/gu, ' ')
    .replace(/[:：]\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase()
    .replace(/ё/g, 'е');
}

export function findTermHelp(текст) {
  const ключ = normalizeTerm(текст);
  if (!ключ) return null;
  const статья = TERM_HELP[ключ];
  if (!статья) return null;
  // Заголовок берём из самой подписи: она уже в нужном падеже и с большой
  // буквы, а держать его копией в словаре — лишний повод разъехаться.
  return { title: текст.replace(/[:：]\s*$/, '').trim(), ...статья };
}

