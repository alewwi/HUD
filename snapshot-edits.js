// hud-manager/snapshot-edits.js
//
// Слой правок снимка: авторские факты игрока поверх того, что написала модель.
//
// Правило важнее фичи: HUD не переписывает молча то, что написала модель, —
// иначе баги невоспроизводимы и непонятно, откуда взялся статус. Поэтому две
// ступени: HUD замечает и предлагает («при Лене это прозвучало — отметить
// „подозревает“?»), человек подтверждает, и правка пишется сюда, а не в
// текст сообщения. Автоматический режим — настройкой secretsAutoRaise.
//
// Хранится на чат (метаданные): { путь: { значение, когда, ход, кем: 'user' } }.
// Путь вешаем не на индекс в массиве (порядок секретов меняется от хода к
// ходу), а на нормализованный ключ секрета и имя: 'sec|<ключ>|<имя>'.
// Правка живёт, пока её не снимут; если модель потом пишет в то же поле
// другое — это показывается как расхождение, а не чинится молча.

import { settings } from './settings.js?v=23.48.3';
import { namesLikelySame } from './names.js?v=23.48.3';

const КЛЮЧ = 'tavernosHudEdits';
const объект = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);

function мета() {
  try { const c = window.SillyTavern?.getContext?.(); return c && (c.chatMetadata || c.chat_metadata) || null; } catch (_) { return null; }
}
function сохранить() {
  try { const c = window.SillyTavern?.getContext?.(); (c?.saveMetadataDebounced || c?.saveMetadata)?.call(c); } catch (_) { /* сохранится со следующим */ }
}
export function правки(м = мета()) {
  if (!м) return {};
  if (!объект(м[КЛЮЧ])) return {};
  return м[КЛЮЧ];
}
export function правитьСнимок(путь, значение, ход = null, м = мета()) {
  if (!м || !путь) return false;
  if (!объект(м[КЛЮЧ])) м[КЛЮЧ] = {};
  м[КЛЮЧ][путь] = { значение, когда: Date.now(), ход, кем: 'user' };
  сохранить();
  return true;
}
export function снятьПравку(путь, м = мета()) {
  if (!м || !объект(м[КЛЮЧ]) || !(путь in м[КЛЮЧ])) return false;
  delete м[КЛЮЧ][путь];
  сохранить();
  return true;
}

// Ключ секрета: первые значимые слова факта — порядок и мелкие правки
// модели («Софи знала о помолвке» / «Софи знала про помолвку») его не ломают.
const норм = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е');
export function ключСекрета(факт) {
  return норм(факт).split(/[^\p{L}\p{N}]+/u).filter(w => w.length >= 4).slice(0, 5).map(w => w.slice(0, 6)).join(' ');
}
export const путьСекрета = (факт, имя) => `sec|${ключСекрета(факт)}|${String(имя || '').trim()}`;
const тот = (a, b) => a && b && (a === b || namesLikelySame(a, b));

/** Правка клетки «секрет × человек»: { значение, когда, ход, путь } или null. */
export function правкаСекрета(факт, имя, все = правки()) {
  const ключ = ключСекрета(факт);
  if (!ключ) return null;
  for (const [путь, п] of Object.entries(все)) {
    const [вид, к, кто] = путь.split('|');
    if (вид === 'sec' && к === ключ && тот(кто, имя)) return { ...п, путь };
  }
  return null;
}

/**
 * Снимок с наложенными правками — то, что уходит модели. Отмеченный «знает»
 * встаёт в knw с пометкой, откуда; «подозревает» — тоже в knw, но так и
 * подписан; из hd он уходит. Копию не делаем: строкаСнимка уже работает
 * с копией.
 */
export function наложитьНаСнимок(к, все = правки()) {
  const пам = объект(к && к.me) ? к.me : объект(к && к.memory) ? к.memory : null;
  const секреты = пам && Array.isArray(пам.sec) ? пам.sec : пам && Array.isArray(пам.secrets) ? пам.secrets : null;
  if (!секреты || !Object.keys(все).length) return к;
  for (const с of секреты) {
    if (!объект(с)) continue;
    const факт = с.f || с.fact || '';
    for (const [путь, п] of Object.entries(все)) {
      const [вид, ключ, кто] = путь.split('|');
      if (вид !== 'sec' || ключ !== ключСекрета(факт) || !кто || !['known', 'suspected'].includes(п.значение)) continue;
      const знающие = Array.isArray(с.knw) ? с.knw : (с.knw = []);
      if (!знающие.some(x => тот(String((x && (x.n || x.name)) || x || ''), кто))) знающие.push({ n: кто, src: п.значение === 'known' ? 'узнал(а) — отметил игрок' : 'подозревает — отметил игрок' });
      if (Array.isArray(с.hd)) с.hd = с.hd.filter(x => !тот(String(x || ''), кто));
    }
  }
  return к;
}

// --- Что всплыло в споре -------------------------------------------------------
// Сопоставление нечёткое, поэтому порог консервативный: два и больше
// значимых слова (по пятибуквенным корням). Ложное срабатывание, которое молча
// поменяло статус критического секрета, — худший баг этой фичи, поэтому по
// умолчанию — спросить.
const корни = (s) => new Set(норм(s).split(/[^\p{L}\p{N}]+/u).filter(w => w.length >= 5).map(w => w.slice(0, 5)));
export function совпадаетССекретом(текст, факт) {
  const а = корни(факт), б = корни(текст);
  if (а.size < 2 || !б.size) return false;
  let общих = 0;
  for (const w of а) if (б.has(w)) общих++;
  return общих >= 2;
}

/**
 * Предложения: [{ факт, кто, значение: 'known'|'suspected', откуда, путь }].
 * секреты — разобранные (fact, knows, hidden/unaware, status); дуэли —
 * [{ уступка, суть }] из «Словесной дуэли» и «Глубины конфликта» хода;
 * присутствующие — имена в ходе (cs и игрок); состояние(сек, имя) → вид
 * клетки по данным модели (secrets-grid.js → клеткаСекрета).
 * Уступка в дуэли («признала, что знала») — прямо: «знает». Совпала только
 * суть спора — намёком: «подозревает».
 */
export function всплывшиеСекреты(секреты, дуэли, присутствующие, состояние, все = правки()) {
  if (settings.secretsAutoRaise === 'off') return [];
  const out = [];
  for (const с of Array.isArray(секреты) ? секреты : []) {
    const факт = с && с.fact;
    if (!факт) continue;
    let значение = null, откуда = '';
    for (const д of дуэли) {
      if (д.уступка && совпадаетССекретом(д.уступка, факт)) { значение = 'known'; откуда = д.уступка; break; }
      if (!значение && д.суть && совпадаетССекретом(д.суть, факт)) { значение = 'suspected'; откуда = д.суть; }
    }
    if (!значение) continue;
    for (const кто of присутствующие) {
      if (правкаСекрета(факт, кто, все)) continue;   // уже решено (в т. ч. «нет»)
      const вид = состояние(с, кто).вид;
      if (вид === 'knows' || вид === 'wrong') continue;
      if (значение === 'suspected' && вид === 'suspects') continue;
      out.push({ факт, кто, значение, откуда, путь: путьСекрета(факт, кто) });
    }
  }
  return out;
}
