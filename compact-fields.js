// «Сжатые значения» (Настройки → Генерация). Обычно промт просит модель
// писать HUD как можно полнее, и поля раздуваются: отношения по абзацу,
// дневник на страницу. Со сжатием у выбранных полей появляется жёсткий
// размер — «не больше 15 слов», «до 3 пунктов по 6 слов» — прямо в описании
// поля в схеме и общим правилом: размер важнее всех «как можно больше» и
