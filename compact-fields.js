const ВСЕ = КАТАЛОГ_СЖАТИЯ.flatMap(г => г.поля);
export const ПУТИ_СЖАТИЯ = ВСЕ.map(([путь]) => путь);
const ПО_ПУТИ = new Map(ВСЕ.map(([путь, имя, лимит]) => [путь, { имя, лимит }]));
// Поле персонажа — то же поле игрока.
const У_ИГРОКА = (путь) => (/^cs\./.test(путь) ? [путь, 'us.' + (путь === 'cs.W' ? 'UW' : путь.slice(3))] : [путь]);

export const МАКС_СЛОВ = 400;
export const МАКС_ПУНКТОВ = 50;
// Пустое поле ввода — не 0, а «не трогали».
const целое = (v, от, до) => { if (v === '' || v === null || v === undefined) return null; const n = Math.round(Number(v)); return Number.isFinite(n) ? Math.min(до, Math.max(от, n)) : null; };

/** Встроенный размер поля (копия). */
export function лимитПоУмолчанию(путь) {
  const з = ПО_ПУТИ.get(путь);
  return з ? { ...з.лимит } : null;
}

/** Размер поля с правкой из «Глубокой настройки»; кривая правка не в счёт. */
export function лимитПоля(s, путь) {
  const база = лимитПоУмолчанию(путь);
  if (!база) return null;
  const своё = s && s.compactLimits && typeof s.compactLimits === 'object' ? s.compactLimits[путь] : null;
  if (!своё || typeof своё !== 'object') return база;
  const w = целое(своё.w, 1, МАКС_СЛОВ);
  const i = 'i' in база ? целое(своё.i, 0, МАКС_ПУНКТОВ) : null;
  return { ...база, ...(w !== null ? { w } : {}), ...(i !== null ? { i } : {}) };
}

/**
 * Правки размеров для настроек: только то, что отличается от встроенного,
 * и только известные поля. Принимает { путь: { w, i } }.
 */
export function очиститьЛимиты(сырые) {
  const out = {};
  if (!сырые || typeof сырые !== 'object') return out;
  for (const [путь, v] of Object.entries(сырые)) {
    const база = лимитПоУмолчанию(путь);
    if (!база || !v || typeof v !== 'object') continue;
    const w = целое(v.w, 1, МАКС_СЛОВ);
    const i = 'i' in база ? целое(v.i, 0, МАКС_ПУНКТОВ) : null;
    const запись = {};
    if (w !== null && w !== база.w) запись.w = w;
    if (i !== null && i !== база.i) запись.i = i;
    if (Object.keys(запись).length) out[путь] = запись;
  }
  return out;
}

/** Какие поля сжимаются: пусто, если сжатие выключено. */
export function сжатыеПоля(s) {
  if (!s || s.hudCompact !== true) return [];
  const снято = new Set(Array.isArray(s.compactOff) ? s.compactOff : []);
  return ПУТИ_СЖАТИЯ.filter(путь => !снято.has(путь));
}

/** Размер словами для модели. */
export function текстЛимита(л) {
  if (!л) return '';
  if (!('i' in л)) return `at most ${л.w} words`;
  return л.i > 0 ? `at most ${л.i} items, ${л.w} words each` : `every item kept, at most ${л.w} words each`;
}

/** Размер словами для настроек. */
export function подписьЛимита(л) {
  if (!л) return '';
  if (!('i' in л)) return `до ${л.w} слов`;
  return л.i > 0 ? `до ${л.i} пунктов по ${л.w} слов` : `все пункты, по ${л.w} слов`;
}

// Последняя строка-значение в строке схемы — описание поля. У списков
// ("lg": ["[образец]", "описание"]) это второй элемент. Метка размера —
// в конец описания, внутрь его скобок [ … ], если они есть.
const ПОСЛЕДНЯЯ_СТРОКА = /"((?:[^"\\]|\\.)*)"(\s*\]?\s*,?\s*)$/;
function пометитьСтроку(строка, метка) {
  const м = строка.match(ПОСЛЕДНЯЯ_СТРОКА);
  if (!м) return строка;
  const текст = м[1];
  const новый = /\]$/.test(текст) ? текст.slice(0, -1) + ' ' + метка + ']' : текст + ' ' + метка;
  return строка.slice(0, м.index) + '"' + новый + '"' + м[2];
}

export const ПРАВИЛО_СЖАТИЯ = `
- 🗜️ COMPACT VALUES: a field marked «LIMIT» has a hard size set by the user. It overrides any "at least", "as many as", sentence count, "in full" or "every turn in detail" asked anywhere in these instructions or in that field. Shorter, never poorer: keep every fact the HUD tracks — every person, item, mark, plan, thread, promise and fear; every label and code of the field's format (xp:, gt:, nw:, sn:, lt:, dt:, pr:, en:); every number, time, date, fade time, level, status, protection and name — and cut only the describing words around them. Labels, codes, numbers, times, dates, names and emoji do not count as words. A limit with an item count caps entries that are written anew each turn; "every item kept" means no entry may be dropped to fit — only shortened. Quoted lines («…») are chosen shorter, never cut mid-phrase. A diary stays a real entry in full sentences, just a shorter one.`;

/**
 * Схема промта с размерами сжатых полей и правило о них (после правила
 * FORMATTING). Поля, которых в схеме нет (блок выключен), пропускаются.
 */
export function сжатьСхему(текст, s) {
  const пути = сжатыеПоля(s);
  if (!пути.length) return текст;
  const строки = String(текст).split('\n');
  let помечено = 0;
  for (const путь of пути) {
    const метка = `LIMIT: ${текстЛимита(лимитПоля(s, путь))}`;
    for (const где of У_ИГРОКА(путь)) {
      const i = строкаПоляСхемы(строки, где);
      // Поле-блок ("sec": [ … на несколько строк) — не сжимается.
      if (i < 0 || /[[{]\s*,?\s*$/.test(строки[i])) continue;
      const было = строки[i];
      строки[i] = пометитьСтроку(было, метка);
      if (строки[i] !== было) помечено++;
    }
  }
  if (!помечено) return текст;
  return строки.join('\n').replace(/(- ⚠️ FORMATTING:[^\n]*)/, (всё) => всё + ПРАВИЛО_СЖАТИЯ);
}
