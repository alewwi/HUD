// hud-manager/disputes.js
//
// Вопросы о противоречиях (настройка askContradictions, по умолчанию выкл.).
//
// HUD сам считает многое — срок беременности от зачатия, вес с пределом
// скорости, бодрость после сна, сытость после еды — и там, где модель
// написала другое, молча ставил своё. С настройкой он сначала спрашивает:
// что написала модель, что считает HUD и почему спрашивает. Пока ответа
// нет, остаётся написанное моделью: HUD ничего не перезаписывает.
//
// Ответы:
//  · «Верно у модели» — HUD принимает её число (и, где это расчёт, пересчитывает
//    основу: срок дальше идёт от её недели);
//  · «Верно у HUD» — остаётся счёт HUD, а модель в следующем ответе получает
//    поправку;
//  · «Своё» — игрок задаёт основу сам (неделю, вес, сколько спал, когда ели),
//    и дальше HUD считает от неё.
//
// Решение запоминается: тот же спор с теми же данными больше не всплывает.
// Новый вопрос — только когда данные другие (модель написала новое число).
//
// Хранится в метаданных чата: { r: решения, o: открытые }.

import { settings } from './settings.js?v=23.89.65';

const КЛЮЧ = 'tavernosHudDisputes';
const объект = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
let пример = null;
/** Набор для примера «Кастомизации» и тестов: в чат ничего не пишется. */
export function задатьПримерСпоров(набор) { пример = набор || null; }

function хранилище() {
  if (пример) { if (!объект(пример.r)) пример.r = {}; if (!объект(пример.o)) пример.o = {}; return пример; }
  let м = null;
  try { const c = window.SillyTavern?.getContext?.(); м = c && (c.chatMetadata || c.chat_metadata) || null; } catch (_) { м = null; }
  if (!м) return null;
  if (!объект(м[КЛЮЧ])) м[КЛЮЧ] = {};
  const х = м[КЛЮЧ];
  if (!объект(х.r)) х.r = {};
  if (!объект(х.o)) х.o = {};
  return х;
}
function сохранить() {
  if (пример) return;
  try { const c = window.SillyTavern?.getContext?.(); (c?.saveMetadataDebounced || c?.saveMetadata)?.call(c); } catch (_) { /* со следующим */ }
}
function сообщить() { try { document.dispatchEvent(new CustomEvent('hud:disputes')); } catch (_) { /* без страницы */ } }

export const спрашивать = () => settings.askContradictions === true;

// Спор открывается только о последнем ответе (д.ход — его номер в чате):
// старые ходы рисуются по тем же правилам, но спорить о них поздно.
// Свайп ответа номер i: вопрос держится только при том варианте, о котором он.
function свайпОтвета(i) {
  if (пример) return пример.свайп ?? 0;
  try { const м = window.SillyTavern?.getContext?.()?.chat?.[i]; return м ? (м.swipe_id ?? 0) : null; } catch (_) { return null; }
}
function последнийОтвет() {
  if (пример) return пример.последний ?? null;
  try {
    const чат = window.SillyTavern?.getContext?.()?.chat;
    if (!Array.isArray(чат)) return null;
    for (let i = чат.length - 1; i >= 0; i--) if (чат[i] && !чат[i].is_user && !чат[i].is_system) return i;
  } catch (_) { /* без Таверны */ }
  return null;
}

const тотЖе = (а, б, допуск = 0) => {
  if (typeof а === 'number' && typeof б === 'number') return Math.abs(а - б) <= допуск;
  return String(а ?? '') === String(б ?? '');
};

/**
 * Противоречие: модель написала одно, HUD считает другое.
 *   ключ     — что и чьё ('prg|Мари'): один спор на это место;
 *   подпись  — данные спора (число или строка): та же подпись — тот же спор;
 *   допуск   — для числовой подписи: насколько она может «дрожать»;
 *   что, кто, модель, hud, почему — для окна;
 *   основа   — что игрок может задать сам: { вид: 'число'|'время'|'текст', подпись, мин, макс, единица };
 *   сказатьHUD, сказатьСвоё — поправка модели (в «Своё» {v} — введённое);
 *   база     — что нужно, чтобы пересчитать основу (сцена, неделя модели…).
 * Возвращает решение: { решение: 'hud'|'model'|'own'|'ask', своё }.
 * Настройка выключена — 'hud', как было всегда.
 */
export function спор(д) {
  if (!спрашивать() || !д || !д.ключ) return { решение: 'hud' };
  const х = хранилище();
  if (!х) return { решение: 'hud' };
  const р = х.r[д.ключ];
  if (р && тотЖе(р.подпись, д.подпись, д.допуск || 0)) {
    if (х.o[д.ключ]) { delete х.o[д.ключ]; сохранить(); }
    return р;
  }
  const открыт = х.o[д.ключ];
  const последний = Number.isInteger(д.ход) && д.ход === последнийОтвет();
  // Открытый о прежнем свайпе — уже не тот: открываем заново о нынешнем.
  const свежий = открыт && (!Number.isInteger(открыт.ход) || (открыт.ход === д.ход && (открыт.свайп ?? null) === свайпОтвета(д.ход)));
  if (последний && (!свежий || !тотЖе(открыт.подпись, д.подпись, д.допуск || 0))) {
    const { ключ, подпись, допуск = 0, что = '', кто = '', модель = '', hud = '', почему = '', основа = null, сказатьHUD = '', сказатьСвоё = '', база = null } = д;
    х.o[ключ] = { ключ, подпись, допуск, что, кто, модель: String(модель), hud: String(hud), почему, основа, сказатьHUD, сказатьСвоё, база, ход: д.ход, свайп: свайпОтвета(д.ход), когда: Date.now() };
    сохранить();
    сообщить();
  }
  // Пока не ответили — остаётся написанное моделью.
  return { решение: 'ask' };
}

/** Решение по месту, если оно есть (без нового спора). */
export function решениеСпора(ключ) {
  const х = спрашивать() ? хранилище() : null;
  return х && х.r[ключ] ? х.r[ключ] : null;
}
export function открытыеСпоры() {
  const х = спрашивать() ? хранилище() : null;
  if (!х) return [];
  // Пришёл новый ответ или свайп — вопрос о прежнем варианте больше не к месту.
  const последний = последнийОтвет();
  let менялось = false;
  for (const [к, о] of Object.entries(х.o)) {
    if (Number.isInteger(о.ход) && (о.ход !== последний || (о.свайп ?? null) !== свайпОтвета(о.ход))) { delete х.o[к]; менялось = true; }
  }
  if (менялось) сохранить();
  return Object.values(х.o).sort((а, б) => (а.когда || 0) - (б.когда || 0));
}
/** Снять открытый спор без решения (например, место пропало из HUD). */
export function забытьСпор(ключ) {
  const х = хранилище();
  if (!х || !х.o[ключ]) return false;
  delete х.o[ключ];
  сохранить(); сообщить();
  return true;
}

/** Ответ игрока: решение 'model' | 'hud' | 'own'; своё — введённая основа. */
export function решитьСпор(ключ, решение, своё = null) {
  const х = хранилище();
  const о = х && х.o[ключ];
  if (!о || !['model', 'hud', 'own'].includes(решение)) return false;
  const сказать = решение === 'hud' ? о.сказатьHUD : решение === 'own' && о.сказатьСвоё ? String(о.сказатьСвоё).replace(/\{v\}/g, String(своё)) : '';
  х.r[ключ] = { решение, подпись: о.подпись, своё, база: о.база, что: о.что, кто: о.кто, модель: о.модель, hud: о.hud, когда: Date.now(), ...(сказать ? { сказать, цель: null } : {}) };
  delete х.o[ключ];
  сохранить(); сообщить();
  return true;
}
/** Забыть решение: место снова считается по правилам, спор может открыться. */
export function снятьРешение(ключ) {
  const х = хранилище();
  if (!х || !х.r[ключ]) return false;
  delete х.r[ключ];
  сохранить(); сообщить();
  return true;
}
export function решённыеСпоры() {
  const х = спрашивать() ? хранилище() : null;
  return х ? Object.entries(х.r).map(([ключ, р]) => ({ ключ, ...р })).sort((а, б) => (б.когда || 0) - (а.когда || 0)) : [];
}

/**
 * Поправки модели на этот ответ (цель — номер сообщения, которое она пишет):
 * уходят в ответ после решения и во все его свайпы, дальше — нет.
 */
export function заметкаСпоров(цель) {
  // Без настройки тоже: основу из правки «Быта» модель должна узнать.
  const х = хранилище();
  if (!х) return [];
  const строки = [];
  let менялось = false;
  for (const р of Object.values(х.r)) {
    if (!р.сказать) continue;
    if (р.цель === null || р.цель === undefined) { р.цель = цель; менялось = true; }
    if (р.цель !== цель) { delete р.сказать; delete р.цель; менялось = true; continue; }
    строки.push(р.сказать);
  }
  if (менялось) сохранить();
  return строки;
}

/** Подпись спора «бодрость после сна»: та же бодрость при той же записи сна — тот же спор. */
export const подписьСна = (awk, сон) => `${awk}|${String(сон || '').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' ').trim().slice(0, 30)}`;
/** Решение по подписи, без имени (шкалы тела не знают, чьи они). */
export function решениеПоПодписи(начало, подпись) {
  const х = спрашивать() ? хранилище() : null;
  if (!х) return null;
  return Object.entries(х.r).find(([к, р]) => к.startsWith(начало) && р.подпись === подпись)?.[1] || null;
}

/**
 * Основа, которую игрок задал сам — без спора (правка «Быта»: когда ели,
 * когда мылись, сколько спал). Действует и без настройки вопросов: это не
 * спор с моделью, а поправка счёта HUD. сказать — что передать модели.
 */
export function задатьОснову(ключ, { что = '', кто = '', своё, база = null, сказать = '' } = {}) {
  const х = хранилище();
  if (!х || !ключ) return false;
  х.r[ключ] = { решение: 'own', своё, база, что, кто, подпись: '__игрок', когда: Date.now(), ...(сказать ? { сказать, цель: null } : {}) };
  delete х.o[ключ];
  сохранить(); сообщить();
  return true;
}
/** Все основы игрока («своё»): из вопросов и из правки «Быта». */
export function основыИгрока() {
  const х = хранилище();
  return х ? Object.entries(х.r).filter(([, р]) => р && р.решение === 'own').map(([ключ, р]) => ({ ключ, ...р })) : [];
}
