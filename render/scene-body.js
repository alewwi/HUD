function состояниеВещи(кусок) {
  const к = кусок.toLowerCase();
  const есть = (s) => слово(s).test(к);
  const с = { открыто: 0, задрано: 0, спущено: 0, сдвинуто: false, порвано: false, мокро: false, сплечо: false, рукава: '' };
  // Расстёгнуто/распахнуто: 1 — на груди, несколько пуговиц; 2 — до пояса, распахнуто.
  if (есть('распахн|расст[её]гнут\\p{L}* до пояса|расст[её]гнут\\p{L}* полностью|нараспашку|разорван\\p{L}* на груди|сорван\\p{L}* с плеч')) с.открыто = 2;
  else if (есть('расст[её]гн|на несколько пуговиц|ворот расст')) с.открыто = есть('на груди|ворот|несколько пуговиц|верхн') ? 1 : 2;
  // Задрано: 3 — выше груди, 2 — до груди, 1 — до талии/живота.
  if (есть('задран\\p{L}* (?:выше|над) груд|сдвинут\\p{L}* вверх|поднят\\p{L}* (?:выше|над) груд|задрал\\p{L}* (?:выше|над) груд')) с.задрано = 3;
  else if (есть('задран\\p{L}* до груд|до подмыш')) с.задрано = 2;
  else if (есть('задран|задрал|поднят\\p{L}* до тали|до пояса задр|собран\\p{L}* на тали|подол\\p{L}* (?:поднят|задран)')) с.задрано = 1;
  // Спущено: 1 — приспущено, на бёдрах; 2 — до бёдер; 3 — до колен; 4 — до щиколоток.
  if (есть('до щиколот|до лодыж|до пят|к щиколот')) с.спущено = 4;
  else if (есть('до колен|к колен|на колен')) с.спущено = 3;
  else if (есть('до бедер|до бёдер|до середины бед|на бедр|спущен|стянут')) с.спущено = есть('приспущ') ? 1 : 2;
  else if (есть('приспущ|сполз')) с.спущено = 1;
  if (есть('сдвинут\\p{L}* (?:в сторон|набок|вбок)|отодвинут|сдвинут(?![\\p{L}])')) с.сдвинуто = true;
  if (есть('порван|разорван|рван(?:ый|ая|ое)|разодран|лопнул')) с.порвано = true;
  if (есть('мокр|влажн|намок|промок|пропотевш|в поту|залит')) с.мокро = true;
  if (есть('сполз\\p{L}* с плеч|спущен\\p{L}* с плеч|с одного плеча|оголя\\p{L}* плеч|соскользн\\p{L}* с плеч')) { с.сплечо = true; if (с.спущено === 1) с.спущено = 0; }
  if (есть('рукава закатан|закатанн\\p{L}* рукав')) с.рукава = 'roll';
  if (есть('без рукав|на бретел')) с.рукава = 'none';
  return с;
}

