/** «Поза» и пол персонажа ('m'|'f'|'') → ключ позы. */
export function позаТела(текстПозы, пол = '') {
  const t = текст(текстПозы);
  if (!t) return 'fours';
  const куски = t.split(/[,;.]/).map(x => x.trim()).filter(Boolean);
  const чей = (к) => /(?:^|\s)(?:она|её|she|she's)(?:\s|$)/i.test(к) ? 'f' : /(?:^|\s)(?:он|he|he's)(?:\s|$)/i.test(к) ? 'm' : '';
  const поза = (к) => (СЛОВА_ПОЗ.find(([, rx]) => rx.test(к)) || [])[0];
  let своя = null, чужая = null, ничья = null;
  for (const к of куски) {
    let п = поза(к);
    if (!п) continue;
    const кто = чей(к);
    // «она сверху» — обычно верхом, а не нависает.
    if (п === 'over' && кто === 'f' && !/навалил|нависа|pinning|pins|looming|leaning over|hovering over/i.test(к)) п = 'top';
    if (!кто) { ничья ||= п; continue; }
    if (!пол || кто === пол) своя ||= п; else чужая ||= п;
  }
  return своя || (чужая ? ОТВЕТ[чужая] : null) || ничья || 'fours';
}
// «М, высокий брюнет…» / «Ж, …» — пол по биологии, модель ставит его первой
