export function гдеНазваниеВещи(кусок, id) {
  const свои = ВИДЫ_ВЕЩЕЙ.filter(([и]) => и === id || (и === 'suit' && (id === 'outer' || id === 'pants')));
  for (const набор of [свои, ВИДЫ_ВЕЩЕЙ]) {
    const где = набор.map(([, , rx]) => { const m = rx.exec(кусок); return m ? m.index : -1; }).filter(i => i >= 0);
    if (где.length) return Math.min(...где);
  }
  return -1;
}

