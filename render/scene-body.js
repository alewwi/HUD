/**
 * «Одежда» → [{ id, имя, текст, состояние: 'on'|'half'|'off', цвет, ткань, ...флаги }].
 * Совсем голый — пустой список с пометкой голый.
 */
export function одеждаПодробно(t) {
  const весь = текст(t);
  const out = [];
  if (!весь || /^(empty|none|нет|пусто)$/i.test(весь)) return out;
  const голый = ГОЛЫЙ.test(весь) && !/(?:трусик|бель[её]|чулк|рубашк|брюк|штан|юбк|плать|шорт)/i.test(весь.replace(/без [^,;]+/gi, ''));
  if (голый) { out.голый = true; return out; }
  // Запятые в скобках — пояснение к той же вещи: «бельё (бюстгальтер и трусики, сдвинутые в сторону)».
  const безСкобок = весь.replace(/\(([^)]*)\)/g, (m, x) => ' ' + x.replace(/[,;]/g, ' ') + ' ');
  for (const кусок of безСкобок.split(/[,;\n]|\s+—\s+|\s+и\s+(?=[\p{L}-]+\s+(?:рубашк|брюк|штан|юбк|бель|трус|шорт|чул|туфл|топ|футболк|майк))/u).map(x => x.trim()).filter(Boolean)) {
    if (БОСОЙ.test(кусок)) { if (!out.some(в => в.id === 'shoes')) out.push({ id: 'shoes', имя: 'Обувь', текст: кусок, состояние: 'off' }); continue; }
    if (ГОЛЫЙ_ТОРС.test(кусок)) { if (!out.some(в => в.id === 'shirt')) out.push({ id: 'shirt', имя: 'Верх', текст: кусок, состояние: 'off' }); continue; }
    // «без пиджака», «без галстука» — вещи нет.
    const без = кусок.match(/^без\s+(\p{L}+)/iu);
    const вещи = ВИДЫ_ВЕЩЕЙ.filter(([, , rx]) => rx.test(кусок));
    if (!вещи.length) continue;
    // «шорты и бельё стянуты до колен» — обе вещи с одним состоянием.
    const берём = /\sи\s/.test(кусок) && вещи.length > 1 ? вещи.slice(0, 2) : вещи.slice(0, 1);
    for (const [id, имя] of берём) {
      if (out.some(в => в.id === id)) continue;
      const с = состояниеВещи(кусок);
      const снято = !!без || СНЯТО.test(кусок);
      const частично = с.открыто || с.задрано || с.спущено || с.сдвинуто || с.порвано || с.сплечо;
      out.push({ id, имя, текст: кусок, состояние: снято ? 'off' : частично ? 'half' : 'on', цвет: цветВещи(кусок, id), ткань: (ТКАНЬ.find(([, rx]) => rx.test(кусок)) || [''])[0], ...с });
    }
  }
  // Костюм — это пиджак и брюки, если их не назвали отдельно.
  const костюм = out.find(в => в.id === 'suit');
  if (костюм) {
    if (!out.some(в => в.id === 'outer')) out.push({ ...костюм, id: 'outer', имя: 'Пиджак' });
    if (!out.some(в => в.id === 'pants')) out.push({ ...костюм, id: 'pants', имя: 'Брюки', открыто: 0, задрано: 0 });
  }
  return out.filter(в => в.id !== 'suit');
}

