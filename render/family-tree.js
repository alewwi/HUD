// Кем «кому» приходится тому, у кого записано отношение. Ищем только в
// первых словах: дальше идёт чувство, где «любит как сына» или «брат по
// несчастью» родством не являются. Ё заранее заменяется на е.
const РОДСТВО = [
  ['exSpouse', /^(?:бывш(?:ий|ая) (?:муж|жена|супруг|супруга)|ex[- ]?(?:husband|wife|spouse))$/],
  ['spouse', /^(?:муж|жена|супруг|супруга|husband|wife|spouse)$/],
  ['parentInLaw', /^(?:свекровь|свекор|теща|тесть|(?:mother|father)[- ]in[- ]law)$/],
  ['childInLaw', /^(?:зять|невестка|сноха|(?:son|daughter)[- ]in[- ]law)$/],
  ['grandparent', /^(?:дед|дедушка|бабушка|бабуля|прадед|прабабушка|grandfather|grandmother|grandpa|grandma|grandparent)$/],
  ['grandchild', /^(?:внук|внучка|правнук|правнучка|grandson|granddaughter|grandchild)$/],
  ['parent', /^(?:отец|папа|мать|мама|отчим|мачеха|приемный отец|приемная мать|father|mother|dad|mom|stepfather|stepmother|parent)$/],
  ['child', /^(?:сын|сынок|дочь|дочка|пасынок|падчерица|приемный сын|приемная дочь|son|daughter|stepson|stepdaughter|child)$/],
  ['sibling', /^(?:брат|сестра|сводный брат|сводная сестра|единокровный брат|единокровная сестра|близнец|близняшка|brother|sister|twin|sibling|half[- ]brother|half[- ]sister|stepbrother|stepsister)$/],
  ['uncle', /^(?:дядя|тетя|uncle|aunt)$/],
  ['nephew', /^(?:племянник|племянница|nephew|niece)$/],
  ['cousin', /^(?:кузен|кузина|двоюродный брат|двоюродная сестра|cousin)$/],
];
// Слова перед родством, которые его не меняют: «мой муж», «старшая сестра».
const ПРИСТАВКИ = /^(?:мой|моя|мое|мои|ее|его|их|наш|наша|родной|родная|младший|младшая|старший|старшая|любимый|любимая|покойный|покойная|my|her|his|their|our|older|younger|little|big|late)\s+/;

// Возвращает { тип, слово, чей }. «чей» — имя из «сестра Брэндона»: родство
// тогда не с говорящим, а с названным человеком.
export function родствоИз(отношение) {
  // Регистр нужен, чтобы отличить имя («сестра Брэндона») от обычного слова
  // («сестра жены»), поэтому слова берём в двух видах с одинаковой нумерацией.
  const исходная = String(отношение || '').replace(/ё/g, 'е').replace(/Ё/g, 'Е')
    .split(/[,;:—–(]|\s-\s/)[0].trim();
  let исходные = исходная.split(/\s+/).filter(Boolean);
  let слова = исходные.map(w => w.toLowerCase());
  for (let i = 0; i < 3 && слова.length && ПРИСТАВКИ.test(слова[0] + ' '); i++) { слова = слова.slice(1); исходные = исходные.slice(1); }
  for (let n = Math.min(3, слова.length); n >= 1; n--) {
    const кусок = слова.slice(0, n).join(' ');
    const найдено = РОДСТВО.find(([, rx]) => rx.test(кусок));
    if (!найдено) continue;
    const следом = слова[n];
    if (!следом) return { тип: найдено[0], слово: кусок, чей: '' };
    // «Брат по оружию», «как сестра» — оборот, а не родство.
    if (/^(?:по|как|of|in|like)$/.test(следом)) return null;
    // «Сестра Брэндона» — родство с Брэндоном. Имя — одно-два слова с заглавной.
    if (/^\p{Lu}/u.test(исходные[n])) {
      const имя = [исходные[n]];
      if (исходные[n + 1] && /^\p{Lu}/u.test(исходные[n + 1])) имя.push(исходные[n + 1]);
      return { тип: найдено[0], слово: кусок, чей: имя.join(' ') };
    }
    // «Сестра жены», «мать моего друга» — родство не с говорящим.
    return null;
  }
  return null;
}

// Пол по слову родства о человеке: «сын», «жена», «брат» его выдают. Нужен,
// чтобы достроить недостающую сторону подписи: у отца «Tristan: сын» не
// записано, но Софи назвала Тристана мужем — значит, отцу он сын.
const МУЖСКОЕ = /^(?:отец|папа|отчим|приемный отец|сын|сынок|пасынок|приемный сын|муж|бывший муж|супруг|брат|сводный брат|единокровный брат|двоюродный брат|кузен|дед|дедушка|прадед|внук|правнук|дядя|племянник|свекор|тесть|зять|father|dad|stepfather|son|stepson|husband|ex[- ]?husband|brother|half[- ]brother|stepbrother|grandfather|grandpa|grandson|uncle|nephew|son[- ]in[- ]law|father[- ]in[- ]law)$/;
const ЖЕНСКОЕ = /^(?:мать|мама|мачеха|приемная мать|дочь|дочка|падчерица|приемная дочь|жена|бывшая жена|супруга|сестра|сводная сестра|единокровная сестра|двоюродная сестра|кузина|бабушка|бабуля|прабабушка|внучка|правнучка|тетя|племянница|свекровь|теща|невестка|сноха|mother|mom|stepmother|daughter|stepdaughter|wife|ex[- ]?wife|sister|half[- ]sister|stepsister|grandmother|grandma|granddaughter|aunt|niece|daughter[- ]in[- ]law|mother[- ]in[- ]law)$/;
const полПоСлову = (слово) => МУЖСКОЕ.test(слово) ? 'м' : ЖЕНСКОЕ.test(слово) ? 'ж' : '';

// Слово для роли по полу: «отец/мать», «сын/дочь», «муж/жена». Приёмное
// родство сохраняем: отчиму — пасынок, мачехе — падчерица. Пол неизвестен —
// нейтральное слово, чтобы подпись не обрывалась на стрелке.
export function словоПоРоли(роль, пол, парное) {
  const приёмный = /отчим|мачеха|пасын|падчериц|приемн|step/.test(парное || '');
  const варианты = {
    parent: приёмный ? ['отчим', 'мачеха', 'родитель'] : ['отец', 'мать', 'родитель'],
    child: приёмный ? ['пасынок', 'падчерица', 'ребёнок'] : ['сын', 'дочь', 'ребёнок'],
    spouse: /бывш|ex/.test(парное || '') ? ['бывший муж', 'бывшая жена', ''] : ['муж', 'жена', ''],
  }[роль];
  if (!варианты) return '';
  return пол === 'м' ? варианты[0] : пол === 'ж' ? варианты[1] : варианты[2];
}

// Имя из «сестра Брэндона» → человек графа. Через общее сравнение имён: падеж
// («Брэндона», «Софии»), другой алфавит («Тристана» и Tristan) и уменьшительные
// («Миши» и Michael) там уже учтены. Двое подходят одинаково — не угадываем.
function узелПоИмени(люди, имя, кромеId) {
  const список = [...люди.values()].filter(ч => !ч.virtual && ч.id !== кромеId);
  const i = найтиПоИмени(имя, список.map(ч => ч.name));
  return i >= 0 ? список[i].id : null;
}

// Поле сверху шире: над верхней парой встаёт подпись «жена ⚭ муж».
const W_УЗЛА = 136, H_УЗЛА = 58, ЗАЗОР_СУПРУГОВ = 28, ЗАЗОР = 26, ШАГ_РЯДА = 124, ПОЛЕ = 24;

// nodes: [{ id, name, isUser, isPrimary }], edges: [{ from, to, label }].
// Возвращает null, если родства нет, иначе { svg, people, positions }.
export function buildFamilyTree(nodes, edges, idBase) {
  const люди = new Map((nodes || []).map(n => [n.id, { ...n }]));
  const родители = new Map();     // ребёнок → Set(родителей)
  const супруги = new Map();      // id → Map(id → бывший ли)
  const братья = new Map();       // id → Set
  const кузены = [];
  const ктоИгроку = new Map();    // id → слово родства со стороны игрока
  // «ктокому» → кем «кому» приходится «кто»: для подписей на линиях.
  const словоРодства = new Map();
  const пол = new Map();          // id → 'м' | 'ж' по словам родства о человеке
  const пара = (a, b) => a + '' + b;
  const игрок = (nodes || []).find(n => n.isUser);
  let виртуальных = 0;

  const набор = (карта, ключ) => { if (!карта.has(ключ)) карта.set(ключ, new Set()); return карта.get(ключ); };
  const новыйНеизвестный = (скрытый) => {
    const id = `?${++виртуальных}`;
    люди.set(id, { id, name: '?', virtual: true, hidden: !!скрытый });
    return id;
  };
  const родитель = (р, д) => { if (р && д && р !== д) набор(родители, д).add(р); };
  const брак = (a, b, бывший) => {
    if (!a || !b || a === b) return;
    if (!супруги.has(a)) супруги.set(a, new Map());
    if (!супруги.has(b)) супруги.set(b, new Map());
    супруги.get(a).set(b, бывший); супруги.get(b).set(a, бывший);
  };
  const родня = (a, b) => { if (a && b && a !== b) { набор(братья, a).add(b); набор(братья, b).add(a); } };
  const детиИз = (id) => [...родители.entries()].filter(([, s]) => s.has(id)).map(([д]) => д);
  const первыйРодитель = (id) => {
    const список = [...(родители.get(id) || [])];
    return список.find(p => !(родители.get(p) || new Set()).size) || список[0] || null;
  };

  const отложенные = [];
  let найдено = 0;
  for (const e of edges || []) {
    const р = родствоИз(e.label);
    if (!р || !люди.has(e.from) || !люди.has(e.to) || e.from === e.to) continue;
    let кто = e.from;
    const кому = e.to;
    if (р.чей) {
      // «Эванджелина: сестра Брэндона» у Тристана — сестра Брэндона, а не
      // Тристана. Брэндона нет в графе — связь не рисуем вовсе.
      const чей = узелПоИмени(люди, р.чей, кому);
      if (!чей) continue;
      кто = чей;
    }
    найдено++;
    if (!словоРодства.has(пара(кто, кому))) словоРодства.set(пара(кто, кому), р.слово);
    { const g = полПоСлову(р.слово); if (g && !пол.has(кому)) пол.set(кому, g); }
    if (игрок && кто === игрок.id && !ктоИгроку.has(кому)) ктоИгроку.set(кому, р.слово);
    switch (р.тип) {
      case 'parent': родитель(кому, кто); break;
      case 'child': родитель(кто, кому); break;
      case 'spouse': брак(кто, кому, false); break;
      case 'exSpouse': брак(кто, кому, true); break;
      case 'sibling': родня(кто, кому); break;
      case 'cousin': кузены.push([кто, кому]); break;
      default: отложенные.push([р.тип, кто, кому]);
    }
  }
  if (!найдено) return null;

  // Братья и сёстры делят родителей: кого знают у одного, тот родитель всем.
  const группыБратьев = () => {
    const группы = [], посещён = new Set();
    for (const id of братья.keys()) {
      if (посещён.has(id)) continue;
      const группа = [], стек = [id];
      посещён.add(id);
      while (стек.length) {
        const x = стек.pop(); группа.push(x);
        for (const y of (братья.get(x) || [])) if (!посещён.has(y)) { посещён.add(y); стек.push(y); }
      }
      группы.push(группа);
    }
    return группы;
  };
  const раздатьРодителей = () => группыБратьев().forEach(группа => {
    const общие = new Set();
    группа.forEach(id => (родители.get(id) || []).forEach(р => общие.add(р)));
    группа.forEach(id => общие.forEach(р => родитель(р, id)));
  });
  раздатьРодителей();

  // Дальнее родство достраиваем через ближнее; неизвестное звено — узел «?».
  for (const [тип, кто, кому] of отложенные) {
    if (тип === 'grandparent') {
      let мост = первыйРодитель(кто);
      if (!мост) { мост = новыйНеизвестный(); родитель(мост, кто); }
      родитель(кому, мост);
    } else if (тип === 'grandchild') {
      const дети = детиИз(кто);
      let мост = дети.find(c => !детиИз(c).length) || дети[0];
      if (!мост) { мост = новыйНеизвестный(); родитель(кто, мост); }
      родитель(мост, кому);
    } else if (тип === 'uncle') {
      let мост = первыйРодитель(кто);
      if (!мост) { мост = новыйНеизвестный(); родитель(мост, кто); }
      родня(мост, кому);
    } else if (тип === 'nephew') {
      let мост = первыйРодитель(кому);
      if (!мост) { мост = новыйНеизвестный(); родитель(мост, кому); }
      родня(мост, кто);
    } else if (тип === 'parentInLaw') {
      let супруг = [...(супруги.get(кто) || new Map())].filter(([, бывший]) => !бывший).map(([id]) => id)[0];
      if (!супруг) { супруг = новыйНеизвестный(); брак(кто, супруг, false); }
      родитель(кому, супруг);
    } else if (тип === 'childInLaw') {
      const дети = детиИз(кто);
      let ребёнок = дети.find(c => !супруги.has(c)) || дети[0];
      if (!ребёнок) { ребёнок = новыйНеизвестный(); родитель(кто, ребёнок); }
      брак(ребёнок, кому, false);
    }
  }
  раздатьРодителей();

  // Братья и сёстры без родителей получают скрытого общего родителя: так
  // они встают рядом под одной шиной, а не разбегаются по разным краям.
  группыБратьев().forEach(группа => {
    if (группа.some(id => (родители.get(id) || new Set()).size)) return;
    const скрытый = новыйНеизвестный(true);
    группа.forEach(id => родитель(скрытый, id));
  });

  // --- Поколения ---
  const дети = new Map();
  for (const [д, s] of родители) s.forEach(р => набор(дети, р).add(д));
  const связан = (id) => родители.has(id) || дети.has(id) || супруги.has(id) || братья.has(id) || кузены.some(p => p.includes(id));
  const соседи = (id) => {
    const out = [];
    (родители.get(id) || []).forEach(р => out.push([р, -1]));
    (дети.get(id) || []).forEach(д => out.push([д, 1]));
    (супруги.get(id) || new Map()).forEach((_, s) => out.push([s, 0]));
    (братья.get(id) || []).forEach(b => out.push([b, 0]));
    кузены.forEach(([a, b]) => { if (a === id) out.push([b, 0]); if (b === id) out.push([a, 0]); });
    return out;
  };
  const порядок = [...люди.keys()].filter(связан).sort((a, b) => {
    const ва = люди.get(a), вб = люди.get(b);
    return (вб.isUser - ва.isUser) || (вб.isPrimary - ва.isPrimary);
  });
  const поколение = new Map();
  const компонент = new Map();
  let компонентов = 0;
  for (const старт of порядок) {
    if (поколение.has(старт)) continue;
    const номер = компонентов++;
    поколение.set(старт, 0); компонент.set(старт, номер);
    const очередь = [старт];
    while (очередь.length) {
      const x = очередь.shift();
      for (const [y, шаг] of соседи(x)) {
        if (поколение.has(y)) continue;
        поколение.set(y, поколение.get(x) + шаг); компонент.set(y, номер);
        очередь.push(y);
      }
    }
  }

  // --- Блоки: человек вместе с супругами, цепочкой ---
  const блокЧеловека = new Map();
  const блоки = [];
  for (const id of порядок) {
    if (блокЧеловека.has(id)) continue;
    const группа = [], стек = [id], видел = new Set([id]);
    while (стек.length) {
      const x = стек.pop(); группа.push(x);
      (супруги.get(x) || new Map()).forEach((_, s) => {
        if (!видел.has(s) && поколение.get(s) === поколение.get(x)) { видел.add(s); стек.push(s); }
      });
    }
    // Цепочку ставим от края: «бывшая — он — нынешняя» с ним посередине.
    const край = группа.find(x => (супруги.get(x) || new Map()).size <= 1) || группа[0];
    const члены = [], очередь = [край], поставлен = new Set([край]);
    while (очередь.length) {
      const x = очередь.shift(); члены.push(x);
      (супруги.get(x) || new Map()).forEach((_, s) => { if (группа.includes(s) && !поставлен.has(s)) { поставлен.add(s); очередь.push(s); } });
    }
    группа.forEach(x => { if (!поставлен.has(x)) члены.push(x); });
    const блок = { члены, поколение: поколение.get(id), компонент: компонент.get(id), дети: [], родитель: null };
    члены.forEach(x => блокЧеловека.set(x, блок));
    блоки.push(блок);
  }
  блоки.sort((a, b) => a.поколение - b.поколение);
  for (const блок of блоки) {
    const детскиеБлоки = [];
    блок.члены.forEach(x => (дети.get(x) || []).forEach(д => {
      const б = блокЧеловека.get(д);
      if (б && б !== блок && б.поколение === блок.поколение + 1 && !б.родитель && !детскиеБлоки.includes(б)) детскиеБлоки.push(б);
    }));
    детскиеБлоки.forEach(б => { б.родитель = блок; блок.дети.push(б); });
  }

  // --- Раскладка: ширина поддерева и расстановка сверху вниз ---
  const ширинаСвоя = (б) => б.члены.length * W_УЗЛА + (б.члены.length - 1) * ЗАЗОР_СУПРУГОВ;
  const ширинаДетей = (б) => б.дети.reduce((s, д, i) => s + ширина(д) + (i ? ЗАЗОР : 0), 0);
  function ширина(б) {
    if (б._w === undefined) б._w = Math.max(ширинаСвоя(б), ширинаДетей(б));
    return б._w;
  }
  const позиция = new Map();
  function расставить(б, x0) {
    const w = ширина(б);
    let x = x0 + (w - ширинаДетей(б)) / 2;
    б.дети.forEach(д => { расставить(д, x); x += ширина(д) + ЗАЗОР; });
    let сам = x0 + (w - ширинаСвоя(б)) / 2;
    б.члены.forEach(id => { позиция.set(id, { x: сам, поколение: поколение.get(id) }); сам += W_УЗЛА + ЗАЗОР_СУПРУГОВ; });
  }
  const корни = блоки.filter(б => !б.родитель).sort((a, b) => a.компонент - b.компонент || a.поколение - b.поколение);
  let курсор = ПОЛЕ;
  let прошлыйКомпонент = null;
  for (const корень of корни) {
    if (прошлыйКомпонент !== null && корень.компонент !== прошлыйКомпонент) курсор += ЗАЗОР * 2;
    расставить(корень, курсор);
    курсор += ширина(корень) + ЗАЗОР;
    прошлыйКомпонент = корень.компонент;
  }

  // Ряды считаем по видимым людям: поколение из одних скрытых родителей
  // пустой строкой не становится.
  const видимые = [...позиция.keys()].filter(id => !люди.get(id).hidden);
  const ряды = [...new Set(видимые.map(id => поколение.get(id)))].sort((a, b) => a - b);
  const номерРяда = new Map(ряды.map((g, i) => [g, i]));
  позиция.forEach((p, id) => {
    const ряд = номерРяда.has(p.поколение) ? номерРяда.get(p.поколение) : -1;
    p.y = ПОЛЕ + ряд * ШАГ_РЯДА;
  });

  const ширинаХолста = Math.max(W_УЗЛА + ПОЛЕ * 2, Math.ceil(Math.max(...видимые.map(id => позиция.get(id).x + W_УЗЛА)) + ПОЛЕ));
  const высотаХолста = ПОЛЕ * 2 + (ряды.length - 1) * ШАГ_РЯДА + H_УЗЛА;
  const f = (n) => n.toFixed(1);

  // --- Линии ---
  let линии = '';
  // Подписи родства — поверх линий и карточек, чтобы их ничего не закрывало.
  let метки = '';
  const пилюля = (x, y, текст) => {
    const w = Math.round(String(текст).length * 6.1 + 14);
    return `<g class="hud-fam-kin"><rect x="${f(x - w / 2)}" y="${f(y - 8)}" width="${w}" height="16" rx="8"/>`
      + `<text x="${f(x)}" y="${f(y)}" text-anchor="middle" dominant-baseline="central">${escapeHtml(текст)}</text></g>`;
  };
  const шины = new Map();
  for (const [ребёнок, s] of родители) {
    if (!позиция.has(ребёнок) || люди.get(ребёнок).hidden) continue;
    const р = [...s].filter(x => позиция.has(x)).sort();
    if (!р.length) continue;
    const ключ = р.join('|');
    if (!шины.has(ключ)) шины.set(ключ, { родители: р, дети: [] });
    шины.get(ключ).дети.push(ребёнок);
  }
  шины.forEach(({ родители: р, дети: д }) => {
    const детиЦ = д.map(id => ({ x: позиция.get(id).x + W_УЗЛА / 2, y: позиция.get(id).y }));
    const шинаY = Math.min(...детиЦ.map(c => c.y)) - (ШАГ_РЯДА - H_УЗЛА) / 2;
    const видимыеРодители = р.filter(id => !люди.get(id).hidden);
    const xs = детиЦ.map(c => c.x);
    let путь = '';
    if (видимыеРодители.length) {
      const центры = видимыеРодители.map(id => ({ x: позиция.get(id).x + W_УЗЛА / 2, y: позиция.get(id).y }));
      const пара = центры.length >= 2 && центры.every(c => Math.abs(c.y - центры[0].y) < 1)
        && Math.abs(центры[0].x - центры[1].x) <= W_УЗЛА + ЗАЗОР_СУПРУГОВ + 1;
      if (пара) {
        const ox = (центры[0].x + центры[1].x) / 2, oy = центры[0].y + H_УЗЛА / 2;
        путь += `M${f(ox)} ${f(oy)}V${f(шинаY)}`; xs.push(ox);
        центры.slice(2).forEach(c => { путь += `M${f(c.x)} ${f(c.y + H_УЗЛА)}V${f(шинаY)}`; xs.push(c.x); });
      } else {
        центры.forEach(c => { путь += `M${f(c.x)} ${f(c.y + H_УЗЛА)}V${f(шинаY)}`; xs.push(c.x); });
      }
    }
    путь += `M${f(Math.min(...xs))} ${f(шинаY)}H${f(Math.max(...xs))}`;
    детиЦ.forEach(c => { путь += `M${f(c.x)} ${f(шинаY)}V${f(c.y)}`; });
    линии += `<path class="hud-fam-link${видимыеРодители.length ? '' : ' is-siblings'}" d="${путь}"/>`;
    // На ветке к каждому ребёнку — кто кому кем: «мать → дочь». У братьев без
    // родителей — кем он приходится соседу по шине: «брат».
    д.forEach(id => {
      const p = позиция.get(id);
      let подпись = '';
      const р = видимыеРодители.find(x => словоРодства.has(пара(id, x))) || видимыеРодители.find(x => словоРодства.has(пара(x, id)));
      if (р) {
        // Кем ребёнку приходится родитель («отец») и кем ребёнок родителям
        // («сын»). Слово ребёнка ищем у любого из родителей; не записал
        // никто — выводим из пола, известного по другим связям.
        const вверхЗаписано = словоРодства.get(пара(id, р)) || '';
        const внизЗаписано = видимыеРодители.map(x => словоРодства.get(пара(x, id))).find(Boolean) || '';
        const вверх = вверхЗаписано || словоПоРоли('parent', пол.get(р), внизЗаписано);
        const вниз = внизЗаписано || словоПоРоли('child', пол.get(id), вверхЗаписано);
        подпись = `${вверх} → ${вниз}`;
      } else {
        const сосед = д.find(b => b !== id && словоРодства.has(пара(b, id)));
        if (сосед) подпись = словоРодства.get(пара(сосед, id));
      }
      if (подпись) метки += пилюля(p.x + W_УЗЛА / 2, (шинаY + p.y) / 2, подпись);
    });
  });
  блоки.forEach(б => {
    for (let i = 0; i + 1 < б.члены.length; i++) {
      const a = б.члены[i], b = б.члены[i + 1];
      if (!супруги.get(a) || !супруги.get(a).has(b)) continue;
      const бывший = супруги.get(a).get(b);
      const pa = позиция.get(a), pb = позиция.get(b);
      if (!pa || !pb) continue;
      const y = pa.y + H_УЗЛА / 2, x1 = pa.x + W_УЗЛА, x2 = pb.x;
      линии += `<path class="hud-fam-spouse${бывший ? ' is-ex' : ''}" d="M${f(x1)} ${f(y)}H${f(x2)}"/>`
        + `<text class="hud-fam-spouse-mark" x="${f((x1 + x2) / 2)}" y="${f(y - 6)}" text-anchor="middle">${бывший ? '✕' : '⚭'}</text>`;
      // Над парой — кем каждый приходится другому, слева направо: «жена ⚭ муж».
      const левыйЗаписано = словоРодства.get(пара(b, a)) || '', правыйЗаписано = словоРодства.get(пара(a, b)) || '';
      // Недостающую сторону пары достраиваем по полу: «жена ⚭ …» → «жена ⚭ муж».
      const левый = левыйЗаписано || словоПоРоли('spouse', пол.get(a), правыйЗаписано);
      const правый = правыйЗаписано || словоПоРоли('spouse', пол.get(b), левыйЗаписано);
      if (левыйЗаписано || правыйЗаписано) метки += пилюля((x1 + x2) / 2, pa.y - 12, `${левый || '…'} ${бывший ? '✕' : '⚭'} ${правый || '…'}`);
    }
  });
  кузены.forEach(([a, b]) => {
    const pa = позиция.get(a), pb = позиция.get(b);
    if (!pa || !pb) return;
    const ax = pa.x + W_УЗЛА / 2, bx = pb.x + W_УЗЛА / 2;
    линии += `<path class="hud-fam-cousin" d="M${f(ax)} ${f(pa.y)}C${f(ax)} ${f(pa.y - 34)} ${f(bx)} ${f(pb.y - 34)} ${f(bx)} ${f(pb.y)}"/>`;
  });

  // --- Люди ---
  let карточки = '';
  let номер = 0;
  const основа = String(idBase || 'fam').replace(/[^a-zA-Z0-9_-]/g, '');
  видимые.forEach(id => {
    const ч = люди.get(id), p = позиция.get(id);
    const r = 19, ax = p.x + 10 + r, ay = p.y + H_УЗЛА / 2;
    const цвет = ч.virtual ? 'rgba(255,255,255,.12)' : HUD_AVATAR_COLORS[hudHashSeed(ч.name) % HUD_AVATAR_COLORS.length];
    let адрес = '';
    if (!ч.virtual) {
      try { адрес = ч.isUser ? (getUserAvatarUrl() || '') : ((getAvatarUrl(ч.name, ч.isPrimary) || {}).url || ''); } catch (_) { адрес = ''; }
    }
    const клип = `${основа}-fam-${номер++}`;
    const имя = ч.virtual ? 'неизвестно' : (ч.name.length > 13 ? ч.name.slice(0, 12) + '…' : ч.name);
    // Под именем — кем человек приходится вам, а если не вам — кому-то в дереве.
    const родня = видимые.find(q => q !== id && словоРодства.has(пара(q, id)));
    const черезРодню = родня ? `${словоРодства.get(пара(родня, id))} · ${String(люди.get(родня).name).split(/\s+/)[0]}` : '';
    const подписьПолная = ч.isUser ? 'это вы' : (ктоИгроку.get(id) || черезРодню || (ч.isPrimary ? 'персонаж' : ''));
    const подпись = подписьПолная.length > 18 ? подписьПолная.slice(0, 17) + '…' : подписьПолная;
    const tx = ax + r + 9;
    карточки += `<g class="hud-fam-node${ч.isUser ? ' is-user' : ''}${ч.isPrimary ? ' is-primary' : ''}${ч.virtual ? ' is-unknown' : ''}" data-node-name="${escapeHtml(ч.name)}">`
      + `<title>${escapeHtml(ч.virtual ? 'Звено родства не названо' : ч.name)}</title>`
      + `<rect class="hud-fam-card" x="${f(p.x)}" y="${f(p.y)}" width="${W_УЗЛА}" height="${H_УЗЛА}" rx="14"/>`
      + `<circle class="hud-fam-ava-bg" cx="${f(ax)}" cy="${f(ay)}" r="${r}" fill="${цвет}"/>`
      + `<text class="hud-fam-initials" x="${f(ax)}" y="${f(ay)}" text-anchor="middle" dominant-baseline="central">${escapeHtml(ч.virtual ? '?' : commentInitials(ч.name))}</text>`
      + (адрес ? `<clipPath id="${клип}"><circle cx="${f(ax)}" cy="${f(ay)}" r="${r - 1}"/></clipPath>`
        + `<image href="${escapeHtml(адрес).replace(/"/g, '&quot;')}" x="${f(ax - r + 1)}" y="${f(ay - r + 1)}" width="${(r - 1) * 2}" height="${(r - 1) * 2}" clip-path="url(#${клип})" preserveAspectRatio="xMidYMid slice"/>` : '')
      + `<text class="hud-fam-name" x="${f(tx)}" y="${f(p.y + (подпись ? 25 : 33))}">${escapeHtml(имя)}</text>`
      + (подпись ? `<text class="hud-fam-role" x="${f(tx)}" y="${f(p.y + 41)}">${escapeHtml(подпись)}</text>` : '')
      + `</g>`;
  });

  const svg = `<svg class="hud-fam-svg" viewBox="0 0 ${ширинаХолста} ${высотаХолста}" width="${ширинаХолста}" height="${высотаХолста}" role="img" aria-label="Генеалогическое дерево">${линии}${карточки}${метки}</svg>`;
  const positions = {};
  позиция.forEach((p, id) => { if (!люди.get(id).hidden) positions[id] = { x: Math.round(p.x), y: Math.round(p.y) }; });
  return { svg, people: видимые.length, positions };
}
