// Генеалогическое дерево из «Отношений». Родство модель ставит в начало
// отношения («Ричард: муж, любит, но боится»); отсюда собираются родители,
// дети, супруги, братья и сёстры, а из них — дерево: от родителей ветка вниз
// к детям, супруги рядом по горизонтали.
//
// Модуль не знает про граф отношений: получает готовые узлы и рёбра и отдаёт
// SVG. Так нет круговой зависимости с relations-graph.js.

