// Пух по краю: тонкие пряди наружу, длина — по весу точек контура.
function пух(точки, длина, rnd, цвет) {
  let d = '';
  for (const p of обход(точки, .95)) {
    if (p.w <= .05) continue;
    const L = длина * p.w * (.45 + rnd() * .5), к = (rnd() - .5) * .7, ш = .75 + rnd() * .4;
    const bx = p.x - p.nx * .6, by = p.y - p.ny * .6;
    const tx = p.x + p.nx * L + p.tx * L * к, ty = p.y + p.ny * L + p.ty * L * к + L * .25;
    // прядь: широкое основание, мягко сходится к кончику
    d += `M${т([bx - p.tx * ш, by - p.ty * ш])}C${т([p.x - p.tx * ш * .6 + p.nx * L * .5, p.y - p.ty * ш * .6 + p.ny * L * .5])} ${т([tx - p.tx * .25, ty - p.ty * .25])} ${т([tx, ty])}C${т([tx + p.tx * .15, ty + p.ty * .15])} ${т([p.x + p.tx * ш * .5 + p.nx * L * .4, p.y + p.ty * ш * .5 + p.ny * L * .4])} ${т([bx + p.tx * ш, by + p.ty * ш])}Z`;
  }
  return d ? `<path d="${d}" fill="${цвет}"/>` : '';
}
// Мех штрихами: направление роста — от носа наружу, с лёгким сносом вниз.
function шерсть(точки, поток, rnd, { n = 520, длина = 1.5, тёмные = .22, светлые = .17, ширина = .3 } = {}) {
  const поли = обход(точки, 1.1);
  let x0 = 99, y0 = 99, x1 = -99, y1 = -99;
  for (const p of поли) { x0 = Math.min(x0, p.x); y0 = Math.min(y0, p.y); x1 = Math.max(x1, p.x); y1 = Math.max(y1, p.y); }
  let a = '', b = '';
  for (let i = 0; i < n; i++) {
    const x = x0 + rnd() * (x1 - x0), y = y0 + rnd() * (y1 - y0);
    if (!внутри(поли, x, y)) continue;
    let [dx, dy] = поток(x, y);
    const у = (rnd() - .5) * .5, c = Math.cos(у), s = Math.sin(у);
    [dx, dy] = [dx * c - dy * s, dx * s + dy * c];
    const L = длина * (.6 + rnd() * .7);
    const ш = `M${т([x, y])}q${ф(dx * L * .5 - dy * .25)} ${ф(dy * L * .5 + dx * .25)} ${ф(dx * L)} ${ф(dy * L)}`;
    if (i % 2) a += ш; else b += ш;
  }
  return `<path d="${a}" fill="none" stroke="#000" stroke-opacity="${тёмные}" stroke-width="${ширина}" stroke-linecap="round"/>`
    + `<path d="${b}" fill="none" stroke="#fff" stroke-opacity="${светлые}" stroke-width="${ширина * .9}" stroke-linecap="round"/>`;
}
const отЦентра = (cx, cy, вниз = .35) => (x, y) => {
  let dx = x - cx, dy = y - cy; const l = Math.hypot(dx, dy) || 1;
  dx /= l; dy = dy / l + вниз; const k = Math.hypot(dx, dy) || 1;
  return [dx / k, dy / k];
};
const вдоль = (ax, ay, bx, by) => () => { const l = Math.hypot(bx - ax, by - ay) || 1; return [(bx - ax) / l, (by - ay) / l]; };

// Глаз: миндалина с радужкой (градиент цвета глаз), зрачок по виду,
// тень века сверху, тёмный ободок и блики.
function глаз(u, x, y, { w = 3, h = 2.4, наклон = .5, зрачок = 'round', правый = false } = {}) {
  const к = правый ? 1 : -1;
  const вн = [x + к * w, y - наклон], вт = [x - к * w, y + наклон * .35];
  const верх = y - h * 1.35, низ = y + h * 1.15;
  const d = `M${т(вн)}Q${ф(x)} ${ф(верх)} ${т(вт)}Q${ф(x)} ${ф(низ)} ${т(вн)}Z`;
  const з = зрачок === 'slit' ? `<ellipse cx="${ф(x)}" cy="${ф(y)}" rx="${ф(w * .22)}" ry="${ф(h * .6)}" fill="#0b0809"/>`
    : зрачок === 'hslit' ? `<ellipse cx="${ф(x)}" cy="${ф(y)}" rx="${ф(w * .45)}" ry="${ф(h * .22)}" fill="#0b0809"/>`
    : `<circle cx="${ф(x)}" cy="${ф(y + h * .02)}" r="${ф(h * (зрачок === 'big' ? .48 : .4))}" fill="#0b0809"/>`;
  return `<path d="${d}" fill="url(#${u}${правый ? 'i2' : 'i1'})"/>${з}`
    + `<path d="M${т(вн)}Q${ф(x)} ${ф(верх)} ${т(вт)}Q${ф(x)} ${ф(y - h * .95)} ${т(вн)}Z" fill="#000" opacity=".22"/>`
    + `<path d="${d}" fill="none" stroke="#0f0b0d" stroke-width=".6" stroke-linejoin="round"/>`
    + `<ellipse cx="${ф(x - к * w * .26)}" cy="${ф(y - h * .28)}" rx="${ф(h * .3)}" ry="${ф(h * .24)}" fill="#fff" opacity=".95"/>`
    + `<circle cx="${ф(x + к * w * .3)}" cy="${ф(y + h * .3)}" r="${ф(h * .09)}" fill="#fff" opacity=".55"/>`;
}
const ГЛАЗА = (u, x1, x2, y, о) => `<g class="eyes">${глаз(u, x1, y, о)}${глаз(u, x2, y, { ...о, правый: true })}</g>`;
// Круглый глаз (сова, грызун, кролик): шар с бликом.
