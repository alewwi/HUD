// Реалистичный портрет спутника: анфас, мех штрихами по направлению роста,
// пушистый край, объём светом и тенью, глаза с радужкой и зрачком по виду.
// Окрас — те же переменные карточки, что у милых портретов (render/extras.js):
// --fur, --fur2, --eye/--eye2 (иначе --eye-d рода), поэтому ложится любой цвет.
// Свет и тень — белым и чёрным поверх, без своих цветов меха.

const ф = (n) => Math.round(n * 100) / 100;
const т = (p) => `${ф(p[0])} ${ф(p[1])}`;

function случай(текст) {
  let s = 2166136261;
  for (const ch of String(текст)) s = Math.imul(s ^ ch.codePointAt(0), 16777619) >>> 0;
  return () => ((s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 4294967296);
}

// Замкнутый сплайн через точки [x, y, флаг]: флаг 's' — острый угол (кончик уха),
// число — длина пуха на этом участке края (0 — гладко).
function сегменты(точки) {
  const n = точки.length, P = (i) => точки[(i + n) % n];
  const с = [];
  for (let i = 0; i < n; i++) {
    const p0 = P(i - 1), p1 = P(i), p2 = P(i + 1), p3 = P(i + 2);
    const c1 = p1[2] === 's' ? [p1[0], p1[1]] : [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = p2[2] === 's' ? [p2[0], p2[1]] : [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    с.push([p1, c1, c2, p2]);
  }
  return с;
}
const контур = (точки) => {
  const с = сегменты(точки);
  return 'M' + т(с[0][0]) + с.map(([, a, b, p]) => `C${т(a)} ${т(b)} ${т(p)}`).join('') + 'Z';
};
const вес = (p) => (typeof p[2] === 'number' ? p[2] : p[2] === 's' ? 0 : 1);
function обход(точки, шаг = .8) {
  const res = [];
  for (const [p0, c1, c2, p3] of сегменты(точки)) {
    const L = Math.hypot(c1[0] - p0[0], c1[1] - p0[1]) + Math.hypot(c2[0] - c1[0], c2[1] - c1[1]) + Math.hypot(p3[0] - c2[0], p3[1] - c2[1]);
    const m = Math.max(1, Math.round(L / шаг));
    for (let j = 0; j < m; j++) {
      const t = j / m, u = 1 - t;
      const x = u * u * u * p0[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t * t * t * p3[0];
      const y = u * u * u * p0[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t * t * t * p3[1];
      let tx = 3 * u * u * (c1[0] - p0[0]) + 6 * u * t * (c2[0] - c1[0]) + 3 * t * t * (p3[0] - c2[0]);
      let ty = 3 * u * u * (c1[1] - p0[1]) + 6 * u * t * (c2[1] - c1[1]) + 3 * t * t * (p3[1] - c2[1]);
      const l = Math.hypot(tx, ty) || 1; tx /= l; ty /= l;
      res.push({ x, y, tx, ty, w: вес(p0) * u + вес(p3) * t });
    }
  }
  let пл = 0;
  for (let i = 0; i < точки.length; i++) { const a = точки[i], b = точки[(i + 1) % точки.length]; пл += a[0] * b[1] - b[0] * a[1]; }
  const з = пл > 0 ? 1 : -1;
  for (const r of res) { r.nx = з * r.ty; r.ny = -з * r.tx; }
  return res;
}
function внутри(поли, x, y) {
  let в = false;
  for (let i = 0, j = поли.length - 1; i < поли.length; j = i++) {
    const a = поли[i], b = поли[j];
    if ((a.y > y) !== (b.y > y) && x < (b.x - a.x) * (y - a.y) / (b.y - a.y) + a.x) в = !в;
  }
  return в;
}
const симм = (правая) => [...правая, ...правая.slice(1, -1).reverse().map(([x, y, f]) => [48 - x, y, f])];
const зеркало = (точки) => точки.map(([x, y, f]) => [48 - x, y, f]).reverse();
const эллипс = (cx, cy, rx, ry) => `M${ф(cx - rx)} ${ф(cy)}a${ф(rx)} ${ф(ry)} 0 1 0 ${ф(rx * 2)} 0a${ф(rx)} ${ф(ry)} 0 1 0 ${ф(-rx * 2)} 0Z`;

