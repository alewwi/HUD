    const былая = снимокБеременности(кто);
    const плоды = плодыОт(кто);
    if (!плоды || плоды.число <= часть) return false;
    if (х.потери.some(п => п && п.кто === кто && п.часть && !п.отменена && (п.когда === текст || (день !== null && п.дата === день)))) return false;
    if (!вручную && х.потери.some(п => п && п.кто === кто && п.часть && п.отменена && п.когда === текст)) return false;
    if (былая) { delete былая.потери; delete былая.журнал; }
