/* ==========================================================================
   Роды. Отмечаются, когда модель пишет в Prg «brn» (или «родила» в ходе
   беременности), либо игрок жмёт «Роды состоялись». С этого хода промт
   беременности уступает место трекеру малышей и послеродовому периоду.
   ========================================================================== */
export function зарегистрироватьРоды(кто, { когда = '', дата = null, отец = '', знают = '' } = {}) {
  const х = хранилище();
  if (!х || !кто) return false;
  кто = своёИмя(х, кто);
  if (х.роды.some(р => р.кто === кто && !р.закрыто && (р.когда === когда || (дата && р.дата === дата)))) return false;
  const п = плодыОт(кто, { вСюжете: true });
  х.роды.push({ кто, когда: String(когда || '').slice(0, 80), дата, отец: String(отец || '').slice(0, 80), знают: String(знают || '').slice(0, 200),
    тип: п ? п.тип : 'one', полы: п ? п.полы : null, число: п ? п.число : 1 });
  delete х.зачатие[кто];
  delete х.судьба[кто];
  delete х.плоды[кто];
  if (х.беременности) delete х.беременности[кто];
  if (х.угрозы) delete х.угрозы[кто];
  if (х.осмотры) delete х.осмотры[кто];
  вЖурнал(х, кто, 'роды', Number.isFinite(дата) ? дата : null);
  сохранить();
  return true;
}
/* --- Даты ---------------------------------------------------------------------
   Своя разборка даты (без history-analyzer — тот тянет схему по кругу):
   «11.10.2024», «2024-10-11», «11.10» (год — из сцены). */
const ДЕНЬ_МС = 864e5;
export const дм = (ms) => { const d = new Date(ms), z = (n) => String(n).padStart(2, '0'); return `${z(d.getUTCDate())}.${z(d.getUTCMonth() + 1)}.${d.getUTCFullYear()}`; };
export function датаИзТекста(т, годСцены = null) {
  const s = String(т || '');
  let m = s.match(/(\d{4})[-./](\d{1,2})[-./](\d{1,2})/);
  if (m) return Date.UTC(+m[1], +m[2] - 1, +m[3]);
  m = s.match(/(\d{1,2})[-./](\d{1,2})[-./](\d{2,4})/);
  if (m) { const y = +m[3]; return Date.UTC(y < 100 ? 2000 + y : y, +m[2] - 1, +m[1]); }
  m = s.match(/(?:^|[^\d.])(\d{1,2})\.(\d{1,2})(?![.\d])/);
  if (m && годСцены && +m[2] >= 1 && +m[2] <= 12) return Date.UTC(годСцены, +m[2] - 1, +m[1]);
  return null;
}
// День родов: дата из записи, иначе — день, когда HUD их отметил.
export function деньРодов(р, сценаMs = null) {
  if (!р) return null;
  const год = сценаMs !== null && сценаMs !== undefined ? new Date(сценаMs).getUTCFullYear() : null;
  let д = датаИзТекста(р.когда, год);
  // «03.10» без года, а сцена уже в январе — значит, прошлый год.
  if (д !== null && сценаMs !== null && сценаMs !== undefined && д > сценаMs + ДЕНЬ_МС && !/\d{1,2}[-./]\d{1,2}[-./]\d{2,4}|\d{4}[-./]/.test(String(р.когда))) д = Date.UTC(год - 1, new Date(д).getUTCMonth(), new Date(д).getUTCDate());
  return д ?? (Number.isFinite(р.дата) ? р.дата : null);
}
