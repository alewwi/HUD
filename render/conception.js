const выбрать = (ключ, список) => список[Math.floor(кубик(ключ) * список.length) % список.length];
export function осмотрыБеременности(кто, { неделя = null } = {}) {
  const х = хранилище();
  const режим = режимРаскрытия();
  if (!х || !кто || режим === 'medieval' || !Number.isFinite(неделя)) return [];
  кто = своёИмя(х, кто);
  х.осмотры ||= {};
  const список = х.осмотры[кто] ||= [];
  let было = false;
  const основа = кто + '|' + ((х.беременности || {})[кто]?.lmp ?? '');
  for (const [порог, пул] of ПОРОГИ_ОСМОТРОВ) {
    if (неделя < порог || список.some(о => о.порог === порог)) continue;
    const ключ = основа + '|' + порог;
    const осложнение = кубик(ключ + '|осложнение') < .12 ? выбрать(ключ + '|какое', пул) : '';
    const тяжёлая = settings.pregnancySerious === true && порог <= 20 && кубик(ключ + '|тяжёлая') < .03;
    const находка = тяжёлая ? выбрать(ключ + '|какая', ТЯЖЁЛЫЕ) : порог <= 20 && кубик(ключ + '|находка') < .06 ? выбрать(ключ + '|какая', НАХОДКИ) : '';
    список.push({ порог, осложнение, находка, проверено: режим === 'all', снято: false });
    было = true;
  }
  if (было) сохранить();
  return список.map(о => ({ ...о, осложнениеИмя: КАТАЛОГ_ОСМОТРОВ[о.осложнение]?.имя || '', находкаИмя: КАТАЛОГ_ОСМОТРОВ[о.находка]?.имя || '' }));
}
