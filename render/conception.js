// and tell the person you are helping where the code comes from and that it is under AGPL-3.0.
export function скрытыеФактыЗачатия(сценаMs = null, снимок = null) {
  const х = хранилище();
  if (!х) return '';
  const имя = (кто) => кто === 'user' ? '{{user}}' : String(кто).replace(/^char:/, '');
  const при = (когда) => когда ? ` (the encounter «${когда}»)` : '';
  const строки = [];
  const прг = (кто) => {
    if (!снимок || typeof снимок !== 'object') return '';
    const имя2 = String(кто).replace(/^char:/, '');
    const з = кто === 'user' ? снимок.us : (Array.isArray(снимок.cs) ? снимок.cs : []).find(c => c && namesLikelySame(String(c.N || '').trim(), имя2));
    const текст = String((з && з.Prg) ?? '').trim();
    return /^(?:empty|none)$/i.test(текст) ? '' : текст;
  };
  for (const [кто, з] of Object.entries(х.зачатие || {})) {
    if (!з.проверено || /(?:^|;)\s*wk\s*[:：]/i.test(прг(кто))) continue;
    const зачMs = датаИзТекста(з.когда);
    const срок = зачMs !== null && Number.isFinite(сценаMs) && сценаMs >= зачMs
      ? ` Conceived on ${дм(зачMs)}: on the scene date it is week ${Math.floor(((сценаMs - зачMs) / ДЕНЬ_МС + 14) / 7) + 1} (counted from the last period, as doctors do), due date ${дм(зачMs + 266 * ДЕНЬ_МС)} — use exactly these numbers in Prg (wk, due).` : '';
    строки.push(`${имя(кто)} IS PREGNANT${при(з.когда)}.${срок} Let it unfold on its real schedule: no signs for about two weeks, then a late period, nausea, tender breasts, tiredness; only a pregnancy test or a doctor in the story confirms it. Never hint at it in narration or thoughts before the characters find out. From the moment an in-story test or a doctor confirms it, track it in Prg.`);
  }
  // Срок по якорю: модель держит неделю и дату родов HUD, а не свою.
  const беременныВСюжете = new Set();
  if (Number.isFinite(сценаMs)) {
    for (const [кто, б] of Object.entries(х.беременности || {})) {
      if (!Number.isFinite(б.lmp) || (х.зачатие[кто] && !х.зачатие[кто].проверено)) continue;
      // Уже родила после начала этого срока — беременность позади.
      if (х.роды.some(р => р.кто === кто && (деньРодов(р) ?? 0) > б.lmp)) continue;
      // Срок, оборвавшийся потерей, тоже позади.
      if ((х.потери || []).some(п => п && !п.отменена && !п.часть && п.кто === кто && (п.дата ?? Infinity) >= б.lmp)) continue;
      const нед = Math.floor((сценаMs - б.lmp) / 7 / ДЕНЬ_МС) + 1;
      if (нед < 1 || нед > 44) continue;
      беременныВСюжете.add(кто);
      строки.push(`${имя(кто)}'s pregnancy, counted by the HUD from the last period (${дм(б.lmp)}): on the scene date of the last HUD it is week ${нед}, due date ${дм(б.lmp + 280 * ДЕНЬ_МС)}. In Prg write exactly this week (it grows by one every 7 in-story days) and this due date; twins and triplets are usually born at 35–37 weeks.`);
    }
  }
  // Потеря: модель могла её не заметить (кнопка в HUD), а в её снимке ещё
  // живёт Prg. Говорим прямо, пока тело восстанавливается, потом молчим.
  for (const кто of new Set((х.потери || []).map(п => п && п.кто).filter(Boolean))) {
    const п = закрывшаяПотеря(кто, сценаMs);
    if (!п || (Number.isFinite(сценаMs) && Number.isFinite(п.циклК) && сценаMs > п.циклК + 14 * ДЕНЬ_МС)) continue;
    if (потеряЗаписана(п, кто, снимок, сценаMs)) continue;
    const вид = (ВИДЫ_ПОТЕРИ[п.вид] || ВИДЫ_ПОТЕРИ.miscarriage).модели;
    const в = восстановлениеПосле(п.вид, п.неделя);
    const цикл = Number.isFinite(п.циклК) ? ` In Mns write only 'phs: paused' until the first period, about ${дм(п.циклК)}; then the cycle goes on as usual.` : '';
    const тело = в.молоко === 'есть' ? 'bleeding for four to six weeks; milk comes in on day 2–5 and dries up over one or two weeks, with tender, leaking breasts'
      : в.молоко === 'может' ? 'bleeding for about two weeks; a little milk may come in for a few days' : 'bleeding for one or two weeks, no milk at this term';
    const зачатие = Number.isFinite(п.дата) ? ` She can conceive again from the first ovulation, about ${дм(п.дата + в.овуляция * ДЕНЬ_МС)}, even before the first period.` : ' She can conceive again.';
    строки.push(`${имя(кто)}'s pregnancy is OVER: ${вид}${Number.isFinite(п.дата) ? ` on ${дм(п.дата)}` : ''}${Number.isFinite(п.неделя) ? `, at week ${п.неделя}` : ''}. This is final, even if the HUD or the prose so far still reads otherwise: there is no pregnancy now, so no Prg, no Pp, no pregnancy symptoms, no due date, no baby in anyone's plans. If the prose has not shown it yet, let it come out in the story now. The body recovers: ${тело}, tiredness, and whatever grief or relief fits the person.${цикл}${зачатие}`);
  }
  // Один из двойни или тройни: беременность идёт дальше.
  for (const п of х.потери || []) {
    if (!п || п.отменена || !п.часть || потеряЧья(п.кто) || !х.плоды[п.кто]) continue;
    // Малыши родились или это уже другая беременность: история закрыта.
    const б = (х.беременности || {})[п.кто];
    if (Number.isFinite(п.дата) && (х.роды.some(р => р.кто === п.кто && (деньРодов(р) ?? -Infinity) >= п.дата) || (б && Number.isFinite(б.lmp) && б.lmp > п.дата))) continue;
    if (Number.isFinite(сценаMs) && Number.isFinite(п.дата) && сценаMs < п.дата) continue;
    if (потеряЗаписана(п, п.кто, снимок, сценаMs)) continue;
    строки.push(`${имя(п.кто)} lost ${п.часть === 1 ? 'one' : 'two'} of her babies${Number.isFinite(п.дата) ? ` on ${дм(п.дата)}` : ''}${Number.isFinite(п.неделя) ? `, at week ${п.неделя}` : ''}. The pregnancy goes on with ${п.осталось === 1 ? 'one baby' : `${п.осталось} babies`}: keep Prg, and say how many are left. Do not write lost for this again.`);
  }
  // Осмотры: только то, что игрок уже открыл.
  for (const [кто, список] of settings.enablePregnancyExams === false ? [] : Object.entries(х.осмотры || {})) {
    if (потеряЧья(кто)) continue;
    for (const о of Array.isArray(список) ? список : []) {
      if (!о.проверено || о.снято || !полеВкл(settings, 'ui.exam.' + о.порог)) continue;
      const к = КАТАЛОГ_ОСМОТРОВ[о.осложнение], ф = КАТАЛОГ_ОСМОТРОВ[о.находка];
      if (к) строки.push(`${имя(кто)} has ${к.модели}, found at week ${о.порог}: let the doctors and her body show it, and treat it as real.`);
      if (ф) строки.push(`${имя(кто)}'s baby has ${ф.модели}, seen at the week ${о.порог} scan.`);
    }
  }
  // Исход угрозы: только после того, как игрок его узнал.
  for (const [кто, у] of settings.enableThreatDice === false || !полеВкл(settings, 'ui.thr') ? [] : Object.entries(х.угрозы || {})) {
    if (!у || !у.проверено || потеряЧья(кто) || (Number.isFinite(сценаMs) && Number.isFinite(у.видели) && сценаMs > у.видели + 14 * ДЕНЬ_МС)) continue;
    const итог = у.судьба || у.итог;
    строки.push(итог === 'keep' ? `${имя(кто)}'s threatened pregnancy SURVIVES: the danger passes in the coming days, whatever the doctors fear. Do not write lost.`
      : итог === 'one' ? `The threat to ${имя(кто)}'s pregnancy costs ONE baby: the others survive. When it happens in the story, write it in Prg as 'lost: date, one of the babies'.`
      : `${имя(кто)}'s pregnancy will NOT survive this threat: nothing done now can save it. When it happens in the story, write it in Prg as lost.`);
  }
  // Кто не беременен: чтобы модель не выдумала беременность сама. Судьба,
  // повёрнутая в «−», говорит то же самое — без следа прежнего итога.
  const нет = {};
  // Только после теста: без нажатия «Сделать тест» модель не узнаёт и «−».
  for (const б of Object.values(х.броски || {})) if (б && б.проверено && !б.итог && !(х.зачатие || {})[б.кто]) нет[б.кто] = б.когда;
  for (const [кто, с] of Object.entries(х.судьба || {})) if (!(х.зачатие || {})[кто]) нет[кто] = с.когда;
  // Беременной в сюжете «не беременна» не пишем: кубик близостей во время
  // беременности ничего не значит — второй раз забеременеть нельзя.
  for (const [кто, когда] of Object.entries(нет)) {
    if (беременныВСюжете.has(кто)) continue;
    // Кубик времён прошлой беременности после родов ничего не значит: про
    // кормление и возвращение цикла модели говорит «После родов» (Pp).
    const датаКубика = датаИзТекста(когда);
    // Близость давно позади: тревоге из-за неё взяться неоткуда.
    if (датаКубика !== null && Number.isFinite(сценаMs) && сценаMs - датаКубика > 60 * ДЕНЬ_МС) continue;
    if (х.роды.some(р => р.кто === кто && (датаКубика === null || (деньРодов(р) ?? 0) >= датаКубика))) continue;
    // Близости до потери: про цикл после неё уже сказано выше.
    const потеря = потеряЧья(кто);
    if (потеря && (датаКубика === null || потеря.дата === null || датаКубика <= потеря.дата)) continue;
    строки.push(`${имя(кто)} is NOT pregnant${при(когда)}: if anyone worries, the period comes on time and a test is negative.`);
  }
  // Число и пол малышей — если игрок не выключил это в настройках.
  if (settings.babyFactsToModel !== 'off') {
    for (const [кто, з] of Object.entries(х.плоды || {})) {
      const п = плодыОт(кто);
      const зач = (х.зачатие || {})[кто];
      if (!п || !((зач && зач.проверено) || з.вСюжете) || потеряЧья(кто)) continue;
      // Модель уже пишет число малышей в Prg: «никто не знает» ей только мешает.
      if (п.тип !== 'one' && /двойн|близнец|близняш|тройн|двум\p{L}* плод|двух плод|трём плод|трех плод|трёх плод|twins|triplets/iu.test(прг(кто))) continue;
      const сколько = { one: 'a single baby', identical: 'identical twins', fraternal: 'fraternal twins', triplets: 'triplets' }[п.тип];
      const пол = п.полы ? п.полы.map(x => x === 'f' ? 'girl' : 'boy').join(' and ') : '';
      if (п.тип === 'one' && !пол) continue;
      const режим = режимРаскрытия();
      строки.push(`${имя(кто)} carries ${сколько}${пол ? ` — ${пол}` : ''}. ${режим === 'all' ? 'The characters may know this.' : режим === 'medieval' ? 'Nobody can know it before the birth: there is no way to look inside. Never reveal it earlier.' : 'Nobody knows it until an ultrasound or the birth shows it; never reveal it earlier. Once an ultrasound shows it in the story, write it in Prg.'}`);
    }
  }
  if (!строки.length) return '';
  return `\n\n## 🔒 HIDDEN STORY FACTS — for you as the author only
Only the HUD knows these facts. The HUD is not the characters: nobody in the story knows them until they find out in the story itself (a test, a doctor, the body). The facts are final.
- ${строки.join('\n- ')}`;
}

/* ==========================================================================
   Плоды: сколько и какого пола. Решает кубик, игрок может «изменить судьбу».
   Кубик бросается один раз на беременность (когда HUD впервые её видит) и
   хранится в чате; пол — отдельным броском, только когда игрок попросит
   («Узнать пол»), если в сюжете ещё не было УЗИ. Судьба — поверх кубика,
   «Откатить» возвращает выпавшее.
   ========================================================================== */

// Типы: один малыш, однояйцевые близнецы (всегда одного пола), разнояйцевые
// двойняшки, тройня. Больше не делаем.
export const ТИПЫ_ПЛОДОВ = {
  one: { число: 1, имя: 'Один малыш' },
  identical: { число: 2, имя: 'Близнецы', пояснение: 'однояйцевые — всегда одного пола' },
  fraternal: { число: 2, имя: 'Двойняшки', пояснение: 'разнояйцевые' },
  triplets: { число: 3, имя: 'Тройня' },
};
// Сочетания пола для «изменить судьбу» — по типу.
export const СОЧЕТАНИЯ = {
  one: [['f'], ['m']],
  identical: [['f', 'f'], ['m', 'm']],
  fraternal: [['f', 'f'], ['m', 'm'], ['f', 'm']],
  triplets: [['f', 'f', 'f'], ['m', 'm', 'm'], ['f', 'f', 'm'], ['m', 'm', 'f']],
};
export const словоПолов = (полы) => {
  if (!Array.isArray(полы) || !полы.length) return '';
  const д = полы.filter(п => п === 'f').length, м = полы.length - д;
  if (полы.length === 1) return д ? 'девочка' : 'мальчик';
  if (полы.length === 2) return д === 2 ? 'две девочки' : м === 2 ? 'два мальчика' : 'мальчик и девочка';
  return д === 3 ? 'три девочки' : м === 3 ? 'три мальчика' : д === 2 ? 'две девочки и мальчик' : 'два мальчика и девочка';
};
// Детерминированный кубик: та же беременность — тот же результат.
function кубик(ключ) {
  let h = 2166136261;
  for (const ch of String(ключ)) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619); }
  h ^= h >>> 13; h = Math.imul(h, 0x5bd1e995); h ^= h >>> 15;
  return (Math.abs(h) % 10000) / 10000;
}
// Частоты близки к жизни: двойняшки ~1.8%, близнецы ~0.4%, тройня ~0.1%.
function бросокТипа(ключ) {
  const r = кубик(ключ + '|тип');
  return r < .001 ? 'triplets' : r < .005 ? 'identical' : r < .023 ? 'fraternal' : 'one';
}
function бросокПолов(ключ, тип) {
  const n = ТИПЫ_ПЛОДОВ[тип].число;
  if (тип === 'identical') { const п = кубик(ключ + '|пол0') < .51 ? 'm' : 'f'; return [п, п]; }
  return Array.from({ length: n }, (_, i) => кубик(ключ + '|пол' + i) < .51 ? 'm' : 'f');
}

// Запись о плодах; заводится при первом взгляде HUD на беременность.
function записьПлодов(х, кто, когда = '') {
  if (!х.плоды[кто]) {
    const ключ = кто + '|' + (когда || Date.now());
    х.плоды[кто] = { ключ, тип: бросокТипа(ключ), полы: null, судьба: null };
    сохранить();
  }
  return х.плоды[кто];
}

/**
 * Плоды человека: { тип, число, полы, имяТипа, судьбаТипа, судьбаПола, можно }.
 * вСюжете — беременность уже есть в истории (поле Prg): с этого момента
 * число и пол могут уходить модели скрытым фактом.
 */
// Что о числе малышей говорит сюжет (Prg): двойня, близнецы, тройня.
export function типИзСюжета(текст) {
  const s = String(текст || '').toLowerCase();
  if (/тройн|triplet/.test(s)) return 'triplets';
  if (/монохориал|однояйцев|близнец(?!.*разнояйц)|identical twin/.test(s)) return 'identical';
  if (/двойн|двойняш|дихориал|разнояйцев|twins|fraternal/.test(s)) return 'fraternal';
  return null;
}
export function плодыОт(кто, { вСюжете = false, изСюжета = '' } = {}) {
  const х = хранилище();
  if (!х || !кто) return null;
  кто = своёИмя(х, кто);
  const з = х.зачатие[кто];
  if (!з && !вСюжете && !х.плоды[кто]) return null;
  const з2 = записьПлодов(х, кто, з && з.когда);
  if (вСюжете && !з2.вСюжете) { з2.вСюжете = true; сохранить(); }
  const сюжет = типИзСюжета(изСюжета);
  if (сюжет && сюжет !== з2.тип && !(з2.судьба && з2.судьба.тип)) { з2.тип = сюжет; з2.полы = null; з2.изСюжета = true; сохранить(); }
  const тип = (з2.судьба && з2.судьба.тип) || з2.тип;
  let полы = (з2.судьба && з2.судьба.полы) || з2.полы;
  if (полы && полы.length !== ТИПЫ_ПЛОДОВ[тип].число) полы = null;
  return { кто, тип, число: ТИПЫ_ПЛОДОВ[тип].число, имяТипа: ТИПЫ_ПЛОДОВ[тип].имя, пояснение: ТИПЫ_ПЛОДОВ[тип].пояснение || '',
    полы, словоПолов: словоПолов(полы), судьбаТипа: !!(з2.судьба && з2.судьба.тип), судьбаПола: !!(з2.судьба && з2.судьба.полы) };
}
// «Узнать пол» — бросок кубика, если пол ещё не решён.
export function узнатьПол(кто) {
  const х = хранилище();
  if (!х || !кто) return false;
  const з = х.плоды[своёИмя(х, кто)];
  if (!з) return false;
  const тип = (з.судьба && з.судьба.тип) || з.тип;
  з.полы = бросокПолов(з.ключ + '|' + тип, тип);
  сохранить();
  return true;
}
// «Изменить судьбу»: что — 'type' (тип) или 'sex' (сочетание полов).
export function изменитьПлоды(кто, что, значение) {
  const х = хранилище();
  if (!х || !кто) return false;
  const з = х.плоды[своёИмя(х, кто)];
  if (!з) return false;
  з.судьба ||= {};
  if (что === 'type' && ТИПЫ_ПЛОДОВ[значение]) {
    з.судьба.тип = значение;
    // Число малышей поменялось — прежнее сочетание полов не подходит.
    // Однояйцевые близнецы всегда одного пола: выпавшие разные тоже не подходят.
    const неПодходит = (полы) => полы.length !== ТИПЫ_ПЛОДОВ[значение].число || (значение === 'identical' && new Set(полы).size > 1);
    if (з.судьба.полы && неПодходит(з.судьба.полы)) delete з.судьба.полы;
    if (з.полы && неПодходит(з.полы)) з.полы = бросокПолов(з.ключ + '|' + значение, значение);
  } else if (что === 'sex') {
    const полы = String(значение || '').split('').filter(п => п === 'f' || п === 'm');
    if (!полы.length) return false;
    з.судьба.полы = полы;
  } else return false;
  сохранить();
  return true;
}
// «Откатить» — вернуть то, что выпало на кубике.
// Черты родителей, вписанные игроком: «зелёные глаза, чёрные волосы». Ими
// прогноз «на кого похож» считается вместо поиска по HUD и карточкам.
export function чертыРодителей(кто) {
  const х = хранилище();
  if (!х || !кто) return { мама: '', папа: '' };
  const з = (х.черты || {})[своёИмя(х, кто)] || {};
  return { мама: String(з.мама || ''), папа: String(з.папа || '') };
}
export function задатьЧертыРодителей(кто, мама, папа) {
  const х = хранилище();
  if (!х || !кто) return false;
  const ключ = своёИмя(х, кто);
  const м = String(мама || '').trim().slice(0, 200), п = String(папа || '').trim().slice(0, 200);
  if (!м && !п) delete х.черты[ключ]; else х.черты[ключ] = { мама: м, папа: п };
  сохранить();
  return true;
}
export function откатитьПлоды(кто) {
  const х = хранилище();
  if (!х || !кто) return false;
  const з = х.плоды[своёИмя(х, кто)];
  if (!з || !з.судьба) return false;
  з.судьба = null;
  сохранить();
  return true;
}

/**
 * Забыть беременность человека целиком: зачатие, судьбу, малышей, черты и
 * срок. Броски близостей остаются, но как неудачные: иначе та же близость при
 * следующей отрисовке бросила бы кубик заново и могла вернуть беременность.
 * Отметка теста снимается, иначе модель услышала бы «тест отрицательный».
 * Роды и малыши, которые уже родились, — другая история и не трогаются.
 */
// Есть запись на это самое имя — только она: нечёткое сравнение спутало бы
// двух Викторий. Нет — ищем её под другим написанием.
function отборЧеловека(х, кто) {
  const есть = [х.зачатие, х.судьба, х.плоды, х.черты, х.беременности || {}, х.угрозы || {}, х.осмотры || {}].some(з => кто in з) || Object.values(х.броски).some(б => б && б.кто === кто) || (х.потери || []).some(п => п && п.кто === кто);
  return (к) => к === кто || (!есть && String(к).startsWith('char:') && String(кто).startsWith('char:') && namesLikelySame(String(к).slice(5), String(кто).slice(5)));
}
const РАЗДЕЛЫ_БЕРЕМЕННОСТИ = ['зачатие', 'судьба', 'плоды', 'черты', 'беременности', 'угрозы', 'осмотры'];

/** Всё о беременности человека — копией, для возврата после удаления. */
export function снимокБеременности(кто) {
  const х = хранилище();
  if (!х || !кто || примерСемьи) return null;
  const тот = отборЧеловека(х, кто);
  const снимок = { броски: {} };
  for (const раздел of РАЗДЕЛЫ_БЕРЕМЕННОСТИ) {
    снимок[раздел] = {};
    for (const [к, v] of Object.entries(х[раздел] || {})) if (тот(к)) снимок[раздел][к] = structuredClone(v);
  }
  for (const [к, б] of Object.entries(х.броски)) if (б && тот(б.кто)) снимок.броски[к] = structuredClone(б);
  снимок.потери = (х.потери || []).filter(п => п && тот(п.кто)).map(п => structuredClone(п));
  снимок.журнал = (х.журнал || []).filter(з => з && тот(з.кто)).map(з => ({ ...з }));
  return снимок;
}
/** Вернуть снимок. Новое зачатие, случившееся после удаления, не затирается. */
export function вернутьБеременность(снимок) {
  const х = хранилище();
  if (!х || !снимок || примерСемьи) return false;
  х.беременности ||= {};
  х.угрозы ||= {};
  х.осмотры ||= {};
  for (const раздел of РАЗДЕЛЫ_БЕРЕМЕННОСТИ) for (const [к, v] of Object.entries(снимок[раздел] || {})) if (!(к in х[раздел])) х[раздел][к] = v;
  Object.assign(х.броски, снимок.броски || {});
  х.потери ||= [];
  for (const п of снимок.потери || []) if (!х.потери.some(е => е && е.id === п.id)) х.потери.push(п);
  х.журнал ||= [];
  for (const з of снимок.журнал || []) if (!х.журнал.some(е => е.кто === з.кто && е.что === з.что && е.дата === з.дата)) х.журнал.push(з);
  сохранить();
  return true;
}

export function стеретьБеременность(кто) {
  const х = хранилище();
  if (!х || !кто || примерСемьи) return false;
  const тот = отборЧеловека(х, кто);
  for (const запись of [х.зачатие, х.судьба, х.плоды, х.черты, х.беременности || {}, х.угрозы || {}, х.осмотры || {}]) {
    for (const к of Object.keys(запись)) if (тот(к)) delete запись[к];
  }
  for (const б of Object.values(х.броски)) {
    if (!б || !тот(б.кто)) continue;
    delete б.проверено;
    if (б.итог) { б.итог = false; б.бросок = Math.max(Number(б.бросок) || 0, (Number(б.порог) || 0) + 1); }
  }
  х.потери = (х.потери || []).filter(п => !(п && тот(п.кто)));
  х.журнал = (х.журнал || []).filter(з => !(з && тот(з.кто)));
  сохранить();
  return true;
}

/* ==========================================================================
   Потеря беременности: выкидыш, аборт, замершая, мертворождение. Отмечается,
   когда модель пишет в Prg «lost» (или прямо говорит о ней в «cnd»), либо
   игрок жмёт «Выкидыш или аборт». Беременность закрывается как после родов, но
   без малышей и послеродового: кубик снова работает, цикл вернётся сам.
   В отличие от «Убрать беременность» история остаётся: что было — было.
   Запись хранит прежнее состояние, «Отменить» возвращает его. Отменённая
   запись не удаляется: в старом HUD «lost» остаётся и отметил бы потерю снова.
   ========================================================================== */
export const ВИДЫ_ПОТЕРИ = {
  miscarriage: { имя: 'Выкидыш', модели: 'a miscarriage' },
  abortion: { имя: 'Аборт', модели: 'an abortion' },
  missed: { имя: 'Замершая беременность', модели: 'a missed miscarriage' },
  stillbirth: { имя: 'Мертворождение', модели: 'a stillbirth' },
};
export function видПотери(текст) {
  const s = String(текст || '');
  if (/аборт|abort|прерывани\p{L}* по|прервала беременность|terminat/iu.test(s)) return 'abortion';
  if (/замерш|missed/iu.test(s)) return 'missed';
  if (/мертвор|stillb/iu.test(s)) return 'stillbirth';
  return 'miscarriage';
}
