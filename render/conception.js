// Есть ли беременность, о которой HUD знает (для решения про промт).
export function естьЗачатия() {
  const х = хранилище();
  return !!х && Object.keys(х.зачатие || {}).length > 0;
}

// Близости без зачатия у человека (тексты «когда») — для «пытаются N месяцев».
export function близостиБезЗачатия(кто) {
  const х = хранилище();
  if (!х || !кто) return [];
  кто = своёИмя(х, кто);
  if (х.зачатие[кто]) return [];
  return Object.values(х.броски || {}).filter(б => б && б.кто === кто && !б.итог).map(б => б.когда);
}
