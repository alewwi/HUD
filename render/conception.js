const ПОТЕРЯ_В_ХОДЕ = /(?<![\p{L}])(?:случил\p{L}* (?:\p{L}+ )?выкидыш|произош[её]л (?:\p{L}+ )?выкидыш|потеряла (?:ребёнка|ребенка|беременность|плод|малыша|одн\p{L}* из)|беременность прервал\p{L}*|сделала аборт|прервала беременность|miscarried|had a miscarriage|lost the (?:baby|pregnancy)|lost one of|had an abortion|terminated the pregnancy)/iu;
const НЕ_ПОТЕРЯ = /(?<![\p{L}])(?:угроз\p{L}*|риск\p{L}*|не потеряла|не сделала|чуть не|едва не|может|вероятн\p{L}*|возможн\p{L}*|подозрен\p{L}*|боится|если|прошл\p{L}*|раньше|ранее|до этого|в анамнезе|дума\p{L}*|хочет|планиру\p{L}*|запис\p{L}*|отказал\p{L}*|решает|threat\p{L}*|risk|might|may|possibl\p{L}*|suspect\p{L}*|almost|nearly|not lost|previous\p{L}*|earlier|before|past|ago|wants?|consider\p{L}*|plans?|scheduled)/iu;
// Сколько малышей потеряно, если не все: «одного из двойни», «двоих из тройни».
export const частьПотери = (текст) => /(?<![\p{L}])(?:двух из|двоих из|two of)/iu.test(String(текст || '')) ? 2 : /(?<![\p{L}])(?:одн\p{L}* из|one of)/iu.test(String(текст || '')) ? 1 : 0;

// Восстановление зависит от срока: на ранних о молоке речи нет, цикл и
// овуляция возвращаются быстро; после 22-й недели тело проходит почти то же,
// что после родов, а с 16-й молоко уже может прийти. Дни — от дня потери.
export function восстановлениеПосле(вид, неделя = null) {
  const н = Number.isFinite(неделя) ? неделя : 0;
  const поздно = н >= 22 || вид === 'stillbirth', средне = н >= 13;
  return { цикл: поздно ? 56 : средне ? 42 : 35, овуляция: поздно ? 28 : средне ? 21 : 14, кровь: поздно ? 35 : средне ? 14 : 10,
    близость: поздно ? 42 : средне ? 21 : 14, // только напоминание игроку (render/rest-hint.js), модели не идёт
    молоко: поздно ? 'есть' : н >= 16 ? 'может' : '' };
}
const ОСЛОЖНЕНИЕ = /выскабл|кюретаж|операц|хирург|травм|ранени|пулев|разрыв|инфекц|сепсис|curettage|d&c|surgery|surgical|trauma|gunshot|wound|rupture|infection|sepsis/iu;
// Что говорит о потере в здоровье, пока идёт кровь.
const СЛОВА_ПОТЕРИ = /выкидыш|аборт|прерыван|потер\p{L}* (?:беремен|реб[её]н|малыш|плод)|кровотеч|кровянист|выскабл|кюретаж|miscarr|abortion|bleeding|pregnancy loss|curettage/iu;
/**
 * Напоминать ли модели о потере. Заметка нужна, только пока HUD её не держит:
 * модель ещё пишет живую беременность, забыла кровотечение, пока оно идёт, или
 * вернула цикл раньше срока. Отмена и новая беременность сюда не доходят:
 * их отсекает закрывшаяПотеря. Без снимка напоминаем, человека вне сцены — нет.
 */
export function потеряЗаписана(п, кто, снимок, сценаMs = null) {
  if (!снимок || typeof снимок !== 'object') return false;
  const имя = String(кто).replace(/^char:/, '');
  const з = кто === 'user' ? снимок.us : (Array.isArray(снимок.cs) ? снимок.cs : []).find(c => c && namesLikelySame(String(c.N || '').trim(), имя));
  if (!з || typeof з !== 'object') return true;
  const prg = String(з.Prg ?? '').trim();
  if (МЕТКА_ПОТЕРИ.test(prg)) return true;
  const вЗдоровье = СЛОВА_ПОТЕРИ.test([з.Ill, з.H, з.Ph].map(v => String(v ?? '')).join(' '));
  // Один из двойни: беременность идёт дальше, Prg остаётся и сама ничего не значит.
  if (п.часть) {
    if (вЗдоровье || СЛОВА_ПОТЕРИ.test(prg) || частьПотери(prg)) return true;
    if (!Number.isFinite(сценаMs) || !Number.isFinite(п.дата)) return true;
    if ((сценаMs - п.дата) / ДЕНЬ_МС < восстановлениеПосле(п.вид, п.неделя).кровь) return false;
    return !(п.осталось === 1 && /двойн|близнец|близняш|тройн|twins|triplets/i.test(prg));
  }
  if (prg && !/^(?:empty|none)$/i.test(prg)) return /(?:^|;)\s*brn\s*:\s*(?!empty|none)/i.test(prg);
  if (!Number.isFinite(сценаMs) || !Number.isFinite(п.дата)) return true;
  const цикл = String(з.Mns ?? '').trim();
  if (цикл && !/paus|пауз/i.test(цикл) && Number.isFinite(п.циклК) && сценаMs < п.циклК) return false;
  const дней = (сценаMs - п.дата) / ДЕНЬ_МС;
  return дней >= восстановлениеПосле(п.вид, п.неделя).кровь || вЗдоровье;
}

/**
 * Шанс зачатия после потери или аборта. Овуляция приходит раньше первых
 * месячных, поэтому зачать можно уже до них: сама потеря шанс надолго не
 * снижает. До первой овуляции шанса нет, до первых месячных цикл ещё неровный.
 * Дольше след остаётся только после осложнений: операция, травма, инфекция.
 */
export function послеПотери(кто, сценаMs = null) {
  const п = потеряЧья(кто);
  if (!п || !Number.isFinite(п.дата) || !Number.isFinite(сценаMs) || сценаMs < п.дата) return null;
  const дней = (сценаMs - п.дата) / ДЕНЬ_МС, в = восстановлениеПосле(п.вид, п.неделя);
  const после = п.вид === 'abortion' ? 'после аборта' : 'после потери';
  if (дней < в.овуляция) return { плодовитость: .02, причина: `${после} овуляции ещё не было` };
  if (дней < в.цикл) return { плодовитость: .7, причина: `${после} цикл ещё неровный` };
  if (п.осложнение && дней < в.цикл + 90) return { плодовитость: .75, причина: `${после} с осложнением: матка ещё восстанавливается` };
  return null;
}
export const словаПотери = (ход) => ПОТЕРЯ_В_ХОДЕ.test(String(ход || '')) && !НЕ_ПОТЕРЯ.test(String(ход || ''));
// Есть ли отметка потери в последних ответах модели.
const МЕТКА_ПОТЕРИ = /(?:^|[;"\s])lost\s*:\s*(?!empty|none)/i;
const отметкаВХвосте = (чат) => (Array.isArray(чат) ? чат.slice(-4) : []).some(м => м && !м.is_user && typeof м.mes === 'string' && (МЕТКА_ПОТЕРИ.test(м.mes) || ПОТЕРЯ_В_ХОДЕ.test(м.mes)));
