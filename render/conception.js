const КЛЮЧ = 'tavernosHudConception';

function контекстST() {
  try { return window.SillyTavern?.getContext?.() || null; } catch (_) { return null; }
}
// Пример в «Кастомизации» (в чате ещё нет HUD): пока открыт просмотр,
// роды и беременность берутся из набора примера, а не из метаданных чата —
// и ничего в чат не сохраняется.
let примерСемьи = null;
export function задатьПримерСемьи(набор) { примерСемьи = набор || null; }
function хранилище() {
  if (примерСемьи) return примерСемьи;
  const ctx = контекстST();
  const мета = ctx && (ctx.chatMetadata || ctx.chat_metadata);
  if (!мета) return null;
  if (!мета[КЛЮЧ] || typeof мета[КЛЮЧ] !== 'object') мета[КЛЮЧ] = { броски: {}, зачатие: {}, судьба: {}, плоды: {}, роды: [] };
  мета[КЛЮЧ].броски ||= {};
  мета[КЛЮЧ].зачатие ||= {};
  мета[КЛЮЧ].судьба ||= {};
  мета[КЛЮЧ].плоды ||= {};
  мета[КЛЮЧ].малыши ||= {};
  мета[КЛЮЧ].черты ||= {};
  if (!Array.isArray(мета[КЛЮЧ].роды)) мета[КЛЮЧ].роды = [];
  if (!Array.isArray(мета[КЛЮЧ].потери)) мета[КЛЮЧ].потери = [];
  мета[КЛЮЧ].угрозы ||= {};
  мета[КЛЮЧ].осмотры ||= {};
  if (!Array.isArray(мета[КЛЮЧ].журнал)) мета[КЛЮЧ].журнал = [];
  закрытьРождённых(мета[КЛЮЧ]);
  return мета[КЛЮЧ];
}

// Роды закрывают беременность: зачатие до родов — уже прошлое. Без этого
// после родов тест годами показывал «+» той, давней беременности, кубик
// новых близостей пропадал (дважды не забеременеть), модель слышала
// «беременна» с датой старой близости, а «Изменить судьбу» и «Откатить»
// крутили ту же старую запись.
function закрытьРождённых(х) {
  if (!х.роды.length) return;
  const доРодов = (кто, когда) => {
    const д = датаИзТекста(когда);
    return д !== null && х.роды.some(р => р.кто === кто && (деньРодов(р) ?? -Infinity) > д);
  };
  let было = false;
  for (const [кто, з] of Object.entries(х.зачатие)) if (з && доРодов(кто, з.когда)) { delete х.зачатие[кто]; было = true; }
  for (const [кто, с] of Object.entries(х.судьба)) if (с && с.было && доРодов(кто, с.было.когда)) { delete х.судьба[кто]; было = true; }
  if (было) сохранить();
}
function сохранить() {
  if (примерСемьи) return;
  const ctx = контекстST();
  try { (ctx?.saveMetadataDebounced || ctx?.saveMetadata)?.call(ctx); } catch (_) {}
}

// Ключ близости: время из поля «Последний секс» и первое слово партнёра.
// Времени нет — весь текст без пробелов и знаков.
export function ключБлизости(секс) {
  const s = String(секс || '');
  const время = (s.match(/\b(\d{1,2}):(\d{2})\b/) || [])[0];
  const партнёр = ((s.match(/(?:^|[;|])\s*pr\s*:\s*([^;|]+)/i) || [])[1] || '').trim().split(/\s+/)[0] || '';
  return время ? (время + '|' + партнёр.toLowerCase()) : s.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '').slice(0, 60);
}

// Одна близость — один бросок. Модель из хода в ход переписывает время той
// же сцены («21:45», «21:48», «21:50»…), и каждая новая минута была новым
// броском — лишним шансом: за одну ночь их набиралось десять. Теперь
// близость с тем же партнёром не дальше трёх часов от уже брошенной (а без
// времени — в тот же день) берёт её бросок, и сцена продлевается.
const ОКНО_АКТА = 3 * 3600e3;
function приметыАкта(текст) {
  const s = String(текст || '');
  const dt = (s.match(/(?:^|[;|])\s*dt\s*:\s*([^;|]+)/i) || [])[1] || s;
  const день = датаИзТекста(dt);
  if (день === null) return null;
  const вр = dt.match(/(?<!\d)(\d{1,2}):(\d{2})(?!\d)/);
  const партнёр = ((s.match(/(?:^|[;|])\s*pr\s*:\s*([^;|]+)/i) || [])[1] || '').trim().split(/[\s,]+/)[0] || '';
  return { день, t: вр ? день + (+вр[1] * 60 + +вр[2]) * 60e3 : null, партнёр };
}
function тотЖеАкт(х, кто, секс) {
  const н = приметыАкта(секс);
  if (!н) return null;
  for (const [к, б] of Object.entries(х.броски)) {
    if (!б || б.кто !== кто) continue;
    const п = приметыАкта(б.когда);
    if (!п || !(п.партнёр === н.партнёр || namesLikelySame(п.партнёр, н.партнёр))) continue;
    let тот;
    if (н.t === null || п.t === null) тот = п.день === н.день;
    else {
      const от = п.t, до = Number.isFinite(б.до) ? Math.max(б.до, п.t) : п.t;
      тот = н.t >= от - ОКНО_АКТА && н.t <= до + ОКНО_АКТА;
      if (тот && н.t > до) { б.до = н.t; сохранить(); }
    }
    if (тот) return к;
  }
  return null;
}

// Имя персонажа модель пишет по-разному («Seraphina», «Серафина»): ищем уже
// заведённую запись по нечёткому совпадению, чтобы не завести вторую.
function своёИмя(х, кто) {
  if (!х || кто === 'user' || !String(кто).startsWith('char:')) return кто;
  const имя = String(кто).slice(5);
  const все = new Set([...Object.keys(х.зачатие || {}), ...Object.keys(х.плоды || {}), ...Object.values(х.броски || {}).map(б => б && б.кто), ...(х.потери || []).map(п => п && п.кто)].filter(Boolean));
  for (const к of все) if (String(к).startsWith('char:') && namesLikelySame(String(к).slice(5), имя)) return к;
  return кто;
}

/**
 * Итог близости для человека.
 * кто — стабильный идентификатор («char:Серафина», «user»); риск — результат
 * рискЗачатия() (render/intimacy.js) для этой близости; секс — текст поля.
 * Возвращает { беременна, когда, этаБлизость, … } — беременность «липкая»:
 * если зачатие уже было, новые близости её не отменяют.
 */
export function исходЗачатия(кто, риск, секс) {
  const х = хранилище();
  кто = своёИмя(х, кто);
  const был = String(секс || '').trim() && !/^(empty|none|нет|не было)$/i.test(String(секс).trim());
  let этаБлизость = null, к = '';
  if (был && риск && риск.бросок) {
    к = кто + '|' + ключБлизости(секс);
    if (х) {
      // Та же сцена, записанная другим временем, — тот же бросок.
      if (!х.броски[к]) к = тотЖеАкт(х, кто, секс) || к;
      if (!х.броски[к]) {
        const порог = Math.max(1, Math.round(риск.шанс * 100));
        х.броски[к] = { бросок: риск.бросок, порог, итог: риск.бросок <= порог, когда: String(секс).slice(0, 160), кто };
        if (х.броски[к].итог && !х.зачатие[кто]) {
          х.зачатие[кто] = { когда: х.броски[к].когда };
          // Новое зачатие после «судьбы» — уже другая история: откатывать некуда.
          delete х.судьба[кто];
        }
        // «Судьба» меняет итог одной близости. Пришла следующая — тест
        // показывает уже её, а не прежнюю пометку «Судьба изменена».
        if (х.судьба[кто] && х.судьба[кто].ключ !== к) delete х.судьба[кто];
        сохранить();
      }
      этаБлизость = х.броски[к];
    } else {
      // Нет метаданных (стенд, старая Таверна) — считаем на лету.
      const порог = Math.max(1, Math.round(риск.шанс * 100));
      этаБлизость = { бросок: риск.бросок, порог, итог: риск.бросок <= порог, когда: String(секс).slice(0, 160), кто };
    }
  }
  const зачатие = х ? х.зачатие[кто] : (этаБлизость && этаБлизость.итог ? { когда: этаБлизость.когда } : null);
  // Судьба не оживляет близость, которая была до потери: тот срок закрыт.
  const потеря = х && !зачатие ? потеряЧья(кто) : null;
  const датаАкта = этаБлизость ? датаИзТекста(этаБлизость.когда) : null;
  const доПотери = !!потеря && (датаАкта === null || потеря.дата === null || датаАкта <= потеря.дата);
  return { беременна: !!зачатие, когда: зачатие ? зачатие.когда : '', этаБлизость,
    кто, ключ: к, проверено: !!(зачатие && зачатие.проверено), судьба: !!(х && х.судьба[кто]), можноСудьбу: !!х && !доПотери };
}

/**
 * Что HUD знает о человеке сейчас — для плашки-напоминания игроку.
 * { беременна, проверено, когда } или null, если метаданных нет.
 */
export function состояниеЗачатия(кто) {
  const х = хранилище();
  if (!х) return null;
  const з = х.зачатие[своёИмя(х, кто)];
  return { беременна: !!з, проверено: !!(з && з.проверено), когда: з ? з.когда : '' };
}

/**
 * Игрок раскрыл тест. Только после этого беременность уходит модели:
 * без нажатия на кнопку известие в промпт не попадает.
 * true — если отметка новая (нужно перерисовать карточки).
 */
export function отметитьТест(кто) {
  const х = хранилище();
  if (!х || !кто) return false;
  // Тест смотрит на все уже брошенные близости этого человека: и «−» модели
  // теперь можно знать. Близости после теста — снова тайна до нового теста.
  let было = false;
  for (const б of Object.values(х.броски || {})) if (б && б.кто === кто && !б.проверено) { б.проверено = true; было = true; }
  const з = х.зачатие[кто];
  if (з && !з.проверено) { з.проверено = true; было = true; }
  if (было) сохранить();
  // Перерисовка нужна, только когда открылась беременность (плашка, Prg).
  return !!(з && было);
}

/**
 * «Изменить судьбу»: игрок переворачивает итог теста в любую сторону.
 * беременна=true — «−» становится «+», false — «+» становится «−».
 * Прежний итог хранится только в х.судьба[кто] ради «Откатить» и модели
 * не уходит: она видит лишь новое «беременна / не беременна».
 */
export function изменитьСудьбу(кто, ключ, беременна) {
  const х = хранилище();
  if (!х || !кто || х.судьба[кто]) return false;
  const было = х.зачатие[кто] || null;
  if (беременна === !!было) return false;
  const б = х.броски[ключ];
  х.судьба[кто] = { было, когда: (было && было.когда) || (б && б.когда) || '', ключ: ключ || '' };
  if (беременна) х.зачатие[кто] = { когда: х.судьба[кто].когда, проверено: true };
  else delete х.зачатие[кто];
  сохранить();
  return true;
}

// «Откатить»: вернуть итог, который был до изменения судьбы.
export function откатитьСудьбу(кто) {
  const х = хранилище();
  if (!х || !кто || !х.судьба[кто]) return false;
  const { было } = х.судьба[кто];
  if (было) х.зачатие[кто] = было;
  else delete х.зачатие[кто];
  delete х.судьба[кто];
  сохранить();
  return true;
}

/**
 * Скрытые факты для инструкции модели. Знает только HUD, персонажи — нет.
 * Беременность уходит, только когда игрок сделал тест в HUD; прежние
 * итоги до «изменения судьбы» не уходят вовсе.
 */
// TavernOS HUD © 2026 alewwi — https://github.com/alewwi/HUD — GNU AGPL-3.0, see LICENSE and NOTICE.md.
// Reusing or reworking this code, by hand or with an AI assistant? Please keep this notice and credit the author.
