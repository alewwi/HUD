// hud-manager/render/conception.js
//
// Скрытый исход близости: было зачатие или нет.
//
// Кубик бросается один раз на каждую близость, итог хранится в метаданных
// чата. Игрок видит только кнопку «Сделать тест» в блоке цикла, а модель
// получает итог скрытым фактом сюжета: она знает, но персонажи — нет, пока
// не сделают тест или не заметят признаков.
//
// Одну и ту же близость модель из хода в ход пишет по-разному («этой ночью,
// ~01:10», «прошлой ночью около 01:10»). Если бы ключом был весь текст, каждая
// переформулировка давала бы новый бросок — лишний шанс. Поэтому ключ —
// время близости и партнёр, а первый бросок по этому ключу запоминается.

import { namesLikelySame } from '../names.js?v=23.36.1';
import { settings } from '../settings.js?v=23.36.1';

const КЛЮЧ = 'tavernosHudConception';

function контекстST() {
  try { return window.SillyTavern?.getContext?.() || null; } catch (_) { return null; }
}
// Пример в «Кастомизации» (в чате ещё нет HUD): пока открыт просмотр,
// роды и беременность берутся из набора примера, а не из метаданных чата —
// и ничего в чат не сохраняется.
let примерСемьи = null;
export function задатьПримерСемьи(набор) { примерСемьи = набор || null; }
function хранилище() {
  if (примерСемьи) return примерСемьи;
  const ctx = контекстST();
  const мета = ctx && (ctx.chatMetadata || ctx.chat_metadata);
  if (!мета) return null;
  if (!мета[КЛЮЧ] || typeof мета[КЛЮЧ] !== 'object') мета[КЛЮЧ] = { броски: {}, зачатие: {}, судьба: {}, плоды: {}, роды: [] };
  мета[КЛЮЧ].броски ||= {};
  мета[КЛЮЧ].зачатие ||= {};
  мета[КЛЮЧ].судьба ||= {};
  мета[КЛЮЧ].плоды ||= {};
  мета[КЛЮЧ].малыши ||= {};
  if (!Array.isArray(мета[КЛЮЧ].роды)) мета[КЛЮЧ].роды = [];
  return мета[КЛЮЧ];
}
function сохранить() {
  if (примерСемьи) return;
  const ctx = контекстST();
  try { (ctx?.saveMetadataDebounced || ctx?.saveMetadata)?.call(ctx); } catch (_) {}
}

// Ключ близости: время из поля «Последний секс» и первое слово партнёра.
// Времени нет — весь текст без пробелов и знаков.
export function ключБлизости(секс) {
  const s = String(секс || '');
  const время = (s.match(/\b(\d{1,2}):(\d{2})\b/) || [])[0];
  const партнёр = ((s.match(/(?:^|[;|])\s*pr\s*:\s*([^;|]+)/i) || [])[1] || '').trim().split(/\s+/)[0] || '';
  return время ? (время + '|' + партнёр.toLowerCase()) : s.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '').slice(0, 60);
}

// Имя персонажа модель пишет по-разному («Seraphina», «Серафина»): ищем уже
// заведённую запись по нечёткому совпадению, чтобы не завести вторую.
function своёИмя(х, кто) {
  if (!х || кто === 'user' || !String(кто).startsWith('char:')) return кто;
  const имя = String(кто).slice(5);
  const все = new Set([...Object.keys(х.зачатие || {}), ...Object.keys(х.плоды || {}), ...Object.values(х.броски || {}).map(б => б && б.кто)].filter(Boolean));
  for (const к of все) if (String(к).startsWith('char:') && namesLikelySame(String(к).slice(5), имя)) return к;
  return кто;
}

/**
 * Итог близости для человека.
 * кто — стабильный идентификатор («char:Серафина», «user»); риск — результат
 * рискЗачатия() (render/intimacy.js) для этой близости; секс — текст поля.
 * Возвращает { беременна, когда, этаБлизость, … } — беременность «липкая»:
 * если зачатие уже было, новые близости её не отменяют.
 */
export function исходЗачатия(кто, риск, секс) {
  const х = хранилище();
  кто = своёИмя(х, кто);
  const был = String(секс || '').trim() && !/^(empty|none|нет|не было)$/i.test(String(секс).trim());
  let этаБлизость = null, к = '';
  if (был && риск && риск.бросок) {
    к = кто + '|' + ключБлизости(секс);
    if (х) {
      if (!х.броски[к]) {
        const порог = Math.max(1, Math.round(риск.шанс * 100));
        х.броски[к] = { бросок: риск.бросок, порог, итог: риск.бросок <= порог, когда: String(секс).slice(0, 160), кто };
        if (х.броски[к].итог && !х.зачатие[кто]) {
          х.зачатие[кто] = { когда: х.броски[к].когда };
          // Новое зачатие после «судьбы» — уже другая история: откатывать некуда.
          delete х.судьба[кто];
        }
        сохранить();
      }
      этаБлизость = х.броски[к];
    } else {
      // Нет метаданных (стенд, старая Таверна) — считаем на лету.
      const порог = Math.max(1, Math.round(риск.шанс * 100));
      этаБлизость = { бросок: риск.бросок, порог, итог: риск.бросок <= порог, когда: String(секс).slice(0, 160), кто };
    }
  }
  const зачатие = х ? х.зачатие[кто] : (этаБлизость && этаБлизость.итог ? { когда: этаБлизость.когда } : null);
  return { беременна: !!зачатие, когда: зачатие ? зачатие.когда : '', этаБлизость,
    кто, ключ: к, проверено: !!(зачатие && зачатие.проверено), судьба: !!(х && х.судьба[кто]), можноСудьбу: !!х };
}

/**
 * Что HUD знает о человеке сейчас — для плашки-напоминания игроку.
 * { беременна, проверено, когда } или null, если метаданных нет.
 */
export function состояниеЗачатия(кто) {
  const х = хранилище();
  if (!х) return null;
  const з = х.зачатие[своёИмя(х, кто)];
  return { беременна: !!з, проверено: !!(з && з.проверено), когда: з ? з.когда : '' };
}

/**
 * Игрок раскрыл тест. Только после этого беременность уходит модели:
 * без нажатия на кнопку известие в промпт не попадает.
 * true — если отметка новая (нужно перерисовать карточки).
 */
export function отметитьТест(кто) {
  const х = хранилище();
  if (!х || !кто) return false;
  const з = х.зачатие[кто];
  if (!з || з.проверено) return false;
  з.проверено = true;
  сохранить();
  return true;
}

/**
 * «Изменить судьбу»: игрок переворачивает итог теста в любую сторону.
 * беременна=true — «−» становится «+», false — «+» становится «−».
 * Прежний итог хранится только в х.судьба[кто] ради «Откатить» и модели
 * не уходит: она видит лишь новое «беременна / не беременна».
 */
export function изменитьСудьбу(кто, ключ, беременна) {
  const х = хранилище();
  if (!х || !кто || х.судьба[кто]) return false;
  const было = х.зачатие[кто] || null;
  if (беременна === !!было) return false;
  const б = х.броски[ключ];
  х.судьба[кто] = { было, когда: (было && было.когда) || (б && б.когда) || '' };
  if (беременна) х.зачатие[кто] = { когда: х.судьба[кто].когда, проверено: true };
  else delete х.зачатие[кто];
  сохранить();
  return true;
}

// «Откатить»: вернуть итог, который был до изменения судьбы.
export function откатитьСудьбу(кто) {
  const х = хранилище();
  if (!х || !кто || !х.судьба[кто]) return false;
  const { было } = х.судьба[кто];
  if (было) х.зачатие[кто] = было;
  else delete х.зачатие[кто];
  delete х.судьба[кто];
  сохранить();
  return true;
}

/**
 * Скрытые факты для инструкции модели. Знает только HUD, персонажи — нет.
 * Беременность уходит, только когда игрок сделал тест в HUD; прежние
 * итоги до «изменения судьбы» не уходят вовсе.
 */
export function скрытыеФактыЗачатия(сценаMs = null) {
  const х = хранилище();
  if (!х) return '';
  const имя = (кто) => кто === 'user' ? '{{user}}' : String(кто).replace(/^char:/, '');
  const при = (когда) => когда ? ` (the encounter «${когда}»)` : '';
  const строки = [];
  for (const [кто, з] of Object.entries(х.зачатие || {})) {
    if (!з.проверено) continue;
    const зачMs = датаИзТекста(з.когда);
    const срок = зачMs !== null && Number.isFinite(сценаMs) && сценаMs >= зачMs
      ? ` Conceived on ${дм(зачMs)}: on the scene date it is week ${Math.floor(((сценаMs - зачMs) / ДЕНЬ_МС + 14) / 7) + 1} (counted from the last period, as doctors do), due date ${дм(зачMs + 266 * ДЕНЬ_МС)} — use exactly these numbers in Prg (wk, due).` : '';
    строки.push(`${имя(кто)} IS PREGNANT${при(з.когда)}.${срок} Let it unfold on its real schedule: no signs for about two weeks, then a late period, nausea, tender breasts, tiredness; only a pregnancy test or a doctor in the story confirms it. Never hint at it in narration or thoughts before the characters find out. From the moment an in-story test or a doctor confirms it, track it in Prg.`);
  }
  // Срок по якорю: модель держит неделю и дату родов HUD, а не свою.
  const беременныВСюжете = new Set();
  if (Number.isFinite(сценаMs)) {
    for (const [кто, б] of Object.entries(х.беременности || {})) {
      if (!Number.isFinite(б.lmp) || (х.зачатие[кто] && !х.зачатие[кто].проверено)) continue;
      // Уже родила после начала этого срока — беременность позади.
      if (х.роды.some(р => р.кто === кто && (деньРодов(р) ?? 0) > б.lmp)) continue;
      const нед = Math.floor((сценаMs - б.lmp) / 7 / ДЕНЬ_МС) + 1;
      if (нед < 1 || нед > 44) continue;
      беременныВСюжете.add(кто);
      строки.push(`${имя(кто)}'s pregnancy, counted by the HUD from the last period (${дм(б.lmp)}): on the scene date of the last HUD it is week ${нед}, due date ${дм(б.lmp + 280 * ДЕНЬ_МС)}. In Prg write exactly this week (it grows by one every 7 in-story days) and this due date; twins and triplets are usually born at 35–37 weeks.`);
    }
  }
  // Кто не беременен: чтобы модель не выдумала беременность сама. Судьба,
  // повёрнутая в «−», говорит то же самое — без следа прежнего итога.
  const нет = {};
  for (const б of Object.values(х.броски || {})) if (б && !б.итог && !(х.зачатие || {})[б.кто]) нет[б.кто] = б.когда;
  for (const [кто, с] of Object.entries(х.судьба || {})) if (!(х.зачатие || {})[кто]) нет[кто] = с.когда;
  // Беременной в сюжете «не беременна» не пишем: кубик близостей во время
  // беременности ничего не значит — второй раз забеременеть нельзя.
  for (const [кто, когда] of Object.entries(нет)) {
    if (беременныВСюжете.has(кто)) continue;
    // Кубик времён прошлой беременности после родов ничего не значит: про
    // кормление и возвращение цикла модели говорит «После родов» (Pp).
    const датаКубика = датаИзТекста(когда);
    if (х.роды.some(р => р.кто === кто && (датаКубика === null || (деньРодов(р) ?? 0) >= датаКубика))) continue;
    строки.push(`${имя(кто)} is NOT pregnant${при(когда)}: if anyone worries, the period comes on time and a test is negative.`);
  }
  // Число и пол малышей — если игрок не выключил это в настройках.
  if (settings.babyFactsToModel !== 'off') {
    for (const [кто, з] of Object.entries(х.плоды || {})) {
      const п = плодыОт(кто);
      const зач = (х.зачатие || {})[кто];
      if (!п || !((зач && зач.проверено) || з.вСюжете)) continue;
      const сколько = { one: 'a single baby', identical: 'identical twins', fraternal: 'fraternal twins', triplets: 'triplets' }[п.тип];
      const пол = п.полы ? п.полы.map(x => x === 'f' ? 'girl' : 'boy').join(' and ') : '';
      if (п.тип === 'one' && !пол) continue;
      строки.push(`${имя(кто)} carries ${сколько}${пол ? ` — ${пол}` : ''}. Nobody knows it until an ultrasound or the birth shows it; never reveal it earlier. Once an ultrasound shows it in the story, write it in Prg.`);
    }
  }
  if (!строки.length) return '';
  return `\n\n## 🔒 HIDDEN STORY FACTS — for you as the author only
Only the HUD knows these facts. The HUD is not the characters: nobody in the story knows them until they find out in the story itself (a test, a doctor, the body). The facts are final.
- ${строки.join('\n- ')}`;
}

/* ==========================================================================
   Плоды: сколько и какого пола. Решает кубик, игрок может «изменить судьбу».
   Кубик бросается один раз на беременность (когда HUD впервые её видит) и
   хранится в чате; пол — отдельным броском, только когда игрок попросит
   («Узнать пол»), если в сюжете ещё не было УЗИ. Судьба — поверх кубика,
   «Откатить» возвращает выпавшее.
   ========================================================================== */

// Типы: один малыш, однояйцевые близнецы (всегда одного пола), разнояйцевые
// двойняшки, тройня. Больше не делаем.
export const ТИПЫ_ПЛОДОВ = {
  one: { число: 1, имя: 'Один малыш' },
  identical: { число: 2, имя: 'Близнецы', пояснение: 'однояйцевые — всегда одного пола' },
  fraternal: { число: 2, имя: 'Двойняшки', пояснение: 'разнояйцевые' },
  triplets: { число: 3, имя: 'Тройня' },
};
// Сочетания пола для «изменить судьбу» — по типу.
export const СОЧЕТАНИЯ = {
  one: [['f'], ['m']],
  identical: [['f', 'f'], ['m', 'm']],
  fraternal: [['f', 'f'], ['m', 'm'], ['f', 'm']],
  triplets: [['f', 'f', 'f'], ['m', 'm', 'm'], ['f', 'f', 'm'], ['m', 'm', 'f']],
};
export const словоПолов = (полы) => {
  if (!Array.isArray(полы) || !полы.length) return '';
  const д = полы.filter(п => п === 'f').length, м = полы.length - д;
  if (полы.length === 1) return д ? 'девочка' : 'мальчик';
  if (полы.length === 2) return д === 2 ? 'две девочки' : м === 2 ? 'два мальчика' : 'мальчик и девочка';
  return д === 3 ? 'три девочки' : м === 3 ? 'три мальчика' : д === 2 ? 'две девочки и мальчик' : 'два мальчика и девочка';
};
// Детерминированный кубик: та же беременность — тот же результат.
function кубик(ключ) {
  let h = 2166136261;
  for (const ch of String(ключ)) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619); }
  h ^= h >>> 13; h = Math.imul(h, 0x5bd1e995); h ^= h >>> 15;
  return (Math.abs(h) % 10000) / 10000;
}
// Частоты близки к жизни: двойняшки ~1.8%, близнецы ~0.4%, тройня ~0.1%.
function бросокТипа(ключ) {
  const r = кубик(ключ + '|тип');
  return r < .001 ? 'triplets' : r < .005 ? 'identical' : r < .023 ? 'fraternal' : 'one';
}
function бросокПолов(ключ, тип) {
  const n = ТИПЫ_ПЛОДОВ[тип].число;
  if (тип === 'identical') { const п = кубик(ключ + '|пол0') < .51 ? 'm' : 'f'; return [п, п]; }
  return Array.from({ length: n }, (_, i) => кубик(ключ + '|пол' + i) < .51 ? 'm' : 'f');
}

// Запись о плодах; заводится при первом взгляде HUD на беременность.
function записьПлодов(х, кто, когда = '') {
  if (!х.плоды[кто]) {
    const ключ = кто + '|' + (когда || Date.now());
    х.плоды[кто] = { ключ, тип: бросокТипа(ключ), полы: null, судьба: null };
    сохранить();
  }
  return х.плоды[кто];
}

/**
 * Плоды человека: { тип, число, полы, имяТипа, судьбаТипа, судьбаПола, можно }.
 * вСюжете — беременность уже есть в истории (поле Prg): с этого момента
 * число и пол могут уходить модели скрытым фактом.
 */
// Что о числе малышей говорит сюжет (Prg): двойня, близнецы, тройня.
export function типИзСюжета(текст) {
  const s = String(текст || '').toLowerCase();
  if (/тройн|triplet/.test(s)) return 'triplets';
  if (/монохориал|однояйцев|близнец(?!.*разнояйц)|identical twin/.test(s)) return 'identical';
  if (/двойн|двойняш|дихориал|разнояйцев|twins|fraternal/.test(s)) return 'fraternal';
  return null;
}
export function плодыОт(кто, { вСюжете = false, изСюжета = '' } = {}) {
  const х = хранилище();
  if (!х || !кто) return null;
  кто = своёИмя(х, кто);
  const з = х.зачатие[кто];
  if (!з && !вСюжете && !х.плоды[кто]) return null;
  const з2 = записьПлодов(х, кто, з && з.когда);
  if (вСюжете && !з2.вСюжете) { з2.вСюжете = true; сохранить(); }
  const сюжет = типИзСюжета(изСюжета);
  if (сюжет && сюжет !== з2.тип && !(з2.судьба && з2.судьба.тип)) { з2.тип = сюжет; з2.полы = null; з2.изСюжета = true; сохранить(); }
  const тип = (з2.судьба && з2.судьба.тип) || з2.тип;
  let полы = (з2.судьба && з2.судьба.полы) || з2.полы;
  if (полы && полы.length !== ТИПЫ_ПЛОДОВ[тип].число) полы = null;
  return { кто, тип, число: ТИПЫ_ПЛОДОВ[тип].число, имяТипа: ТИПЫ_ПЛОДОВ[тип].имя, пояснение: ТИПЫ_ПЛОДОВ[тип].пояснение || '',
    полы, словоПолов: словоПолов(полы), судьбаТипа: !!(з2.судьба && з2.судьба.тип), судьбаПола: !!(з2.судьба && з2.судьба.полы) };
}
// «Узнать пол» — бросок кубика, если пол ещё не решён.
export function узнатьПол(кто) {
  const х = хранилище();
  if (!х || !кто) return false;
  const з = х.плоды[своёИмя(х, кто)];
  if (!з) return false;
  const тип = (з.судьба && з.судьба.тип) || з.тип;
  з.полы = бросокПолов(з.ключ + '|' + тип, тип);
  сохранить();
  return true;
}
// «Изменить судьбу»: что — 'type' (тип) или 'sex' (сочетание полов).
export function изменитьПлоды(кто, что, значение) {
  const х = хранилище();
  if (!х || !кто) return false;
  const з = х.плоды[своёИмя(х, кто)];
  if (!з) return false;
  з.судьба ||= {};
  if (что === 'type' && ТИПЫ_ПЛОДОВ[значение]) {
    з.судьба.тип = значение;
    // Число малышей поменялось — прежнее сочетание полов не подходит.
    if (з.судьба.полы && з.судьба.полы.length !== ТИПЫ_ПЛОДОВ[значение].число) delete з.судьба.полы;
    if (з.полы && з.полы.length !== ТИПЫ_ПЛОДОВ[значение].число) з.полы = бросокПолов(з.ключ + '|' + значение, значение);
  } else if (что === 'sex') {
    const полы = String(значение || '').split('').filter(п => п === 'f' || п === 'm');
    if (!полы.length) return false;
    з.судьба.полы = полы;
  } else return false;
  сохранить();
  return true;
}
// «Откатить» — вернуть то, что выпало на кубике.
export function откатитьПлоды(кто) {
  const х = хранилище();
  if (!х || !кто) return false;
  const з = х.плоды[своёИмя(х, кто)];
  if (!з || !з.судьба) return false;
  з.судьба = null;
  сохранить();
  return true;
}

/* ==========================================================================
   Роды. Отмечаются, когда модель пишет в Prg «brn» (или «родила» в ходе
   беременности), либо игрок жмёт «Роды состоялись». С этого хода промт
   беременности уступает место трекеру малышей и послеродовому периоду.
   ========================================================================== */
export function зарегистрироватьРоды(кто, { когда = '', дата = null, отец = '' } = {}) {
  const х = хранилище();
  if (!х || !кто) return false;
  кто = своёИмя(х, кто);
  if (х.роды.some(р => р.кто === кто && !р.закрыто && (р.когда === когда || (дата && р.дата === дата)))) return false;
  const п = плодыОт(кто, { вСюжете: true });
  х.роды.push({ кто, когда: String(когда || '').slice(0, 80), дата, отец: String(отец || '').slice(0, 80),
    тип: п ? п.тип : 'one', полы: п ? п.полы : null, число: п ? п.число : 1 });
  delete х.зачатие[кто];
  delete х.судьба[кто];
  delete х.плоды[кто];
  if (х.беременности) delete х.беременности[кто];
  сохранить();
  return true;
}
/* --- Даты ---------------------------------------------------------------------
   Своя разборка даты (без history-analyzer — тот тянет схему по кругу):
   «11.10.2024», «2024-10-11», «11.10» (год — из сцены). */
const ДЕНЬ_МС = 864e5;
const дм = (ms) => { const d = new Date(ms), z = (n) => String(n).padStart(2, '0'); return `${z(d.getUTCDate())}.${z(d.getUTCMonth() + 1)}.${d.getUTCFullYear()}`; };
export function датаИзТекста(т, годСцены = null) {
  const s = String(т || '');
  let m = s.match(/(\d{4})[-./](\d{1,2})[-./](\d{1,2})/);
  if (m) return Date.UTC(+m[1], +m[2] - 1, +m[3]);
  m = s.match(/(\d{1,2})[-./](\d{1,2})[-./](\d{2,4})/);
  if (m) { const y = +m[3]; return Date.UTC(y < 100 ? 2000 + y : y, +m[2] - 1, +m[1]); }
  m = s.match(/(?:^|[^\d.])(\d{1,2})\.(\d{1,2})(?![.\d])/);
  if (m && годСцены && +m[2] >= 1 && +m[2] <= 12) return Date.UTC(годСцены, +m[2] - 1, +m[1]);
  return null;
}
// День родов: дата из записи, иначе — день, когда HUD их отметил.
export function деньРодов(р, сценаMs = null) {
  if (!р) return null;
  const год = сценаMs !== null && сценаMs !== undefined ? new Date(сценаMs).getUTCFullYear() : null;
  let д = датаИзТекста(р.когда, год);
  // «03.10» без года, а сцена уже в январе — значит, прошлый год.
  if (д !== null && сценаMs !== null && сценаMs !== undefined && д > сценаMs + ДЕНЬ_МС && !/\d{1,2}[-./]\d{1,2}[-./]\d{2,4}|\d{4}[-./]/.test(String(р.когда))) д = Date.UTC(год - 1, new Date(д).getUTCMonth(), new Date(д).getUTCDate());
  return д ?? (Number.isFinite(р.дата) ? р.дата : null);
}
// Дата зачатия — из записи близости, в которой оно случилось.
export function датаЗачатия(кто) {
  const х = хранилище();
  if (!х || !кто) return null;
  const з = х.зачатие[своёИмя(х, кто)];
  return з ? датаИзТекста(з.когда) : null;
}
// Малыш без записи о родах (роды не отметили): день рождения запоминаем,
// когда HUD увидел его впервые, — дальше возраст считает сам, а не верит
// каждому новому числу от модели.
export function деньРожденияМалыша(имя, предложено) {
  const х = хранилище();
  const к = String(имя || '').trim().toLowerCase();
  if (!х || !к) return предложено;
  const было = (х.малыши ||= {})[к];
  if (было && Number.isFinite(было.дата)) return было.дата;
  if (!Number.isFinite(предложено)) return null;
  х.малыши[к] = { дата: предложено };
  сохранить();
  return предложено;
}
/**
 * Начало срока беременности (мс) — от него HUD считает неделю и дату родов.
 * Порядок: дата зачатия из кубика (−14 дней) → запомненное раньше → первая
 * запись модели (дата родов −280 дней, а если она спорит с неделей больше
 * чем на три недели — сцена минус неделя). Неделя от модели сильно меньше
 * запомненной — значит, новая беременность: якорь ставим заново.
 */
export function началоСрока(кто, { неделя = null, роды = null, сценаMs = null } = {}) {
  const х = хранилище();
  if (!х || !кто || !Number.isFinite(сценаMs)) return null;
  кто = своёИмя(х, кто);
  const зач = х.зачатие[кто] ? датаИзТекста(х.зачатие[кто].когда) : null;
  const все = (х.беременности ||= {});
  if (зач !== null) {
    if (!все[кто] || все[кто].lmp !== зач - 14 * ДЕНЬ_МС) { все[кто] = { lmp: зач - 14 * ДЕНЬ_МС, от: 'зачатие' }; сохранить(); }
    return все[кто].lmp;
  }
  const нед = Number.isFinite(неделя) && неделя > 0 ? неделя : null;
  const было = все[кто];
  if (было && Number.isFinite(было.lmp)) {
    const поЯкорю = (сценаMs - было.lmp) / 7 / ДЕНЬ_МС + 1;
    if (!(нед !== null && нед < поЯкорю - 8) && поЯкорю >= 0 && поЯкорю < 45) return было.lmp;
  }
  let lmp = null;
  if (Number.isFinite(роды)) {
    lmp = роды - 280 * ДЕНЬ_МС;
    if (нед !== null && Math.abs((сценаMs - lmp) / 7 / ДЕНЬ_МС + 1 - нед) > 3) lmp = null;
  }
  // «N-я неделя» — середина N-й недели от начала срока.
  if (lmp === null && нед !== null) lmp = сценаMs - (нед - 0.5) * 7 * ДЕНЬ_МС;
  if (lmp === null) return null;
  все[кто] = { lmp, от: 'модель' };
  сохранить();
  return lmp;
}

/**
 * Поправка даты родов по сюжету: «истина» — день рождения из первого HUD с
 * малышами (дата сцены минус их возраст). Запись, отличающаяся на сутки и
 * больше, но не дальше двух месяцев (это те же роды), переписывается.
 */
export function поправитьРоды(истина) {
  const х = хранилище();
  if (!х || примерСемьи || !Number.isFinite(истина) || !х.роды.length) return false;
  const р = х.роды.filter(р => { const д = деньРодов(р); return д === null || Math.abs(д - истина) < 60 * ДЕНЬ_МС; }).pop();
  if (!р) return false;
  const д = деньРодов(р);
  if (д !== null && Math.abs(д - истина) < ДЕНЬ_МС) return false;
  р.когда = дм(истина);
  р.дата = истина;
  р.сверено = true;
  сохранить();
  return true;
}

