// Состояние вещи: снята совсем, частично (расстёгнута, спущена, задрана)
// или надета. «Босиком» — обувь снята.
const СНЯТО = слово('сброшен|снят|сорван|стянут|скинут|на полу|валяется|без (?:него|неё|нее|одежд|бель|трусик|лифчик|обув)|босиком|боса|разделась|раздет');
