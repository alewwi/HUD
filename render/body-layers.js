// «жарко, пересохло во рту, сильное возбуждение, лёгкий хмель от вина» →
// [{ id, имя, значок, сторона, xy, куски: ['пересохло во рту'] }].
export function ощущенияИзТекста(...тексты) {
  const найдено = new Map();
  for (const t of тексты) {
    for (const кусок of текст(t).split(/[,;\n]|\s+—\s+/).map(x => x.trim()).filter(Boolean)) {
      if (/^(empty|none|нет|пусто)$/i.test(кусок)) continue;
      const о = ОРГАНЫ.find(([, , , rx]) => rx.test(кусок));
      if (!о) continue;
      const [id, имя, значок, , сторона, xy] = о;
      if (!найдено.has(id)) найдено.set(id, { id, имя, значок, сторона, xy, куски: [] });
      const куски = найдено.get(id).куски;
      if (!куски.includes(кусок)) куски.push(кусок);
    }
  }
  return [...найдено.values()];
}

