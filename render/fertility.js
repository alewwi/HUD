// Тексты по старшинству (строка или список): «Внешность» из HUD, потом
// описание из карточки. Признак берём из первого текста, где он назван.
function признак(тексты, таблица) {
  for (const текст of [].concat(тексты)) {
    const s = String(текст || '');
    if (!s) continue;
    // В одном тексте — по первому упоминанию, а не по порядку таблицы.
    let лучший = null;
    for (const [имя, rx, ранг] of таблица) {
      const m = s.match(rx);
      if (m && (!лучший || m.index < лучший.где)) лучший = { имя, ранг, где: m.index };
    }
    if (лучший) return { имя: лучший.имя, ранг: лучший.ранг };
  }
  return null;
}
function кубик(ключ) {
  let h = 2166136261;
  for (const ch of String(ключ)) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619); }
  h ^= h >>> 13; h = Math.imul(h, 0x5bd1e995); h ^= h >>> 15;
  return (Math.abs(h) % 1000) / 1000;
}
// Один признак: от кого из двух; тёмный побеждает в 70% случаев.
function унаследовать(а, б, ключ) {
  if (!а && !б) return null;
  if (!а || !б) return { имя: (а || б).имя, шанс: 60 };
  if (а.имя === б.имя) return { имя: а.имя, шанс: 90 };
  const [сильный, слабый] = а.ранг >= б.ранг ? [а, б] : [б, а];
  return кубик(ключ) < .7 ? { имя: сильный.имя, шанс: 70 } : { имя: слабый.имя, шанс: 30 };
}
/** → { глаза: {имя, шанс}, волосы: {имя, шанс} } или null, если не из чего. */
export function наследование(мама, папа, ключ = '') {
  const глаза = унаследовать(признак(мама, ГЛАЗА), признак(папа, ГЛАЗА), ключ + '|глаза');
  const волосы = унаследовать(признак(мама, ВОЛОСЫ), признак(папа, ВОЛОСЫ), ключ + '|волосы');
  return глаза || волосы ? { глаза, волосы } : null;
}
