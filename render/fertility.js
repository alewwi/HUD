// «Не бесплодна», «без эндометриоза», «вылечили» — не считается.
function нашлось(текст, rx) {
  const m = String(текст || '').match(rx);
  if (!m) return false;
  const перед = String(текст).slice(Math.max(0, m.index - 12), m.index).toLowerCase();
  if (/(?:^|\s)(?:не|нет|без|no|not)\s*$/.test(перед)) return false;
  const после = String(текст).slice(m.index, m.index + 60).toLowerCase();
  if (/(?:вылечен|излечен|прошл[аио]|cured)/.test(после)) return false;
  return true;
}

/**
 * Плодовитость: во сколько раз меньше шанс и почему.
 * свой — текст здоровья, болезней и цикла человека; партнёр — то же у
 * партнёра; послеродовое — результат послеродовое(), если недавно родила.
 * → { доля: 0…1, причины: [{ имя, доля }] }
 */
export function плодовитость(свой = '', партнёр = '', послеродовое = null) {
  const причины = [];
  for (const [rx, доля, имя] of СВОЁ) if (нашлось(свой, rx)) причины.push({ имя, доля });
  for (const [rx, доля, имя] of ПАРТНЁРА) if (нашлось(партнёр, rx)) причины.push({ имя, доля });
  if (послеродовое && послеродовое.плодовитость < 1) причины.push({ имя: послеродовое.причина, доля: послеродовое.плодовитость });
  // Несколько причин сразу — множим, но не ниже нуля; ноль остаётся нулём.
  const доля = причины.reduce((д, п) => д * п.доля, 1);
  return { доля, причины };
}

