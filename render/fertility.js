// Плодовитость и всё, что вокруг неё, — HUD считает сам, модели ничего
// лишнего писать не нужно:
//   • сила кровотечения в дни месячных;
//   • бесплодие и болезни, которые снижают шанс зачатия (из «Здоровья»,
//     «Болезней» и цикла — своих и партнёра);
//   • сбой цикла от стресса, болезни, голода, перелёта, перегрузок;
//   • «пытаются N месяцев» без результата;
//   • послеродовой период и кормление грудью: молоко, его стадия, объём,
//     наполненность груди по времени с последнего кормления;
//   • на кого будет похож малыш — глаза и волосы от мамы и папы.

const пусто = (v) => !String(v ?? '').trim() || /^(empty|none|null|нет|пусто)$/i.test(String(v).trim());
const огр = (v, a, b) => Math.max(a, Math.min(b, v));

/* --- Кровотечение ------------------------------------------------------------ */

// День месячных → сила: первый день начинается, 2–3 обильно, 4 умеренно,
// дальше мажет. Для длинных месячных шкала растягивается.
export function кровотечение(день, длина = 5) {
  const d = Math.round(Number(день));
  if (!Number.isFinite(d) || d < 1 || d > Math.max(5, длина)) return null;
  const к = Math.max(5, длина) / 5;
  const x = d / к;
  if (x <= 1) return { капли: 2, слово: 'начинается' };
  if (x <= 3) return { капли: 3, слово: 'обильно' };
  if (x <= 4) return { капли: 2, слово: 'умеренно' };
  return { капли: 1, слово: 'мажет' };
}

