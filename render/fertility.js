// Что сдвигает овуляцию, а с ней и месячные. Возвращает подсказки.
const СБОИ = [
  [/температур|лихорад|грипп|простуд|ангин|инфекц|fever|flu/i, 'болезнь — месячные могут сдвинуться на 2–7 дней'],
  [/недоед|голода|диет|истощ|starv/i, 'недоедание — цикл может растянуться на 5–14 дней'],
  [/перел[её]т|часов[а-яё]* пояс|jet\s*lag/i, 'смена часовых поясов — сдвиг на 1–5 дней'],
  [/перетрен|марафон|изнуряющ[а-яё]* трениров/i, 'перегрузки — сдвиг на 3–9 дней'],
];
export function сбойЦикла({ стресс = NaN, текст = '' } = {}) {
  const out = [];
  if (Number.isFinite(стресс) && стресс >= 75) out.push(`стресс ${Math.round(стресс)} — месячные могут сдвинуться на 3–10 дней`);
  else if (/паник|сильн[а-яё]*\s+стресс|нервн[а-яё]*\s+срыв|шок/i.test(текст)) out.push('сильный стресс — месячные могут сдвинуться на 3–10 дней');
  for (const [rx, слова] of СБОИ) if (нашлось(текст, rx)) out.push(слова);
  return out;
}

/* --- «Пытаются» ------------------------------------------------------------------ */

export function пытаются(месяцев) {
  const m = Math.floor(Number(месяцев));
  if (!Number.isFinite(m) || m < 6) return null;
  return m < 12
    ? { уровень: 'concern', текст: `${m} мес. без результата — стоит провериться обоим` }
    : { уровень: 'serious', текст: `${m} мес. без результата — повод сходить к репродуктологу` };
}

/* --- Послеродовой период и молоко ------------------------------------------------ */

const ЧАСЫ = (t) => { const m = String(t || '').match(/(\d{1,2})[:.](\d{2})/); return m ? +m[1] + +m[2] / 60 : NaN; };
// Сколько часов прошло между двумя «ЧЧ:ММ» (через полночь — тоже).
export function часовМежду(с, по) {
  const a = ЧАСЫ(с), b = ЧАСЫ(по);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return NaN;
  return (b - a + 24) % 24;
}
/**
 * Послеродовое состояние по числу дней с родов и способу кормления.
 * кормление — 'breast' | 'formula' | 'mixed' (из поля Pp или по словам).
 * часыСКормления — сколько часов грудь не опорожняли; детей — сколько.
 */
export function послеродовое(дней, { кормление = 'breast', часыСКормления = NaN, детей = 1 } = {}) {
  const d = Math.max(0, Math.round(Number(дней) || 0));
  const грудью = кормление !== 'formula';
  const заживление = d < 10 ? 'швы свежие, больно сидеть и вставать' : d < 25 ? 'заживает, тянет при нагрузке' : d < 42 ? 'почти зажило' : 'зажило';
  const выделения = d < 4 ? 'обильные, ярко-красные' : d < 12 ? 'умеренные, буроватые' : d < 35 ? 'скудные, светлые' : '';
  const циклВернулся = кормление === 'breast' ? d >= 180 : кормление === 'mixed' ? d >= 90 : d >= 45;
  const плод = циклВернулся ? 1 : кормление === 'breast' ? .05 : кормление === 'mixed' ? .15 : .3;
  const этап = d < 42 ? 'ранний послеродовой период' : циклВернулся ? 'восстановление завершено' : 'кормление, цикл ещё не вернулся';
  let молоко = null;
  if (грудью) {
    const стадия = d <= 3 ? 'молозиво' : d <= 14 ? 'переходное молоко' : 'зрелое молоко';
    // Сколько нужно малышу в сутки, мл: молозиво — ложки, к месяцу — 600–800.
    const вСутки = d <= 3 ? 30 + d * 25 : d <= 14 ? 150 + (d - 3) * 35 : d <= 30 ? 550 + (d - 14) * 10 : d <= 180 ? 750 : 600;
    const доля = кормление === 'mixed' ? .5 : 1;
    const ч = Number(часыСКормления);
    // Наполненность: 0 — мягкая после кормления, 100 — нагрубание.
    const полнота = Number.isFinite(ч) ? огр(Math.round(ч / 4 * 100 * (d <= 3 ? .5 : 1)), 0, 100) : null;
    const слово = полнота === null ? '' : полнота < 25 ? 'мягкая, недавно кормила' : полнота < 55 ? 'наполняется' : полнота < 80 ? 'полная, пора кормить' : 'тугая, может подтекать — риск застоя';
    молоко = { стадия, вСутки: Math.round(вСутки * доля * огр(детей, 1, 3)), полнота, слово };
  }
  return { дней: d, этап, заживление, выделения, циклВернулся, плодовитость: плод,
    причина: циклВернулся ? '' : кормление === 'breast' ? 'кормит грудью — цикл не вернулся' : 'после родов цикл ещё не вернулся', молоко };
}
export function видКормления(текст) {
  const s = String(текст || '').toLowerCase();
  if (/смесь|бутылоч|formula|bottle|искусствен/.test(s) && /груд|breast/.test(s)) return 'mixed';
  if (/смешан|mixed/.test(s)) return 'mixed';
  if (/смесь|бутылоч|formula|bottle|искусствен|не кормит/.test(s)) return 'formula';
  return 'breast';
}

