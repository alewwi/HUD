// «код: значение; …» → объект по русским меткам в нижнем регистре.
function метки(текст) {
  const out = {};
  String(текст || '').split(/[;\n]/).forEach(часть => {
    const m = часть.match(/^\s*([^:：]{1,40})[:：]\s*(.*)$/);
    if (m) out[перевестиМетку(m[1].trim()).toLowerCase()] = m[2].trim();
  });
  return out;
}
const пусто = (v) => !v || /^(empty|none|null|нет|пусто|-|—|неизвестно|unknown)$/i.test(String(v).trim());
const ДЕНЬ = 864e5;
const склон = (n, a, b, c) => { const k = Math.abs(n) % 100, d = k % 10; return k > 10 && k < 20 ? c : d === 1 ? a : d >= 2 && d <= 4 ? b : c; };

// Дата из текста модели: «12.03.2025», «12.03», «12 марта 2025».
function дата(текст, годПоУмолчанию) {
  const s = String(текст || '');
  const ms = parseSceneDate(s);
  if (ms !== null && /\d{4}|\d{1,2}[./-]\d{1,2}[./-]\d{2}(?!\d)/.test(s)) return ms;
  const m = s.match(/(\d{1,2})[./-](\d{1,2})(?![./-]?\d)/);
  if (m && годПоУмолчанию) return Date.UTC(годПоУмолчанию, +m[2] - 1, +m[1]);
  return ms;
}
const дм = (ms) => { const t = new Date(ms); return String(t.getUTCDate()).padStart(2, '0') + '.' + String(t.getUTCMonth() + 1).padStart(2, '0') + '.' + t.getUTCFullYear(); };

// Силуэт женщины в профиль (лицом вправо) до середины бедра: голова, шея,
// спина с естественным прогибом поясницы, грудь, живот, бёдра. Живот растёт
// по настоящей кривой — до 12-й недели его почти не видно, дальше он
// округляется и к сроку выходит вперёд на ладонь; грудь тоже чуть больше.
// Рука лежит на животе, внутри со второго триместра угадывается малыш.
let номерСилуэта = 0;
function силуэт(н) {
  const w = н || 0;
  const k = w < 12 ? w / 12 * .06 : Math.min(1, .06 + Math.pow((w - 12) / 28, .85) * .94);
  const B = k * 24;              // насколько живот выходит вперёд
  const гр = k * 3;              // грудь
  const f = (v) => v.toFixed(1);
  const X = (v) => f(54 + v);    // передняя линия от нулевого живота
  // Одним контуром: затылок → спина → ягодицы → бедро сзади → низ →
  // бедро спереди → живот снизу вверх → грудь → шея.
  const тело = `M43 20 C43 27 36 33 34 42 C32 52 35 62 37 70 C38 77 30 85 31 96 C32 108 36 118 37 130 L38 142 L51 142 L51 130 `
    + `C52 118 54 110 53 102 C${X(B * .4)} 100 ${X(B)} 92 ${X(B)} 80 C${X(B)} 68 ${X(B * .6)} 60 54 58 `
    + `C57 56 ${f(60 + гр)} 52 ${f(59 + гр)} 46 C${f(58 + гр)} 40 54 37 50 36 C50 31 50 26 50 20 Z`;
  // Рука от плеча к животу; кисть ложится на самую выпуклую часть.
  const ладоньX = 47 + B * .72, ладоньY = 74 + B * .12;
  const рука = `M43 37 C40 46 39 56 40 63 C41 70 ${f(ладоньX - 5)} ${f(ладоньY + 2)} ${f(ладоньX)} ${f(ладоньY)}`;
  // Малыш: голова и свернувшееся тельце, едва заметно, внутри живота.
  const малыш = k > .35 ? (() => {
    const s = .45 + k * .55, cx = 50 + B * .5, cy = 82;
    return `<g class="b-baby" transform="translate(${f(cx)} ${f(cy)}) scale(${s.toFixed(2)}) rotate(-20)">`
      + `<ellipse cx="0" cy="3" rx="6" ry="8"/><circle cx="2" cy="-6" r="5"/></g>`;
  })() : '';
  // Свечение и малыш обрезаются контуром тела — наружу не выходят.
  const клип = 'prg-clip-' + (++номерСилуэта);
  return `<svg class="hud-prg-belly" viewBox="18 2 72 142" role="img" aria-label="Силуэт на ${н || '—'}-й неделе">`
    + `<defs><clipPath id="${клип}"><path d="${тело}"/></clipPath></defs>`
    + `<ellipse class="b-head" cx="47" cy="15" rx="9" ry="10.5"/>`
    + `<path class="b-hair" d="M38 15 C37 6 45 2 51 5 C55 7 56 10 55 13 C50 9 44 10 40 18 C39 20 38 18 38 15 Z"/>`
    + `<path class="b-body" d="${тело}"/>`
    + `<g clip-path="url(#${клип})">`
    + (B > 3 ? `<ellipse class="b-glow" cx="${f(52 + B * .55)}" cy="80" rx="${f(4 + B * .45)}" ry="${f(8 + B * .5)}"/>` : '')
    + малыш + `</g>`
    + `<path class="b-arm" d="${рука}"/>`
    + `</svg>`;
}

/**
 * value — строка Prg; контекст.сцена — дата сцены (для отсчёта до родов).
 */
export function buildPregnancy(value, контекст = {}) {
  const п = метки(value);
  const неделяЧисло = parseInt(String(п['неделя'] || '').replace(/[^\d]/g, ''), 10);
  const н = Number.isFinite(неделяЧисло) && неделяЧисло > 0 ? Math.min(неделяЧисло, 42) : null;
  const триместр = н === null ? 0 : н < 14 ? 1 : н < 28 ? 2 : 3;
  const вид = (к) => пусто(п[к]) ? '' : п[к];

  // Отсчёт до родов: дата родов от модели, иначе — оценка по неделе.
  const сцена = контекст.сцена ? parseSceneDate(контекст.сцена) : null;
  const годСцены = сцена !== null ? new Date(сцена).getUTCFullYear() : null;
  let роды = вид('роды') ? дата(вид('роды'), годСцены) : null;
  let оценка = false;
  if (роды === null && сцена !== null && н !== null) { роды = сцена + (40 - н) * 7 * ДЕНЬ; оценка = true; }
  let отсчёт = '';
  if (роды !== null && сцена !== null) {
    const дней = Math.round((роды - сцена) / ДЕНЬ);
    if (дней > 13) { const нед = Math.floor(дней / 7); отсчёт = `до родов ${оценка ? '≈ ' : ''}${нед} ${склон(нед, 'неделя', 'недели', 'недель')} (${дней} ${склон(дней, 'день', 'дня', 'дней')})`; }
    else if (дней > 0) отсчёт = `до родов ${дней} ${склон(дней, 'день', 'дня', 'дней')} — пора держать сумку у двери`;
    else if (дней === 0) отсчёт = 'сегодня — предполагаемая дата родов';
    else отсчёт = `переношено на ${-дней} ${склон(-дней, 'день', 'дня', 'дней')}`;
  }

  // Шкала: триместры, засечки этапов, отметка сегодня.
  const доля = (w) => (Math.min(42, Math.max(0, w)) / 42 * 100).toFixed(2);
  const засечки = ЭТАПЫ.map(([w, имя]) => `<s class="${н !== null && н >= w ? 'is-past' : ''}" style="left:${доля(w)}%" title="${w}-я неделя: ${имя}"></s>`).join('');
  const шкала = `<div class="hud-prg-track" role="img" aria-label="${н === null ? 'Срок не назван' : н + '-я неделя из 40'}">`
    + `<div class="hud-prg-meter"><b class="t1" style="width:${доля(13)}%"></b><b class="t2" style="left:${доля(13)}%;width:${(доля(27) - доля(13)).toFixed(2)}%"></b><b class="t3" style="left:${доля(27)}%;right:0"></b>`
    + (н !== null ? `<i style="width:${доля(н)}%"></i>` : '') + засечки
    + (н !== null ? `<em class="now" style="left:clamp(8px, ${доля(н)}%, calc(100% - 8px))"></em>` : '') + `</div>`
    + `<div class="hud-prg-tri"><span style="width:${доля(13)}%">I</span><span style="width:${(доля(27) - доля(13)).toFixed(2)}%">II</span><span>III</span></div></div>`;

  // Малыш сейчас и что дальше.
  const размер = н !== null ? (РАЗМЕР[Math.max(4, н)] || РАЗМЕР[42]) : null;
  const событие = н !== null ? (СОБЫТИЯ.filter(([w]) => w <= н).pop() || СОБЫТИЯ[0])[1] : '';
  const следующий = н !== null ? ЭТАПЫ.find(([w]) => w > н) : null;
  const малыш = н === null ? '' : `<div class="hud-prg-baby">`
    + `<div class="hud-prg-size"><span>размером с</span><b>${escapeHtml(размер[0])}</b><small>${размер[1]}${размер[2] ? ' · ' + размер[2] : ''}</small></div>`
    + `<p class="hud-prg-event">${escapeHtml(событие)}</p>`
    + (следующий ? `<p class="hud-prg-next">Дальше: <b>${следующий[1]}</b> — через ${следующий[0] - н} ${склон(следующий[0] - н, 'неделю', 'недели', 'недель')}</p>` : '')
    + `</div>`;

  // Как проходит — с оценкой настроения.
  const ход = вид('как проходит');
  // «без осложнений», «угрозы нет» — не тревога: отрицания вычищаем до проверки.
  const безОтрицаний = ход.replace(/(?:без|нет)\s+(?:\p{L}+\s+)?(?:осложн|угроз|кровотеч|риск)\p{L}*|(?:осложн|угроз|кровотеч|риск)\p{L}*\s+(?:нет|не\s+\p{L}+)/giu, '');
  const тон = ТРЕВОЖНО.test(безОтрицаний) ? ' is-risk' : СПОКОЙНО.test(ход) ? ' is-ok' : '';

  const строка = (подпись, текст, класс = '') => текст ? `<div class="hud-prg-row${класс}"><span>${escapeHtml(подпись)}</span><p>${applyTooltips(текст)}</p></div>` : '';
  const пол = вид('пол ребёнка');
  const имя = вид('имя ребёнка');
  const малышИмя = [пол ? (/дев|girl|жен/i.test(пол) ? '♀ ' : /мал|boy|муж/i.test(пол) ? '♂ ' : '') + пол : '', имя ? `«${имя}»` : ''].filter(Boolean).join(' · ');
  const советы = триместр ? СОВЕТЫ[триместр].concat(ТРЕВОГА) : [];

  return `<div class="hud-prg${тон}">`
    + `<div class="hud-prg-head"><span class="hud-prg-ico" aria-hidden="true">🤰</span><b>${н === null ? 'Срок не назван' : н + '-я неделя'}</b>`
    + (триместр ? `<em>${['', 'I', 'II', 'III'][триместр]} триместр</em>` : '')
    + (роды !== null ? `<small>роды ${оценка ? '≈ ' : ''}${escapeHtml(вид('роды') && !оценка ? вид('роды') : дм(роды))}</small>` : '') + `</div>`
    + (отсчёт ? `<div class="hud-prg-count${/переношено|держать сумку|сегодня/.test(отсчёт) ? ' is-soon' : ''}">${escapeHtml(отсчёт)}</div>` : '')
    + шкала
    + (н !== null ? `<div class="hud-prg-main">${силуэт(н)}${малыш}</div>` : '')
    + строка('Малыш', малышИмя)
    + строка('Отец', вид('отец'))
    + строка('Симптомы', вид('симптомы'))
    + строка('Тянет на', вид('тяга'))
    + строка('Кто знает', вид('кто знает'))
    + строка('Как проходит', ход, тон)
    + строка('Визит к врачу', вид('визит к врачу'))
    + (советы.length ? `<ul class="hud-prg-tips">${советы.map((с, i) => `<li${i === советы.length - 1 ? ' class="is-alarm"' : ''}>${escapeHtml(с)}</li>`).join('')}</ul>` : '')
    + `</div>`;
}
