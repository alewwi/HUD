//
//  • Справа — тот, кого берут: профиль тела по коже (губы и клитор,
//    промежность; или тёмный силуэт лица), а внутри — только канал и то, во
//    что он упирается: шейка; кишка с крестцом и простатой; рот, язык, горло.
//  • Слева — тот, кто проникает: лобок с мошонкой и член нужной длины
//    (размер из «NSFW»: pn:/an:), кисть с пальцами, кулак, игрушка с упором
//    или лицо в профиль с высунутым языком. Всё это ходит в такт темпу.
//  • Стенки канала обхватывают то, что внутри, и наезжают на него буграми;
//    дальше кончика — сомкнутая щель со складками.
//  • Линейка в сантиметрах, вспышка на кончике при упоре, простата
//    вспыхивает, когда её задевают. Влага («lb:») — блеск, капли и ниточки;
//    семя при окончании внутрь. Внизу — волна темпа.
//
// Движение — от --k блока темпа (css/scene-body.css): 1 — на глубине,
// ~0.1 — отошёл назад. --amp — ход в px, --kp — момент, когда кончик
// проходит простату, --push — насколько упор сдвигает шейку.

const экран = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const ф = (n) => (Math.round(n * 10) / 10).toString();
const см = (v) => (Math.round(v * 10) / 10).toString().replace('.', ',');
// Путь из шаблона: числа в ${} округляются до десятых.
const d = (строки, ...ч) => строки.reduce((a, s, i) => a + s + (i < ч.length ? (typeof ч[i] === 'number' ? ф(ч[i]) : ч[i]) : ''), '');

