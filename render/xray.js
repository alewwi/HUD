// Большой обхватывает с другой стороны: через верх ложится наискось у
// указательного. тон 'f' — её рука (тоньше, светлее), 'm' — его (крупнее,
// теплее, предплечье вверх-назад, к телу).
function кистьНаСтволе(x0, r, тон, id, W = тон === 'm' ? 50 : 25, кл = '') {
  const жен = тон === 'f', верх = -(r + 2.2), к = x0 + W, ш = W / 4;
  const зап = жен ? [к - W * .38, верх - 30] : [x0 + W * .36, верх - 32];
  const шз = жен ? 9.4 : 12, шп = жен ? 14 : 18;
  // Её предплечье уходит назад-вверх (к телу): левая и правая руки расходятся,
  // а не сходятся домиком над стволом.
  const даль = жен ? [зап[0] - 22, -130] : [зап[0] - 76, -130];
  // Низ: пальцы доходят до нижнего края ствола и уходят за него — обхватывают
  // с той стороны (кончиков не видно; у края — тень заворота, ниже). Мизинец — чуть выше.
  // Его пальцы длиннее: заходят за нижний край ствола и обхватывают его.
  const низ = жен ? [r - .2, r + .6, r + .8, r + .6] : [r + 2, r + 3.4, r + 3.8, r + 3];
  // Пальцы веером: к кончикам сходятся (у него сильнее — иначе кисть
  // брусок), костяшки — дугой: средний выше, мизинец ниже.
  const веер = жен ? .94 : .8, ц = (x0 + к) / 2, шк = ш * веер;
  const цх = (i) => ц + (x0 + ш * (i + .5) - ц) * веер - 1.4;   // середина пальца у кончика
  const выемка = (i) => (цх(i - 1) + цх(i)) / 2;                    // между кончиками i−1 и i
  const дуга = [1.4, .1, -.6, .3];
  // Кончик сужается: палец к концу уже, низ — пологий, почти по краю ствола
  // (палец уходит за ствол), а не круглая «сосиска».
  const кончик = (i) => { const h = шк * .34; return [[цх(i) - h, низ[i] - 1.2], [цх(i), низ[i]], [цх(i) + h, низ[i] - 1.2]]; };
  const контур = сглаженный([
    [даль[0] - шп, даль[1]], [зап[0] - шз, зап[1]], [x0 + W * .12, верх - 10], [x0 + .6, верх - 2.4],
    // Сторона мизинца — округлая, не отвесная стенка.
    [x0 - 1.4, -r * .3], [x0 - 2 + (цх(0) - шк / 2 - x0 + 1.4) * .5, r * .2], [цх(0) - шк / 2 - .6, r * .62], ...кончик(0), [выемка(1), Math.min(низ[0], низ[1]) - 3.8, 'у'],
    ...кончик(1), [выемка(2), Math.min(низ[1], низ[2]) - 3.8, 'у'],
    ...кончик(2), [выемка(3), Math.min(низ[2], низ[3]) - 3.8, 'у'],
    ...кончик(3), [цх(3) + шк / 2 - .2, низ[3] - 3.4], [(цх(3) + шк / 2 + к) / 2 + .4, r * .34], [к + 2.2, -r * .42, 'у'],
    // большой: из-под ладони ровно наискось вниз — вытянутый, с круглой
    // подушечкой на стволе у указательного.
    [к + 5, -r * .02], [к + 7, r * .36], [к + 8.6, r * .52], [к + 10.2, r * .36], [к + 11.4, r * .02], [к + 11.6, -r * .44], [к + 8, верх + .6], [к + 3, верх - 7.6],
    // Тыл ладони к запястью — плавной дугой, без излома.
    [зап[0] + шз, зап[1]], [даль[0] + шп, даль[1]],
  ]);
  // Бороздки между пальцами: от впадин между костяшками к впадинам у кончиков.
  const бороздки = [1, 2, 3].map(i => { const xa = x0 + ш * i, xb = выемка(i); return d`M${xa + .4} ${верх + 1 + (дуга[i - 1] + дуга[i]) / 2} C${xa - .2} ${-r * .3} ${(xa + xb) / 2} ${r * .45} ${xb} ${низ[i] - 3.4}`; }).join(' ');
  // Только средний сустав — одна мягкая складка на пальце (и костяшки, ниже).
  const морщинки = [0, 1, 2, 3].map(i => { const x = (x0 + ш * (i + .5) + цх(i)) / 2 - .4, w = ш * .26 * (1 + веер) / 2;
    return d`M${x - w} ${-r * .1} Q${x} ${-r * .1 + 1} ${x + w} ${-r * .1 - .2}`; }).join(' ');
  // Заворот за ствол: у нижнего края пальцы темнеют — уходят на ту сторону.
  const заворот = d`M${x0 - 4} ${r - 1.2} L${к + 1} ${r - 1.2}`;
  // Свет вдоль середины каждого пальца — цилиндр.
  const свет = [0, 1, 2, 3].map(i => { const x = x0 + ш * (i + .5); return d`M${x - .6} ${верх + 2} C${x - 1} ${-r * .2} ${x - 2} ${r * .4} ${цх(i) - .4} ${низ[i] - 4}`; }).join(' ');
  // Большой: граница с указательным — складка.
  const граньБ = d`M${к - .4} ${верх + 1.4} C${к + .6} ${-r * .7} ${к + 1.6} ${-r * .52} ${к + 2.2} ${-r * .42}`;
  // Большой — в стиле остальных: свет вдоль середины, складка на суставе,
  // бугорок сустава у основания.
  const Бx = (t) => (к + 5.6) + (к + 8.6 - (к + 5.6)) * t, Бy = (t) => (верх - 3) + (r * .42 - (верх - 3)) * t;
  const большой = `<path class="xr-hj-groove" d="${граньБ}"/><path class="xr-hj-sep" d="${граньБ}"/>`
    + `<path class="xr-vol-shine" d="${d`M${Бx(.08) - 1.2} ${Бy(.08)} L${Бx(.86) - 1} ${Бy(.86)}`}"/>`
    + `<path class="xr-crease" d="${d`M${Бx(.56) - 2.4} ${Бy(.56) - .8} Q${Бx(.56)} ${Бy(.56) + .6} ${Бx(.56) + 2.4} ${Бy(.56) - .4}`}"/>`
    + `<ellipse class="xr-hj-knuckle" cx="${ф(Бx(.14))}" cy="${ф(Бy(.14))}" rx="2.2" ry="1.5"/>`;
  const сухожилия = [0, 1, 2, 3].map(i => { const x = x0 + ш * (i + .5); return d`M${x + (зап[0] - x) * .55} ${верх - 14} Q${x + (зап[0] - x) * .2} ${верх - 7} ${x} ${верх - 1}`; }).join(' ');
  // Костяшки — выпуклые бугорки: свет на макушке, под ней — мягкая тень
  // (палец уходит вниз от сустава), между костяшками — ямки.
  const костяшки = [0, 1, 2, 3].map(i => { const x = x0 + ш * (i + .5), y = верх - .6 + дуга[i], w = ш * (жен ? .3 : .34);
    return `<path class="xr-hj-knuckle-sh" d="${d`M${x - w * 1.1} ${y + 1.4} Q${x} ${y + 3.6} ${x + w * 1.1} ${y + 1.4}`}"/>`
      + `<ellipse class="xr-hj-knuckle" cx="${ф(x - .3)}" cy="${ф(y - .2)}" rx="${ф(w)}" ry="${жен ? 1.4 : 1.9}"/>`; }).join('')
    + [1, 2, 3].map(i => `<ellipse class="xr-hj-dimple" cx="${ф(x0 + ш * i + .3)}" cy="${ф(верх + .6 + (дуга[i - 1] + дуга[i]) / 2)}" rx="1" ry="1.6"/>`).join('');
  // Пальцы раздельно: глубокие выемки между кончиками (выше) и чёткая линия
  // вдоль каждой бороздки — от костяшек до выемки.
  const внутри = `<path class="xr-vol-shine" d="${свет}"/><path class="xr-hj-groove" d="${бороздки}"/><path class="xr-hj-sep" d="${бороздки}"/><path class="xr-hj-tendon" d="${сухожилия}"/>${костяшки}<path class="xr-crease" d="${морщинки}"/><path class="xr-hj-wrap" d="${заворот}"/>${большой}`;
  // Красота: тёплый румянец на костяшках и подушечках (кожа там тоньше),
  // косточка запястья, едва видные венки на тыле, блик по краю предплечья;
  // под кистью — мягкая тень на стволе.
  const румянец = [0, 1, 2, 3].map(i => `<ellipse class="xr-hj-blush" cx="${ф(x0 + ш * (i + .5))}" cy="${ф(верх + 1.2)}" rx="${ф(ш * .42)}" ry="2.4"/><ellipse class="xr-hj-blush is-tip" cx="${ф(цх(i))}" cy="${ф(низ[i] - 2.6)}" rx="${ф(ш * .36)}" ry="2"/>`).join('')
    + `<ellipse class="xr-hj-blush is-tip" cx="${ф(к + 8.4)}" cy="${ф(r * .08)}" rx="2.6" ry="2.2"/>`;
  const косточка = `<ellipse class="xr-hj-bone" cx="${ф(зап[0] + (жен ? шз * .55 : -шз * .55))}" cy="${ф(зап[1] + 3)}" rx="2.6" ry="1.8"/>`;
  const вены = d`M${зап[0] - 2} ${зап[1] + 4} C${зап[0] - 3} ${верх - 16} ${x0 + ш * 1.6} ${верх - 10} ${x0 + ш * 1.4} ${верх - 3} M${зап[0] + 1} ${зап[1] + 6} C${зап[0] + 1} ${верх - 14} ${x0 + ш * 2.8} ${верх - 9} ${x0 + ш * 2.6} ${верх - 4}`;
  const блик = d`M${даль[0] - шп + 3} ${даль[1] + 4} C${зап[0] - шз + (даль[0] - зап[0]) * .45 + 2} ${зап[1] - 26} ${зап[0] - шз + 2} ${зап[1] - 4} ${x0 + W * .12} ${верх - 9}`;
  const красота = `<path class="xr-hj-vein" d="${вены}"/>${косточка}<path class="xr-hj-rimlight" d="${блик}"/>${румянец}`;
  const тень = `<ellipse class="xr-hj-cast" cx="${ф((x0 + к) / 2 + 2)}" cy="${ф(r * .2)}" rx="${ф(W * .62)}" ry="${ф(r * .9)}"/>`;
  return `<g class="xr-hj${жен ? ' is-f' : ' is-m'}${кл ? ' ' + кл : ''}">${тень}${объём(контур, id, '', красота + внутри)}</g>`;
}

