// Ключевые кадры hud-tk / hud-tk-ragged (css/scene-body.css) и их сглаживание.
// У ровного толчка выход трогается мягко с глубины и плавно замедляется к краю, вход — разгоном до удара:
// третье число — сглаживание отрезка, который начинается в этом кадре.
const КАДРЫ = [[0, 1, [.6, 0, .35, 1]], [.64, .12, [.5, 0, .85, .5]], [1, 1]];
const КАДРЫ_РВАНО = [[0, 1], [.14, .15], [.28, .75], [.40, .3], [.48, .6], [.72, .08], [1, 1]];
const ИЗГИБ = [.5, 0, .3, 1];
// Плавный ход по синусу — у трения и «дразнит» (как в css/scene-body.css).
const СИНУС = [.37, 0, .63, 1];
// Узоры толчка (темпИзТекста → т.узор) — те же кадры, что у hud-tk-<узор>
// в css/scene-body.css. × — во сколько раз цикл длиннее одного толчка,
// повторов — сколько циклов на волне.
//   tease — без проникновения: головкой по губам к клитору, кругами на нём,
//           два шлепка по клитору, вниз и два нажима на вход (волна — как у
//           трения: подъём головки, 0 — вход, 1 — клитор);
//   grind — в глубине, покачивание без хода;
//   build — толчки всё чаще, к концу цикла;
//   long  — медленный ход до самой головки и обратно до основания.
export const УЗОРЫ = {
  ragged: { кадры: КАДРЫ_РВАНО, x: 3, повторов: 1 },
  tease: { кадры: [[0, .04, СИНУС], [.2, 1, СИНУС], [.3, .9, СИНУС], [.4, 1, СИНУС], [.64, 1, СИНУС], [.78, .04], [1, .04]], x: 6, повторов: 1 },
  grind: { кадры: [[0, 1, [.37, 0, .63, 1]], [.5, .8, [.37, 0, .63, 1]], [1, 1]], x: 1.5, повторов: 2 },
  build: { кадры: [[0, 1], [.2, .12], [.36, 1], [.5, .16], [.62, 1], [.71, .2], [.79, 1], [.86, .24], [.92, 1], [.96, .3], [1, 1]], x: 4, повторов: 1 },
  long: { кадры: [[0, 1, [.6, 0, .35, 1]], [.6, .02, [.5, 0, .85, .5]], [1, 1]], x: 1.4, повторов: 2 },
  // Трётся у входа: на волне — не глубина, а ход по губам к клитору (--ry).
  // Вверх и вниз — ровно, по синусу; цикл в полтора толчка — без спешки.
  rub: { кадры: [[0, .04, СИНУС], [.5, 1, СИНУС], [1, .04]], x: 1.5, повторов: 2 },
};
/** Длина цикла анимации в толчках: у рваного и узоров — несколько толчков. */
export const длинаУзора = (т) => (т && УЗОРЫ[т.узор || (т.рвано ? 'ragged' : '')] || { x: 1 }).x;

function волна(т, id) {
  const рвано = !!(т && т.рвано), стоп = т && !т.уровень;
  const узор = т && УЗОРЫ[т.узор || (рвано ? 'ragged' : '')];
  const повторов = узор ? узор.повторов : 2;
  const x0 = 6, x1 = 234, верх = 5, низ = 27, ш = (x1 - x0) / повторов;
  const Y = (k) => низ - (низ - верх) * k;
  const кадры = узор ? узор.кадры : КАДРЫ;
  // Начало — первый кадр узора: «дразнит» начинается снаружи, а не с глубины.
  let путь = `M${x0} ${ф(Y(узор && !(т && т.фаза === 'climax') ? кадры[0][1] : 1))}`;
  const финал = т && т.фаза === 'climax';
  if (финал) {
    // Семь пульсаций, каждая слабее: 0.8 с, как у настоящего семяизвержения.
    const n = 7, шаг = (x1 - x0) / n;
    for (let i = 0; i < n; i++) {
      const xa = x0 + шаг * i, a = .5 * (1 - i / n) + .06;
      путь += ` L${ф(xa + шаг * .15)} ${ф(Y(1))} Q${ф(xa + шаг * .35)} ${ф(Y(1 - a))} ${ф(xa + шаг * .55)} ${ф(Y(1))}`;
    }
    путь += ` H${x1}`;
  } else if (стоп) путь += ` H${x1}`;
  else for (let r = 0; r < повторов; r++) {
    for (let i = 1; i < кадры.length; i++) {
      const [t0, k0, изг = ИЗГИБ] = кадры[i - 1], [t1, k1] = кадры[i];
      const X = (t) => x0 + ш * (r + t);
      // Тот же cubic-bezier, что у анимации: точка на волне = положение кончика.
      путь += ` C${ф(X(t0 + изг[0] * (t1 - t0)))} ${ф(Y(k0 + изг[1] * (k1 - k0)))} ${ф(X(t0 + изг[2] * (t1 - t0)))} ${ф(Y(k0 + изг[3] * (k1 - k0)))} ${ф(X(t1))} ${ф(Y(k1))}`;
    }
  }
  // Риски толчков — там, где кончик на глубине.
  let риски = '';
  if (финал) for (let i = 0; i < 7; i++) риски += `<path class="xr-wave-beat" d="M${ф(x0 + (x1 - x0) / 7 * (i + .35))} ${верх - 2} V${низ + 3}"/>`;
  if (!стоп) for (let r = 0; r < повторов; r++) кадры.forEach(([t, k], i) => {
    if (i === кадры.length - 1 && r < повторов - 1) return;
    if (k >= .6 && !(i > 0 && кадры[i - 1][1] >= .9 && k >= .9)) риски += `<path class="xr-wave-beat" d="M${ф(x0 + ш * (r + t))} ${верх - 2} V${низ + 3}"/>`;
  });
  // Точки на пиках: где кончик на глубине.
  let пики = '';
  if (!стоп) for (let r = 0; r < повторов; r++) кадры.forEach(([t, k], i) => {
    if (i === кадры.length - 1 && r < повторов - 1) return;
    if (k >= .6 && !(i > 0 && кадры[i - 1][1] >= .9 && k >= .9)) пики += `<circle class="xr-wave-peak" cx="${ф(x0 + ш * (r + t))}" cy="${ф(Y(k))}" r="1.5"/>`;
  });
  const сетка = [.25, .5, .75].map(у => `<path class="xr-wave-grid" d="M${x0} ${ф(Y(у))} H${x1}"/>`).join('');
  return `<svg class="xr-wave" viewBox="0 0 240 32" aria-hidden="true" style="--reps:${повторов}">
    <defs><linearGradient id="${id}-wf" x1="0" y1="0" x2="0" y2="1"><stop class="xr-wf0" offset="0"/><stop class="xr-wf1" offset="1"/></linearGradient></defs>
    ${сетка}<path class="xr-wave-base" d="M${x0} ${низ} H${x1}"/>${риски}
    <path class="xr-wave-fill" fill="url(#${id}-wf)" d="${путь} V${низ} H${x0} Z"/>
    <path class="xr-wave-glow" d="${путь}"/>
    <path class="xr-wave-line" d="${путь}"/>${пики}
    <g class="xr-wave-run"><g class="xr-wave-dot" style="--wy:${низ - верх}px">
      <path class="xr-wave-head" d="M${x0} ${верх - 2} V${низ + 3}"/><circle class="xr-wave-halo" cx="${x0}" cy="${верх}" r="5"/><circle cx="${x0}" cy="${верх}" r="2.6"/></g></g>
  </svg>`;
}

