  // по поверхности шейки от зева расползается белая плёнка.
  const ш = сцена.шейка;
  const струи = [[-2.2, 0], [0, .12], [2.2, .24]].map(([y, з]) => `<path class="xr-cum-jet" pathLength="100" d="${d`M${кончик + 1} ${y * .4} Q${(кончик + ш) / 2} ${y} ${ш + 2} ${y * .3}`}" style="--dl:${з}s"/>`).join('');
