// Средняя линия согнутой части: n звеньев, каждое повёрнуто на угол/n у своего
// начала. Возвращает точки от (x0, 0) и итоговый угол.
const ЗВЕНЬЯ = 12;
// Дуга длиной b − жёстко (гнётся ствол), дальше прямо — жёстко px (головка).
function дуга(x0, угол, b, жёстко = 0) {
  const pts = [[x0, 0]], дл = (b - жёстко) / ЗВЕНЬЯ;
  let x = x0, y = 0, а = 0;
  for (let i = 0; i < ЗВЕНЬЯ; i++) { а += угол / ЗВЕНЬЯ * Math.PI / 180; x += дл * Math.cos(а); y += дл * Math.sin(а); pts.push([x, y]); }
  if (жёстко) pts.push([x + жёстко * Math.cos(а), y + жёстко * Math.sin(а)]);
  return { pts, а };
}
// Полоса вдоль ломаной: смещение на ±w по нормали.
function полоса(pts, w) {
  const норм = (i) => { const [a, b] = [pts[Math.max(0, i - 1)], pts[Math.min(pts.length - 1, i + 1)]]; const dx = b[0] - a[0], dy = b[1] - a[1], l = Math.hypot(dx, dy) || 1; return [-dy / l, dx / l]; };
  const верх = pts.map((p, i) => { const n = норм(i); return [p[0] - n[0] * w, p[1] - n[1] * w]; });
  const низ = pts.map((p, i) => { const n = норм(i); return [p[0] + n[0] * w, p[1] + n[1] * w]; }).reverse();
  return 'M' + [...верх, ...низ].map(([x, y]) => ф(x) + ' ' + ф(y)).join(' L') + ' Z';
}
const ломаная = (pts) => 'M' + pts.map(([x, y]) => ф(x) + ' ' + ф(y)).join(' L');

