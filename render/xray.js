  // проходит к глотке и сгибается в неё — тем сильнее, чем глубже (--kb —
  // момент толчка, когда кончик доходит до глотки).
  // Пальцы ходят коротко (~0,8 см): главное движение — сгиб «иди сюда», а
  // не ход кисти; большой палец с кистью — одно целое и скользит по клитору.
  const ход = трётся ? 0 : И.пальцы ? кончик * .12 : изгиб ? Math.min(кончик - 20, кончик - сцена.глотка + 30) : Math.min(кончик * .58, Math.max(0, кончик - 8), 70);
