// Полупрозрачные напоминания игроку о близости: после потери, родов и свежей
// раны. Только на экран: в промпт и заметки модели это не идёт, сцену решает
// игрок. Сроки потери — в восстановлениеПосле() (render/conception.js).

import { escapeHtml } from '../utils.js?v=23.88.86';
import { settings } from '../settings.js?v=23.88.86';
import { полеВкл } from '../deep-fields.js?v=23.88.86';

/** После родов: обычный срок, когда врач смотрит и разрешает. */
export const ДНЕЙ_ПОСЛЕ_РОДОВ = 42;
/** Осложнение (операция, инфекция) добавляет к сроку после потери. */
export const ДНЕЙ_ОСЛОЖНЕНИЕ = 14;
// Зоны, где рана мешает близости: корпус и таз, а не рука или голова.
const ЗОНЫ = new Set(['chest', 'belly', 'waist', 'lowback', 'groin', 'buttocks', 'thighs']);
const ЗНАЧОК = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M12 20s-7.5-4.6-9.3-9.2A4.8 4.8 0 0 1 12 8a4.8 4.8 0 0 1 9.3 2.8C19.5 15.4 12 20 12 20z"/></svg>';

const вкл = (вид) => settings.enableRestHints !== false && полеВкл(settings, 'ui.rest.' + вид);
const напоминание = (текст) => `<div class="hud-rest-hint">${ЗНАЧОК}<span>${escapeHtml(текст)}</span></div>`;
/** вид — loss или birth: глубокая настройка выключает их по отдельности. */
export const подождатьДо = (дата, вид = 'loss') => (вкл(вид) ? напоминание(`Близость: лучше подождать до ${дата}`) : '');

/** Свежая или открывшаяся рана на корпусе. травма — решение карточки, что это не болезнь. */
export const мешаетБлизости = (б, травма) => !!(б && травма && ЗОНЫ.has(б.зона) && ['fresh', 'worsening'].includes(б.стадия && б.стадия.ключ));
export const больноПриБлизости = () => (вкл('wound') ? напоминание('Близость сейчас будет болезненной') : '');
