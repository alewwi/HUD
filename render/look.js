  let out = '';
  if (облик.щетина) out += `<path class="z-beard${облик.щетина === 'борода' ? ' is-full' : ''}" d="${облик.щетина === 'борода' ? 'M36.4 18 Q36.6 27.4 45 30.2 Q53.4 27.4 53.6 18 Q51 24.2 45 24.6 Q39 24.2 36.4 18Z' : 'M37.4 19.4 Q38.4 26.6 45 28.6 Q51.6 26.6 52.6 19.4 Q50.4 24.4 45 24.8 Q39.6 24.4 37.4 19.4Z'}"/>`;
  if (облик.веснушки) out += `<g class="z-freckles">${[[39.6, 19.4], [41, 18.6], [40.2, 20.6], [38.6, 18.8], [50.4, 19.4], [49, 18.6], [49.8, 20.6], [51.4, 18.8], [44.2, 18.4], [45.8, 18.4]].map(([x, y]) => `<circle cx="${x}" cy="${y}" r=".45"/>`).join('')}</g>`;
  if (облик.очки) out += '<g class="z-glasses"><rect x="37.4" y="13.2" width="6.6" height="4.6" rx="1.8"/><rect x="46" y="13.2" width="6.6" height="4.6" rx="1.8"/><path d="M44 15 Q45 14.2 46 15 M37.4 14.6 L35 13.8 M52.6 14.6 L55 13.8"/></g>';
