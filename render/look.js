// Ищем в кусках (по запятым и точкам), и не берём кусок, где перед словом
// в пределах двух слов стоит отрицание.
function найти(куски, rx) {
  for (const к of куски) {
    const м = к.match(rx);
    if (!м) continue;
    const до = к.slice(0, м.index).trim().split(/\s+/).slice(-2).join(' ');
    if (ОТРИЦАНИЕ.test(до)) continue;
    return { кусок: к, м };
  }
  return null;
}

