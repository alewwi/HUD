/**
 * Облик по нескольким «Внешностям» — от новой к старой. Каждое свойство —
 * голосованием (при равенстве — новее). Признаки-флаги и отметины берутся,
 * если встречались хотя бы дважды или в одном из трёх последних ходов:
 * разовое «рассечённая бровь» не становится шрамом навсегда, а татуировка,
 * названная пару раз за двадцать ходов, — остаётся. Татуировки и пирсинг
 * — постоянные по природе: им хватает одного упоминания.
 */
export function обликИзТекстов(тексты, { зона = () => null, канон = [] } = {}) {
  const разборы = (тексты || []).map(т => (Array.isArray(т) ? разобратьОблик(т[0], т[1], { зона }) : разобратьОблик(т, '', { зона })));
  // Канон — карточка персонажа или описание персоны: облик там описан всегда
  // и целиком. Голос карточки весит как три хода: случайная фраза в чате его
  // не перебьёт, а сюжет, повторённый несколько раз (перекрасилась, отрастила),
  // — перебьёт. Отметины и признаки из карточки постоянны: им хватает её одной.
  const каноны = (канон || []).filter(т => String(т || '').trim()).map(т => разобратьОблик(т, '', { зона, карточка: true }));
  const итог = { кожа: null, волосы: null, сложение: null, рост: null, очки: false, веснушки: false, щетина: null, виски: false, форма: null, отметины: [] };
  if (!разборы.length && !каноны.length) return итог;
  // Недавние ходы весят вдвое: волосы перекрасили — новое побеждает старое.
  const вес = (i) => (i < 20 ? 1 : 0.5);
  const ВЕС_КАНОНА = 3;
  const мода = (f) => {
    const счёт = new Map();
    const учесть = (v, w, i) => { if (v == null) return; const с = счёт.get(v) || { n: 0, i }; с.n += w; с.i = Math.min(с.i, i); счёт.set(v, с); };
    разборы.forEach((р, i) => учесть(f(р), вес(i), i));
    каноны.forEach((р) => учесть(f(р), ВЕС_КАНОНА, 1e6));
    let лучший = null;
    for (const [v, с] of счёт) if (!лучший || с.n > лучший.n || (с.n === лучший.n && с.i < лучший.i)) лучший = { v, ...с };
    return лучший ? лучший.v : null;
  };
  итог.кожа = мода(р => р.кожа);
  const цвет = мода(р => р.волосы && р.волосы.цвет);
  const длина = мода(р => р.волосы && р.волосы.длина);
  // Причёску меняют за вечер: пучок распустили — и в этом ходе волосы уже
  // «падают на плечи». Вид — из последнего хода, где о нём сказано (среди
  // трёх последних), и только без такого — по всей истории и карточке.
  const свежий = разборы.slice(0, 3).find(р => р.волосы && р.волосы.вид);
  const вид = свежий ? свежий.волосы.вид : мода(р => р.волосы && р.волосы.вид);
  if (цвет || длина || вид) итог.волосы = { цвет, длина, вид };
  итог.сложение = мода(р => р.сложение);
  // Рост — из последнего хода, где он назван, иначе из карточки.
  итог.рост = (разборы.find(р => р.рост) || каноны.find(р => р.рост) || {}).рост || null;
  const устойчиво = (f) => {
    if (каноны.some(f)) return true;
    const где = разборы.map((р, i) => f(р) ? i : -1).filter(i => i >= 0);
    return где.length >= 2 || (где.length === 1 && где[0] < 3);
  };
  // Форма тела — по каждому признаку отдельно; рельеф и вены — как флаги.
  {
    const ф = {};
    for (const к of ['плечи', 'талия', 'бёдра', 'грудь']) { const v = мода(р => (р.форма ? р.форма[к] : null) ?? null); if (v != null) ф[к] = v; }
    for (const к of ['рельеф', 'вены']) if (устойчиво(р => !!(р.форма && р.форма[к]))) ф[к] = true;
    итог.форма = Object.keys(ф).length ? ф : null;
  }
  итог.очки = устойчиво(р => р.очки);
  итог.веснушки = устойчиво(р => р.веснушки);
  итог.виски = устойчиво(р => р.виски);
  // Седые виски без описания волос — короткая стрижка с проседью: голова без
  // волос с серебром у ушей читалась как наушники.
  if (итог.виски && !итог.волосы) итог.волосы = { цвет: 'с проседью', длина: 'короткие', вид: null };
  итог.щетина = устойчиво(р => !!р.щетина) ? мода(р => р.щетина) : null;
  const отметины = new Map();
  const добавить = (о, i, изКанона) => {
    const к = о.зона + '|' + о.тип;
    const было = отметины.get(к);
    if (было) { было.n += 1; было.рукав = было.рукав || о.рукав; было.сетка = было.сетка || о.сетка; было.канон = было.канон || изКанона; } else отметины.set(к, { ...о, n: 1, i, канон: изКанона });
  };
  разборы.forEach((р, i) => р.отметины.forEach(о => добавить(о, i, false)));
  каноны.forEach(р => р.отметины.forEach(о => добавить(о, 1e6, true)));
  итог.отметины = [...отметины.values()]
    .filter(о => о.канон || о.n >= 2 || о.i < 3 || о.тип === 'tattoo' || о.тип === 'piercing')
    .sort((a, b) => b.n - a.n || a.i - b.i).slice(0, 10)
    .map(({ n, i, канон, ...о }) => о);
  return итог;
}

/** Ручной облик игрока (настройка userLook) поверх разобранного: ручное побеждает. */
export function сУчётомРучного(облик, ручной = {}) {
  const о = { ...облик, отметины: [...(облик.отметины || [])] };
  const тон = ручной.кожа === '' || ручной.кожа == null ? NaN : Number(ручной.кожа);
  if (Number.isInteger(тон) && тон >= 0 && тон <= 5) о.кожа = тон;
  // «Распущенные» (гладкие) — явное «без особой причёски»: вид снимается.
  if (ручной.волосы || ручной.длина || ручной.вид) о.волосы = { цвет: ручной.волосы || (о.волосы && о.волосы.цвет) || null, длина: ручной.длина || (о.волосы && о.волосы.длина) || null,
    вид: ручной.вид === 'гладкие' ? null : (ручной.вид || (о.волосы && о.волосы.вид) || null) };
  if (ручной.сложение) о.сложение = ручной.сложение;
  return о;
}

