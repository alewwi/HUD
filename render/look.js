// Сложение — масштаб по X всей группы стороны (силуэт, зоны, одежда), не
// одного контура: иначе одежда и пятна разошлись бы с телом.
export const МАСШТАБ_СЛОЖЕНИЯ = { хрупкое: 0.94, среднее: 1, крепкое: 1.06, пышное: 1.05 };
export const масштабСложения = (облик) => МАСШТАБ_СЛОЖЕНИЯ[облик && облик.сложение] || 1;
// Рост — масштаб по Y от ступней: 190 см и выше — во весь рост, 155 — на
// десятую ниже. Выше рамки фигура не растёт: голова не уходит за край.
export const масштабРоста = (облик) => {
  const р = облик && облик.рост;
  if (!р) return 1;
  return Math.round(Math.min(1, Math.max(0.9, 0.9 + (р - 155) / 35 * 0.1)) * 1000) / 1000;
};

/** Переменные стиля силуэта: тон кожи и цвет волос. */
export function стильОблика(облик) {
  if (!естьОблик(облик)) return '';
  const части = [];
  if (облик.кожа != null && ТОНА_КОЖИ[облик.кожа]) части.push(`--skin:${ТОНА_КОЖИ[облик.кожа]}`);
  const цвет = облик.волосы && облик.волосы.цвет && ЦВЕТА_ВОЛОС[облик.волосы.цвет];
  if (цвет) части.push(`--hair:${цвет}`);
  return части.join(';');
}

/* --- Отметины --------------------------------------------------------------
   Татуировка — орнамент по месту: «рукав» вдоль руки, узор на груди, на
   спине между лопатками, штрихи на шее и кистях. Шрам — зигзаг (сетка
   шрамов — несколько), ожог — неровное пятно, пирсинг — колечко, родинка —
   точка. Места — точки зон карты тела (ПЯТНА в intimacy.js). */
const шеврон = (x, y, w = 2.2) => `M${(x - w).toFixed(1)} ${(y - 1).toFixed(1)} L${x.toFixed(1)} ${(y + 0.6).toFixed(1)} L${(x + w).toFixed(1)} ${(y - 1).toFixed(1)}`;
const ТАТУ = {
  // Вдоль руки: сверху вниз шевроны и ромбы — «рукав»; без «забита» — короче.
  arms: (x, y, рукав) => {
    const от = рукав ? y - 16 : y - 7, до = рукав ? y + 18 : y + 7, шаг = рукав ? 3.4 : 4.4;
    const сдвиг = (yy) => (yy - y) * (x < 45 ? -0.09 : 0.09);
    let d = '';
    for (let yy = от, i = 0; yy <= до; yy += шаг, i++) d += (i % 3 === 2 ? `M${(x + сдвиг(yy)).toFixed(1)} ${(yy - 1.4).toFixed(1)} l1.4 1.4 -1.4 1.4 -1.4 -1.4Z ` : шеврон(x + сдвиг(yy), yy, рукав ? 2.6 : 2) + ' ');
    return `<path d="${d.trim()}"/>`;
  },
  chest: () => '<path d="M37.6 46.6 Q41.4 44 45 47.4 Q48.6 44 52.4 46.6 M41 49.4 Q45 52 49 49.4 M45 47.4 V53.4"/>',
  belly: () => '<path d="M41.4 76 Q45 72.4 48.6 76 Q45 79.6 41.4 76Z M45 72.4 V70.4 M45 79.6 V81.6"/>',
  back: () => '<path d="M45 44 V66 M37 49 Q41 53 45 50 Q49 53 53 49 M38.6 57 Q42 60 45 57.4 Q48 60 51.4 57 M41.4 63 Q45 65.6 48.6 63"/>',
  lowback: () => '<path d="M38 79 Q41.6 75.6 45 79 Q48.4 75.6 52 79 M41 82 Q45 84.4 49 82"/>',
  neck: () => '<path d="M47.8 29 l1.4 1.6 -1.4 1.6 M49.4 29.4 l1.2 1.2 -1.2 1.2"/>',
  nape: () => '<path d="M42.6 30.4 H47.4 M43.6 32.6 H46.4"/>',
  hands: (x, y) => `<path d="M${x - 1.6} ${y - 1.4} h3.2 M${x - 1.6} ${y + 0.4} h3.2"/>`,
  shoulders: (x, y) => `<path d="${шеврон(x, y - 1.6, 2.6)} ${шеврон(x, y + 1.2, 2.6)}"/>`,
  thighs: (x, y) => `<path d="M${x} ${y - 4} l2.2 4 -2.2 4 -2.2 -4Z"/>`,
  calves: (x, y) => `<path d="${шеврон(x, y - 2)} ${шеврон(x, y + 1.4)}"/>`,
};
const ЗНАК_ОТМЕТИНЫ = {
  scar: (x, y, о) => о.сетка
    ? `<path d="${[-6, -2, 2, 6].map((dx, i) => `M${x + dx - 2} ${y - 5 + i * 3} l4 -2.4`).join(' ')} M${x - 5} ${y + 5} l3.4 1.6 M${x + 2} ${y + 6} l3.6 -1.4"/>`
    : `<path d="M${x - 3} ${y - 1.4} l1.5 1.4 1.5-1.4 1.5 1.4 1.5-1.4"/>`,
  burn: (x, y) => `<path d="M${x - 2.2} ${y} q0.4 -2.2 2.4 -2 q2.4 0.2 2 2.4 q-0.2 2 -2.4 1.8 q-2.2 0 -2 -2.2Z"/>`,
  mole: (x, y) => `<circle cx="${x}" cy="${y}" r="1.1"/>`,
  piercing: (x, y) => `<circle cx="${x}" cy="${y}" r="1.6"/>`,
};
const ПОДПИСЬ = { scar: 'Шрам', tattoo: 'Татуировка', mole: 'Родинка', piercing: 'Пирсинг', burn: 'Ожог' };
// Пирсинг губы и родинку у губ — ровно у губ, а не сбоку от пятна зоны.
const ТОЧНО = { lips: { piercing: [46.6, 25.2], mole: [48.4, 21.4] }, ears: { piercing: [34.4, 19.6] } };
export function меткиОтметин(облик, сторона, пятна) {
  return (облик && облик.отметины || []).map(о => {
    const по = пятна[о.зона] || {};
    const подпись = `<title>${ПОДПИСЬ[о.тип]}: ${String(о.текст).replace(/[<>&"]/g, '')}</title>`;
    if (о.тип === 'tattoo' && ТАТУ[о.зона]) {
      // Татуировка — на каждой стороне, где эта зона есть (руки — с обеих).
      if (!по[сторона]) return '';
      const точки = по[сторона];
      const узор = ['chest', 'belly', 'back', 'lowback', 'neck', 'nape'].includes(о.зона) ? ТАТУ[о.зона]() : точки.map(([x, y]) => ТАТУ[о.зона](x, y, о.рукав)).join('');
      return `<g class="z-look-mark is-tattoo${о.рукав ? ' is-sleeve' : ''}">${узор}${подпись}</g>`;
    }
    const где = по.f ? 'f' : 'b';
    // Сетка шрамов на спине и шрамы на лопатках — сзади.
    const сторонаМетки = (о.зона === 'back' || о.зона === 'lowback' || о.зона === 'nape') ? 'b' : где;
    if (сторонаМетки !== сторона || !по[сторона]) return '';
    const точно = ТОЧНО[о.зона] && ТОЧНО[о.зона][о.тип];
    const [x, y] = точно || [по[сторона][0][0] + 6, по[сторона][0][1] - 4];
    const знак = ЗНАК_ОТМЕТИНЫ[о.тип] || ЗНАК_ОТМЕТИНЫ.mole;
    return `<g class="z-look-mark is-${о.тип}">${знак(x, y, о)}${подпись}</g>`;
  }).join('');
}

