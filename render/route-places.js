// hud-manager/render/route-places.js
//
// Общие места маршрутов героя и игрока. Схема маршрута ставит место по хэшу
// названия, и одна локация под разными подписями («квартира Лилиан» у игрока,
// «квартира Лилиан, гостиная» у героя) оказывалась в двух разных точках —
// будто они в разных местах, хотя стоят рядом. Здесь подписи сводятся к одной.
//
// Одно место, если:
//  · названия совпадают без регистра и знаков;
//  · одно название целиком входит в другое по словам («Кингсли-Тауэр» и
//    «Кингсли-Тауэр, пентхаус 45F»);
//  · оба были там в одно время (±15 минут) и в названиях есть общее
//    значимое слово («квартира Лилиан» и «квартира Лилиан на Садовой»).

const СЛУЖЕБНЫЕ = new Set(['в', 'во', 'на', 'у', 'к', 'с', 'со', 'из', 'от', 'до', 'по', 'за', 'под', 'над', 'и', 'около', 'возле', 'рядом', 'the', 'a', 'an', 'at', 'in', 'on', 'of', 'to', 'near']);
const норм = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/[«»"'`()[\]{}.,;:!?]/g, ' ').replace(/\s+/g, ' ').trim();
// Основа слова — первые 5 букв: «квартира/квартире», «коттеджа/коттедж».
const основы = (s) => норм(s).split(/[\s/–—-]+/).filter(w => w && !СЛУЖЕБНЫЕ.has(w) && (w.length > 2 || /\d/.test(w))).map(w => w.slice(0, 5));

function минуты(t) {
  const m = String(t || '').match(/(\d{1,2})[:.](\d{2})/);
  return m ? +m[1] * 60 + +m[2] : null;
}

const входит = (а, б) => а.length > 0 && а.every(w => б.includes(w));

/**
 * точкиА, точкиБ — разобранные точки маршрутов ({ time, place, … }).
 * Возвращает функцию (точка) → ключ места, общий для обоих маршрутов.
 */
export function общиеМеста(точкиА = [], точкиБ = []) {
  const все = [...(точкиА || []), ...(точкиБ || [])].filter(p => p && String(p.place || '').trim());
  // Канон — самое короткое из совпавших названий: оно обычно и есть «место»
  // («Кингсли-Тауэр»), а длинное — уточнение внутри него.
  const группы = [];
  const найти = (p) => {
    const н = норм(p.place), о = основы(p.place), м = минуты(p.time);
    for (const г of группы) {
      for (const q of г.точки) {
        const нq = норм(q.place), оq = основы(q.place), мq = минуты(q.time);
        if (н === нq) return г;
        // Дальше — только между маршрутами: внутри одного «Бостон» и
        // «автовокзал Бостона» — разные остановки пути.
        if (q.__из === p.__из) continue;
        if (входит(о, оq) || входит(оq, о)) return г;
        const вместе = м !== null && мq !== null && Math.abs(м - мq) <= 15;
        if (вместе && о.some(w => оq.includes(w))) return г;
      }
    }
    return null;
  };
  (точкиА || []).forEach(p => { if (p) p.__из = 'а'; });
  (точкиБ || []).forEach(p => { if (p) p.__из = 'б'; });
  for (const p of все) {
    const г = найти(p);
    if (г) г.точки.push(p); else группы.push({ точки: [p] });
  }
  const ключ = new Map();
  for (const г of группы) {
    const канон = г.точки.map(p => норм(p.place)).sort((a, b) => a.length - b.length)[0];
    г.точки.forEach(p => ключ.set(p, канон));
  }
  return (p) => (p && ключ.has(p) ? ключ.get(p) : норм(p && p.place));
}
