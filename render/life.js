const словаВещи = (s) => норм(s).split(' ').filter(w => w.length > 1);
export function слитьВещи(вещи) {
  const out = [...вещи].sort((a, b) => словаВещи(b.вещь).length - словаВещи(a.вещь).length);
  for (let i = out.length - 1; i >= 0; i--) {
    const к = словаВещи(out[i].вещь);
    if (!к.length) continue;
    const шире = out.filter((x, j) => j !== i && словаВещи(x.вещь).length > к.length && к.every(w => словаВещи(x.вещь).includes(w)));
    if (!шире.length) continue;
    const в = шире.sort((a, b) => b.t - a.t)[0], м = out[i];
    в.раз += м.раз; в.износ += м.износ; в.первый = Math.min(в.первый, м.первый);
    if (м.t > в.t) { в.t = м.t; в.состояние = м.состояние; в.текст = м.текст; в.грязное = м.грязное; }
    out.splice(i, 1);
  }
  return out;
}

