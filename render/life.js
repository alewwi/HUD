/**
 * Противоречия хода с журналом (hud-check.js, settings.hudConsistencyCheck):
 * HUD посчитал «не ели 7 ч», а модель пишет сытость высокой и про еду ни
 * слова; баланс сдвинулся без единой транзакции. Мягкий повод перегенерировать.
 */
export function противоречияБыта(chat, индекс) {
  if (!Array.isArray(chat) || !chat[индекс]) return [];
  const ж = журналБыта(chat, индекс);
  if (!ж) return [];
  let d = null;
  try { d = разобратьХод(chat[индекс]); } catch (_) { d = null; }
  if (!d) return [];
  const t = моментСцены(d.scene);
  const нет = [];
  const главный = (Array.isArray(d.characters) ? d.characters : []).find(c => c && c['Имя']);
  const sat = главный ? числоBs(поле(главный, 'Состояние тела'), 'sat') : null;
  const пам = d.memory || {};
  const елиСейчас = событияHk(пам.household).some(с => с.вид === 'eat') || событияТаймлайна(пам.timeline).some(с => с.вид === 'eat');
  const еда = ж.последнее('eat');
  if (t && еда && (t - еда.t) / Ч >= 7 && sat !== null && sat >= 70 && !елиСейчас) нет.push(`сытость ${sat} без еды (ели ${Math.round((t - еда.t) / Ч)} ч назад)`);
  const кош = (d.phone && d.phone.wallet) || (d.satchel && d.satchel.wallet) || null;
  const сейчасБаланс = кош ? Number(String(текст(кош.balance)).replace(/[\s ]/g, '').replace(',', '.')) : NaN;
  const былБаланс = Number(String(ж.деньги.баланс ?? '').replace(/[\s ]/g, '').replace(',', '.'));
  if (Number.isFinite(сейчасБаланс) && Number.isFinite(былБаланс) && Math.abs(сейчасБаланс - былБаланс) > Math.max(1, былБаланс * .01)) {
    const трх = Array.isArray(кош.transactions) ? кош.transactions.map(x => суммаТрх(x && x.amount)).filter(x => x !== null) : [];
    const новых = трх.filter(с => !ж.события.some(е => (е.вид === 'buy' || е.вид === 'income') && Math.abs(е.сумма - Math.abs(с)) < .01));
    if (!новых.length) нет.push(`баланс ${былБаланс} → ${сейчасБаланс} без транзакций`);
  }
  return нет.map(х => 'противоречие: ' + х);
}

