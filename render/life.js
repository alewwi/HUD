/** Сутки: последние 24 часа — сон полосой, быт значками, «сейчас» отметкой. */
function суткиБыта(ж) {
  const вид = видБыта('lifeDayView', ВИДЫ_СУТОК);
  if (вид === 'off') return '';
  const от = ж.сейчас - 24 * Ч;
  const события = ж.события.filter(с => с.t > от && с.t <= ж.сейчас + 60e3 && с.вид !== 'sleep');
  const ночь = ночьГлавного(ж);
  const сон = ночь && ночь.конец > от && ночь.начало < ж.сейчас ? { с: Math.max(от, ночь.начало), по: Math.min(ж.сейчас, ночь.конец), точно: ночь.точно } : null;
  if (!события.length && !сон) return '';
  const подсказка = (с) => `${чм(с.t)} · ${ИМЯ_СОБЫТИЯ(с.вид)}: ${с.что}${с.сумма ? ' — ' + деньги(с.сумма, ж.деньги.валюта) : ''}`;
  // Близкие по времени события — одной плашкой: один ход часто приносит и
  // еду, и покупку, и душ, и по отдельности значки ложились друг на друга.
  const группы = [];
  for (const с of [...события].sort((a, b) => a.t - b.t)) {
    const г = группы[группы.length - 1];
    if (г && с.t - г.по <= 75 * 60e3) { г.все.push(с); г.по = с.t; } else группы.push({ с: с.t, по: с.t, все: [с] });
  }
  for (const г of группы) {
    г.t = (г.с + г.по) / 2;
    г.виды = [...new Set(г.все.map(с => с.вид))];
    г.подсказка = г.все.map(подсказка).join('\n');
  }
  const плашка = (г) => `${г.виды.slice(0, 3).map(в => икоСобытия(в)).join('')}${г.все.length > 1 ? `<b>${г.все.length}</b>` : ''}`;
  const легенда = `<ul class="hud-life-day-legend">${сон ? `<li>${ико('moon')}<span>сон ${чм(сон.с)}–${чм(сон.по)}${сон.точно ? '' : ' (примерно)'}</span></li>` : ''}`
    + группы.slice(-4).reverse().map(г => `<li title="${escapeHtml(г.подсказка)}">${икоСобытия(г.виды[0])}<span><time>${чм(г.все[г.все.length - 1].t)}</time> ${escapeHtml(г.все.map(с => с.что).join(' · ').slice(0, 70))}</span></li>`).join('') + `</ul>`;
  if (вид === 'clock') {
    // Циферблат на 24 часа: полночь сверху, сон дугой, быт значками по кругу.
    const угол = (t) => (((t / Ч) % 24) / 24) * 2 * Math.PI;
    const точка = (t, r) => { const a = угол(t); return [50 + r * Math.sin(a), 50 - r * Math.cos(a)]; };
    const ф = (n) => n.toFixed(2);
    let дуга = '';
    if (сон) {
      const [x1, y1] = точка(сон.с, 37), [x2, y2] = точка(сон.по, 37);
      дуга = `<path class="sleep${сон.точно ? '' : ' is-approx'}" d="M${ф(x1)} ${ф(y1)} A37 37 0 ${(сон.по - сон.с) > 12 * Ч ? 1 : 0} 1 ${ф(x2)} ${ф(y2)}"><title>Сон ${чм(сон.с)}–${чм(сон.по)}</title></path>`;
    }
    const деления = Array.from({ length: 24 }, (_, h) => { const [x1, y1] = точка(h * Ч, 45), [x2, y2] = точка(h * Ч, h % 6 ? 43 : 41); return `<line class="${h % 6 ? '' : 'is-major'}" x1="${ф(x1)}" y1="${ф(y1)}" x2="${ф(x2)}" y2="${ф(y2)}"/>`; }).join('')
      + [0, 6, 12, 18].map(h => { const [tx, ty] = точка(h * Ч, 30.5); return `<text x="${ф(tx)}" y="${ф(ty)}">${String(h).padStart(2, '0')}</text>`; }).join('');
    const [sx, sy] = точка(ж.сейчас, 33);
    const значки = группы.map((г, i) => {
      const [x, y] = точка(г.t, i % 2 ? 19 : 25);
      return `<g class="ev" transform="translate(${ф(x)} ${ф(y)})"><title>${escapeHtml(г.подсказка)}</title><circle r="5.2"/><path transform="translate(-3.3 -3.3) scale(.275)" d="${ИКОНКИ[ИКОНКА_СОБЫТИЯ[г.виды[0]]] || ИКОНКИ.diamond}"/>`
        + (г.все.length > 1 ? `<circle class="n" cx="4.2" cy="-4.2" r="2.6"/><text class="n" x="4.2" y="-4.2">${г.все.length}</text>` : '') + `</g>`;
    }).join('');
    return `<div class="hud-life-day is-clock"><svg class="hud-life-dial" viewBox="0 0 100 100" role="img" aria-label="Сутки: сон и быт">`
      + `<defs><radialGradient id="hud-life-dial-g" cx=".35" cy=".3" r=".8"><stop offset="0" stop-color="rgba(255,255,255,.1)"/><stop offset="1" stop-color="rgba(0,0,0,.25)"/></radialGradient></defs>`
      + `<circle class="bezel" cx="50" cy="50" r="48"/><circle class="face" cx="50" cy="50" r="46" fill="url(#hud-life-dial-g)"/><circle class="track" cx="50" cy="50" r="37"/><g class="ticks">${деления}</g>${дуга}`
      + `<line class="hand" x1="50" y1="50" x2="${ф(sx)}" y2="${ф(sy)}"/><circle class="hub" cx="50" cy="50" r="2.4"/>${значки}</svg>${легенда}</div>`;
  }
  // Лента: слева — сутки назад, справа — сейчас.
  const x = (t) => Math.max(0, Math.min(100, (t - от) / (24 * Ч) * 100)).toFixed(2);
  const метки = [];
  // Метки у правого края не ставим: там подпись «сейчас».
  for (let t = Math.ceil(от / (3 * Ч)) * 3 * Ч; t <= ж.сейчас - 5.5 * Ч; t += 3 * Ч) метки.push(`<span class="hud-life-day-tick${new Date(t).getUTCHours() % 6 ? ' is-minor' : ''}" style="left:${x(t)}%">${new Date(t).getUTCHours() % 6 ? '' : чм(t)}</span>`);
  // Плашки у краёв прижимаются внутрь: у правого края — линия «сейчас».
  // Соседние ближе 15% — одна выше, другая ниже середины.
  группы.forEach((г, i) => {
    г.п = +x(г.t); г.ряд = '';
    const пред = группы[i - 1];
    if (пред && г.п - пред.п < 15) { if (!пред.ряд) пред.ряд = ' r1'; г.ряд = пред.ряд === ' r1' ? ' r2' : ' r1'; }
  });
  const значки = группы.map(г => {
    const край = г.п > 90 ? ' is-end' : г.п < 6 ? ' is-start' : '';
    const место = г.п > 90 ? 'right:8px' : г.п < 6 ? 'left:2px' : `left:${г.п}%`;
    return `<span class="hud-life-day-ev${г.ряд}${край}${г.все.length > 1 ? ' is-many' : ''}" style="${место}" title="${escapeHtml(г.подсказка)}">${плашка(г)}</span>`;
  }).join('');
  const полоса = сон ? `<span class="hud-life-day-sleep${сон.точно ? '' : ' is-approx'}" style="left:${x(сон.с)}%;width:${(x(сон.по) - x(сон.с)).toFixed(2)}%" title="Сон ${чм(сон.с)}–${чм(сон.по)}${сон.точно ? '' : ' (примерно)'}">${ико('moon')}</span>` : '';
  return `<div class="hud-life-day is-strip" role="img" aria-label="Последние сутки"><div class="hud-life-day-track"><i class="hud-life-day-sky"></i>${полоса}${значки}<span class="hud-life-day-now" title="Сейчас ${чм(ж.сейчас)}"></span></div>`
    + `<div class="hud-life-day-ticks">${метки.join('')}<span class="hud-life-day-tick is-now" style="left:100%">сейчас ${чм(ж.сейчас)}</span></div>${легенда}</div>`;
}

/** Гардероб: бирки, вешалка или список; у вещи — значок вида, цвет и ткань. */
function гардеробБыта(ж) {
  const вид = видБыта('wardrobeView', ВИДЫ_ГАРДЕРОБА);
  const метки = (в) => [в.наСебе ? 'на себе' : '', в.вСтирке ? 'в стирке' : '', в.износилось ? 'потрёпано' : '', в.неПоПогоде ? 'не по погоде' : ''].filter(Boolean);
  const классы = (в) => `${в.наСебе ? ' is-on' : ''}${в.вСтирке ? ' is-dirty' : ''}${в.износилось ? ' is-worn' : ''}${в.неПоПогоде ? ' is-weather' : ''}`;
  const подсказка = (в) => [в.текст || в.вещь, ТКАНИ[в.ткань] || '', `надевали ${в.раз} ${склон(в.раз, ['раз', 'раза', 'раз'])}`].filter(Boolean).join(' · ');
  const цвет = (в) => (в.цвет ? ` style="--wc:${escapeHtml(в.цвет)}"` : '');
  const значок = (в) => ико(ИКОНКА_ВЕЩИ[в.вид] || 'shirt');
  const люди = ж.гардероб.filter(г => г.вещи.length).map(г => {
    const вещи = г.вещи.slice(0, 14);
    const на = г.вещи.filter(в => в.наСебе).length;
    const шапка = `${лицоБыта(г.имя)}<b>${escapeHtml(г.имя)}</b><small>${г.вещи.length} ${склон(г.вещи.length, ['вещь', 'вещи', 'вещей'])}${на ? ` · на себе ${на}` : ''}</small>`;
    let тело;
    if (вид === 'rail') {
      тело = `<div class="hud-life-rail">${вещи.map(в => `<span class="hud-life-hanger${классы(в)}"${цвет(в)} title="${escapeHtml(подсказка(в))}">`
        + `<svg viewBox="0 0 44 54" aria-hidden="true"><path class="hook" d="M22 10 V7 a3 3 0 1 1 3 -3"/><path class="bar" d="M22 10 L5 21 H39 Z"/><path class="cloth" d="M8 21 H36 L38 50 Q22 54 6 50 Z"/><path class="fold" d="M22 21 V50"/></svg>`
        + `<i aria-hidden="true">${значок(в)}</i><span>${escapeHtml(в.вещь)}</span>${метки(в).length ? `<small>${метки(в).join(' · ')}</small>` : ''}</span>`).join('')}</div>`;
    } else if (вид === 'list') {
      тело = `<ul class="hud-life-wlist">${вещи.map(в => `<li class="${классы(в).trim()}"${цвет(в)} title="${escapeHtml(подсказка(в))}">${значок(в)}<s></s><span>${escapeHtml(в.вещь)}</span><small>${метки(в).join(' · ') || escapeHtml(сколькоПрошло(в.t, ж.сейчас))}</small></li>`).join('')}</ul>`;
    } else {
      тело = `<div class="hud-life-items">${вещи.map(в => `<span class="hud-life-item${классы(в)}"${цвет(в)} title="${escapeHtml(подсказка(в))}"><s></s>${значок(в)}<span><b>${escapeHtml(в.вещь)}</b>${метки(в).length ? `<small>${метки(в).join(' · ')}</small>` : ''}</span></span>`).join('')}</div>`;
    }
    return `<div class="hud-life-wardrobe"><div class="hud-life-wardrobe-head">${шапка}</div>${тело}</div>`;
  }).join('');
  const погода = ж.неПоПогоде.length ? `<p class="hud-life-alert is-cold">${ико('thermo')}<span>${ж.неПоПогоде.map(н => `<b>${escapeHtml(н.кто)}</b> — ${escapeHtml(н.что)}`).join('; ')}</span></p>` : '';
  return погода + люди;
}

const ИКОНКА_КАТЕГОРИИ = { еда: 'fork', транспорт: 'run', одежда: 'hanger' };
function деньгиБыта(ж) {
  const вал = ж.деньги.валюта;
  const баланс = ж.деньги.баланс ? `<div class="hud-life-wallet"><i class="hud-life-wallet-chip" aria-hidden="true"></i><span class="hud-life-wallet-cap">${ико('wallet')}На счету</span><b>${escapeHtml(балансСловами(ж.деньги))}</b>`
    + (ж.хватит.length ? `<div class="hud-life-afford">${ж.хватит.map(х => `<span title="средняя покупка ~${деньги(х.средняя, вал)}">${ико(ИКОНКА_КАТЕГОРИИ[х.кат] || 'bag')}≈ ${х.раз.toLocaleString('ru-RU').replace(/\s/g, ' ')} ${склон(х.раз, х.чего)}<small>по ~${деньги(х.средняя, вал)}</small></span>`).join('')}</div>` : '') + `</div>` : '';
  const макс = Math.max(1, ...ж.траты.map(т => т.сумма));
  const всего = ж.траты.reduce((s, т) => s + т.сумма, 0);
  const траты = всего ? `<div class="hud-life-spend-box"><div class="hud-life-spend-cap"><span>${ико('receipt')}Траты за 7 дней</span><b class="hud-v-num">${деньги(всего, вал)}</b></div><div class="hud-life-spend">${ж.траты.map((т, i) => `<span class="${i === ж.траты.length - 1 ? 'is-today' : ''}${т.сумма === макс ? ' is-max' : ''}" style="--h:${(т.сумма / макс).toFixed(2)}" title="${escapeHtml(дм(т.сутки) + ': ' + деньги(т.сумма, вал))}"><i></i><small>${ДНИ[new Date(т.сутки).getUTCDay()]}</small></span>`).join('')}</div></div>` : '';
  const цены = ж.деньги.цены.length ? `<details class="hud-life-prices-box"${ж.деньги.цены.length <= 4 ? ' open' : ''}><summary>${ико('bag')}Знакомые цены <small>${ж.деньги.цены.length}</small></summary><ul class="hud-life-prices">${ж.деньги.цены.slice(0, 8).map(ц => `<li><span>${escapeHtml(ц.что)}</span><i></i><b>${деньги(ц.сумма, вал)}</b></li>`).join('')}</ul></details>` : '';
  const долги = ж.долги.length ? `<div class="hud-life-debts-wrap"><span class="hud-life-sub">${ико('chain')}Долги и обязательства</span><ul class="hud-life-debts">${ж.долги.map(д => `<li class="${д.грамота ? 'is-paper' : ''}">${медаль(д.грамота ? 'scroll' : 'chain')}<span><b>${escapeHtml(д.что)}</b>${д.кто ? `<small>${escapeHtml(д.кто)}</small>` : ''}</span>${д.сумма && !/\d/.test(д.что) ? `<b class="hud-v-num">${деньги(д.сумма)}</b>` : ''}${д.срок && !д.что.includes(д.срок) ? `<em class="hud-v-tag">до ${escapeHtml(д.срок)}</em>` : ''}</li>`).join('')}</ul></div>` : '';
  return баланс + траты + цены + долги;
}

export function buildLifeHTML(ж, uid, active) {
  if (!ж) return '';
  const раздел = (ик, заголовок, тело, доп = '') => тело ? `<section class="hud-v-card hud-life-sec"><div class="hud-v-head"><b>${медаль(ик)}${заголовок}</b>${доп ? `<span>${доп}</span>` : ''}</div>${тело}</section>` : '';
  // Голод: причина и следствие.
  const г = ж.голод;
  const голод = г ? `<p class="hud-life-alert">${ико('alert')}<span><b>Сытость ${г.sat}</b>${г.часов !== null ? ` — последний раз ели ${Math.round(г.часов)} ч назад` : ' — когда ели, в истории нет'}${г.силыБыло !== null && г.силы !== null && г.силыБыло - г.силы >= 10 ? `; силы упали с ${г.силыБыло} до ${г.силы}` : ''}</span></p>` : '';
  // Еда: последние приёмы — лентой с точками, догадка по сытости — пунктиром.
  const еды = ж.события.filter(с => с.вид === 'eat').slice(-6).reverse().map(с => `<li class="${с.источник === 'sat' ? 'is-guess' : ''}"><time>${escapeHtml(сколькоПрошло(с.t, ж.сейчас))}</time><span>${escapeHtml(с.что)}${с.сытость ? `<small>сытость ${с.сытость[0]} → ${с.сытость[1]}</small>` : ''}</span></li>`).join('');
  const любимое = ж.любимое.length ? `<div class="hud-life-fav"><span class="hud-life-sub">${ико('heart')}Любимое</span>${ж.любимое.map(([б, n]) => `<span class="hud-v-tag" title="${n} ${склон(n, ['раз', 'раза', 'раз'])}">${escapeHtml(б)} ×${n}</span>`).join('')}</div>` : '';
  // Сон: столбики ночей с линией нормы; ночь со сном — луной со звездой.
  const сон = ж.сон.map(с => {
    const полосы = с.ночи.map(н => `<span class="hud-life-night${н.часов < ж.норма - 1 ? ' is-short' : ''}${н.сон ? ' has-dream' : ''}" style="--h:${Math.min(1, н.часов / 12).toFixed(2)}" title="${escapeHtml(дм(н.сутки) + ': ' + н.текст + (н.сон ? ' · снилось: ' + н.сон : ''))}"><i></i><small>${часы(н.часов)}</small>${н.сон ? `<b>${ико('moonstar')}</b>` : ''}<em>${ДНИ[new Date(н.сутки).getUTCDay()]}</em></span>`).join('');
    const долг = с.долг >= 1 ? `<span class="hud-v-tag${с.долг >= 3 ? ' s5' : ''}">долг ${часы(с.долг)}</span>` : `<span class="hud-v-tag">высыпается</span>`;
    return `<div class="hud-life-sleep"><div class="hud-life-sleep-head">${лицоБыта(с.имя)}<b>${escapeHtml(с.имя)}</b>${долг}</div><div class="hud-life-nights" style="--norm:${(ж.норма / 12).toFixed(2)}">${полосы}</div></div>`;
  }).join('');
  const ночиСнов = ж.сныНочей.filter(с => !ж.сон.some(x => x.ночи.some(н => н.сутки === с.сутки)));
  const сны = ночиСнов.length ? `<ul class="hud-life-dreams">${ночиСнов.map(с => `<li>${ико('moonstar')}<time>${дм(с.сутки)}</time><span>${escapeHtml(с.текст.length > 90 ? с.текст.slice(0, 90) + '…' : с.текст)}</span></li>`).join('')}</ul>` : '';
  // Дом.
  const д = ж.дом;
  const строкаДома = (ик, кл, подпись, текст) => `<li class="${кл}">${ико(ик)}<span><small>${подпись}</small>${текст}</span></li>`;
  const дом = (д.место || д.сломано.length || д.закончилось.length || д.уборка) ? `<ul class="hud-life-home">`
    + (д.место ? строкаДома('house', 'is-home', 'ночуют здесь', `<b>${escapeHtml(д.место)}</b> · ${д.ночей} ${склон(д.ночей, ['раз', 'раза', 'раз'])}`) : '')
    + (д.сломано.length ? строкаДома('alert', 'is-broken', 'сломано', д.сломано.slice(-4).map(с => escapeHtml(с.что)).join('; ')) : '')
    + (д.закончилось.length ? строкаДома('box', 'is-out', 'закончилось', д.закончилось.map(с => escapeHtml(с.что)).join('; ')) : '')
    + (д.уборка ? строкаДома('broom', '', 'уборка', escapeHtml(сколькоПрошло(д.уборка.t, ж.сейчас))) : '') + `</ul>` : '';
  const сутки = суткиБыта(ж);
  const норма = `норма ${ж.норма} ч`;
  return `<div class="hud-tab-content${active ? ' active' : ''}" id="content-${uid}"><div class="hud-body hud-life hud-v">`
    + сводкаБыта(ж) + таймерыБыта(ж)
    + (сутки ? раздел('clock', 'Сутки', сутки, 'последние 24 часа') : '')
    + раздел('fork', 'Еда', голод + (еды ? `<ul class="hud-life-meals">${еды}</ul>` : '') + любимое)
    + раздел('bed', 'Сон', сон + сны, норма)
    + раздел('hanger', 'Гардероб', гардеробБыта(ж))
    + раздел('wallet', 'Деньги', деньгиБыта(ж))
    + раздел('house', 'Дом', дом)
    + `</div></div>`;
}
