// Последняя ночь главного: для сводки и полосы сна в сутках.
function ночьГлавного(ж) {
  const с = ж.сон.find(x => x.имя === ж.главный) || ж.сон[0];
  if (!с || !с.ночи.length) return null;
  const н = с.ночи[с.ночи.length - 1];
  // Когда спал: «легла в 03:20» — от этого времени; без него — до 07:00 утра той ночи.
  const м = String(н.легла || '').match(/(\d{1,2})[:.](\d{2})/);
  let начало;
  if (м) { начало = н.сутки + (+м[1] * 60 + +м[2]) * 60e3; if (+м[1] >= 15) начало -= СУТКИ; }
  else начало = н.сутки + 7 * Ч - н.часов * Ч;
  return { ...н, имя: с.имя, долг: с.долг, начало, конец: начало + н.часов * Ч, точно: !!м };
}

