/** hk: «eat: завтрак, овсянка, дома, одна; buy: кофе 450» → [{ вид, что, сумма }]. */
export function событияHk(значение) {
  const s = Array.isArray(значение) ? значение.join('; ') : текст(значение);
  if (пусто(s)) return [];
  return s.split(/;/).map(ч => ч.trim()).filter(Boolean).map(ч => {
    const м = ч.match(/^([a-z]{2,6})\s*[:：]\s*(.+)$/i);
    if (!м) return null;
    const вид = видHk(м[1], м[2]);
    if (!вид) return null;
    const что = м[2].trim();
    const деньги = что.match(/(-?\d[\d\s]*(?:[.,]\d+)?)\s*(?:₽|руб|р\.|\$|€|£|¥|usd|eur)?\s*$/i);
    return { вид, что, сумма: вид === 'buy' && деньги ? Math.abs(parseFloat(деньги[1].replace(/\s/g, '').replace(',', '.'))) : null };
  }).filter(Boolean);
}
