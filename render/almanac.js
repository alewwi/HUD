/** Дни святых года: [{ имя, модели, дата }]. */
export function святыеГода(год, православные = православныйМир()) {
  return СВЯТЫЕ.filter(([, , , , т]) => !т || (т === 'o') === православные)
    .map(([м, ч, имя, модели]) => ({ имя, модели, дата: православные ? юл(год, м, ч) : д(год, м, ч) }));
}
export function святойДня(ms, православные = православныйМир()) {
  if (!Number.isFinite(ms)) return null;
  return святыеГода(new Date(ms).getUTCFullYear(), православные).find(с => с.дата === ms) || null;
}

// Сезон работ по месяцу (северный год): что делают в деревне.
const СЕЗОНЫ = ['прядут и чинят утварь, рубят лес', 'готовят семена и сохи', 'пашут', 'сеют яровые', 'выгоняют скот на пастбище', 'косят сено',
  'сенокос и прополка', 'жатва', 'молотьба и сбор яблок', 'сбор винограда, сев озимых', 'забой скота и засолка', 'прядут и ремесленничают у очага'];
export const сезонРабот = (ms) => (Number.isFinite(ms) ? СЕЗОНЫ[new Date(ms).getUTCMonth()] : '');

const склон = (n, а, б, в) => { const к = Math.abs(n) % 100, е = к % 10; return к > 10 && к < 20 ? в : е === 1 ? а : е >= 2 && е <= 4 ? б : в; };
/** Части строки «Сегодня»: пост (или постный день), святой, сезон работ. */
export function частиСегодня(ms, православные = православныйМир()) {
  if (!Number.isFinite(ms)) return [];
  const out = [];
  const пост = постДня(ms, православные);
  if (пост) { const ещё = Math.round((пост.до - ms) / ДЕНЬ); out.push(ещё > 0 ? `${пост.имя} · ещё ${ещё} ${склон(ещё, 'день', 'дня', 'дней')}` : `${пост.имя} · последний день`); }
  else { const нд = new Date(ms).getUTCDay(); if (нд === 3 || нд === 5) out.push(нд === 3 ? 'постная среда' : 'постная пятница'); }
  const святой = святойДня(ms, православные);
  if (святой) out.push(святой.имя);
  const сезон = сезонРабот(ms);
  if (сезон) out.push(сезон);
  return out;
}

/** Строка модели в дни многодневного поста (настройка medievalFastNote, по умолчанию выключена). */
export function заметкаПоста(ms) {
  if (!святцыВкл() || settings.medievalFastNote !== true || !Number.isFinite(ms)) return '';
  const пост = постДня(ms);
  if (!пост) return '';
  const ещё = Math.round((пост.до - ms) / ДЕНЬ);
  return `It is ${пост.модели}${ещё > 0 ? ` (${ещё} more ${ещё === 1 ? 'day' : 'days'})` : ', its last day'}: the devout avoid meat and feasting, and weddings are not held. Let it show where it fits; never force it.`;
}
