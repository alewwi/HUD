// Святцы средневековья: посты, дни святых и сезон работ — HUD считает сам по
// дате сцены, модель ничего не пишет (настройка medievalAlmanac).
//
//   · посты — Великий (от Пасхи), Рождественский / Адвент, у православных
//     Петров и Успенский; постные среда и пятница — только в строке «Сегодня»;
//   · дни святых — около тридцати общеизвестных, своим календарём «Святые»;
//   · сезон работ — по месяцу: пахота, сев, сенокос, жатва, забой скота…
//
// Православные даты — юлианские, как у пасхи (render/holidays.js): с 1583
// года они переводятся в григорианский календарь, раньше остаются как есть.
// В фэнтези с явной магией (ларец чародея) и в приземлённом фэнтези (сутки
// по двенадцати зверям) церкви нет — святцев тоже.
//
// По желанию — одна строка модели в дни многодневного поста
// (medievalFastNote).

import { settings } from '../settings.js?v=23.89.75';
import { старина, явнаяМагия, приземлённое } from '../era.js?v=23.89.75';
import { пасхаЗападная, пасхаПравославная, православныйМир } from './holidays.js?v=23.89.75';

const ДЕНЬ = 864e5;
// Мир старых богов («Вера мира», render/medieval-life.js) — без святых и постов.
export const святцыВкл = () => старина() && !явнаяМагия() && !приземлённое() && settings.medievalAlmanac !== false && settings.medFaithWorld !== 'old';
const сдвигЮлианский = (год) => (год >= 1583 ? Math.floor(год / 100) - Math.floor(год / 400) - 2 : 0);
/** Юлианская дата православного календаря → UTC полночь (с переводом после 1583). */
const юл = (год, месяц, число) => Date.UTC(год, месяц - 1, число + сдвигЮлианский(год));
const д = (год, месяц, число) => Date.UTC(год, месяц - 1, число);

/** Многодневные посты года: [{ имя, модели, от, до }] (UTC полночь, включительно). */
export function постыГода(год, православные = православныйМир()) {
  const п = православные ? пасхаПравославная(год) : пасхаЗападная(год);
  const пасха = д(год, п.месяц, п.число);
  if (православные) {
    // Рождественский пост начинается в ноябре этого года и идёт до Сочельника
    // следующего: в январе этого года — хвост прошлогоднего.
    return [
      { имя: 'Рождественский пост', модели: 'the Nativity Fast', от: юл(год - 1, 11, 15), до: юл(год - 1, 12, 24) },
      { имя: 'Великий пост', модели: 'Great Lent', от: пасха - 48 * ДЕНЬ, до: пасха - ДЕНЬ },
      { имя: 'Петров пост', модели: "the Apostles' Fast", от: пасха + 57 * ДЕНЬ, до: юл(год, 6, 28) },
      { имя: 'Успенский пост', модели: 'the Dormition Fast', от: юл(год, 8, 1), до: юл(год, 8, 14) },
      { имя: 'Рождественский пост', модели: 'the Nativity Fast', от: юл(год, 11, 15), до: юл(год, 12, 24) },
    ].filter(с => с.до >= с.от);
  }
  // Адвент — с четвёртого воскресенья перед Рождеством до Сочельника.
  const адвент = (г) => { const рожд = new Date(д(г, 12, 25)); const нед = рожд.getUTCDay() || 7; return д(г, 12, 25) - (нед + 21) * ДЕНЬ; };
  return [
    { имя: 'Великий пост', модели: 'Lent', от: пасха - 46 * ДЕНЬ, до: пасха - ДЕНЬ },
    { имя: 'Адвент', модели: 'Advent', от: адвент(год), до: д(год, 12, 24) },
  ];
}
/** Пост, который идёт в этот день, или null. */
export function постДня(ms, православные = православныйМир()) {
  if (!Number.isFinite(ms)) return null;
  const год = new Date(ms).getUTCFullYear();
  for (const п of постыГода(год, православные)) if (ms >= п.от && ms <= п.до) return п;
  return null;
}

// Дни святых: [месяц, число, имя, модели, традиция: 'w' западная, 'o' православная, '' обе].
