// hud-manager/render/life-combat.js
//
// Бой → быт: последствия, которые живут днями.
//
// Бой — срез хода (cb), он намеренно не копится, и «неделю назад была
// схватка» из него не узнать. Поэтому бой оставляет запись в журнале быта —
// как еда и душ, — а последствия считает быт из своего журнала: ни новой
// строки в промте, ни нового хранилища. Раны копятся сами: они в «Болезнях и
// травмах» с зоной (zn) и переносятся между ходами.
//
// Модель о последствиях не вспомнит: что с зашитым предплечьем нельзя под
// душ, что ночь после схватки короткая, что после боя кусок в горло не лезет.

import { settings } from '../settings.js?v=23.48.1';
import { flattenFieldValue, снятьЗаглушки } from '../utils.js?v=23.48.1';
import { namesLikelySame } from '../names.js?v=23.48.1';

const Ч = 3600e3, СУТКИ = 864e5;
const текст = (v) => (v === null || v === undefined ? '' : String(снятьЗаглушки(flattenFieldValue(v)) || '')).trim();
const пусто = (s) => !s || /^(empty|none|нет|—|-|null)$/i.test(String(s).trim());
const поле = (о, имя) => {
  if (!о || typeof о !== 'object') return '';
  const ключ = Object.keys(о).find(k => k.toLowerCase() === имя.toLowerCase());
  return ключ ? текст(о[ключ]) : '';
};
const имяКоротко = (имя) => String(имя || '').replace(/^.*\s{2,}/, '').trim();

// Какая зона чему мешает. Это и есть вся фича.
export const МЕШАЕТ = {
  'предплечье': ['мыться', 'нести'],
  'кисть': ['мыться', 'одеваться', 'нести'],
  'плечо': ['одеваться через голову', 'нести'],
  'шея': ['поворачивать голову'],
  'грудь': ['глубоко дышать', 'спать на животе'],
  'живот': ['есть помногу', 'наклоняться'],
  'бедро': ['идти быстро', 'сидеть долго'],
  'голень': ['идти быстро'],
  'стопа': ['идти', 'обувь'],
  'голова': ['спать', 'свет', 'читать'],
  'спина': ['спать на спине', 'нести'],
};
// Порядок важен: «предплечье» раньше «плеча», «кисть» раньше «руки».
// С начала слова: иначе «диагНОСтическая ошибка» становилась раной на носу.
const сНачала = (s) => new RegExp('(?<![\\p{L}])(?:' + s + ')', 'iu');
const ЗОНЫ = [
  ['кисть', сНачала('кист|ладон|пальц|запяст')], ['предплечье', сНачала('предплеч|локт|рук')], ['плечо', сНачала('плеч|ключиц')],
  ['шея', сНачала('ше[яиюе](?![\\p{L}])|горл')], ['голова', сНачала('голов|лоб|висок|висков|затыл|череп|лиц[оаеу]?(?![\\p{L}])|скул|челюст|нос(?:а|у|ом|е)?(?![\\p{L}])|глаз|бров')],
  ['грудь', сНачала('груд|ребр|рёбр')], ['живот', сНачала('живот|бок(?:а|у|ом|е)?(?![\\p{L}])|печен|пах(?:а|у|е)?(?![\\p{L}])')], ['спина', сНачала('спин|лопат|поясниц')],
  ['бедро', сНачала('бедр|ягодиц')], ['голень', сНачала('голен|колен|икр(?:а|ы|у|е)?(?![\\p{L}])')], ['стопа', сНачала('стоп|лодыж|пятк|ступн|ног(?:а|и|у|е|ой)?(?![\\p{L}])')],
];
export function зонаРаны(zn) {
  const s = String(zn || '');
  const н = ЗОНЫ.find(([, rx]) => rx.test(s));
  return н ? н[0] : '';
}

// «nm: порез; sg: fresh; rc: 20%; sy: …; trt: шов; zn: левое предплечье | nm: …»
export function раныИз(значение) {
  const s = текст(значение);
  if (пусто(s)) return [];
  return s.split('|').map(г => {
    const ч = {};
    for (const кусок of г.split(';')) { const м = кусок.match(/^\s*([a-z]{2,4})\s*[:：]\s*(.+?)\s*$/i); if (м) ч[м[1].toLowerCase()] = м[2]; }
    if (!ч.nm) return null;
    const rc = ч.rc !== undefined ? parseFloat(String(ч.rc).replace(',', '.')) : NaN;
    return { nm: ч.nm, sg: (ч.sg || '').toLowerCase(), rc: Number.isFinite(rc) ? Math.max(0, Math.min(100, rc)) : null, zn: ч.zn || '', зона: зонаРаны(ч.zn || ч.nm), trt: ч.trt || '', sy: ч.sy || '' };
  }).filter(Boolean);
}
// Рана, а не болезнь: есть зона или слово раны.
const РАНА = /пул|огнестр|порез|резан|нож|колот|рассеч|ран(?:а|ы|у|ен)|шов|швы|ожог|перелом|трещин|вывих|растяж|ушиб|синяк|гематом|ссадин|укус|травм/i;
const ЗАЖИЛО = /healed|зажил|chronic|хрон/i;
// Ключ раны без стороны, скобок и знаков: одна рана — одна кривая.
const ключРаны = (nm) => String(nm || '').toLowerCase().replace(/ё/g, 'е').replace(/\([^)]*\)/g, ' ')
  .replace(/(?<![\p{L}])(?:справа|слева|прав\p{L}*|лев\p{L}*)(?![\p{L}])/gu, ' ').replace(/[^\p{L}\p{N}]+/gu, ' ').trim().slice(0, 40);

const ЭТАП = (st) => {
  const s = String(st || '').toLowerCase();
  return /кончен|закончен|over/.test(s) ? 'кончено' : /погон|chase/.test(s) ? 'погоня' : /пауз/.test(s) ? 'пауза' : /угроз/.test(s) ? 'угроза' : /схватк|бой|драк|fight/.test(s) ? 'схватка' : '';
};
// «Имя: своя | враг; вплотную; нож; ранен | …» → [{ имя, сторона, состояние }]
export function участникиБоя(pt) {
  return текст(pt).split('|').map(x => x.trim()).filter(Boolean).map(x => {
    const [имя, ...ост] = x.split(':');
    const части = ост.join(':').split(';').map(y => y.trim().toLowerCase());
    return { имя: имя.trim(), сторона: /враг/.test(части[0] || '') ? 'враг' : /сво/.test(части[0] || '') ? 'свой' : 'нейтрал', состояние: части.find(ч => /цел|ранен|оглуш|вне строя/.test(ч)) || '' };
  }).filter(у => у.имя);
}
const адреналинИз = (ad, имя) => {
  for (const кусок of текст(ad).split(';')) {
    const м = кусок.match(/^\s*([^:]+):\s*(\d{1,3})/);
    if (м && (!имя || namesLikelySame(м[1].trim(), имя))) return Math.min(100, +м[2]);
  }
  return null;
};

/**
 * Учёт по ходам: журнал быта зовёт ход() для каждого хода по порядку, затем
 * итог(). добавить — добавить событие в журнал быта (схватка, отходняк).
 */
export function новыйУчётБоя() {
  const схватки = [];        // { t, конец, этапы:Set, кто: Map(имя → {сторона, состояние}), где, раны:[] }
  const раны = new Map();    // 'имя|рана' → { кто, nm, зона, zn, trt, sg, первый, точки:[{t, rc}] }
  let прошлыйЭтап = '', открыта = null;
  return {
    ход(d, t, { добавить, главный, люди = [] }) {
      const cb = d && d.combat;
      const этап = cb ? ЭТАП(cb.st) : '';
      if (этап) {
        // Новая схватка — если прошлая кончилась больше двух часов назад.
        if (!открыта || t - открыта.конец > 2 * Ч || (прошлыйЭтап === 'кончено' && этап !== 'кончено')) {
          открыта = { t, конец: t, этапы: new Set(), кто: new Map(), где: поле(главный, 'Место'), раны: [], адреналин: null };
          схватки.push(открыта);
          добавить({ вид: 'fight', что: 'схватка', t, источник: 'cb' });
        }
        открыта.конец = t;
        открыта.этапы.add(этап);
        for (const у of участникиБоя(cb.pt)) открыта.кто.set(у.имя, у);
        const ад = адреналинИз(cb.ad, главный && главный['Имя']);
        if (ад !== null) открыта.адреналин = ад;
        // Отходняк — с хода, где бой стал «кончено» (раз на схватку).
        if (этап === 'кончено' && !открыта.кончено) {
          открыта.кончено = t;
          добавить({ вид: 'crash', что: 'отходняк после схватки', t, источник: 'cb', адреналин: открыта.адреналин });
        }
      }
      прошлыйЭтап = этап || (прошлыйЭтап === 'кончено' ? '' : прошлыйЭтап);
      // Раны — у всех, кто в ходе, и у игрока: точки для кривой заживления.
      const кто = [...люди, ...(d && d.user ? [{ ...d.user, 'Имя': d.user['Имя'] || 'Вы' }] : [])];
      for (const c of кто) {
        const имя = имяКоротко(c['Имя']);
        for (const р of раныИз(поле(c, 'Болезни и травмы'))) {
          if (!р.зона && !РАНА.test(р.nm)) continue;
          const к = имя + '|' + ключРаны(р.nm);
          const было = раны.get(к) || { кто: имя, nm: р.nm, первый: t, точки: [] };
          Object.assign(было, { зона: р.зона || было.зона, zn: р.zn || было.zn, trt: р.trt || было.trt, sg: р.sg || было.sg, последний: t });
          if (р.rc !== null && !было.точки.some(т => т.t === t)) было.точки.push({ t, rc: р.rc });
          раны.set(к, было);
          // Рана, появившаяся в схватке или в течение часа после неё, — её след.
          const с = схватки.find(с => было.первый >= с.t - 10 * 60e3 && было.первый <= (с.кончено || с.конец) + Ч);
          if (с && !с.раны.includes(было)) с.раны.push(было);
        }
      }
    },

    итог(сейчас, { главный = '', события = [], сон = [], голод = null, норма = 8 } = {}) {
      if (settings.combatAftermath === false) return null;
      const днейГигиена = Math.max(0, Number(settings.aftermathHygieneDays ?? 3));
      const днейСон = Math.max(0, Number(settings.aftermathSleepDays ?? 1));
      const днейАппетит = Math.max(0, Number(settings.aftermathAppetiteDays ?? 1));
      const свой = (имя) => !главный || имя === главный || namesLikelySame(имя, главный);
      // Раны: кривая rc по ходам и прогноз — две-три точки дают наклон.
      const всеРаны = [...раны.values()].filter(р => р.последний >= сейчас - 14 * СУТКИ && !ЗАЖИЛО.test(р.sg) && !(р.точки.length && р.точки[р.точки.length - 1].rc >= 100)).map(р => {
        const т = р.точки.slice(-4);
        let прогноз = null;
        if (т.length >= 2) {
          const [а, б] = [т[0], т[т.length - 1]];
          const заДень = (б.rc - а.rc) / Math.max(1 / 24, (б.t - а.t) / СУТКИ);
          if (заДень > 0.5 && б.rc < 100) прогноз = б.t + (100 - б.rc) / заДень * СУТКИ;
        }
        return { ...р, день: Math.floor((сейчас - р.первый) / СУТКИ) + 1, rc: т.length ? т[т.length - 1].rc : null, прогноз, мешает: МЕШАЕТ[р.зона] || [] };
      });
      // Гигиена: свежая рана в зоне, где «мыться» мешает, — таймер душа не
      // ругается, а меняет смысл: «мыться нельзя: шов на предплечье, 3-й день».
      const мешаетМыться = всеРаны.filter(р => свой(р.кто) && р.мешает.includes('мыться') && р.день <= днейГигиена + 1 && (р.rc === null || р.rc < 70));
      const обтирался = события.some(с => с.вид === 'wash' && /обте|обтир|влажн\p{L}* салфет|губк/iu.test(с.что) && мешаетМыться.some(р => с.t >= р.первый));
      const мытьёНельзя = мешаетМыться.length ? { рана: мешаетМыться[0], обтирался } : null;
      // Сон: ночь после схватки — пометка к короткой ночи.
      const ночи = [];
      for (const с of сон) for (const н of с.ночи) {
        if (н.сутки < сейчас - (днейСон + 1) * СУТКИ) continue;
        const была = схватки.some(х => х.t >= н.сутки - 12 * Ч && х.t <= н.сутки + 10 * Ч);
        if (была) { н.послеСхватки = true; if (н.часов < норма - 2) ночи.push({ кто: с.имя, часов: н.часов, сутки: н.сутки }); }
      }
      // Аппетит: сытость низкая, а схватка была недавно — вот и причина.
      const последняя = схватки[схватки.length - 1] || null;
      const аппетит = голод && последняя && сейчас - последняя.t <= днейАппетит * СУТКИ ? { часов: (сейчас - последняя.t) / Ч } : null;
      if (аппетит && голод) голод.послеСхватки = true;
      // Отходняк: адреналин отпускает за ~20 минут игрового времени, затем
      // слабость и дрожь часа два. Шаг — по времени сцены, а не реальному.
      const crash = [...события].reverse().find(с => с.вид === 'crash');
      let отходняк = null;
      if (crash) {
        const мин = (сейчас - crash.t) / 60e3;
        const пик = crash.адреналин ?? 70;
        const отпустит = Math.round(10 + пик / 5);  // 70 → ~24 мин
        if (мин < отпустит) отходняк = { стадия: 'адреналин', осталось: Math.max(1, Math.round(отпустит - мин)), пик };
        else if (мин < отпустит + 120) отходняк = { стадия: 'слабость', прошло: Math.round(мин), пик };
      }
      // Журнал схваток: когда, где, с кем, чем кончилось, что осталось.
      const журнал = схватки.slice(-8).reverse().map(с => {
        const враги = [...с.кто.values()].filter(у => у.сторона === 'враг');
        const выведено = враги.filter(у => /вне строя|оглуш/.test(у.состояние)).length;
        return { t: с.t, где: с.где, враги: враги.map(у => у.имя), свои: [...с.кто.values()].filter(у => у.сторона === 'свой').map(у => у.имя), выведено, кончилось: с.кончено ? 'кончено' : [...с.этапы].pop() || '', раны: с.раны.map(р => `${р.nm}${р.zn ? ' — ' + р.zn : ''}`) };
      });
      const итогСхваток = { всего: схватки.length, выведено: журнал.reduce((s, с) => s + с.выведено, 0) };
      if (!всеРаны.length && !схватки.length) return null;
      return { раны: всеРаны, мытьёНельзя, ночи, аппетит, отходняк, журнал, итогСхваток };
    },
  };
}

// «Заживёт примерно к четвергу» — день недели, а дальше недели — дата.
const ДНИ = ['воскресенью', 'понедельнику', 'вторнику', 'среде', 'четвергу', 'пятнице', 'субботе'];
export function когдаЗаживёт(прогноз, сейчас) {
  if (!Number.isFinite(прогноз)) return '';
  const дней = (прогноз - сейчас) / СУТКИ;
  if (дней <= 1) return 'заживёт к завтрашнему дню';
  if (дней <= 7) return 'заживёт примерно к ' + ДНИ[new Date(прогноз).getUTCDay()];
  const d = new Date(прогноз);
  return `заживёт примерно к ${String(d.getUTCDate()).padStart(2, '0')}.${String(d.getUTCMonth() + 1).padStart(2, '0')}`;
}

/**
 * Прогнозы заживления для вкладки «Бой» (рядом с силуэтом): тот же учёт по
 * прошлым ходам. ходы — [{ момент, ход }], от старых к новым или вперемешку.
 * Возвращает [{ кто, nm, текст, rc }].
 */
export function прогнозыЗаживления(ходы, сейчас) {
  const учёт = новыйУчётБоя();
  const по = (Array.isArray(ходы) ? ходы : []).filter(х => х && х.ход && Number.isFinite(х.момент)).sort((a, b) => a.момент - b.момент);
  for (const х of по) учёт.ход(х.ход, х.момент, { добавить: () => {}, главный: null, люди: Array.isArray(х.ход.characters) ? х.ход.characters : [] });
  const итог = учёт.итог(Number.isFinite(сейчас) ? сейчас : (по.length ? по[по.length - 1].момент : 0), {});
  return итог ? итог.раны.filter(р => р.прогноз).map(р => ({ кто: р.кто, nm: р.nm, текст: когдаЗаживёт(р.прогноз, сейчас), rc: р.rc })) : [];
}
