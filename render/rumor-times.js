// hud-manager/render/rumor-times.js
//
// Время у слухов и комментариев в телефоне («Слухи»). Модель пишет их без
// времени, а одно время хода у всех выглядело бы неживо. Поэтому:
//  • дата и час — из хода, где запись появилась впервые (render/carryover.js
//    отмечает первое появление, пока копит слухи по ходам);
//  • минуты и секунды — случайные, но не позже времени того хода: без
//    скачков в будущее (в «21:00» — до четверти часа назад, в прошлый час). Случайность от текста записи — та же при каждой
//    отрисовке;
//  • раз выданное время запоминается в метаданных чата: старая запись
//    держит его и через двадцать ходов, когда её первый ход уже вне окна
//    переноса. Новые записи получают время своего, нового хода.
// TavernOS HUD © 2026 alewwi — https://github.com/alewwi/HUD — GNU AGPL-3.0, see LICENSE and NOTICE.md.

import { hudHashSeed } from '../utils.js?v=23.89.26';

const КЛЮЧ_ХРАНИЛИЩА = 'tavernosHudRumorTimes';
const ПРЕДЕЛ = 600;

/** Ключ записи: тот же текст, записанный чуть иначе, — та же запись. */
export const ключСлуха = (v) => String(v ?? '').trim().toLowerCase().replace(/ё/g, 'е').replace(/[«»"'`.,;:!?()[\]]/g, '').replace(/\s+/g, ' ');

/** «Thursday, 17.10.2024» → «17.10»; без цифр даты — как есть, коротко. */
export function датаКоротко(дата) {
  const м = /(\d{1,2})[./](\d{1,2})(?:[./]\d{2,4})?/.exec(String(дата || ''));
  if (м) return м[1].padStart(2, '0') + '.' + м[2].padStart(2, '0');
  return String(дата || '').replace(/^[^,]*,\s*/, '').trim().slice(0, 16);
}

/**
 * Время записи от хода её появления: { дата, время, секунды } или null, если
 * у хода нет времени «ЧЧ:ММ». Минуты и секунды — от текста, не позже ЧЧ:ММ хода.
 */
export function времяИзХода(ключ, база) {
  const м = /(\d{1,2})\s*:\s*(\d{2})/.exec(String((база && база.время) || ''));
  if (!м) return null;
  const час = Math.min(23, +м[1]), минут = Math.min(59, +м[2]);
  // Назад от времени хода: в пределах его часа, но не меньше четверти часа —
  // в «21:00» внутри часа места нет, и все записи вышли бы 21:00:00.
  const конец = час * 3600 + минут * 60;
  const окно = Math.max(минут * 60, 15 * 60);
  const всего = Math.max(0, конец - hudHashSeed(ключ + '|' + ((база && база.дата) || '') + '|' + час + ':' + минут) % (окно + 1));
  const z = (n) => String(n).padStart(2, '0');
  return { дата: датаКоротко(база.дата), время: `${z(Math.floor(всего / 3600))}:${z(Math.floor(всего % 3600 / 60))}:${z(всего % 60)}`, секунды: всего };
}

function хранилище() {
  try {
    const ctx = window.SillyTavern?.getContext?.();
    const мета = ctx && (ctx.chatMetadata || ctx.chat_metadata);
    if (!мета || !ctx.chatId && !ctx.getCurrentChatId?.()) return null;
    if (!мета[КЛЮЧ_ХРАНИЛИЩА] || typeof мета[КЛЮЧ_ХРАНИЛИЩА] !== 'object') мета[КЛЮЧ_ХРАНИЛИЩА] = {};
    return { записи: мета[КЛЮЧ_ХРАНИЛИЩА], ctx };
  } catch (_) { return null; }
}
let таймер = 0;
function сохранить(ctx) {
  clearTimeout(таймер);
  таймер = setTimeout(() => { try { (ctx.saveMetadataDebounced || ctx.saveMetadata)?.call(ctx); } catch (_) { /* в следующий раз */ } }, 1500);
}

/**
 * Время для списка записей. впервые — { ключ: { дата, время, ход } } из
 * переноса (может не быть); сцена — { дата, время } текущего хода, для
 * записей, первого появления которых не нашлось. запомнить: false — пример
 * в «Кастомизации», в чат ничего не пишем.
 * тексты — в порядке списка, от старых к новым: новые записи одного хода
 * получают свои времена по возрастанию в этом порядке, и лента не путается.
 * → Map ключ → { дата, время, секунды, ход } (без времени у хода — нет записи).
 */
export function временаСлухов(тексты, впервые, сцена, { запомнить = true } = {}) {
  const х = запомнить ? хранилище() : null;
  const итог = new Map();
  const поХодам = new Map();   // ход → новые записи [{ к, в, база }] в порядке списка
  for (const т of тексты) {
    const к = ключСлуха(т);
    if (!к || итог.has(к)) continue;
    const было = х && х.записи[к];
    if (было && typeof было === 'object' && было.время) { итог.set(к, { ...было, ход: Number.isFinite(было.ход) ? было.ход : Infinity }); continue; }
    const база = (впервые && впервые[к]) || сцена;
    const в = времяИзХода(к, база);
    if (!в) continue;
    const ход = Number.isFinite(база && база.ход) ? база.ход : Infinity;
    const группа = `${ход}|${в.дата}`;
    if (!поХодам.has(группа)) поХодам.set(группа, []);
    поХодам.get(группа).push({ к, в, ход });
    итог.set(к, null);
  }
  let новых = 0;
  for (const записи of поХодам.values()) {
    // Те же времена, но по возрастанию — в порядке, в каком записи стоят в списке.
    const времена = записи.map(з => з.в).sort((a, b) => a.секунды - b.секунды);
    записи.forEach((з, i) => {
      const запись = { ...времена[i], ход: з.ход };
      итог.set(з.к, запись);
      if (х) { х.записи[з.к] = { ...запись, ход: Number.isFinite(з.ход) ? з.ход : null }; новых++; }
    });
  }
  for (const [к, v] of итог) if (!v) итог.delete(к);
  if (х && новых) {
    const ключи = Object.keys(х.записи);
    for (const к of ключи.slice(0, Math.max(0, ключи.length - ПРЕДЕЛ))) delete х.записи[к];
    сохранить(х.ctx);
  }
  return итог;
}
