/**
 * Ступени для готовых данных карточки вне ленты чата (просмотр в
 * «Кастомизации»): числа под потолком и замками, сведения — в
 * __ступениДоверия. набор — свои пары примера; без него — пары чата.
 */
export function ступениДанных(данные, индекс, набор = null) {
  if (!ступениВкл() || !данные || typeof данные !== 'object') return данные;
  const было = пример;
  if (набор) пример = набор;
  try {
    const люди = [...(Array.isArray(данные.characters) ? данные.characters.map(c => [c, c && c['Имя']]) : []), ...(данные.user && typeof данные.user === 'object' ? [[данные.user, getSafeUserName()]] : [])];
    for (const [о, имя] of люди) {
      if (!о || !имя || о['Доверие'] === undefined) continue;
      const { значение, сведения } = применитьСтупени(String(имя), о['Доверие'], Number.isFinite(индекс) ? индекс : Infinity);
      if (!сведения) continue;
      о['Доверие'] = значение;
      Object.defineProperty(о, '__ступениДоверия', { value: сведения, enumerable: false, configurable: true });
    }
  } finally { пример = было; }
  return данные;
}
