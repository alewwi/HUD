/** «Вера: 82 (выручила); Павел: -9 [locked: Холодок]» → [{ имя, v, хвост }]. */
export function разобратьСтроку(значение) {
  const s = flattenFieldValue(значение);
  return s.split(/[;\n]/).map(ч => {
    const m = ч.match(/^\s*([^:：]{1,60}?)\s*[:：]\s*([−–—-]?\s*\d{1,3})\s*(.*)$/);
    if (!m) return ч.trim() ? { сырое: ч.trim() } : null;
    // Пометку замка модель могла переписать — её ставит только HUD. По
    // заметке «held at» модель сочиняет и «[held: Холодок]» — тоже долой.
    const хвост = m[3].replace(/\s*\[(?:locked|held|зафикс|потолок)[^\]]*\]/gi, '').trim();
    return { имя: m[1].trim(), v: чистоеЧисло(m[2]), хвост };
  }).filter(Boolean).flatMap(ч => (именаГруппы(ч.имя) || [ч.имя]).map(имя => имя ? { ...ч, имя } : ч));
}
const собрать = (части) => части.map(ч => ч.сырое !== undefined ? ч.сырое : `${ч.имя}: ${ч.v}${ч.хвост ? ' ' + ч.хвост : ''}`).join('; ');

/**
 * Доверие одного человека по ступеням.
 * кто — чьё доверие; значение — строка Tr; индекс — номер сообщения;
 * последний — это самый свежий ход с HUD: только он заводит новые пары.
 * → { значение: строка для показа, сведения: { [к]: { v, ступень, замок, ждёт, хотела, потолок } } }
 */
export function применитьСтупени(кто, значение, индекс, { последний = false } = {}) {
  if (!ступениВкл() || !кто) return { значение, сведения: null };
  const части = разобратьСтроку(значение);
  const х = хранилище();
  const список = ступени();
  const сведения = Object.create(null);
  let изменено = false, записано = false;
  for (const пара of х?.пары || []) {
    if (!пара.замок || !namesLikelySame(кто, пара.кто) || индекс < пара.замок.с || части.some(ч => namesLikelySame(ч.имя, пара.к))) continue;
    части.push({ имя: пара.к, v: пара.замок.v, хвост: '' });
    изменено = true;
  }
  if (!части.some(ч => ч.имя)) return { значение, сведения: null };
  for (const ч of части) {
    if (!ч.имя || !Number.isFinite(ч.v)) continue;
    let пара = найтиПару(х, кто, ч.имя);
    const сырое = ч.v;
    const и = { v: сырое, сырое, замок: false, ждёт: null, хотела: null, потолок: null, кто, к: ч.имя };
    if (!пара && последний && х && !пример) {
      // Первая встреча ровно на верху ступени — ещё не просьба подняться.
      пара = { кто, к: ч.имя, потолок: ступеньДля(сырое, список).max, с: индекс, просит: false };
      х.пары.push(пара);
      записано = true;
    }
    // Сообщения удалили — номер хода стал меньше: свежий ход всё равно под ступенями.
    if (пара && последний && Number.isFinite(индекс) && !пример) {
      if (индекс < (пара.с ?? 0)) { пара.с = индекс; записано = true; }
      if (пара.замок && индекс < (пара.замок.с ?? 0)) { пара.замок.с = индекс; записано = true; }
    }
    // Infinity — снимок для модели: действует всё, что заведено.
    const номер = typeof индекс === 'number' && !Number.isNaN(индекс) ? индекс : NaN;
    const действует = пара && !Number.isNaN(номер) && номер >= (пара.с ?? 0);
    if (действует && пара.замок && номер >= (пара.замок.с ?? 0)) {
      и.v = пара.замок.v;
      и.замок = true;
      if (сырое !== и.v) и.нарушено = true;
      if (ч.хвост) { ч.хвост = ''; изменено = true; }
    } else if (действует && разрешениеНужно()) {
      и.потолок = ступеньДля(пара.потолок, список).max;
      // Большое падение (на две ступени и ниже под потолком) закрывает ступени
      // над новой: после предательства прежняя близость снова — с разрешения.
      // Мелкие колебания у границы потолок не трогают. Считаем до кнопки:
      // раньше кнопка решалась по старому потолку и вылезала только при
      // перерисовке — после нажатия у соседа.
      if (последний && !пример) {
        const верх = ступеньДля(пара.потолок, список), сейчас = ступеньДля(Math.min(сырое, и.потолок), список);
        if (верх.i - сейчас.i >= 2) { пара.потолок = сейчас.max; и.потолок = пара.потолок; пара.просит = false; delete пара.хочет; записано = true; }
      }
      // Просьба модели: число выше потолка. Повтор потолка из снимка просьбу
      // держит, число ниже — снимает. Старые пары без пометки — как раньше.
      if (последний && !пример) {
        if (сырое > и.потолок) {
          if (пара.просит !== true || пара.хочет !== сырое) { пара.просит = true; пара.хочет = сырое; записано = true; }
        } else if (сырое < и.потолок && пара.просит !== false) { пара.просит = false; delete пара.хочет; записано = true; }
      }
      if (сырое > и.потолок || (сырое === и.потолок && пара.просит !== false)) {
        и.v = и.потолок;
        и.хотела = сырое > и.потолок ? сырое : Number.isFinite(пара.хочет) && пара.хочет > и.потолок ? пара.хочет : null;
        const над = список.find(с => с.min > и.потолок);
        if (над) и.ждёт = над;
      }
    }
    и.ступень = ступеньДля(и.v, список);
    if (и.v !== сырое) { ч.v = и.v; изменено = true; }
    сведения[ч.имя] = и;
  }
  if (записано) сохранить();
  return { значение: изменено ? собрать(части.filter(ч => !ч.сырое || !/^(empty|none|nc|нет|пусто)$/i.test(ч.сырое))) : значение, сведения };
}

// --- Действия игрока ---------------------------------------------------------

/** Открыть следующую ступень над потолком пары; до — номер ступени, до
 *  которой открыть сразу все (модель хочет на несколько ступеней выше). */
export function разрешитьСтупень(кто, к, до = null) {
  const х = хранилище();
  const пара = найтиПару(х, кто, к);
  if (!пара || пара.замок || !разрешениеНужно()) return false;
  const список = ступени();
  const следующая = список.find(с => с.min > ступеньДля(пара.потолок, список).max);
  if (!следующая) return false;
  const цель = Number.isInteger(Number(до)) && до !== null && до !== '' ? список[Number(до)] : null;
  const над = цель && цель.i > следующая.i ? цель : следующая;
  пара.потолок = над.max;
  пара.открыта = над.name;
  пара.объявить = true;
  // Просьба исполнена — повтор нового потолка в следующем ходу уже не просьба.
  if (!(Number.isFinite(пара.хочет) && пара.хочет > пара.потолок)) { пара.просит = false; delete пара.хочет; }
  сохранить();
  return true;
}
/** Зафиксировать пару на числе v, начиная с хода индекс; повторно — снять замок. */
export function переключитьЗамок(кто, к, v, индекс) {
  const х = хранилище();
  if (!х) return false;
  let пара = найтиПару(х, кто, к);
  if (!пара) {
    const значение = чистоеЧисло(v);
    if (!Number.isFinite(значение)) return false;
    пара = { кто, к, потолок: ступеньДля(значение).max, с: Number.isFinite(индекс) ? индекс : 0 };
    х.пары.push(пара);
  }
  if (пара.замок) {
    // Снятый замок оставляет потолок на зафиксированной ступени: дальше —
    // снова по одной ступени с разрешения, а не сразу к прежней близости.
    пара.потолок = ступеньДля(пара.замок.v).max;
    delete пара.замок;
    // На верху ступени после замка — снова можно разрешить, не дожидаясь просьбы.
    delete пара.просит; delete пара.хочет;
  } else {
    const значение = чистоеЧисло(v);
    if (!Number.isFinite(значение)) return false;
    пара.замок = { v: значение, с: Number.isFinite(индекс) ? индекс : 0 };
  }
  сохранить();
  return true;
}

