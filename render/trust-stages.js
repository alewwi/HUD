/** Лесенка ступеней: текущая горит, выше потолка — пунктир, отрицательные — тёмно-красные. */
function лесенка(и, список) {
  const n = список.length;
  return `<i class="hud-tst-steps" aria-hidden="true">${список.map((с, k) => {
    const кл = [с.min < 0 ? 'neg' : 'pos'];
    if (и.ступень && (и.ступень.min >= 0 ? с.min >= 0 && k <= и.ступень.i : с.min < 0 && k >= и.ступень.i)) кл.push('on');
    if (и.ступень && k === и.ступень.i) кл.push('cur');
    if (и.потолок !== null && с.min > и.потолок) кл.push('shut');
    return `<i class="${кл.join(' ')}" style="--h:${(28 + 72 * k / Math.max(1, n - 1)).toFixed(0)}%"></i>`;
  }).join('')}</i>`;
}

/**
 * Плашка ступени для карточки доверия: имя ступени, лесенка, замок и, когда
 * модель упёрлась в потолок, кнопка «разрешить». и — сведения из
 * применитьСтупени; кто — чьё доверие.
 */
export function плашкаСтупени(и, { компактно = false } = {}) {
  if (!и || !и.ступень) return '';
  const список = ступени();
  const имя = имяСтупени(и.ступень);
  const атр = `data-who="${escapeHtml(и.кто)}" data-to="${escapeHtml(и.к)}" data-v="${и.v}"`;
  const замок = `<button type="button" class="hud-tst-lock${и.замок ? ' is-on' : ''}" data-hud-trust="lock" ${атр} title="${и.замок ? `Зафиксировано: ${и.v} — ${escapeHtml(имя)}. Нажмите, чтобы снять замок` : `Зафиксировать: доверие ${и.v} и ступень «${escapeHtml(имя)}» больше не будут меняться`}" aria-label="${и.замок ? 'Снять замок доверия' : 'Зафиксировать доверие'}" aria-pressed="${и.замок ? 'true' : 'false'}">${ико(и.замок ? 'lock' : 'unlock')}</button>`;
  // Модель хочет на несколько ступеней выше открытой: «Разрешить» открывает
  // одну, рядом — «сразу до …», чтобы не нажимать по кнопке на ступень.
  const цель = и.хотела !== null && и.ждёт ? ступеньДля(и.хотела, список) : null;
  const ещё = цель ? цель.i - и.ждёт.i : 0;
  const ждёт = и.ждёт && !и.замок
    ? `<button type="button" class="hud-tst-up" data-hud-trust="allow" ${атр} title="${и.хотела === null ? 'Разрешить следующую ступень?' : `Модель хочет поднять доверие до ${и.хотела} — это уже «${escapeHtml(имяСтупени(цель))}». Разрешить следующую ступень?`}">${ико('stairs')}<span>${компактно ? '' : 'Разрешить '}«${escapeHtml(имяСтупени(и.ждёт))}»</span></button>`
      + (ещё > 0 ? `<button type="button" class="hud-tst-up hud-tst-all" data-hud-trust="allow" data-stage="${цель.i}" ${атр} title="${`Открыть сразу ${ещё + 1} ${ещё + 1 < 5 ? 'ступени' : 'ступеней'} — до «${escapeHtml(имяСтупени(цель))}»`}"><span>${компактно ? `+${ещё + 1}` : `сразу до «${escapeHtml(имяСтупени(цель))}»`}</span></button>` : '')
    : '';
  const тон = и.v < 0 ? 'neg' : и.ждёт ? 'wait' : 'pos';
  return `<span class="hud-tst is-${тон}${и.замок ? ' is-locked' : ''}${компактно ? ' is-compact' : ''}">${лесенка(и, список)}<b class="hud-tst-name">${escapeHtml(имя)}</b>${ждёт}${замок}</span>`;
}

/** Сведения о человеке из карты применитьСтупени: по имени или внутри группы «А, Б: 40». */
export function сведенияДля(сведения, кто) {
  if (!сведения || !кто) return null;
  const ключи = Object.keys(сведения);
  const прямо = ключи.find(к => namesLikelySame(к, кто));
  if (прямо) return сведения[прямо];
  const в = ключи.find(к => (именаГруппы(к) || []).some(и => namesLikelySame(и, кто)));
  return в ? сведения[в] : null;
}

/** Слово ступени для числа — вместо прежних «открыт / насторожен». */
export const словоСтупени = (v) => имяСтупени(ступеньДля(v));

