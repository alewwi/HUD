export const имяСтупени = (с) => !с ? '' : с.name;
/** Имя в редакторе своих ступеней: заводские — на языке интерфейса (английские — прямо). */
export const имяВРедакторе = (с) => !с ? '' : (с.en && английский() ? с.en : с.name);
/** Имя для модели: заводские — на языке значений модели. */
const имяДляМодели = (с) => !с ? '' : (с.en && английский() ? с.en : тМодели(с.name));
export function ступеньДля(v, список = ступени()) {
  if (!Number.isFinite(v)) return null;
  return список.find(с => v >= с.min && v <= с.max) || (v < список[0].min ? список[0] : список[список.length - 1]);
}

