// Ступени доверия — дополнение к шкале «Доверия» (Tr), не отдельный блок.
//
// Шкала −100…100 делится на ступени: от «Заклятых врагов» до «Родных».
// Свои ступени и пороги игрок задаёт в настройках (trustStageList), модель
// получает их списком в описании Tr.
//
//  · Потолок. Выше открытой ступени доверие не поднимается: модель пишет 64,
//    а открыта только «Знакомые» — на экране и в снимке 39, под шкалой —
//    «модель хочет «Симпатию» · разрешить». Следующую ступень открывает
//    только игрок, по одной. Падать можно свободно. Первая встреча пары
//    задаёт стартовую ступень — та, с которой модель её начала.
//  · Замок. Игрок фиксирует пару: число и ступень больше не двигаются. Модель
//    в снимке видит «Павел: -70 [locked: Враги]», а если всё же напишет
//    другое, на экране останется зафиксированное, и в следующий ход уйдёт оно.
//
// Всё держится в метаданных чата (tavernosHudTrust): пары «чьё доверие →
// к кому», потолок и номер хода, с которого он действует. Старые ходы до
// этого номера рисуются как модель их написала.

