/** Столько пар на этой карточке сейчас показывают кнопку «Разрешить». */
export function вопросыДоверия(о, поле) {
  if (settings.enableAttnBadges === false || !полеВкл(settings, поле)) return 0;
  return Object.values(о?.__ступениДоверия || {}).filter(пара => пара.ждёт && !пара.замок).length;
}

/** Строка ступеней для описания Tr: «-100 Заклятые враги, -80 Враги, …». */
export function ступениДляПромпта() {
  return ступени().map(с => `${с.min} ${имяДляМодели(с)}`).join(', ');
}

/**
 * Снимок для модели: потолки и замки. к — объект снимка в кодах (cs[].Tr,
 * us.Tr). Возвращает заметки на этот ход (потолки, нарушенный замок,
 * открытая ступень) — свойство __ступени, неперечисляемое.
 */
export function ступениВСнимке(к, имяИгрока = '') {
  if (!ступениВкл() || !к || typeof к !== 'object') return;
  const заметки = { потолки: [], замки: [], открыты: [] };
  const х = хранилище();
  const люди = [...(Array.isArray(к.cs) ? к.cs.map(c => [c, c && c.N]) : []), ...(к.us && typeof к.us === 'object' ? [[к.us, имяИгрока]] : [])];
  for (const [о, имя] of люди) {
    if (!о || typeof о !== 'object' || !имя || !полеВкл(settings, о === к.us ? 'us.Tr' : 'cs.Tr')) continue;
    const { значение, сведения } = применитьСтупени(String(имя), о.Tr, Infinity);
    if (!сведения) continue;
    const части = разобратьСтроку(значение).map(ч => {
      const и = ч.имя && сведения[ч.имя];
      if (!и) return ч;
      if (и.замок) {
        заметки.замки.push({ кто: String(имя), к: ч.имя, v: и.v, ступень: имяДляМодели(и.ступень), нарушено: !!и.нарушено });
        return { ...ч, v: и.v, хвост: `[locked: ${имяДляМодели(и.ступень)}]` };
      }
      if (и.ждёт) заметки.потолки.push({ кто: String(имя), к: ч.имя, v: и.v, ступень: имяДляМодели(и.ступень), следующая: имяДляМодели(и.ждёт) });
      // Каждая пара на верху открытой ступени — с пометкой прямо в строке:
      // заметок «THIS TURN» всего три, а держится часто десяток пар.
      const закрыта = и.потолок !== null && и.v >= и.потолок && ступени().some(с => с.min > и.потолок);
      if (закрыта) return { ...ч, v: и.v, хвост: `[held: ${имяДляМодели(и.ступень)}]${ч.хвост ? ' ' + ч.хвост : ''}` };
      return { ...ч, v: и.v };
    });
    о.Tr = собрать(части);
  }
  for (const пара of х ? х.пары : []) {
    if (!пара.объявить) continue;
    const с = ступеньДля(пара.потолок);
    заметки.открыты.push({ кто: пара.кто, к: пара.к, ступень: имяДляМодели(с), до: пара.потолок });
  }
  Object.defineProperty(к, '__ступени', { value: заметки, enumerable: false, configurable: true });
}

/** Строки «THIS TURN» по снимку: потолки, замки, только что открытые ступени. */
export function заметкиСтупеней(снимок) {
  const з = снимок && снимок.__ступени;
  if (!з) return [];
  const строки = [];
  for (const п of з.потолки.slice(0, 3)) {
    строки.push(`${п.кто}'s trust in ${п.к} is held at ${п.v} — the top of «${п.ступень}»: the player has not opened «${п.следующая}» yet. Keep ${п.v} and play them as «${п.ступень}» until the player decides.`);
  }
  if (з.замки.length) {
    строки.push(`Trust fixed by the player — write these numbers exactly as they are and play the relation at that stage whatever happens: ${з.замки.map(п => `${п.кто} → ${п.к} ${п.v} «${п.ступень}»`).join('; ')}.`);
  }
  if (з.открыты.length) {
    for (const п of з.открыты.slice(0, 3)) строки.push(`The player opened «${п.ступень}» for ${п.кто} → ${п.к}: that trust may now rise up to ${п.до} once the story earns it.`);
    // Сказали один раз — больше не повторяем.
    const х = хранилище();
    for (const пара of х ? х.пары : []) delete пара.объявить;
    сохранить();
  }
  return строки;
}

