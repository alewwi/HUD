const ё = (s) => String(s || '').replace(/ё/g, 'е').replace(/Ё/g, 'Е');
const первый = (список, текст) => {
  let лучший = null;
  for (const запись of список) {
    const м = new RegExp('(^|[^\\p{L}])(?:' + ё(запись[0]) + ')', 'iu').exec(ё(текст));
    if (м && (!лучший || м.index < лучший.i)) лучший = { i: м.index, запись };
  }
  return лучший ? лучший.запись : null;
};

/** Окрас из текста: { мех, мех2, узор } или null — цвета не названо. */
export function окрасИзТекста(текст) {
  const s = ё(текст);
  if (!s.trim()) return null;
  const узор = (УЗОРЫ.find(([, rx]) => rx.test(s)) || [''])[0];
  // «Чёрно-белый», «серо-голубой»: первый цвет — мех, второй — светлое.
  const пара = s.match(/(\p{L}+?)[оеё]-(\p{L}+)/u);
  if (пара) {
    const a = первый(ОКРАСЫ, пара[1] + 'ый'), b = первый(ОКРАСЫ, пара[2]);
    if (a && b && a !== b) return { мех: a[1], мех2: b[1], узор };
  }
  const з = первый(ОКРАСЫ, s);
  // Трёхцветная, пегая: светлая основа, по ней тёмные и рыжие лоскуты.
  if (!з && узор === 'patches') return { мех: '#ece6dc', мех2: '#ffffff', узор };
  if (!з) return узор ? { мех: '', мех2: '', узор } : null;
  return { мех: з[1], мех2: з[2], узор };
}

/** Цвет глаз из текста: [левый, правый] или null. Ищем только рядом со словом «глаз». */
export function глазаИзТекста(текст) {
  const s = ё(текст);
  if (!s.trim()) return null;
  // «голубоглазый», «green-eyed» — цвет в самом слове.
  const слово = s.match(/(\p{L}+?)[оеё]?глаз\p{L}*|(\p{L}+)-eyed/iu);
  if (слово && !/^(?:глаз)/i.test(слово[0])) {
    const ц = первый(ГЛАЗА, слово[0]);
    if (ц) return [ц[1], ц[1]];
  }
  if (/гетерохром|разн(?:ые|оцветн\p{L}*)\s+глаз|heterochrom|odd[- ]eyed/iu.test(s)) {
    const цвета = [];
    for (const кусок of s.split(/[,;и]|and/)) { const ц = первый(ГЛАЗА, кусок); if (ц && !цвета.includes(ц[1])) цвета.push(ц[1]); }
    return цвета.length >= 2 ? цвета.slice(0, 2) : ['#4aa8ff', '#f2b93a'];
  }
  // «сапфировые глаза», «глаза: янтарные», «с изумрудными глазами», «blue eyes».
  for (const м of s.matchAll(/глаз\p{L}*|\beyes?\b/giu)) {
    const до = s.slice(Math.max(0, м.index - 28), м.index).split(/[;.!?]/).pop();
    const после = s.slice(м.index + м[0].length, м.index + м[0].length + 28).split(/[;.!?,]/)[0];
    const ц = первый(ГЛАЗА, после.replace(/^\s*[:—–-]?\s*/, '')) || первый(ГЛАЗА, до.split(/\s+/).slice(-2).join(' '));
    if (ц) return [ц[1], ц[1]];
  }
  return null;
}

// --- Память по чату -----------------------------------------------------------
function контекстST() {
  try { return globalThis.SillyTavern?.getContext?.() || null; } catch (_) { return null; }
}
function хранилище() {
  const ctx = контекстST();
  const мета = ctx && (ctx.chatMetadata || ctx.chat_metadata);
  if (!мета) return null;
  if (!мета[КЛЮЧ] || typeof мета[КЛЮЧ] !== 'object') мета[КЛЮЧ] = {};
  return мета[КЛЮЧ];
}
let таймер = 0;
function сохранить() {
  clearTimeout(таймер);
  таймер = setTimeout(() => { const ctx = контекстST(); try { (ctx?.saveMetadataDebounced || ctx?.saveMetadata)?.call(ctx); } catch (_) {} }, 400);
}
const ключИмени = (имя) => ё(имя).trim().toLowerCase();

/**
 * Внешность спутника на этот ход: окрас и глаза из его записи, а чего в ней
 * нет — из памяти. Новое упоминание запоминается (ход не старше записанного).
 */
export function внешностьСпутника(p, ход = null) {
  const тексты = [p && p.species, ...(Array.isArray(p && p.extra) ? p.extra.filter(д => /окрас|масть|шерст|цвет|color|colour|coat|fur/i.test(String(д.key))).map(д => д.value) : [])].join('; ');
  const всё = [p && p.eyes, p && p.species, p && p.note, p && p.condition, ...(Array.isArray(p && p.extra) ? p.extra.map(д => `${д.key}: ${д.value}`) : [])].filter(Boolean).join('; ');
  const найдено = { окрас: окрасИзТекста(тексты), глаза: (p && p.eyes ? глазаИзТекста('глаза: ' + p.eyes) : null) || глазаИзТекста(всё) };
  const х = хранилище(), к = ключИмени(p && p.name);
  const было = (х && к && х[к]) || {};
  const номер = Number.isFinite(Number(ход)) ? Number(ход) : null;
  let изменено = false;
  const итог = { ...было };
  for (const поле of ['окрас', 'глаза']) {
    const н = найдено[поле];
    if (!н) continue;
    const старое = было[поле];
    const новее = !старое || номер === null || старое.ход === null || старое.ход === undefined || номер >= старое.ход;
    if (новее && JSON.stringify(старое && старое.з) !== JSON.stringify(н)) { итог[поле] = { з: н, ход: номер }; изменено = true; }
  }
  if (изменено && х && к) { х[к] = итог; сохранить(); }
  return { окрас: найдено.окрас || (итог.окрас && итог.окрас.з) || null, глаза: найдено.глаза || (итог.глаза && итог.глаза.з) || null };
}
