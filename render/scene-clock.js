// hud-manager/render/scene-clock.js
//
// Часы сцены: сколько шла близость по времени сюжета и что за это время
// сдвинулось в расписаниях. Промпт не нужен — всё уже приходит: время и дата
// хода, «Расписание» (S: '<время> - <событие>') у каждого персонажа, фаза
// близости и её «Длительность». Прошлые ходы — из кэша разобранных ходов
// (render/intimacy.js, привязатьИсторию).
//
// Начало сцены — самый ранний ход подряд, где фаза близости 2 или 3. Планы
// берём из того хода, с которого сцена началась: во время сцены модель их
// обычно не обновляет, а после — переписывает уже без пропущенного.
// Три исхода:
//   пропущено — своё дело, время которого прошло за сцену;
//   опаздывает — своё дело в ближайшие полчаса, а сцена ещё идёт;
//   ждал(а)   — пункт чужого расписания с этим персонажем, время прошло.
// Полоса появляется, только когда есть что сказать, и не про сдвиг меньше
// порога (settings.sceneClockMin, по умолчанию 15 минут).

import { escapeHtml, flattenFieldValue, снятьЗаглушки } from '../utils.js?v=23.51.8';
import { settings } from '../settings.js?v=23.51.8';
import { namesLikelySame } from '../names.js?v=23.51.8';
import { моментСцены } from './intimacy.js?v=23.51.8';
import { ико, медаль } from './view-icons.js?v=23.51.8';

const МИН = 60000;
const поле = (о, имя) => {
  if (!о || typeof о !== 'object') return '';
  const ключ = Object.keys(о).find(k => k.toLowerCase() === имя.toLowerCase());
  return ключ ? String(снятьЗаглушки(flattenFieldValue(о[ключ])) || '').trim() : '';
};
const пусто = (s) => !s || /^(empty|none|нет|—|-)$/i.test(String(s).trim());

export function форматДлительности(мин) {
  const всего = Math.max(0, Math.round(мин));
  if (всего < 60) return всего + ' мин';
  const ч = Math.floor(всего / 60), м = всего % 60;
  return ч + ' ч' + (м ? ' ' + м + ' мин' : '');
}

/** «19:00 - ужин с Леной; 21:30 - звонок отцу» → [{ мин, время, что, текст }]. */
export function пунктыРасписания(текст) {
  if (пусто(текст)) return [];
  return String(текст).split(/[;\n]/).map(s => s.trim()).filter(Boolean).map(s => {
    const м = s.match(/^(?:\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?\s*)?(\d{1,2})[:.](\d{2})(?:\s*[–—-]\s*\d{1,2}[:.]\d{2})?\s*[–—:-]?\s*(.*)$/);
    if (!м) return null;
    const ч = +м[1], мм = +м[2];
    if (ч > 23 || мм > 59) return null;
    return { мин: ч * 60 + мм, время: String(ч).padStart(2, '0') + ':' + String(мм).padStart(2, '0'), что: м[3].trim() || s, текст: s };
  }).filter(Boolean);
}

// Момент пункта: в день начала сцены, а если по часам он раньше начала —
// это уже следующие сутки (сцена через полночь, «00:30 - встреча»).
function моментПункта(п, начало) {
  const сутки = Math.floor(начало / 864e5) * 864e5;
  let t = сутки + п.мин * МИН;
  if (t < начало - 6 * 3600e3) t += 864e5;
  return t;
}

const имяКоротко = (имя) => String(имя || '').replace(/^.*\s{2,}/, '').trim().split(/\s+/)[0] || '';
// «встреча с Тристаном» упоминает «THE REGENTS  Tristan Kingsley»: слова с
// заглавной сравниваем с именем без приставки карточки, с учётом латиницы и
// падежей (names.js). Окончания не обрезаем: «Кристин» сошла бы за Tristan.
const упоминает = (текст, имя) => {
  const кор = имяКоротко(имя);
  if (кор.length < 3) return false;
  return String(текст).split(/[^\p{L}-]+/u).some(w => w.length >= 3 && /^\p{Lu}/u.test(w) && namesLikelySame(w, кор));
};

// Пункт — сама сцена, а не пропущенное дело: «00:00 - обладание Софи»,
// «22:00 - глубокое соитие в мастер-спальне», «ночной покой рядом с Софи».
const ПРО_СЦЕНУ = /соити|секс|близост|обладан|прелюд|ласк|постел|поцел|оргазм|интим|кунни|минет|фрикци|толчк|страст|любов|посткоит|захват|ночн\p{L}*\s+(?:отдых|покой)|в\s+спальн|в\s+мастер-спальн/iu;
// Ждать могут встречи, а не «дежурство над спящей Софи».
const ВСТРЕЧА = /встреч|ждёт|ждет|ждать|ожида|ужин|обед|завтрак|кофе|звон|созвон|свидани|при[её]м|сбор|совещан|селектор|заехать|забрать|приехать|прийти|зайти|договор/iu;
// Партнёры сцены — их имена в пункте значат «это про сцену»: «pr: Софи, …».
function партнёрыСцены(c, игрок) {
  const имена = [игрок];
  const nsfw = поле(c, 'NSFW') + ' ; ' + поле(c, 'Последний секс');
  for (const м of nsfw.matchAll(/(?:^|;)\s*pr\s*:\s*([^;]+)/gi)) имена.push(м[1].split(/[,—–(]/)[0].trim());
  return имена.filter(и => и && и.length >= 3);
}

/**
 * Итог сцены для персонажа: { минут, начало, сейчас, идёт, пункты: [{ исход, кто, время, что, текст }] } или null.
 * c — объект персонажа с историей (__hudИстория, __hudМомент, __hudХод);
 * фазаСцены — разбор «Фазы близости» → 'live' | 'after' | ''.
 */
export function итогСцены(c, фазаСцены) {
  if (!c || typeof c.__hudМомент !== 'function') return null;
  const сейчас = c.__hudМомент();
  const фаза = фазаСцены(поле(c, 'Фаза близости'));
  if (!сейчас || !фаза) return null;
  let история = [];
  try { история = typeof c.__hudИстория === 'function' ? c.__hudИстория() : []; } catch (_) { история = []; }
  // Самый ранний ход подряд со сценой.
  let начало = сейчас, ходНачала = typeof c.__hudХод === 'function' ? c.__hudХод() : null;
  for (const х of история) {
    if (!фазаСцены(поле(х.данные, 'Фаза близости')) || !х.момент || х.момент > начало) break;
    начало = х.момент;
    ходНачала = х.ход || ходНачала;
  }
  // Сцена началась в этом же ходу — длительность только со слов модели.
  const длит = parseFloat(поле(c, 'Длительность'));
  if (начало === сейчас && Number.isFinite(длит) && длит > 0) начало = сейчас - длит * МИН;
  const минут = (сейчас - начало) / МИН;
  if (минут < 1) return null;
  const идёт = фаза === 'live';
  const пункты = [];
  const люди = ходНачала && Array.isArray(ходНачала.characters) ? ходНачала.characters : [];
  const я = люди.find(p => p && namesLikelySame(p['Имя'], c['Имя'])) || c;
  const игрок = (() => { try { return window.SillyTavern.getContext().name1 || ''; } catch (_) { return ''; } })();
  const партнёры = партнёрыСцены(c, игрок);
  // План, стоявший на сам момент начала, — это и есть сцена.
  const вСцене = (п, t) => t <= начало + 10 * МИН || ПРО_СЦЕНУ.test(п.что) || партнёры.some(и => упоминает(п.что, и));
  for (const п of пунктыРасписания(поле(я, 'Расписание'))) {
    const t = моментПункта(п, начало);
    if (вСцене(п, t)) continue;
    if (t > начало && t <= сейчас) пункты.push({ исход: 'missed', кто: '', время: п.время, что: п.что, текст: п.текст, t });
    else if (идёт && t > сейчас && t <= сейчас + 30 * МИН) пункты.push({ исход: 'late', кто: '', время: п.время, что: п.что, текст: п.текст, t });
  }
  for (const р of люди) {
    if (!р || р === я || namesLikelySame(р['Имя'], c['Имя'])) continue;
    for (const п of пунктыРасписания(поле(р, 'Расписание'))) {
      if (!упоминает(п.что, c['Имя']) || !ВСТРЕЧА.test(п.что)) continue;
      const t = моментПункта(п, начало);
      if (t <= начало + 10 * МИН) continue;
      if (t > начало && t <= сейчас) пункты.push({ исход: 'wait', кто: имяКоротко(р['Имя']), время: п.время, что: п.что, текст: п.текст, t });
    }
  }
  пункты.sort((a, b) => a.t - b.t);
  return { минут, начало, сейчас, идёт, пункты };
}

const ИСХОДЫ = {
  missed: ['⊘', 'пропущено', 'calendar'],
  late: ['⏱', 'опаздывает', 'clock'],
  wait: ['⌛', 'ждал(а)', 'hourglass'],
};

/** Полоса под сценой: «Сцена шла 1 ч 40 мин · 19:00 ужин — пропущено · Лена ждала с 20:30». */
export function часыСцены(c, фазаСцены) {
  if (settings.enableSceneClock === false) return '';
  const и = итогСцены(c, фазаСцены);
  if (!и || !и.пункты.length) return '';
  const порог = Math.max(0, Number(settings.sceneClockMin ?? 15) || 0);
  if (и.минут < порог) return '';
  const вид = ['chips', 'dial', 'line'].includes(settings.sceneClockView) ? settings.sceneClockView : 'chips';
  const подпись = (п) => п.исход === 'wait' ? `${escapeHtml(п.кто)} ждал(а) с ${п.время}` : `${п.время} ${escapeHtml(п.что)} — ${ИСХОДЫ[п.исход][1]}`;
  const чипы = и.пункты.map(п => `<span class="hud-sclock-chip is-${п.исход}" title="${escapeHtml((п.кто ? п.кто + ': ' : '') + п.текст)}"><i aria-hidden="true">${ико(ИСХОДЫ[п.исход][2])}</i>${подпись(п)}</span>`).join('');
  const длит = `<span class="hud-sclock-dur">${медаль('clock')}Сцена ${и.идёт ? 'идёт' : 'шла'} <b>${форматДлительности(и.минут)}</b></span>`;
  const чм = (t) => new Date(t).toISOString().slice(11, 16);
  if (вид === 'dial') {
    // Настенные часы на 12 часов: дуга — сцена, засечки — что пропустили, стрелки — сейчас.
    const угол = (t) => (((t / 3600e3) % 12) / 12) * 2 * Math.PI;
    const т = (t, r) => { const a = угол(t); return [50 + r * Math.sin(a), 50 - r * Math.cos(a)]; };
    const ф = (n) => n.toFixed(2);
    const от = Math.max(и.начало, и.сейчас - 12 * 3600e3 + 60e3);
    const [x1, y1] = т(от, 40), [x2, y2] = т(и.сейчас, 40);
    const дуга = `<path class="arc" d="M${ф(x1)} ${ф(y1)} A40 40 0 ${(и.сейчас - от) > 6 * 3600e3 ? 1 : 0} 1 ${ф(x2)} ${ф(y2)}"/>`;
    const цифры = [12, 3, 6, 9].map(h => { const [x, y] = т(h * 3600e3, 31); return `<text x="${ф(x)}" y="${ф(y)}">${h}</text>`; }).join('');
    const засечки = Array.from({ length: 12 }, (_, h) => { const [a, b] = т(h * 3600e3, 45), [c, d] = т(h * 3600e3, 42); return `<line x1="${ф(a)}" y1="${ф(b)}" x2="${ф(c)}" y2="${ф(d)}"/>`; }).join('');
    const точки = и.пункты.map(п => { const [x, y] = т(п.t, 40); return `<circle class="is-${п.исход}" cx="${ф(x)}" cy="${ф(y)}" r="4"><title>${escapeHtml(подпись(п).replace(/<[^>]+>/g, ''))}</title></circle>`; }).join('');
    const мин = new Date(и.сейчас).getUTCMinutes(), час = (new Date(и.сейчас).getUTCHours() % 12) + мин / 60;
    const стрелка = (доля, r, кл) => { const a = доля * 2 * Math.PI; return `<line class="${кл}" x1="50" y1="50" x2="${ф(50 + r * Math.sin(a))}" y2="${ф(50 - r * Math.cos(a))}"/>`; };
    return `<div class="hud-sclock hud-v hud-v-card is-dial" role="note"><svg class="hud-sclock-face" viewBox="0 0 100 100" aria-label="Сцена ${чм(и.начало)}–${чм(и.сейчас)}">`
      + `<circle class="face" cx="50" cy="50" r="47"/><g class="ticks">${засечки}</g><g class="nums">${цифры}</g>${дуга}${точки}${стрелка(час / 12, 20, 'h')}${стрелка(мин / 60, 30, 'm')}<circle class="hub" cx="50" cy="50" r="2.4"/></svg>`
      + `<div class="hud-sclock-side">${длит}<small>${чм(и.начало)} → ${чм(и.сейчас)}</small>${чипы}</div></div>`;
  }
  if (вид === 'line') {
    // Линия: от начала сцены до «сейчас» (и чуть дальше — тем, кто вот-вот опоздает).
    const конец = Math.max(и.сейчас, ...и.пункты.map(п => п.t));
    const x = (t) => ((t - и.начало) / Math.max(1, конец - и.начало) * 100).toFixed(2);
    return `<div class="hud-sclock hud-v hud-v-card is-line" role="note">${длит}<div class="hud-sclock-line"><span class="hud-sclock-run" style="width:${x(и.сейчас)}%"></span>`
      + и.пункты.map(п => `<span class="hud-sclock-pin is-${п.исход}" style="left:${x(п.t)}%" title="${escapeHtml(подпись(п).replace(/<[^>]+>/g, ''))}"><i aria-hidden="true">${ико(ИСХОДЫ[п.исход][2])}</i><small>${п.время}</small></span>`).join('')
      + `<span class="hud-sclock-end is-start">${чм(и.начало)}</span><span class="hud-sclock-end is-now" style="left:${x(и.сейчас)}%">сейчас ${чм(и.сейчас)}</span></div>`
      + `<div class="hud-sclock-notes">${и.пункты.map(п => `<span class="is-${п.исход}">${ико(ИСХОДЫ[п.исход][2])}${подпись(п)}</span>`).join('')}</div></div>`;
  }
  return `<div class="hud-sclock hud-v is-chips" role="note">${длит}${чипы}</div>`;
}

/** Одна строка итога для модели: «late: ужин 19:00 пропущен; Лена ждала с 20:30». */
export function строкаЧасовСцены(c, фазаСцены) {
  const и = итогСцены(c, фазаСцены);
  if (!и || !и.пункты.length) return '';
  return 'late: ' + и.пункты.map(п => п.исход === 'wait' ? `${п.кто} ждал(а) с ${п.время}` : `${п.что} ${п.время} ${п.исход === 'late' ? 'не успевает' : 'пропущено'}`).join('; ');
}
