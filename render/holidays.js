// Католическая (григорианская) Пасха — алгоритм Мееуса/Джонса/Бутчера.
export function пасхаЗападная(год) {
  const a = год % 19, b = Math.floor(год / 100), c = год % 100;
  const d = Math.floor(b / 4), e = b % 4, f = Math.floor((b + 8) / 25), g = Math.floor((b - f + 1) / 3);
  const h = (19 * a + b - d - g + 15) % 30, i = Math.floor(c / 4), k = c % 4;
  const l = (32 + 2 * e + 2 * i - h - k) % 7, m = Math.floor((a + 11 * h + 22 * l) / 451);
  const месяц = Math.floor((h + l - 7 * m + 114) / 31), число = ((h + l - 7 * m + 114) % 31) + 1;
  return { месяц, число };
}

// Православная Пасха: юлианская пасхалия, переведённая в григорианский
// календарь (разница календарей растёт на сутки каждое столетие, кроме
// кратных 400). До 1583 года григорианского календаря не было — там
// оставляем юлианскую дату как есть: так её и считали современники.
export function пасхаПравославная(год) {
  const a = год % 4, b = год % 7, c = год % 19;
  const d = (19 * c + 15) % 30, e = (2 * a + 4 * b - d + 34) % 7;
  const юлМесяц = Math.floor((d + e + 114) / 31), юлЧисло = ((d + e + 114) % 31) + 1;
  const сдвиг = год >= 1583 ? Math.floor(год / 100) - Math.floor(год / 400) - 2 : 0;
  const t = new Date(Date.UTC(год, юлМесяц - 1, юлЧисло + сдвиг));
  return { месяц: t.getUTCMonth() + 1, число: t.getUTCDate() };
}

const деньГода = (год, месяц, число) => Math.round((Date.UTC(год, месяц - 1, число) - Date.UTC(год, 0, 1)) / 864e5);

/**
 * Праздничное убранство сцены.
 * число, месяц — из даты сцены; год — если известен (иначе текущий);
 * ночь — тёмная часть суток (фейерверк виден только в темноте).
 */
export function праздникиСцены({ число, месяц, год, ночь = false } = {}) {
  const out = { newYear: false, halloween: false, easter: false, fireworks: false };
  if (!число || !месяц) return out;
  const г = год || new Date().getFullYear();
  out.newYear = (месяц === 12 && число >= 28) || (месяц === 1 && число <= 13);
  // Хэллоуин: неделя до 31 октября и утро 1 ноября — тыквы уже стоят у крыльца.
  out.halloween = (месяц === 10 && число >= 24) || (месяц === 11 && число === 1);
  // Пасхальная неделя: от Великой субботы до следующего воскресенья.
  const сегодня = деньГода(г, месяц, число);
  out.easter = [пасхаЗападная(г), пасхаПравославная(г)].some(п => {
    const д = деньГода(г, п.месяц, п.число);
    return сегодня >= д - 1 && сегодня <= д + 7;
  });
  // Фейерверк — в новогоднюю ночь: 31 декабря вечером и в первую ночь января.
  out.fireworks = ночь && ((месяц === 12 && число === 31) || (месяц === 1 && число === 1));
  return out;
}

/* Календарь эпохи: какие праздники здесь отмечают. Эпоха — из настроек, русский
   календарь или западный — по месту действия в снимке. */
const РУССКОЕ_МЕСТО = /росси|москв|петербург|новосиб|екатеринбург|казан|russia|moscow|petersburg/i;
const США = /сша|нью-йорк|бостон|лос-анджелес|чикаго|usa|new york|boston|los angeles|chicago/i;
// Европа: общий список и праздник своей страны.
const СТРАНЫ = [
  [/франци|париж|лион|марсел|france|paris|lyon/i, { имя: 'День взятия Бастилии', модели: 'Bastille Day', м: 7, ч: 14 }],
  [/герман|берлин|мюнхен|гамбург|germany|berlin|munich|hamburg/i, { имя: 'День единства Германии', модели: 'German Unity Day', м: 10, ч: 3 }],
  [/итали|рим(?!\p{L})|милан|венеци|флоренци|italy|rome|milan|venice|florence/iu, { имя: 'Феррагосто', модели: 'Ferragosto', м: 8, ч: 15 }],
  [/испани|мадрид|барселон|spain|madrid|barcelona/i, { имя: 'День трёх королей', модели: 'Epiphany, the Three Kings', м: 1, ч: 6 }],
  [/ирланд|дублин|ireland|dublin/i, { имя: 'День святого Патрика', модели: "St Patrick's Day", м: 3, ч: 17 }],
  [/британ|англи|лондон|шотланд|эдинбург|britain|england|london|scotland|edinburgh/i, { имя: 'День подарков', модели: 'Boxing Day', м: 12, ч: 26 }],
];
const ЕВРОПА = /европ|австри|вен[аеуы](?!\p{L})|швейцар|цюрих|женев|нидерланд|амстердам|бельги|брюссел|польш|варшав|чехи|прага|праге|греци|афин|португал|лиссабон|швеци|стокгольм|норвег|осло|дани|копенгаген|финлянд|хельсинки|europe|austria|vienna|switzerland|zurich|geneva|netherlands|amsterdam|belgium|brussels|poland|warsaw|prague|greece|athens|portugal|lisbon|sweden|stockholm|norway|oslo|denmark|copenhagen|finland|helsinki/iu;
let последнееМесто = '';
function вераМира(снимок) {
  try {
    const ctx = window.SillyTavern?.getContext?.();
    const карта = ctx?.characters?.[ctx?.characterId];
    const текст = [карта?.description, карта?.data?.description, ctx?.powerUserSettings?.persona_description, снимок?.us?.R, ...(Array.isArray(снимок?.cs) ? снимок.cs.map(c => c && c.R) : [])].filter(Boolean).join(' ');
    if (/православ|orthodox/i.test(текст)) return 'orthodox';
    if (/католи|протестант|catholic|protestant/i.test(текст)) return 'western';
  } catch (_) {}
  return '';
}
export function праздникиГода(год, снимок = null) {
  // Календарь снимка не знает: берёт место из последнего запроса.
  const место = снимок ? (последнееМесто = [снимок.us?.L, ...(Array.isArray(снимок.cs) ? снимок.cs.map(c => c && c.L) : [])].filter(Boolean).join(' ')) : последнееМесто;
  const вера = вераМира(снимок);
  const русское = вера ? вера === 'orthodox' && РУССКОЕ_МЕСТО.test(место) : РУССКОЕ_МЕСТО.test(место);
  const православные = вера ? вера === 'orthodox' : РУССКОЕ_МЕСТО.test(место) || /греци|афин|сербы|greece|athens|serbia/i.test(место);
  const д = (месяц, число) => Date.UTC(год, месяц - 1, число);
  const пасха = православные ? пасхаПравославная(год) : пасхаЗападная(год);
  const деньПасхи = д(пасха.месяц, пасха.число);
  if (settings.era === 'medieval') {
    return [{ имя: 'Рождество', модели: 'Christmas', дата: д(12, 25) }, { имя: 'Крещение', модели: 'Epiphany', дата: д(1, 6) }, { имя: 'Пасха', модели: 'Easter', дата: деньПасхи },
      { имя: 'Троица', модели: 'Pentecost', дата: деньПасхи + 49 * 864e5 }, { имя: 'Иванов день', модели: 'Midsummer', дата: д(6, 24) }, { имя: 'Михайлов день', модели: 'Michaelmas', дата: д(9, 29) }, { имя: 'День всех святых', модели: 'All Saints', дата: д(11, 1) }];
  }
  const общие = [{ имя: 'Новый год', модели: 'New Year', дата: д(1, 1) }, { имя: 'Пасха', модели: 'Easter', дата: деньПасхи }, { имя: 'День святого Валентина', модели: "Valentine's Day", дата: д(2, 14) }];
  if (русское) return [...общие, { имя: 'Рождество', модели: 'Orthodox Christmas', дата: д(1, 7) }, { имя: '8 Марта', модели: "International Women's Day", дата: д(3, 8) }, { имя: 'День Победы', модели: 'Victory Day', дата: д(5, 9) }];
  const страна = СТРАНЫ.find(([rx]) => rx.test(место));
  if (страна || ЕВРОПА.test(место)) {
    const европа = [...общие, { имя: 'Рождество', модели: 'Christmas', дата: д(12, 25) }, { имя: 'Сочельник', модели: 'Christmas Eve', дата: д(12, 24) },
      { имя: 'Пасхальный понедельник', модели: 'Easter Monday', дата: деньПасхи + 864e5 }, { имя: 'Первое мая', модели: 'May Day', дата: д(5, 1) }, { имя: 'День всех святых', модели: 'All Saints', дата: д(11, 1) }];
    if (страна) европа.push({ имя: страна[1].имя, модели: страна[1].модели, дата: д(страна[1].м, страна[1].ч) });
    return европа;
  }
  const западные = [...общие, { имя: 'Рождество', модели: 'Christmas', дата: д(12, 25) }, { имя: 'Хэллоуин', модели: 'Halloween', дата: д(10, 31) }];
  if (США.test(место)) западные.push({ имя: 'День независимости', модели: 'Independence Day', дата: д(7, 4) });
  if (США.test(место)) { const день = new Date(д(11, 1)).getUTCDay(); западные.push({ имя: 'День благодарения', модели: 'Thanksgiving', дата: д(11, 1 + (4 - день + 7) % 7 + 21) }); }
  return западные;
}
