/** Слои объёма внутри обрезки по силуэту (под одеждой и пятнами). */
export function слоиОбъёма(id) {
  return `<rect class="z-shade" width="90" height="190" fill="url(#${id}-shade)"/>`
    + `<ellipse class="z-glow" cx="42" cy="62" rx="22" ry="40" fill="url(#${id}-glow)"/>`;
}
/** Контровая кромка — поверх тела, по контуру. */
export const кромка = (id, силуэт) => `<g class="z-edge" fill="none" stroke="url(#${id}-edge)">${силуэт}</g>`;
