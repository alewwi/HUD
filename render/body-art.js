/** Линии очертаний для стороны 'f' | 'b'. */
// Дуга груди — по размеру (0…3): больше — ниже и шире, меньше — короче.
function дугаПоРазмеру(d, п) {
  const b = п && Number.isFinite(п.грудь) ? п.грудь : 1;
  if (b === 1 && !(п && п.плечи)) return d;
  const ky = 0.75 + 0.25 * b, kx = 0.9 + 0.1 * b, dy = (b - 1) * 0.8, dx = п ? -п.плечи * 0.3 : 0;
  return d.replace(/(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)/g, (_, x, y) => ч(38.6 + (Number(x) - 38.6) * kx + dx) + ' ' + ч(55.6 + (Number(y) - 55.6) * ky + dy));
}
export function очертанияТела(пол, открыто, сторона, п = null) {
  const набор = ОЧЕРТАНИЯ[пол];
  if (!набор || !открыто) return '';
  const линии = [];
  for (const часть of ['грудь', 'пах']) {
    if (!открыто[часть]) continue;
    for (const [исх, центр] of (набор[часть][сторона] || [])) {
      const d = часть === 'грудь' && пол === 'f' ? дугаПоРазмеру(исх, п) : исх;
      линии.push(d);
      if (!центр) линии.push(зеркало(d));
    }
  }
  return линии.length ? `<g class="z-anat" aria-hidden="true">${линии.map(d => `<path d="${d}"/>`).join('')}</g>` : '';
}

