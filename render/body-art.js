// Красота силуэта карты тела (render/intimacy.js: buildHeatMap):
//  · фигура по полу и по описанию — плечи, талия, бёдра, грудь, рельеф
//    мышц, вены, живот при беременности. У каждого героя своя: «широкие
//    мускулистые плечи» и «тонкая талия 58 см» рисуются разными фигурами.
//    Без описания — прежняя фигура пола (или общая, если пол неизвестен);
//  · объём — мягкий свет сверху слева и тень по правому краю, контровая
//    кромка; так плоская заливка читается телом, а не трафаретом;
//  · очертания — только линии, без подробностей: изгиб груди, паховые линии
//    и мягкий контур там, где одежды нет или она открывает это место
//    (настройка silhouetteOutlines). Пустое поле одежды — не «голый»: о
//    чём не написано, того не рисуем.
//
// Система координат одной фигуры — 90×190, как у силуэта в intimacy.js:
// плечи на 41, грудь 47–60, талия 72, бёдра 92, пах ~100.

const зеркало = (d) => d.replace(/(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)/g, (_, x, y) => (90 - parseFloat(x)).toFixed(1) + ' ' + y);
