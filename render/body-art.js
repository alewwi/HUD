/**
 * Параметры фигуры из облика (render/look.js) и срока беременности:
 * сдвиги плеч, талии, бёдер (+ — шире), толщина рук и бёдер, грудь 0…3,
 * рельеф, вены, живот 0…1. null — описания нет, фигура как прежде.
 */
export function параметрыФигуры(пол, облик, недель = 0) {
  const ф = (облик && облик.форма) || {};
  const сл = облик && облик.сложение;
  const п = { плечи: 0, талия: 0, бёдра: 0, руки: 0, ноги: 0, грудь: пол === 'f' ? 1 : 0, рельеф: !!ф.рельеф, вены: !!ф.вены, живот: 0 };
  let есть = false;
  if (сл === 'крепкое') { п.плечи += 1.4; п.руки += 0.8; п.талия += 0.4; есть = true; }
  if (сл === 'хрупкое') { п.плечи -= 0.8; п.талия -= 0.8; п.бёдра -= 0.4; п.руки -= 0.4; п.ноги -= 0.4; есть = true; }
  if (сл === 'пышное') { п.бёдра += 1.8; п.талия += 0.6; п.ноги += 0.8; п.грудь = Math.max(п.грудь, 2); есть = true; }
  if (ф.плечи === 'широкие') { п.плечи += 2; есть = true; } else if (ф.плечи === 'узкие') { п.плечи -= 1.4; есть = true; }
  if (ф.талия === 'тонкая') { п.талия -= 1.8; есть = true; } else if (ф.талия === 'широкая') { п.талия += 1.6; есть = true; }
  if (ф.бёдра === 'широкие') { п.бёдра += 2.2; п.ноги += 0.6; есть = true; } else if (ф.бёдра === 'узкие') { п.бёдра -= 1.4; есть = true; }
  if (Number.isFinite(ф.грудь) && пол === 'f') { п.грудь = ф.грудь; есть = true; }
  if (п.рельеф) { п.руки += 0.5; есть = true; }
  if (п.вены) есть = true;
  const k = Math.max(0, Math.min(1, ((Number(недель) || 0) - 12) / 26));
  if (пол === 'f' && k > 0) { п.живот = Math.round(k * 100) / 100; есть = true; }
  // Пределы: фигура остаётся фигурой, одежда и пятна — на своих местах.
  const огр = (v, a, b) => Math.max(a, Math.min(b, v));
  п.плечи = огр(п.плечи, -2, 3); п.талия = огр(п.талия, -2.4, 2.4); п.бёдра = огр(п.бёдра, -2, 3.2); п.руки = огр(п.руки, -0.6, 1.4); п.ноги = огр(п.ноги, -0.6, 1.4);
  return есть ? п : null;
}

// Стройность: фигура на 5% уже (на глаз — выше), а участок от груди до бёдер
// чуть длиннее — талия опущена на ~2,5 (плавно, пик у талии). Макушка, пах,
// колени и стопы на месте: одежда и зоны карты не съезжают.
const УЖЕ = 0.95, ВЫШЕ_ТАЛИЯ = 2.5;
function вытянуть([x, y, м, острая]) {
  const ny = y > 48 && y < 99 ? y + ВЫШЕ_ТАЛИЯ * Math.sin(Math.PI * (y - 48) / 51) : y;
  return [45 + (x - 45) * УЖЕ, ny, м, острая];
}

/** Линии деталей (ключицы, пресс, очертания) — в ту же стройность, что и контур. */
export const кФигуре = (d) => String(d).replace(/(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)/g, (_, x, y) => { const [nx, ny] = вытянуть([Number(x), Number(y)]); return чч(nx) + ' ' + чч(ny); });

// Сдвиг точки по параметрам фигуры: + — шире (x уменьшается слева).
function сдвиг([x, y, м, острая], п) {
  // Точки на оси (макушка, пах) не двигаются: иначе в паху раскрылась бы щель.
  if (!п || x >= 45) return [x, y, м, острая];
  let d = 0;
  const тут = (a, b) => Math.max(0, Math.min(1, (y - a) / (b - a)));
  const колокол = (c, w) => Math.max(0, 1 - Math.abs(y - c) / w);
  if (м === 'п') d += п.плечи * (0.25 + 0.65 * тут(33, 40));
  if (м === 'р' || м === 'р2') d += п.плечи * (1 - 0.5 * тут(50, 100)) + Math.max(0, п.бёдра) * 0.9 * тут(72, 96) + Math.max(0, п.талия) * 0.5 * тут(60, 80);
  if (м === 'р') d += п.руки;
  if (м === 'т') {
    d += п.плечи * 0.6 * (1 - тут(48, 64));
    d += п.талия * колокол(71, 13);
    d += п.бёдра * колокол(93, 14);
    d += (п.грудь - 1) * 0.7 * колокол(55, 7);
  }
  if (м === 'н') d += п.бёдра * 0.7 * (1 - тут(98, 136)) + п.ноги * (0.9 - 0.5 * тут(110, 172));
  if (м === 'н2') d += п.ноги * 0.3 * (1 - тут(108, 172));
  return [Math.min(м === 'н2' ? 44.8 : 44.6, x - d), y, м, острая];
}
export function контурТела(пол, п = null, { руки = true } = {}) {
  let т = (ФИГУРЫ[пол] || СРЕДНЯЯ).map(t => вытянуть(сдвиг(t, п)));
  if (!руки) {
    // Без рук: от края плеча прямо к подмышке.
    const i0 = т.findIndex(t => t[2] === 'р'), i1 = т.findIndex(t => t[3] && t[2] === 'р2');
    т = [...т.slice(0, i0), [т[i0][0] + 1.2, т[i0][1] + 1.2, 'т'], т[i1], ...т.slice(i1 + 1)];
  }
  // Полный обход: левая половина, потом правая зеркально (без повтора осевых).
  const правая = т.slice(1, -1).reverse().map(([x, y, м, о]) => [90 - x, y, м, о]);
  const все = [...т, ...правая];
  const n = все.length;
  const P = (i) => все[(i + n) % n];
  let d = `M${ч(все[0][0])} ${ч(все[0][1])}`;
  const k = 1 / 6;
  for (let i = 0; i < n; i++) {
    const p0 = P(i - 1), p1 = P(i), p2 = P(i + 1), p3 = P(i + 2);
    // Острая точка: касательная в ней — по своей стороне (не через угол).
    const a = p1[3] ? p1 : p0, b = p2[3] ? p2 : p3;
    const c1 = [p1[0] + (p2[0] - a[0]) * k, p1[1] + (p2[1] - a[1]) * k];
    const c2 = [p2[0] - (b[0] - p1[0]) * k, p2[1] - (b[1] - p1[1]) * k];
    d += `C${ч(c1[0])} ${ч(c1[1])} ${ч(c2[0])} ${ч(c2[1])} ${ч(p2[0])} ${ч(p2[1])}`;
  }
  return d + 'Z';
}

// Живот при беременности: выступает за линию талии и чуть ниже пупка.
const животФигуры = (п) => (п && п.живот ? `<ellipse cx="45" cy="${ч(82 - п.живот * 2)}" rx="${ч((12 + п.живот * 6) * УЖЕ)}" ry="${ч(11 + п.живот * 8)}"/>` : '');

const полФигуры = (пол) => (пол === 'f' || пол === 'm' ? пол : '');

/** Фигура без рук и кистей — обрезка для вещей без рукавов (брюки, юбка,
 * бельё, платье): иначе их прямоугольник заходил на опущенные руки. */
export function силуэтБезРук(пол = '', п = null) {
  return `<path d="${контурТела(полФигуры(пол), п, { руки: false })}"/>` + животФигуры(п);
}

/** Силуэт по полу ('f' | 'm' | '') и параметрам фигуры (параметрыФигуры). */
export function силуэтТела(пол = '', п = null) {
  return `<path d="${контурТела(полФигуры(пол), п)}"/>` + животФигуры(п);
}

/* --- Женская грудь --------------------------------------------------------
   Нижний контур каждой груди — от бока под мышкой вниз, по складке и вверх к
   грудине; над складкой — мягкая тень (объём), между — короткая ложбинка.
   Размер 0…3 (параметрыФигуры): больше — ниже складка и шире. Без сосков
   и подробностей — только форма. */
function контурГруди(п) {
  const b = п && Number.isFinite(п.грудь) ? Math.max(0, Math.min(3, п.грудь)) : 1;
  // Бок груди — у подмышки, чуть за линией рёбер; складка ниже с размером.
  const x0 = 29.4 - 0.45 * b, y0 = 50.4, низ = 59.8 + 1.7 * b, xн = 37.2 - 0.2 * b, вх = 43.6, вy = 56.2 + 0.9 * b;
  const линия = `M ${ч(x0)} ${ч(y0)} C ${ч(x0 - 0.7)} ${ч(y0 + 4.6 + b)} ${ч(xн - 5)} ${ч(низ + 0.2)} ${ч(xн)} ${ч(низ)} C ${ч(xн + 3.8)} ${ч(низ - 0.1)} ${ч(вх - 0.2)} ${ч(вy + 2.4)} ${ч(вх)} ${ч(вy)}`;
  // Падающая тень — серп ПОД складкой (на рёбрах): объём читается по ней.
  const г = 1.6 + 0.35 * b;
  const тень = линия + ` C ${ч(вх + 0.1)} ${ч(вy + 2.6 + г * 0.5)} ${ч(xн + 4)} ${ч(низ + г)} ${ч(xн)} ${ч(низ + г)} C ${ч(xн - 5)} ${ч(низ + г)} ${ч(x0 + 0.2)} ${ч(y0 + 6 + b)} ${ч(x0)} ${ч(y0)} Z`;
  // Блик — мягкий свет на верхней половине груди.
  const блик = { cx: xн - 0.8, cy: низ - 5.2 - 0.4 * b, rx: 3.4 + 0.6 * b, ry: 2.8 + 0.5 * b };
  return { линия, тень, блик, ложбинка: `M 45 ${ч(вy - 3)} Q 45.3 ${ч(вy - 1)} 45 ${ч(вy + 0.8)}` };
}
/** Грудь спереди — тень, блик, контур, ложбинка (слой деталей, под одеждой). */
export function грудьФигуры(п, сторона, пол = '') {
  if (пол !== 'f' || сторона !== 'f') return '';
  const к = контурГруди(п);
  const блик = (cx) => { const [x, y] = вытянуть([cx, к.блик.cy]); return `<ellipse class="z-bust-light" cx="${чч(x)}" cy="${чч(y)}" rx="${чч(к.блик.rx * УЖЕ)}" ry="${чч(к.блик.ry)}"/>`; };
  return `<g class="z-bust">${блик(к.блик.cx)}${блик(90 - к.блик.cx)}<path class="z-bust-shade" d="${кФигуре(к.тень)}"/><path class="z-bust-shade" d="${кФигуре(зеркало(к.тень))}"/>`
    + `<path class="z-bust-line" d="${кФигуре(к.линия)}"/><path class="z-bust-line" d="${кФигуре(зеркало(к.линия))}"/><path class="z-bust-line is-cleft" d="${кФигуре(к.ложбинка)}"/></g>`;
}

/** Рельеф мышц, вены и живот — тонкими линиями деталей тела (под одеждой). */
export function деталиФигуры(п, сторона, пол = '') {
  if (!п) return '';
  const линии = [];
  if (п.рельеф) {
    if (сторона === 'f') {
      // Пресс — три пары мягких дуг, без вертикальной линии: штрихи с линией
      // посередине читались как волосы на груди. Дельты — у плеч.
      for (const y of [63.4, 69.4, 75.2]) { const д = `M 40.8 ${y} Q 42.6 ${ч(y + 1.6)} 44.2 ${y}`; линии.push(д, зеркало(д)); }
      // Граница дельты и груди — от верха плеча к подмышке, по самой руке.
      const дельта = пол === 'f' ? `M ${ч(29.6 - п.плечи)} 38.8 Q ${ч(27.8 - п.плечи)} 42.4 ${ч(28.6 - п.плечи)} 46.6` : `M ${ч(27.4 - п.плечи)} 37.8 Q ${ч(25.2 - п.плечи)} 41.6 ${ч(26.4 - п.плечи)} 46.4`;
      линии.push(дельта, зеркало(дельта));
      if (пол !== 'f') { const грудь = 'M 32.6 52 Q 38.4 57.4 44 54.4'; линии.push(грудь, зеркало(грудь)); }
    } else {
      const трап = 'M 37.6 33.6 Q 41.2 36.4 45 36.6', шир = `M ${ч(33.4 - п.плечи * 0.5)} 55 Q 36 65 38.6 74`;
      линии.push(трап, зеркало(трап), шир, зеркало(шир));
    }
  }
  if (п.вены) {
    // Вена — по середине предплечья (у мужской руки оно шире и дальше от тела).
    const к = п.плечи * 0.6 + п.руки * 0.5 + (пол === 'f' ? -1.2 : 0);
    const вена = `M ${ч(23 - к)} 74 Q ${ч(22.2 - к)} 80 ${ч(22.4 - к)} 85 Q ${ч(22.2 - к)} 89 ${ч(22.6 - к)} 93`;
    линии.push(вена, зеркало(вена));
  }
  let out = линии.length ? `<g class="z-muscle">${линии.map(d => `<path d="${кФигуре(d)}"/>`).join('')}</g>` : '';
  // Живот при беременности спереди — мягкий свет на выпуклости и линия снизу.
  if (п.живот && сторона === 'f') out += `<g class="z-belly"><ellipse cx="44" cy="${ч(78 - п.живот * 2)}" rx="${ч(7 + п.живот * 3)}" ry="${ч(7 + п.живот * 5)}"/><path d="${кФигуре(`M ${ч(36 - п.живот * 3)} ${ч(88 + п.живот * 4)} Q 45 ${ч(93 + п.живот * 5)} ${ч(54 + п.живот * 3)} ${ч(88 + п.живот * 4)}`)}"/></g>`;
  return out;
}

/* --- Что открыто ------------------------------------------------------------
   Грудь закрывает бельё сверху или верх (рубашка, футболка, свитер, платье,
   халат, верхняя одежда), если не снято, не распахнуто до пояса, не задрано
   выше груди и не сползло с плеч. Пах — трусики, брюки, шорты, юбка,
   платье, халат, если не снято, не спущено и не задрано. */
const ГРУДЬ = ['bra', 'tank', 'tee', 'shirt', 'sweater', 'outer', 'robe', 'dress'];
const ПАХ = ['panties', 'pants', 'shorts', 'skirt', 'dress', 'robe'];
const закрываетГрудь = (в) => {
  if (в.состояние === 'off') return false;
  if (в.id === 'bra') return !(в.сдвинуто || в.спущено || в.задрано || в.порвано);
  return !(в.открыто >= 2 || в.задрано >= 2 || в.сплечо || (в.id === 'dress' && в.спущено >= 1));
};
const закрываетПах = (в) => {
  if (в.состояние === 'off') return false;
  if (в.id === 'panties') return !(в.сдвинуто || в.спущено || в.порвано);
  if (в.id === 'skirt' || в.id === 'dress') return !(в.задрано >= 1 || в.спущено >= 2);
  if (в.id === 'robe') return !(в.открыто >= 2 || в.задрано >= 1);
  return !(в.спущено >= 2);
};

/** { грудь, пах } — открыто ли; null — об одежде ничего не известно. */
export function открытоеТело(одежда) {
  if (!одежда) return null;
  if (одежда.голый) return { грудь: true, пах: true };
  if (!одежда.length) return null;
  return {
    грудь: !одежда.some(в => ГРУДЬ.includes(в.id) && закрываетГрудь(в)),
    пах: !одежда.some(в => (ПАХ.includes(в.id) && закрываетПах(в)) || длинныйВерх(в)),
  };
}

// Длинный верх («его рубашка на голое тело», свитер до бёдер, оверсайз)
// прикрывает и пах, хотя обычная рубашка кончается на поясе.
const ДЛИННЫЙ_ВЕРХ = /(?<![\p{L}])(?:его|мужск\p{L}*|длинн\p{L}*|оверсайз\p{L}*|oversize\p{L}*)\s+(?:\p{L}+\s+)?(?:рубашк|свитер|футболк|худи|толстовк|кофт)|(?:рубашк|свитер|футболк|худи|толстовк)\p{L}*\s+(?:\p{L}+\s+)?(?:до бёдер|до бедер|до колен|до середины бедр)/iu;
const длинныйВерх = (в) => ['shirt', 'sweater', 'tee'].includes(в.id) && в.состояние === 'on' && !в.открыто && !в.задрано && ДЛИННЫЙ_ВЕРХ.test(в.текст || '');

/* --- Очертания: только линии ------------------------------------------------ */
// [путь, по центру]: по центру — одна линия, остальные зеркалятся на вторую сторону.
const ОЧЕРТАНИЯ = {
  f: {
    // Нижний изгиб груди — мягкая дуга, без подробностей.
    грудь: { f: [] },
    // Паховые линии к лобку и короткая мягкая черта.
    пах: { f: [['M 31.5 84 Q 38.5 93 44.2 99.4'], ['M 45 98.6 L 45 102.4', true]] },
  },
  m: {
    // Нижний край грудных мышц.
    грудь: { f: [['M 30.2 52.6 Q 37.4 58 44 55']] },
    // Паховые линии и мягкий общий контур — без анатомических подробностей.
    пах: { f: [['M 31.4 83 Q 38.6 92.4 43.4 98.6'], ['M 42.4 99.4 Q 41.8 105.4 45 106.4 Q 48.2 105.4 47.6 99.4', true]] },
  },
};
/** Линии очертаний для стороны 'f' | 'b'. */
export function очертанияТела(пол, открыто, сторона, п = null) {
  const набор = ОЧЕРТАНИЯ[пол];
  if (!набор || !открыто) return '';
  const линии = [];
  for (const часть of ['грудь', 'пах']) {
    if (!открыто[часть]) continue;
    // Женская грудь — форма в слое деталей (грудьФигуры), второй раз не рисуем.
    if (часть === 'грудь' && пол === 'f') continue;
    for (const [исх, центр] of (набор[часть][сторона] || [])) {
      линии.push(исх);
      if (!центр) линии.push(зеркало(исх));
    }
  }
  return линии.length ? `<g class="z-anat" aria-hidden="true">${линии.map(d => `<path d="${кФигуре(d)}"/>`).join('')}</g>` : '';
}

