// Рисунки сцен погоды, которые строятся программно: голые зимние деревья
// (ветвление), ели и новогодняя ёлка (ярусы с провисающими лапами и снегом),
// птицы весны (скворечник с птенцом, скворец, дятел на сучке) и тыквы-фонари
// на Хэллоуин. Всё считается один раз и кэшируется строкой.

const ф = (n) => +n.toFixed(1);

// Детерминированный генератор: у каждого дерева свой, одинаковый при каждой
// отрисовке (иначе дерево менялось бы от сообщения к сообщению).
function генератор(семя) {
  let a = семя >>> 0;
  return () => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// --- Голое зимнее дерево ------------------------------------------------------
// viewBox 0 0 82 180, низ ствола — (41, 180). Ветвь — сужающийся
// четырёхугольник с лёгким изгибом; снег — полоса по верхней кромке
// толстых ветвей, тоньше к концу; самые тонкие веточки — штрихи.
const кэшДеревьев = new Map();
export function голоеДеревоSvg(номер, отражение = false) {
  const ключ = номер + (отражение ? 'r' : '');
  if (кэшДеревьев.has(ключ)) return кэшДеревьев.get(ключ);
  const сл = генератор(номер * 7919 + 13);
  const кора = [], снег = [[], [], [], []], прутья = [];
  // Габарит кроны — чтобы вписать дерево в свою рамку, а не на всё небо.
  let минX = 41, максX = 41, минY = 180;
  const точка = (x, y) => { минX = Math.min(минX, x); максX = Math.max(максX, x); минY = Math.min(минY, y); };
  const ветвь = (x, y, угол, длина, ш, глубина) => {
    const изгиб = (сл() - .5) * .35;
    const у1 = угол + изгиб;
    const cx = x + Math.cos(угол) * длина * .5, cy = y + Math.sin(угол) * длина * .5;
    const ex = cx + Math.cos(у1) * длина * .5, ey = cy + Math.sin(у1) * длина * .5;
    const ш1 = ш * .6;
    точка(ex, ey);
    if (ш < .9) {
      прутья.push(`M${ф(x)} ${ф(y)} Q${ф(cx)} ${ф(cy)} ${ф(ex)} ${ф(ey)}`);
    } else {
      const n0 = [-Math.sin(угол), Math.cos(угол)], n1 = [-Math.sin(у1), Math.cos(у1)];
      const p = (px, py, n, w, s) => [px + n[0] * w * s, py + n[1] * w * s];
      const a = p(x, y, n0, ш / 2, 1), b = p(ex, ey, n1, ш1 / 2, 1), c = p(ex, ey, n1, ш1 / 2, -1), d = p(x, y, n0, ш / 2, -1);
      const mc = p(cx, cy, n0, (ш + ш1) / 4, 1), md = p(cx, cy, n0, (ш + ш1) / 4, -1);
      кора.push(`M${ф(a[0])} ${ф(a[1])} Q${ф(mc[0])} ${ф(mc[1])} ${ф(b[0])} ${ф(b[1])} L${ф(c[0])} ${ф(c[1])} Q${ф(md[0])} ${ф(md[1])} ${ф(d[0])} ${ф(d[1])}Z`);
      // Развилка — наплыв коры: круг чуть шире ветви в месте, где она
      // выходит из родителя, — стык не виден, дерево читается одним рисунком.
      if (глубина > 0 && ш > 2) { const r = ш * .62; кора.push(`M${ф(x - r)} ${ф(y)} a${ф(r)} ${ф(r)} 0 1 0 ${ф(2 * r)} 0 a${ф(r)} ${ф(r)} 0 1 0 ${ф(-2 * r)} 0Z`); }
      // Снег — на той кромке, что смотрит вверх, и только на не слишком крутых ветвях.
      if (глубина < 4 && Math.abs(Math.cos(угол)) > .25) {
        const s = n0[1] < 0 ? 1 : -1;
        const sa = p(x, y, n0, ш / 2, s), sm = p(cx, cy, n0, (ш + ш1) / 4, s), sb = p(ex, ey, n1, ш1 / 2, s);
        снег[глубина].push(`M${ф(sa[0])} ${ф(sa[1])} Q${ф(sm[0])} ${ф(sm[1])} ${ф(sb[0])} ${ф(sb[1])}`);
      }
    }
    if (глубина >= 4 || длина < 3) return;
    const детей = глубина === 0 ? 3 : 2;
    for (let i = 0; i < детей; i++) {
      const доля = детей === 3 ? (i - 1) : (i ? .5 : -.5);
      const размах = (глубина === 0 ? .44 : .36) + сл() * .14;
      const уголР = у1 + доля * размах * 2 * .55 + (сл() - .5) * .25 - (глубина > 1 ? .06 : 0);
      ветвь(ex, ey, уголР, длина * (.58 + сл() * .1), ш1 * (детей === 3 && i === 1 ? .95 : .82), глубина + 1);
    }
    // Боковой сучок с середины толстой ветви.
    if (глубина > 0 && глубина < 3 && сл() < .7) {
      const сторона = сл() < .5 ? -1 : 1;
      ветвь(cx, cy, угол + сторона * (.5 + сл() * .25), длина * .42, ш * .45, глубина + 2);
    }
  };
  const наклон = (сл() - .5) * .12;
  ветвь(41, 180, -Math.PI / 2 + наклон, 60 + сл() * 8, 9, 0);
  // Крона не шире ~1,4 рамки и не выше неё: масштаб от основания ствола.
  const к = Math.min(1, 116 / Math.max(1, 2 * Math.max(41 - минX, максX - 41)), 176 / Math.max(1, 180 - минY));
  const svg = '<svg class="hud-tree-art" viewBox="0 0 82 180" preserveAspectRatio="xMidYMax meet" aria-hidden="true">'
    + `<g transform="translate(41 180) scale(${ф(к)}) translate(-41 -180)">${отражение ? '' : `<path class="tw" d="${прутья.join('')}"/>`}<path class="bark" d="${кора.join('')}"/>`
    + (отражение ? '' : снег.map((d, i) => d.length ? `<path class="sn s${i}" d="${d.join('')}"/>` : '').join(''))
    + '</g></svg>';
  кэшДеревьев.set(ключ, svg);
  return svg;
}

// --- Ель ------------------------------------------------------------------------
// Ярусы снизу вверх. Ярус: от оси двумя дугами к опущенным кончикам лап,
// нижний край неровный (лапы свисают клочьями), внутри — тень у ствола,
// по краю — светлые иголки, сверху — снежная шапка с наплывами.
function ярусы(W, H, n, низ, топ, нарядная) {
  const cx = W / 2, шаг = (низ - топ) / (n + .6);
  let тело = '', тень = '', игла = '', снег = '';
  for (let i = 0; i < n; i++) {
    const yb = низ - i * шаг, h = шаг * 1.75, yt = yb - h;
    const hw = (W / 2 - 1) * (1 - i / n * .78);
    const кривая = (s, t) => { // квадратичная дуга от вершины к кончику лапы
      const x0 = cx, y0 = yt, x1 = cx + s * hw * .42, y1 = yt + h * .5, x2 = cx + s * hw, y2 = yb + h * .06;
      const u = 1 - t; return [u * u * x0 + 2 * u * t * x1 + t * t * x2, u * u * y0 + 2 * u * t * y1 + t * t * y2];
    };
    const зубцы = 6 + (n - i);
    let низЯруса = '';
    for (let k = 1; k < зубцы; k++) {
      const x = cx - hw + 2 * hw * k / зубцы, отЦентра = Math.abs(x - cx) / hw;
      const y = yb - (k % 2 ? h * .2 : 0) - (1 - отЦентра) * h * .1;
      низЯруса += ` L${ф(x)} ${ф(y)}`;
    }
    const L = кривая(-1, 1), R = кривая(1, 1);
    тело += `M${ф(cx)} ${ф(yt)} Q${ф(cx - hw * .42)} ${ф(yt + h * .5)} ${ф(L[0])} ${ф(L[1])}${низЯруса} L${ф(R[0])} ${ф(R[1])} Q${ф(cx + hw * .42)} ${ф(yt + h * .5)} ${ф(cx)} ${ф(yt)}Z`;
    тень += `M${ф(cx)} ${ф(yt + h * .3)} L${ф(cx - hw * .34)} ${ф(yb - h * .14)} L${ф(cx + hw * .34)} ${ф(yb - h * .14)}Z`;
    for (const s of [-1, 1]) for (let k = 1; k <= 3; k++) {
      const [x, y] = кривая(s, .3 + k * .2);
      игла += `M${ф(x)} ${ф(y)} l${ф(s * 1.6)} ${ф(1.4)}`;
    }
    // Шапка снега: по верхним дугам до 70% длины, снизу — волнистый край.
    let шапка = `M${ф(cx)} ${ф(yt - .4)}`;
    for (let k = 1; k <= 6; k++) { const [x, y] = кривая(-1, k / 6 * .72); шапка += ` L${ф(x)} ${ф(y - .3)}`; }
    const толщ = Math.max(1.2, h * .17);
    for (let k = 6; k >= 0; k--) {
      const [x, y] = кривая(-1, k / 6 * .72);
      шапка += ` L${ф(x + .4)} ${ф(y + толщ * (k % 2 ? 1 : .55) * (1 - k / 9))}`;
    }
    for (let k = 0; k <= 6; k++) {
      const [x, y] = кривая(1, k / 6 * .72);
      шапка += ` L${ф(x - .4)} ${ф(y + толщ * (k % 2 ? 1 : .55) * (1 - k / 9))}`;
    }
    for (let k = 6; k >= 1; k--) { const [x, y] = кривая(1, k / 6 * .72); шапка += ` L${ф(x)} ${ф(y - .3)}`; }
    снег += шапка + 'Z';
  }
  return { тело, тень, игла, снег: нарядная ? '' : снег, шаг };
}

let кэшЕли = '';
export function ельSvg() {
  if (кэшЕли) return кэшЕли;
  const W = 40, H = 64, я = ярусы(W, H, 6, 56, 2, false);
  кэшЕли = `<svg viewBox="0 0 ${W} ${H}" aria-hidden="true"><path class="stem" d="M18.4 64 L18.9 52 H21.1 L21.6 64Z"/>`
    + `<path class="needles" d="${я.тело}"/><path class="shade" d="${я.тень}"/><path class="tips" d="${я.игла}"/><path class="snow" d="${я.снег}"/>`
    + '<path class="snow-base" d="M8 63 C14 60.6 26 60.6 32 63Z"/></svg>';
  return кэшЕли;
}

