// Из текста «12 дней», «3 недели», «4 месяца», «1 год 2 месяца».
export function днейИзТекста(т) {
  const s = String(т || '').toLowerCase();
  let д = 0, нашли = false;
  const взять = (rx, k) => { const m = s.match(rx); if (m) { д += parseFloat(m[1].replace(',', '.')) * k; нашли = true; } };
  взять(/(\d+(?:[.,]\d+)?)\s*(?:год|лет|г\.)/, 365);
  взять(/(\d+(?:[.,]\d+)?)\s*(?:мес)/, 30.4);
  взять(/(\d+(?:[.,]\d+)?)\s*(?:нед)/, 7);
  взять(/(\d+(?:[.,]\d+)?)\s*(?:дн|ден|сут)/, 1);
  if (!нашли && /новорожд|только родил/.test(s)) return 0;
  return нашли ? Math.round(д) : null;
}
export function возрастСловами(д) {
  if (д === null || д === undefined) return 'возраст не назван';
  if (д < 1) return 'первый день';
  if (д < 14) return `${д} ${скл(д, 'день', 'дня', 'дней')}`;
  if (д < 60) { const н = Math.floor(д / 7); return `${н} ${скл(н, 'неделя', 'недели', 'недель')}`; }
  if (д < 365) { const м = Math.floor(д / 30.4); return `${м} ${скл(м, 'месяц', 'месяца', 'месяцев')}`; }
  const г = Math.floor(д / 365), м = Math.floor((д - г * 365) / 30.4);
  return `${г} ${скл(г, 'год', 'года', 'лет')}${м ? ` ${м} мес.` : ''}`;
}
// Точный возраст: годы, месяцы и дни — «1 год 2 мес. 5 дн.».
export function возрастТочно(д) {
  if (д === null || д === undefined) return 'возраст не назван';
  if (д < 1) return 'первый день';
  const г = Math.floor(д / 365), м = Math.floor((д - г * 365) / 30.4), дн = Math.round(д - г * 365 - м * 30.4);
  return [г && `${г} ${скл(г, 'год', 'года', 'лет')}`, м && `${м} мес.`, дн && `${дн} ${г || м ? 'дн.' : скл(дн, 'день', 'дня', 'дней')}`].filter(Boolean).join(' ');
}
