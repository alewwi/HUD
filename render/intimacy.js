// отсчёт невозможен — время одного дня не переходит через полночь.
export function моментСцены(сцена) {
  if (!сцена || typeof сцена !== 'object') return null;
  const день = parseSceneDate(поле(сцена, 'Дата'));
  if (день === null || день === undefined) return null;
  const m = поле(сцена, 'Время').match(/(\d{1,2})[:.](\d{2})/);
  return день + (m ? (Math.min(23, +m[1]) * 60 + Math.min(59, +m[2])) * 60000 : 12 * 3600000);
}
