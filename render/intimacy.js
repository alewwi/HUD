function форматМинут(м) {
  const всего = Math.max(0, Math.round(м));
  if (всего < 60) return всего + ' мин';
  const ч = Math.floor(всего / 60), мин = всего % 60;
  return ч + ' ч' + (мин ? ' ' + мин + ' мин' : '');
}

export function buildSceneStrip(c) {
  const взять = (k) => { const v = поле(c, k); return пусто(v) ? '' : v; };
  const поза = взять('Поза'), раунд = взять('Раунд'), длит = взять('Длительность');
  const чипы = [];
  if (поза) чипы.push(`<span class="hud-scene-chip is-pose" title="Поза"><i aria-hidden="true">🛏</i><span>${applyTooltips(поза)}</span></span>`);
  const р = число(раунд);
  if (раунд) {
    // Точки раундов: пройденные залиты, текущий светится. Больше пяти — числом.
    const n = Number.isFinite(р) ? Math.max(1, Math.round(р)) : 0;
    const точки = n && n <= 5 ? `<span class="hud-round-dots" aria-hidden="true">${Array.from({ length: n }, (_, i) => `<i class="${i === n - 1 ? 'is-now' : ''}"></i>`).join('')}</span>` : '';
    чипы.push(`<span class="hud-scene-chip is-round" title="Раунд"><i aria-hidden="true">🔁</i><span>${n ? `<b>${n}-й</b> раунд` : escapeHtml(раунд)}</span>${точки}</span>`);
  }
  const м = число(длит);
  if (длит) чипы.push(`<span class="hud-scene-chip is-time" title="Длительность сцены в игровых минутах"><i aria-hidden="true">⏱</i><span>${Number.isFinite(м) ? `<b>${форматМинут(м)}</b>` : escapeHtml(длит)}</span></span>`);
  return чипы.length ? `<div class="hud-scene-strip">${чипы.join('')}</div>` : '';
}

