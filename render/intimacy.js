/* --- Готовность к оргазму ---------------------------------------------- */

export function buildOrgasm(value) {
  const s = String(value || '').trim();
  const m = s.match(/^\s*(\d{1,3})\s*%?\s*[:：,—–-]?\s*([\s\S]*)$/);
  if (!m) return `<span class="hud-value">${applyTooltips(s)}</span>`;
  const v = ограничить(parseInt(m[1], 10), 0, 100);
  const текст = m[2].trim();
  const ступень = v >= 85 ? 'is-edge' : v >= 50 ? 'is-high' : 'is-low';
  const слово_ = v >= 95 ? 'на грани' : v >= 85 ? 'совсем близко' : v >= 50 ? 'нарастает' : 'далеко';
  return `<div class="hud-org ${ступень}"><div class="hud-org-head"><b>${v}%</b><em>${слово_}</em></div>`
    + `<div class="hud-org-meter" role="meter" aria-valuenow="${v}" aria-valuemin="0" aria-valuemax="100" title="Готовность к оргазму: ${v} из 100">`
    + `<i style="width:${v}%"></i><s style="left:50%" title="нарастает"></s><s style="left:85%" title="совсем близко"></s></div>`
    + `<div class="hud-org-scale" aria-hidden="true"><span>далеко</span><span>нарастает</span><span>на грани</span></div>`
    + `${текст && !пусто(текст) ? `<p>${applyTooltips(текст)}</p>` : ''}</div>`;
}

