// Срок заживания: «12h», «3d», «5 дней», «2 нед» — в часах. Голое число —
// старый формат, срок в ходах.
function срокСледа(текст) {
  const s = String(текст || '').trim().toLowerCase().replace(',', '.');
  if (!s) return {};
  const m = s.match(/(\d+(?:\.\d+)?)\s*(hours?|hr|h|час\p{L}*|ч|days?|d|дн\p{L}*|д|сут\p{L}*|weeks?|w|нед\p{L}*)/u);
  if (m) {
    const n = parseFloat(m[1]), е = m[2];
    const часов = /^(?:h|hr|hour|час|ч)/u.test(е) ? n : /^(?:w|week|нед)/u.test(е) ? n * 168 : n * 24;
    return часов > 0 ? { часов } : {};
  }
  const n = parseInt(s.replace(/[^\d]/g, ''), 10);
  return Number.isFinite(n) && n > 0 ? { ходов: n } : {};
}

// Вид следа по названию и месту. Нужен и болезням: «Порезы правой ладони»
// из «Болезней и травм» — тот же порез, что «Порезы: правая ладонь» в следах.
export function видСледа(что, где = '') {
  // Вид — по названию; виды «по месту» смотрят и на место. Общее название
  // («Следы», «Отметины») добирает вид по месту: «костяшки» — ссадины.
  const тип = ТИПЫ_СЛЕДОВ.find(([rx, , , поМесту]) => rx.test(поМесту ? что + ' ' + где : что))
    || ТИПЫ_СЛЕДОВ.find(([rx, , , поМесту]) => !поМесту && где && rx.test(где));
  return { значок: тип ? тип[1] : '•', вид: тип ? тип[2] : 'other' };
}

function разобратьСлед(кусок) {
  const [голова, срок] = String(кусок).split('|');
  const m = голова.match(/^\s*([^:：]+)[:：]\s*(.*)$/);
  const что = (m ? m[1] : голова).trim();
  // «шея слева — наливается фиолетовым»: место и как след выглядит сейчас.
  const [где = '', ...как] = (m ? m[2] : '').split(/\s+[—–]\s+|\s+-\s+/);
  return {
    что, где: где.trim(), как: как.join(' — ').trim(), ...срокСледа(срок),
    ключ: норм(что) + '|' + норм(где), ...видСледа(что, где.trim()),
  };
}

export const разобратьСледы = (текст) => пусто(текст) ? [] : разбитьСписок(текст).map(разобратьСлед).filter(с => с.что && !пусто(с.что));

const сторона = (s) => /(?<![\p{L}])(?:прав|справ|right)/iu.test(s) ? 'r' : /(?<![\p{L}])(?:лев|слев|left)/iu.test(s) ? 'l' : null;
const зонаВреда = (о) => (о.зона !== undefined && о.зона !== null) ? о.зона : (зонаПоСлову(о.где) || зонаПоСлову(о.что));

// Одна и та же травма или след. Раньше совпадать должно было название, и
// «Резаные раны» из прошлого хода жили рядом с «Порезами» из этого — две
// карточки одного пореза. Теперь хватает одного вида на одной зоне тела;
// разные стороны («правая» и «левая» ладонь) — разные травмы.
export function тотЖеВред(a, b) {
  if (a.ключ && a.ключ === b.ключ) return true;
  const сa = сторона((a.где || '') + ' ' + a.что), сb = сторона((b.где || '') + ' ' + b.что);
  if (сa && сb && сa !== сb) return false;
  const имя = норм(a.что) === норм(b.что);
  const вид = a.вид && a.вид !== 'other' && a.вид === b.вид;
  const зa = зонаВреда(a), зb = зонаВреда(b);
  if (зa && зb) return зa === зb && (имя || вид);
  if (зa || зb) return имя || вид;
  return имя;
}

