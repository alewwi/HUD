function искра(ряд) {
  if (ряд.length < 2) return '';
  const W = 72, H = 22, П = 3;
  let lo = Math.min(...ряд), hi = Math.max(...ряд);
  if (hi - lo < 1) { lo -= 1; hi += 1; }
  const точки = ряд.map((v, i) => [П + i * (W - 2 * П) / (ряд.length - 1), H - П - (v - lo) / (hi - lo) * (H - 2 * П)]);
  const [x, y] = точки[точки.length - 1];
  const линия = точки.map(([a, b]) => a.toFixed(1) + ',' + b.toFixed(1)).join(' ');
  const заливка = `${точки[0][0].toFixed(1)},${H} ${линия} ${x.toFixed(1)},${H}`;
  return `<svg class="hud-vit-spark" viewBox="0 0 ${W} ${H}" aria-hidden="true"><polygon class="area" points="${заливка}"/><polyline points="${линия}"/><circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="3"/></svg>`;
}

export function buildVitals(value, владелец) {
  const п = метки(value);
  const прошлое = история(владелец).slice().reverse();
  const плитки = ПОКАЗАТЕЛИ.map(х => {
    const сырое = п[х.ключ];
    if (пусто(сырое)) return '';
    const v = число(сырое);
    // Описание — то, что после числа и запятой: «30, частое». Запятая внутри
    // самого числа («37,4») описанием не считается.
    const описание = ((сырое.match(/^\s*-?\d+(?:[.,]\d+)?(?![.,]?\d)\s*[^\d\s,]*\s*,\s*(.+)$/) || [])[1] || '').trim();
    const ряд = прошлое.map(р => число(метки(поле(р.данные, 'Жизненные показатели'))[х.ключ])).filter(Number.isFinite);
    if (Number.isFinite(v)) ряд.push(v);
    const хвост = ряд.slice(-8);
    const выше = Number.isFinite(v) && v > х.норма;
    const показ = Number.isFinite(v) ? (х.дробь ? v.toFixed(1).replace('.', ',') : String(Math.round(v))) : escapeHtml(сырое);
    const бит = х.ключ === 'пульс' && Number.isFinite(v) ? ` style="--beat:${(60 / ограничить(v, 30, 220)).toFixed(3)}s"` : '';
    const подсказка = х.подпись + ': ' + сырое + (хвост.length > 1 ? ' · по ходам: ' + хвост.map(n => х.дробь ? n.toFixed(1) : Math.round(n)).join(' → ') : '');
    // Шкала температуры 35–41 °C: где сейчас тело относительно нормы.
    const шкала = х.вид === 'temp' && Number.isFinite(v)
      ? `<i class="hud-vit-gauge" aria-hidden="true"><i style="left:${(ограничить((v - 35) / 6, 0, 1) * 100).toFixed(1)}%"></i></i>` : '';
    return `<div class="hud-vit is-${х.вид}${выше ? ' is-up' : ''}" title="${escapeHtml(подсказка)}">`
      + х.линия
      + `<span class="hud-vit-label"><i class="hud-vit-ico" aria-hidden="true">${х.значок}</i>${х.ключ === 'пульс' ? `<i class="hud-vit-beat"${бит} aria-hidden="true"></i>` : ''}${х.подпись}</span>`
      + `<span class="hud-vit-value"><b>${показ}</b>${Number.isFinite(v) ? `<small>${х.ед}</small>` : ''}</span>`
      + шкала
      + искра(хвост)
      + (выше ? `<span class="hud-vit-flag">↑ выше нормы</span>` : '')
      + (описание ? `<em>${escapeHtml(описание)}</em>` : '')
      + `</div>`;
  }).join('');
  return плитки ? `<div class="hud-vitals">${плитки}</div>` : '';
}

/* --- Облако звуков -------------------------------------------------------
   Громкость — размером, насыщенностью и мини-эквалайзером у слова. */

export function buildSounds(value) {
  const теги = разбитьСписок(value).map(кусок => {
    const m = кусок.match(/^\s*([^:：]+)[:：]\s*(.+)$/);
    const имя = (m ? m[1] : кусок).trim();
    const v = m ? число(m[2]) : NaN;
    // «Стоны: 8 — низкие, протяжные»: после громкости — как звучит.
    const описание = !m ? '' : Number.isFinite(v)
      ? m[2].replace(/^\s*-?\d+(?:[.,]\d+)?\s*(?:\/\s*10)?\s*[—–:,-]?\s*/, '').trim()
      : m[2].trim();
    return { имя, г: Number.isFinite(v) ? ограничить(v, 0, 10) : 5, описание: пусто(описание) ? '' : описание };
  }).filter(т => т.имя && !пусто(т.имя));
  if (!теги.length) return '';
  теги.sort((a, b) => b.г - a.г);
  return `<div class="hud-sounds">${теги.map(т => `<span class="hud-sound${т.описание ? ' has-desc' : ''}" style="--г:${т.г}" title="${escapeHtml(т.имя)} — громкость ${т.г} из 10">`
    + `<i class="hud-sound-eq" aria-hidden="true"><i></i><i></i><i></i><i></i></i><b>${escapeHtml(т.имя)}</b>`
    + `${т.описание ? `<small class="hud-sound-desc">${applyTooltips(т.описание)}</small>` : ''}</span>`).join('')}</div>`;
}

