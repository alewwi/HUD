// «hr: 118; br: 28, частое» → { 'пульс': '118', 'дыхание': '28, частое' }.
function метки(текст) {
  const out = {};
  String(текст || '').split(/[;\n]/).forEach(часть => {
    const m = часть.match(/^\s*([^:：]{1,40})[:：]\s*(.*)$/);
    if (m) out[перевестиМетку(m[1].trim()).toLowerCase()] = m[2].trim();
  });
  return out;
}

function поле(о, имя) {
  if (!о || typeof о !== 'object') return '';
  const низ = имя.toLowerCase();
  const ключ = Object.keys(о).find(k => k.toLowerCase() === низ);
  return ключ ? снятьЗаглушки(flattenFieldValue(о[ключ])) : '';
}

/* ---------------------------------------------------------------------
   ИСТОРИЯ ПРОШЛЫХ ХОДОВ
   ---------------------------------------------------------------------
   Таймеру следов и графикам пульса нужны прошлые ходы. Разбор берём у
   переноса списков — он уже держит разобранные ходы в кэше. Историю вешаем
   на сам объект персонажа неперечисляемым свойством: вкладки собираются
   лениво, иногда много позже отрисовки, и глобальная переменная к тому
   времени указывала бы на другое сообщение. */

const ГЛУБИНА_СООБЩЕНИЙ = 60;
const ГЛУБИНА_ХОДОВ = 20;

function прошлыеХоды(индекс) {
  let chat = null;
  try { const ctx = window.SillyTavern && window.SillyTavern.getContext && window.SillyTavern.getContext(); chat = ctx && Array.isArray(ctx.chat) ? ctx.chat : null; } catch (_) { chat = null; }
  if (!chat) return [];
  const out = [];
  for (let j = Math.min(индекс, chat.length) - 1; j >= 0 && j >= индекс - ГЛУБИНА_СООБЩЕНИЙ && out.length < ГЛУБИНА_ХОДОВ; j--) {
    const d = разобратьХод(chat[j]);
    if (d) out.push({ назад: out.length + 1, d });
  }
  return out;
}

export function привязатьИсторию(data, индекс) {
  if (!data || typeof data !== 'object') return;
  // Момент текущей сцены — для отсчёта следов по времени сюжета.
  const сейчас = моментСцены(data.scene);
  const естьПрошлое = Number.isInteger(индекс) && индекс > 0;
  let кэш = null;
  const ходы = () => (кэш || (кэш = естьПрошлое ? прошлыеХоды(индекс) : []));
  const повесить = (о, достать) => {
    if (!о || typeof о !== 'object') return;
    Object.defineProperty(о, '__hudИстория', {
      value: () => ходы().map(х => ({ назад: х.назад, данные: достать(х.d), момент: моментСцены(х.d.scene) })).filter(x => x.данные),
      enumerable: false, configurable: true,
    });
    Object.defineProperty(о, '__hudМомент', { value: () => сейчас, enumerable: false, configurable: true });
  };
  (Array.isArray(data.characters) ? data.characters : []).forEach(c => {
    if (c && c['Имя']) повесить(c, d => (Array.isArray(d.characters) ? d.characters : []).find(p => p && namesLikelySame(p['Имя'], c['Имя'])));
  });
  повесить(data.user, d => d.user);
}

