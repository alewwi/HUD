// --- Риск зачатия ------------------------------------------------------------
// Вероятность зачатия от одного акта по дню относительно овуляции — по
// данным Уилкокса (NEJM, 1995): окно шесть дней, пик в день овуляции и за
// день-два до неё. Вне окна шанс не нулевой, но мал: цикл может сдвинуться.
const ШАНС_ПО_ДНЮ = { '-5': .10, '-4': .16, '-3': .14, '-2': .27, '-1': .31, '0': .33, '1': .08 };
const ВНЕ_ОКНА = .02;
// Защита: сколько от шанса остаётся. Порвавшийся презерватив и «кончил
// внутрь без защиты» — полный шанс.
const ЗАЩИТА_ЗАЧАТИЯ = [
  [/порвал|соскочил|слетел|сполз|broke|slipped/i, 1, 'защита подвела'],
  // Отрицание раньше названия средства: «без презерватива» — это не презерватив.
  [/(?:без|не\s+(?:надел|использовал|взял|предохранял)[а-яё]*|забыл[а-яё]*(?:\s+про)?|\bno|\bwithout)\s+(?:a\s+)?(?:презерватив|кондом|резинк|защит|контрацеп|таблет|condom|protection)|unprotected|bareback/i, 1, 'без защиты'],
  [/пропуст[а-яё]*\s+(?:при[её]м\s+)?таблет|missed\s+(?:a\s+)?pill/i, .5, 'пропущенная таблетка'],
  [/без защит|не предохран|none|нет защит|кончил (?:в неё|внутрь)|в неё кончил/i, 1, 'без защиты'],
  [/спирал|внутриматоч|iud|имплант/i, .02, 'спираль'],
  [/таблет|противозачат|(?<![а-яё])ок(?![а-яё])|гормональ|pill/i, .08, 'таблетки'],
  [/экстренн|постинор|plan b|morning.after/i, .2, 'экстренная контрацепция'],
  [/презерватив|кондом|condom/i, .15, 'презерватив'],
  [/прерван|вынул|вытащил|кончил (?:на|снаружи)|withdraw|pull.out/i, .25, 'прерванный акт'],
  [/спермицид|свеч/i, .3, 'спермицид'],
];
function защитаИз(текст) {
  const s = String(текст || '');
  if (!s.trim() || /^(empty|none)$/i.test(s.trim())) return null;
  const найдено = ЗАЩИТА_ЗАЧАТИЯ.find(([rx]) => rx.test(s));
  return найдено ? { доля: найдено[1], имя: найдено[2] } : null;
}

// Бросок кубика привязан к конкретной близости: одна и та же сцена всегда
// даёт одно и то же число, как бы часто карточка ни перерисовывалась.
function бросок(ключ) {
  let h = 2166136261;
  for (const ch of String(ключ)) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619); }
  h ^= h >>> 13; h = Math.imul(h, 0x5bd1e995); h ^= h >>> 15;
  return (Math.abs(h) % 100) + 1;
}

/**
 * Риск зачатия и бросок кубика.
 * день, L — день и длина цикла; фаза — ключ фазы; контекст — поля карточки:
 * «Защита» и «Последний секс». Бросок показываем, только если близость была.
 */
export function рискЗачатия(день, L, фаза, контекст = {}) {
  const ov = L - 14;
  let шанс = ВНЕ_ОКНА;
  if (день) шанс = ШАНС_ПО_ДНЮ[String(день - ov)] ?? ВНЕ_ОКНА;
  else if (фаза === 'ovulation') шанс = .3;
  else if (фаза === 'follicular') шанс = .08;
  const защита = защитаИз(контекст.защита);
  const итог = шанс * (защита ? защита.доля : 1);
  const секс = String(контекст.секс || '').trim();
  const был = секс && !/^(empty|none|нет|не было)$/i.test(секс);
  return {
    шанс: итог, базовый: шанс, защита,
    бросок: был ? бросок(секс + '|' + (день || фаза || '')) : null,
  };
}

// Полоса риска и кнопка «Сделать тест». Сам бросок кубика игроку не
