// hud-manager/render/life-prose.js
//
// Душ и ванна из прозы ответа — для быта (render/life.js), когда модель не
// внесла их ни в таймлайн, ни в место. Осторожно, по одному предложению:
//   • только авторская речь: без HUD, рассуждений, вставных блоков (комментарии
//     зрителей, сводки, плееры — всё, что внутри блочных тегов) и прямой речи;
//   • только совершённое действие: «встал под душ», «заперся в ванной»,
//     «смыла с себя пот», «дверь ванной захлопнулась за его спиной»;
//   • мимо — отрицание прямо перед действием («не пошёл в душ»), намерение и
//     условие в той же фразе («хотел», «если», «бы», «сбежать в душ»),
//     воспоминание («вспомнил свой душ», «знала, почему он рванул в душ»),
//     вопрос и чужое тело («смывала акварель с их щёк»).

import { extractHudBlock } from '../hud-block.js?v=23.48.1';

const сл = (rx) => new RegExp('(?<![\\p{L}])(?:' + rx + ')', 'iu');

// Место мытья. «на душе», «душно», «душил», «ни одна живая душа» сюда не попадают.
const ВАННА = 'ванн(?:а|у|ой|е|ая|ую|ые|ых|ами)?(?![\\p{L}])|ванн(?:ой|ая|ую) комнат\\p{L}*|(?<!на )(?<!живая )душ(?:е|ем|а|евой|евую|евая|евых)?(?![\\p{L}])|душев(?:ая|ой|ую|ых) (?:кабин|зон|галере)\\p{L}*|джакузи|купел\\p{L}*|бан(?:я|е|ю)(?![\\p{L}])|саун\\p{L}*|парилк\\p{L}*';
const МЕСТО = сл(ВАННА);

// Совершённое мытьё — у каждого правила есть глагол действия.
const ДЕЙСТВИЯ = [
  // «встал под душ», «зашла в душевую», «ушёл в ванную», «заперся в ванной», «зашагал в сторону ванной»
  сл('(?:встал|встала|встали|стоял|стояла|стоят|стоит|шагнул|шагнула|зашагал|зашагала|зашёл|зашел|зашла|вош[её]л|вошла|ушёл|ушел|ушла|ушли|уходит|сбежал|сбежала|сбегает|убежал|убежала|убегает|рванул|рванула|скрылся|скрылась|заперся|заперлась|запирается|закрылся|закрылась|направился|направилась|направляется|пош[её]л|пошла|отправился|отправилась|двинулся|опустился|опустилась|погрузился|погрузилась|лежал|лежала|лежит|сидел|сидела|сидит|нырнул|нырнула|залез|залезла|исчез|исчезла)(?:\\s+[\\p{L},-]+){0,9}?\\s+(?:в|во|под|за)\\s+(?:[\\p{L}-]+\\s+){0,3}(?:' + ВАННА + ')'),
  // «принял ледяной душ», «приняла ванну»
  сл('(?:принял|приняла|приняли|принимал|принимала|принимает)\\s+(?:\\p{L}+\\s+){0,2}(?:душ|ванн)'),
  // «смыла с себя пот», «смыл сперму с бёдер» — своё тело
  сл('(?:смыл|смыла|смыли|смывал|смывала|смывает|отмыл|отмыла|отмывал|отмывала)\\s+(?:с себя\\s+)?(?:\\p{L}+\\s+){0,3}(?:пот|сперм\\p{L}*|семя|пену|мыло|шампун\\p{L}*)'),
  сл('(?:смыл|смыла|смыли|смывал|смывала|смывает|отмыл|отмыла)\\s+(?:\\p{L}+\\s+){0,4}с\\s+(?:себя|своей|своих|своего|кожи|тела|груди|бёдер|бедер|живота)'),
  // «намылилась», «вымыл голову», «помылась», «ополоснулся», «вытерлась полотенцем», «вышел из душа»
  сл('намылил\\p{L}*|вымыл(?:а|и)?\\s+(?:\\p{L}+\\s+)?(?:голов|волос|тел)|помыл(?:ся|ась|ись)|мылся|мылась|ополоснул(?:ся|ась)|вытер(?:ся|лась)\\s+(?:\\p{L}+\\s+)?полотенц|завернул(?:ся|ась)\\s+в\\s+(?:\\p{L}+\\s+)?полотенц|вышел из (?:душ|ванн)|вышла из (?:душ|ванн)'),
  // «дверь ванной захлопнулась за его спиной» — ушёл в ванную
  сл('двер\\p{L}* (?:\\p{L}+ ){0,2}(?:ванн|душев)\\p{L}*(?:\\s+[\\p{L},-]+){0,8}?\\s+(?:захлопнул|закрыл|хлопнул)\\p{L}*'),
];
// Вода по телу или шум воды — мытьё, только с местом мытья в той же фразе
// (иначе это дождь, море, слёзы).
const ВОДА = сл('(?:вода|воды|струи|струя|струями|капли воды|душ)(?:\\s+[\\p{L},-]+){0,6}?\\s+(?:стека\\p{L}*|бил[аио]?|бьют|хлеста\\p{L}*|барабани\\p{L}*|лил[аио]?|льётся|льется|текл[аио]?|обжига\\p{L}*|смыва\\p{L}*|шумел\\p{L}*|шумит|зашумел\\p{L}*)|шум\\p{L}* (?:\\p{L}+ ){0,3}вод\\p{L}*|под (?:\\p{L}+ )?струями');
// Свежесть после мытья: «капли воды на шее после душа», «мокрые волосы после ванны».
const ПОСЛЕ = сл('после (?:\\p{L}+ )?(?:душа|ванны|бани|сауны)');
const СВЕЖО = сл('капл\\p{L}* воды|мокр\\p{L}*|влажн\\p{L}*|халат\\p{L}*|полотенц\\p{L}*|мыл(?:а|ом|ьн)\\p{L}*|распаренн\\p{L}*|пахн\\p{L}* (?:мыл|гел|шампун|чистот)');
// Близость в ванной/душе: место и сама близость — в одной фразе.
const БЛИЗОСТЬ = сл('вош[её]л в не[её]|входил|вбивал\\p{L}*|толчк\\p{L}*|трахал\\p{L}*|насадил\\p{L}*|член\\p{L}*|соити\\p{L}*|секс\\p{L}*|кончил\\p{L}*|оргазм\\p{L}*|прижал\\p{L}* (?:\\p{L}+ )?к (?:кафел|плитк|стекл|стен)|раунд\\p{L}*');

// Отрицание прямо перед действием: «не пошёл в душ», «так и не принял ванну».
const ОТРИЦАНИЕ = /(?<![\p{L}])(?:не|ни|никак|никаких|никакого|нельзя|без)\s+(?:\p{L}+\s+){0,1}$/iu;
// Намерение, условие, повеление, воспоминание — где угодно во фразе до действия.
const НЕ_СЛУЧИЛОСЬ = сл('хотел\\p{L}*|хочет|хотелось|захотел\\p{L}*|собирал\\p{L}*|собира\\p{L}*|мечта\\p{L}*|попыт\\p{L}*|пыта\\p{L}*|пытал\\p{L}*|намерева\\p{L}*|бы(?![\\p{L}])|если|пойд[её]м|пойд[её]шь|примешь|иди(?![\\p{L}])|сходи(?![\\p{L}])|можно|надо|нужно|должн\\p{L}*|позже|завтра|ждал\\p{L}*|предлож\\p{L}*|разреш\\p{L}*|позвол\\p{L}*|отказ\\p{L}*|вместо|запрет\\p{L}*|никаких|вспомнил\\p{L}*|вспомина\\p{L}*|помнил\\p{L}*|помнит|знал\\p{L}*|знает|почему|вчера|накануне|с утра|утром|прошл\\p{L}* ночь|однажды|когда-то|в детстве|лет назад|годы назад|годами|в (?:\\d+|пятнадцать|шестнадцать|десять|двенадцать|семнадцать|восемнадцать) лет|тогда|ночью, когда|в ту ночь|той ночью|подействовал\\p{L}* как|стал\\p{L}* (?:\\p{L}+ )?душем|как (?:\\p{L}+ )?душ|словно (?:\\p{L}+ )?душ|будто (?:\\p{L}+ )?душ|глушил\\p{L}* (?:\\p{L}+ )?душем|представ\\p{L}*|воображ\\p{L}*|снил\\p{L}*|снится|будто|словно|как будто');
// Инфинитив перед «в душ» — намерение: «сбежать в душ», «уйти в ванную».
const ИНФИНИТИВ = сл('\\p{L}+(?:ть|ться|чь|сти)\\s+(?:\\p{L}+\\s+){0,2}(?:в|под)\\s+(?:' + ВАННА + ')');
// Чужое тело: «смывала акварель с их щёк», «вымыла детям головы».
const ЧУЖОЕ = сл('с (?:их|его|её|ее|детск\\p{L}*) |детям|детей|ребёнк|ребенк|сына|дочер|близнец');

// Строчные теги — прозрачны (внутри обычный текст рассказа), остальные — контейнеры
// вставных блоков, их содержимое выбрасываем целиком.
const СТРОЧНЫЕ = new Set(['b', 'i', 'em', 'strong', 'u', 's', 'span', 'font', 'small', 'sup', 'sub', 'mark', 'q', 'a', 'del', 'ins', 'abbr', 'cite']);
const ПУСТЫЕ = new Set(['br', 'hr', 'img', 'input', 'meta', 'link', 'wbr', 'source', 'area', 'col', 'embed', 'param', 'track']);

/** Проза ответа: только авторский текст вне HUD, вставных блоков и прямой речи. */
export function прозаХода(текстСообщения) {
  // Невидимые «пробелы» (⠀ U+2800, неразрывный, тонкие) — обычными: модели
  // пишут ими целые сообщения, а \s их не видит.
  let s = String(текстСообщения || '').replace(/[⠀  -​  　]/g, ' ');
  const hud = extractHudBlock(s);
  if (hud) s = s.split(hud).join(' ');
  // Рассуждения и код — до разбора тегов: в <plan> модель пишет о тегах
  // текстом («`<time>` в начале»), и такие «теги» сбили бы глубину.
  s = s.replace(/<(plan|think|thinking|reasoning|analysis)\b[^>]*>[\s\S]*?<\/\1\s*>/gi, ' ')
    .replace(/```[\s\S]*?```/g, ' ').replace(/`[^`\n]*`/g, ' ')
    .replace(/\[HUD\][\s\S]*?\[\/HUD\]/gi, ' ').replace(/<!--[\s\S]*?-->/g, ' ');
  // Текст на глубине 0 по блочным тегам.
  let out = '', глубина = 0, с = 0;
  for (const м of s.matchAll(/<\/?([a-zA-Z][\w-]*)\b[^>]*>/g)) {
    const тег = м[1].toLowerCase();
    if (глубина === 0) out += s.slice(с, м.index);
    с = м.index + м[0].length;
    if (СТРОЧНЫЕ.has(тег)) continue;
    if (ПУСТЫЕ.has(тег) || м[0].endsWith('/>')) { if (глубина === 0) out += ' '; continue; }
    if (м[0][1] === '/') { if (глубина > 0) глубина--; } else глубина++;
  }
  if (глубина === 0) out += s.slice(с);
  out = out.replace(/&[a-z#0-9]+;/gi, ' ')
    // Строки-подписи вставок: «AuraSource: …», «Text: …», «• Действие: …», ники зрителей.
    .replace(/(^|\n)\s*(?:[•·▪◦-]\s*)?[A-Za-z_][\w .]{0,30}:[^\n]*/g, '$1 ')
    .replace(/(^|\n)\s*[•·▪◦]\s*[^\n]*/g, '$1 ');
  // Прямая речь: «…», "…", “…” и реплики через тире до конца абзаца.
  out = out.replace(/«[^»]*»/g, ' ').replace(/"[^"\n]*"/g, ' ').replace(/“[^”]*”/g, ' ')
    .replace(/(^|\n)\s*[—–-]\s[^\n]*/g, '$1 ');
  return out.replace(/[*_~]+/g, '').replace(/[ \t]+/g, ' ').trim();
}

// Фраза годится, если правило нашлось и перед ним нет отрицания, а во фразе до
// него — намерения, условия, воспоминания.
function совершено(ф, rx) {
  const м = ф.match(rx);
  if (!м) return false;
  const до = ф.slice(0, м.index);
  return !ОТРИЦАНИЕ.test(до) && !НЕ_СЛУЧИЛОСЬ.test(до + ' ' + м[0]) && !ИНФИНИТИВ.test(ф);
}

/**
 * Мытьё в прозе: { что, сцена, фраза } или null. Фраза — предложение, в
 * котором нашли; «сцена» — близость в душе/ванной.
 */
export function мытьёИзПрозы(проза) {
  const фразы = String(проза || '').split(/(?<=[.!…])\s+|\n+/).map(f => f.trim()).filter(Boolean);
  for (const ф of фразы) {
    if (/\?\s*$/.test(ф) || ф.length < 12) continue;
    const место = (ф.match(МЕСТО) || [''])[0].toLowerCase();
    const где = /джакуз/.test(место) ? 'в джакузи' : /душ/.test(место) ? 'в душе' : /ванн/.test(место) ? 'в ванной' : /бан|саун|парилк/.test(место) ? 'в бане' : 'в душе';
    const подпись = (/джакуз/.test(место) ? 'джакузи' : /душ/.test(место) ? 'душ' : /ванн/.test(место) ? 'ванная' : /бан|саун|парилк/.test(место) ? 'баня' : 'смыл(а) с себя') + ' (по тексту)';
    if (место && совершено(ф, БЛИЗОСТЬ)) return { что: 'близость ' + где, сцена: true, фраза: ф.slice(0, 220) };
    if (ДЕЙСТВИЯ.some(rx => совершено(ф, rx)) && !ЧУЖОЕ.test(ф)) return { что: подпись, сцена: false, фраза: ф.slice(0, 220) };
    if (место && совершено(ф, ВОДА)) return { что: подпись, сцена: false, фраза: ф.slice(0, 220) };
    if (совершено(ф, ПОСЛЕ) && СВЕЖО.test(ф)) return { что: подпись, сцена: false, фраза: ф.slice(0, 220) };
  }
  return null;
}
