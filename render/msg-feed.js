// hud-manager/render/msg-feed.js
//
// Лента переписки: строки сообщений и разделители дней. Одна на оба
// мессенджера — личный телефон и перехваты.
//
// Раньше перехваты рисовали сообщения своим кодом: там не было ни
// черновиков, ни удалённых, ни отметок о прочтении — всё это жило только в
// телефоне. Теперь обе стороны зовут собратьЛенту(), и любое новое умение
// появляется сразу в обоих.
//
// Разделители дней нужны из-за переноса с прошлых ходов: в одной переписке
// оказываются рядом вчерашнее «22:30» и сегодняшнее «08:30», и без подписи
// «Вчера» это читается как один разговор подряд.

import { escapeHtml, defeatWI } from '../utils.js?v=22.99.96';
import { buildBubbleInner, buildCallRow, msgKey } from './msg-parts.js?v=22.99.96';
import { avaFace } from './phone-common.js?v=22.99.96';
import { namesLikelySame } from '../names.js?v=22.99.96';

const МЕСЯЦЫ_РОД = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];

// Поле времени сообщения целиком: «Вчера, 14:30», «12.10 09:00», «10:00».
// msgTimeOf() отдаёт только часы с минутами, а для дня нужна вся подпись.
export function полеВремени(raw) {
  const s = String(raw || '');
  const ДЕНЬ = /(?:вчера|сегодня|завтра|позавчера|\d{1,2}\s*[.\/-]\s*\d{1,2}|\d{1,2}\s+[а-яё]{3,})/i;
  const части = s.split('|').map(x => x.trim());
  if (части.length > 1) {
    // Поле со временем или с днём — любое из полей после первого.
    const поле = части.slice(1).find(x => /\d{1,2}:\d{2}/.test(x) || ДЕНЬ.test(x));
    if (поле) return поле;
  }
  const хвост = s.match(/((?:вчера|сегодня|завтра|позавчера)?[,\s]*\d{1,2}:\d{2})\s*(?:✓+|read|unread|доставлен[а-я]*|прочитан[а-я]*|отправлен[а-я]*|draft|черновик)?\s*$/i);
  return хвост ? хвост[1].trim() : '';
}

// Дата сцены: «16.01.2025», «16.01», «ЧЕТВЕРГ, 16 ЯНВАРЯ 2025».
export function датаСцены(строка) {
  const s = String(строка || '').toLowerCase();
  let m = s.match(/(\d{1,2})\s*[.\/-]\s*(\d{1,2})(?:\s*[.\/-]\s*(\d{2,4}))?/);
  if (m) return { d: +m[1], mo: +m[2], y: m[3] ? (m[3].length === 2 ? 2000 + +m[3] : +m[3]) : null };
  m = s.match(/(\d{1,2})\s+([а-яё]{3,})(?:\s+(\d{3,4}))?/);
  if (m) {
    const i = МЕСЯЦЫ_РОД.findIndex(н => m[2].startsWith(н.slice(0, 4)));
    if (i >= 0) return { d: +m[1], mo: i + 1, y: m[3] ? +m[3] : null };
  }
  return null;
}

const вЧисло = ({ d, mo, y }) => (y || 1970) * 10000 + mo * 100 + d;
// Сдвиг на сутки честным календарём: «1 марта минус день» — это 28 или 29 февраля.
function сдвинуть(дата, дней) {
  const t = new Date(Date.UTC(дата.y || 2000, дата.mo - 1, дата.d + дней));
  return { d: t.getUTCDate(), mo: t.getUTCMonth() + 1, y: дата.y ? t.getUTCFullYear() : null };
}

// День сообщения: абсолютная дата, если её удалось вычислить, иначе сдвиг
// в сутках от дня сцены («вчера» без даты сцены).
export function деньСообщения(поле, сцена) {
  const s = String(поле || '').toLowerCase();
  if (!s) return null;
  const сдвиг = /позавчера/.test(s) ? -2 : /вчера/.test(s) ? -1 : /завтра/.test(s) ? 1 : /сегодня/.test(s) ? 0 : null;
  if (сдвиг !== null) {
    return сцена ? { дата: сдвинуть(сцена, сдвиг) } : { сдвиг };
  }
  let m = s.match(/\b(\d{1,2})\s*[.\/-]\s*(\d{1,2})(?:\s*[.\/-]\s*(\d{2,4}))?/);
  if (m && +m[1] <= 31 && +m[2] <= 12) {
    const y = m[3] ? (m[3].length === 2 ? 2000 + +m[3] : +m[3]) : (сцена && сцена.y) || null;
    return { дата: { d: +m[1], mo: +m[2], y } };
  }
  m = s.match(/\b(\d{1,2})\s+([а-яё]{3,})/);
  if (m) {
    const i = МЕСЯЦЫ_РОД.findIndex(н => m[2].startsWith(н.slice(0, 4)));
    if (i >= 0 && +m[1] <= 31) return { дата: { d: +m[1], mo: i + 1, y: (сцена && сцена.y) || null } };
  }
  return null;
}

// Подпись разделителя: «Сегодня», «Вчера» или «20 сентября».
function подписьДня(день, сцена) {
  if (!день) return '';
  if (день.сдвиг !== undefined) {
    return { '-2': 'Позавчера', '-1': 'Вчера', 0: 'Сегодня', 1: 'Завтра' }[String(день.сдвиг)] || '';
  }
  const d = день.дата;
  if (сцена) {
    const свой = вЧисло({ ...d, y: d.y || сцена.y || 1970 });
    const день0 = вЧисло({ ...сцена, y: сцена.y || 1970 });
    if (свой === день0) return 'Сегодня';
    if (свой === вЧисло({ ...сдвинуть(сцена, -1), y: (сдвинуть(сцена, -1).y) || 1970 })) return 'Вчера';
    if (свой === вЧисло({ ...сдвинуть(сцена, 1), y: (сдвинуть(сцена, 1).y) || 1970 })) return 'Завтра';
  }
  const название = МЕСЯЦЫ_РОД[(d.mo - 1 + 12) % 12] || '';
  const год = d.y && сцена && сцена.y && d.y !== сцена.y ? ` ${d.y}` : '';
  return `${d.d} ${название}${год}`.trim();
}

const ключДня = (день) => день ? (день.сдвиг !== undefined ? 'rel' + день.сдвиг : 'abs' + вЧисло({ ...день.дата, y: день.дата.y || 1970 })) : '';

// Дни всех сообщений подряд. Голые часы («08:30») — это сегодня: промт
// требует писать день у всего, что не из дня сцены. Даты сцены нет —
// угадывать нечем, и тогда голые часы продолжают день предыдущего
// сообщения, как в настоящем мессенджере.
export function дниСообщений(messages, сценаСтрока) {
  const сцена = датаСцены(сценаСтрока);
  const список = (Array.isArray(messages) ? messages : []).map(m => деньСообщения(полеВремени(m), сцена));
  let последний = null;
  const дни = список.map(д => сцена ? (д || { дата: сцена }) : (последний = д || последний));
  return дни.map(д => ({ ключ: ключДня(д), подпись: подписьДня(д, сцена) }));
}

const разделитель = (подпись) => `<div class="hud-msg-day"><span>${escapeHtml(подпись)}</span></div>`;

// Дата хода проставляется сообщению при переносе с прошлых ходов
// (render/carryover.js): в том ходе «08:30» значило его собственный день, а
// не сегодняшний, и «вчера» отсчитывалось от его даты. Без этого сообщение
// трёхдневной давности выглядело сегодняшним. Уже записанную дату не трогаем:
// первый ход, где сообщение появилось, знает день точнее поздних.
export function проставитьДень(строка, датаХода) {
  const raw = String(строка || '');
  const сцена = датаСцены(датаХода);
  if (!сцена) return raw;
  const поле = полеВремени(raw);
  if (!поле || !/\d{1,2}:\d{2}/.test(поле)) return raw;
  // Дата уже есть — значит день известен точно.
  if (/\d{1,2}\s*[.\/-]\s*\d{1,2}|\d{1,2}\s+[а-яё]{3,}/i.test(поле)) return raw;
  const день = деньСообщения(поле, сцена);
  const дата = (день && день.дата) || сцена;
  const часы = (поле.match(/\d{1,2}:\d{2}/) || [''])[0];
  const дд = String(дата.d).padStart(2, '0'), мм = String(дата.mo).padStart(2, '0');
  return raw.replace(поле, `${дд}.${мм}${дата.y ? '.' + дата.y : ''}, ${часы}`);
}

// Момент последнего сообщения переписки — числом, чтобы чаты можно было
// выстроить от свежих к старым. Одни часы сравнивать нельзя: вчерашние 22:30
// старше сегодняшних 08:30, а «22» больше «08».
export function моментПоследнего(messages, сценаСтрока) {
  const строки = (Array.isArray(messages) ? messages : []).filter(m => String(m || '').trim());
  if (!строки.length) return -Infinity;
  const дни = дниСообщений(строки, сценаСтрока);
  let лучший = -Infinity;
  строки.forEach((raw, i) => {
    const д = дни[i] || {};
    let база = 0;
    const m = String(д.ключ || '').match(/^abs(\d+)$/);
    if (m) {
      const n = +m[1];
      база = Date.UTC(Math.floor(n / 10000), Math.floor(n / 100) % 100 - 1, n % 100);
    } else {
      const сдвиг = +(String(д.ключ || '').match(/^rel(-?\d+)$/) || [, 0])[1];
      база = Date.UTC(2000, 0, 1 + сдвиг);
    }
    const часы = (полеВремени(raw).match(/(\d{1,2}):(\d{2})/) || []);
    const минуты = часы.length ? (+часы[1] * 60 + +часы[2]) * 60000 : 0;
    лучший = Math.max(лучший, база + минуты);
  });
  return лучший;
}

// Переписки от свежих к старым. Порядок должен быть один и в списке чатов, и
// в стопке уведомлений: по номеру чата открывается его тело, и разъехавшаяся
// нумерация открывала бы не ту переписку.
export function сортироватьЧаты(chatsMap, сценаСтрока) {
  const карта = chatsMap && typeof chatsMap === 'object' ? chatsMap : {};
  const имена = Object.keys(карта);
  const момент = new Map(имена.map(имя => [имя, моментПоследнего((карта[имя] || {}).messages, сценаСтрока)]));
  // Равные моменты оставляем в исходном порядке: сортировка устойчивая.
  const порядок = имена.slice().sort((a, b) => момент.get(b) - момент.get(a));
  const out = {};
  порядок.forEach(имя => { out[имя] = карта[имя]; });
  return out;
}

// Разбор одной строки: «Кто -> Кому: текст | время | статус».
export function разобратьСообщение(raw) {
  let части = String(raw || '').replace(/^(?:M|Msg|Сообщение|Chat|Чат):\s*/i, '').trim().split('|').map(s => s.trim());
  let тело = части[0], время = части.length > 1 ? части[1] : '', статус = части.length > 2 ? части.slice(2).join(' ') : '';
  if (части.length === 1) {
    const хвост = тело.match(/(.*?)\s*(?:\|?\s*)(\b(?:Вчера|Сегодня|Завтра|Позавчера)[,\s]*\d{1,2}:\d{2}|\b\d{1,2}:\d{2})(?:\s*\|?\s*)(✓+|read|unread|доставлен[а-я]*|прочитан[а-я]*|отправлен[а-я]*|draft|черновик)?$/i);
    if (хвост) { тело = хвост[1].trim(); время = хвост[2].trim(); статус = (хвост[3] || '').trim(); }
  }
  const низ = (статус || '').toLowerCase();
  const удалено = /delete|удален/.test(низ) || /\[удалено\]/i.test(тело);
  const черновик = /draft|черновик/.test(низ) || /\[черновик\]/i.test(тело);
  тело = тело.replace(/\[удалено\]|\[черновик\]|✓+/gi, '').trim();
  let кто = 'Unknown', текст = тело;
  // Дефис — часть фамилии («Ченнинг-Уинтроп»), из имени его не исключаем.
  const m = тело.match(/^([^:]+?)(?:\s*(?:->|→)\s*([^:]+?))?\s*:\s*([\s\S]*)$/);
  if (m) { кто = m[1].trim(); текст = m[3].trim(); }
  // Время в поле дня: «Вчера, 14:30» → на пузыре только часы.
  const часы = (String(время).match(/\d{1,2}:\d{2}/) || [''])[0] || (/\d/.test(время) ? '' : время);
  return { кто, текст, время: часы, статус, удалено, черновик };
}

// Отметка о доставке у своих, точка непрочитанного у чужих.
function отметка(статус, исходящее) {
  const s = String(статус || '').toLowerCase();
  if (исходящее) {
    if (/read|прочитан|✓✓/.test(s)) return '<span class="msg-status read" style="color: #4facfe; font-weight: bold;">✓✓</span>';
    if (/delivered|доставлен/.test(s)) return '<span class="msg-status delivered" style="opacity: 0.8;">✓✓</span>';
    return '<span class="msg-status sent" style="opacity: 0.8;">✓</span>';
  }
  return /unread|не прочитан/.test(s) ? '<span class="msg-status unread-dot"></span>' : '';
}

/**
 * Лента сообщений одной переписки.
 * messages — строки от модели; owner — чьи сообщения считаем исходящими;
 * сцена — дата сцены (для «Сегодня» и «Вчера»); лицо — сборщик кружка
 * отправителя; черновикВПоле — телефон забирает черновик в строку ввода,
 * перехват показывает его пузырём: чужой недописанный текст — находка.
 * Возвращает { html, draft }.
 */
export function собратьЛенту(messages, { owner = '', сцена = '', лицо = null, черновикВПоле = false } = {}) {
  const строки = Array.isArray(messages) ? messages : [];
  const дни = дниСообщений(строки, сцена);
  const кружок = лицо || ((имя) => avaFace(имя, 'hud-msg-avatar', 'rgba(255,255,255,0.1)'));
  let html = '', draft = '', прошлыйДень = '';
  строки.forEach((raw, i) => {
    if (!String(raw || '').trim()) return;
    const { кто, текст, время, статус, удалено, черновик } = разобратьСообщение(raw);
    let исходящее = Boolean(owner && namesLikelySame(кто, owner));
    if (/^(?:user|you|вы|я|player)$/i.test(кто.trim())) исходящее = true;

    if (черновик && исходящее && черновикВПоле) { draft = текст; return; }

    // Разделитель дня — перед первым сообщением этого дня.
    const день = дни[i] || { ключ: '', подпись: '' };
    if (день.подпись && день.ключ !== прошлыйДень) {
      прошлыйДень = день.ключ;
      html += разделитель(день.подпись);
    }

    if (удалено) {
      html += `<div class="hud-msg-wrapper ${исходящее ? 'outgoing' : 'incoming'}">
        ${!исходящее ? кружок(кто) : ''}
        <div class="hud-msg-content" style="max-width: 100%;">
          <span class="hud-msg-sender">${escapeHtml(кто)}</span>
          <details class="hud-msg-deleted-details">
            <summary>🚫 Сообщение удалено</summary>
            <div class="hud-msg-deleted-text">${defeatWI(escapeHtml(текст))}</div>
          </details>
        </div>
      </div>`;
      return;
    }

    // Звонок — событие во всю ширину, а не реплика.
    const звонок = buildCallRow(текст, { sender: кто, time: время, outgoing: исходящее });
    if (звонок) { html += звонок; return; }

    const внутри = buildBubbleInner(текст);
    const мета = (время || отметка(статус, исходящее))
      ? `<div class="hud-msg-meta" style="display: flex; justify-content: flex-end; align-items: center; gap: 4px; font-size: 0.75em; opacity: 0.6; margin-top: 4px;"><span class="hud-msg-time">${escapeHtml(время)}</span>${отметка(статус, исходящее)}</div>`
      : '';
    html += `<div class="hud-msg-wrapper ${исходящее ? 'outgoing' : 'incoming'}${черновик ? ' is-draft' : ''}">
      ${!исходящее ? кружок(кто) : ''}
      <div class="hud-msg-content" style="max-width: 100%;">
        <span class="hud-msg-sender">${escapeHtml(кто)}</span>
        <div class="hud-msg-bubble" data-msg-key="${msgKey(текст)}">
          ${черновик ? '<div class="hud-msg-draft-mark">✎ черновик, не отправлено</div>' : ''}
          ${внутри}
          ${мета}
        </div>
      </div>
    </div>`;
  });
  return { html, draft };
}
