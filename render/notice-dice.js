function последнийОтвет(чат = контекст()?.chat || [], до = чат.length) {
  for (let j = Math.min(до, чат.length) - 1; j >= 0; j--) {
    const м = чат[j];
    if (!м || м.is_user || м.is_system) continue;
    return j;
  }
  return -1;
}

