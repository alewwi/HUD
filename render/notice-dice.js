/** «60% — дрожат руки…», «0 - дрожат руки», «дрожат руки (60%)», «дрожат руки
 *  (шанс заметить: 0%, один в саду)», «дрожат руки — 60%» → { процент, текст };
 *  пусто или «empty» — null. Тире модель ставит любые: дефис, короткое, длинное,
 *  минус, двойное. С кубиком промт не говорит, где ставить шанс, и модель пишет
 *  его и в начале, и в конце, и в скобках с пояснением: прежде такой не
 *  находился, и вид блока выпадал в голый текст с «(35%)».
 *  Число без «%» — шанс только с разделителем и пробелом: «3 бокала вина»,
 *  «3-й бокал», «2-3 человека», «20:15 - вышел» — не шанс. */
const ДЕФИС = String.raw`\-‐‑−﹣－`;
const ДЛИННОЕ = String.raw`‒–—―﹘~〜`;
const ЗНАК = String.raw`[${ДЕФИС}${ДЛИННОЕ}:：·•|=→]`;
const СЛОВО_ШАНСА = String.raw`(?:(?:шанс|риск|вероятност|chance|risk|odds)\p{L}*(?:\s+\p{L}+){0,4}\s*${ЗНАК}?\s*)`;
// Диапазон «20–30%» — среднее.
const СКОЛЬКО = String.raw`[~≈<>≤≥]?\s*(\d{1,3})(?:[.,]\d+)?(?:\s*[${ДЕФИС}${ДЛИННОЕ}]\s*(\d{1,3}))?\s*[%％]`;
const РХ = (т) => new RegExp(т, 'iu');
const ШАНС = {
  спередиСкобки: РХ(String.raw`^[(\[]\s*${СЛОВО_ШАНСА}?${СКОЛЬКО}\s*[)\]]\s*(?:${ЗНАК}|,)*\s*([\s\S]*)$`),
  спереди: РХ(String.raw`^${СЛОВО_ШАНСА}?${СКОЛЬКО}\s*(?:${ЗНАК}|,)*\s*([\s\S]*)$`),
  // Без «%»: пробел хотя бы с одной стороны знака, длинное тире — и вплотную.
  спередиЧисло: РХ(String.raw`^${СЛОВО_ШАНСА}?(\d{1,3})(?:\s+${ЗНАК}+\s*|${ЗНАК}+\s+|[${ДЛИННОЕ}:：|=→]+\s*|\s*${ЗНАК}*$)(?!\s*\d)([\s\S]*)$`),
  спередиНоль: РХ(String.raw`^(0)[${ДЕФИС}]+(?=\p{L})([\s\S]*)$`),
  сзадиСкобки: РХ(String.raw`^([\s\S]*?)\s*[(\[]\s*${СЛОВО_ШАНСА}?${СКОЛЬКО}\s*(?:(?:${ЗНАК}|[,;.])+\s*([^()\[\]]*?))?\s*[)\]]\s*[.;,!]?$`),
  // «(шанс заметить: 80% для Анны)» — без знака, только со словом «шанс».
  сзадиДля: РХ(String.raw`^([\s\S]*?)\s*[(\[]\s*${СЛОВО_ШАНСА}${СКОЛЬКО}\s+([^()\[\]]*?)\s*[)\]]\s*[.;,!]?$`),
  сзадиПояснение: РХ(String.raw`^([\s\S]*?)\s*[(\[]\s*([^()\[\]]*?)\s*(?:${ЗНАК}|[,;.])+\s*${СЛОВО_ШАНСА}?${СКОЛЬКО}\s*[)\]]\s*[.;,!]?$`),
  сзадиЧислоСкобки: РХ(String.raw`^([\s\S]*?)\s*[(\[]\s*(${СЛОВО_ШАНСА}?)(\d{1,3})\s*[)\]]\s*[.;,!]?$`),
  сзади: РХ(String.raw`^([\s\S]*?)\s*(?:${ЗНАК}|[,;.])+\s*${СЛОВО_ШАНСА}?${СКОЛЬКО}\s*\.?$`),
  сзадиЧисло: РХ(String.raw`^([\s\S]*?)(?:\s+${ЗНАК}+\s*|${ЗНАК}+\s+)(${СЛОВО_ШАНСА}?)(\d{1,3})\s*\.?$`),
};
const КРАЯ = РХ(String.raw`^(?:${ЗНАК}|[,;]|\s)+|(?:${ЗНАК}|[,;]|\s)+$`);
// Число без «%» в конце — шанс, если так и сказано или похоже: 0, 10, 15, 20…
const похожеНаШанс = (слово, n) => +n <= 100 && (!!слово || +n === 0 || (+n >= 10 && +n % 5 === 0));
export function разобратьМаску(value) {
  const s = String(Array.isArray(value) ? value.join('; ') : value ?? '').trim();
  if (!s || /^(empty|none|нет|пусто|—|-|nc)$/i.test(s)) return null;
  const ответ = (n, n2, текст, пояснение = '') => {
    const p = n2 === undefined ? parseInt(n, 10) : Math.round((parseInt(n, 10) + parseInt(n2, 10)) / 2);
    let т = String(текст || '').trim();
    while (КРАЯ.test(т)) т = т.replace(КРАЯ, '').trim();
    if (/^(empty|none|нет|пусто|nc)$/i.test(т)) т = '';
    const по = String(пояснение || '').trim();
    return { процент: Math.max(0, Math.min(100, p)), текст: [т, по && `(${по})`].filter(Boolean).join(' ') };
  };
  let m = s.match(ШАНС.спередиСкобки) || s.match(ШАНС.спереди);
  if (m) return ответ(m[1], m[2], m[3]);
  m = s.match(ШАНС.спередиЧисло) || s.match(ШАНС.спередиНоль);
  if (m && +m[1] <= 100) return ответ(m[1], undefined, m[2]);
  m = s.match(ШАНС.сзадиСкобки) || s.match(ШАНС.сзадиДля);
  if (m && m[1].trim()) return ответ(m[2], m[3], m[1], m[4]);
  m = s.match(ШАНС.сзадиПояснение);
  if (m && m[1].trim()) return ответ(m[3], m[4], m[1], m[2]);
  m = s.match(ШАНС.сзади);
  if (m && m[1].trim()) return ответ(m[2], m[3], m[1]);
  m = s.match(ШАНС.сзадиЧислоСкобки) || s.match(ШАНС.сзадиЧисло);
  if (m && m[1].trim() && похожеНаШанс(m[2], m[3])) return ответ(m[3], undefined, m[1]);
  return { процент: null, текст: s };
}
/** Стресс из «Состояния тела»: «str: 85 …» или «стресс: 85». */
export function стресс(данные) {
  const s = flattenFieldValue(данные && (данные['Состояние тела'] ?? данные.Bs)).trim();
  const m = s.match(/(?:^|[;\n,]\s*)(?:str|стресс|stress)\w*\s*[:：]\s*(\d{1,3})/i);
  return m ? +m[1] : null;
}
/** Доверие наблюдателя к человеку: его же строка «Доверие». */
function доверие(наблюдатель, кому) {
  const s = String(наблюдатель && наблюдатель['Доверие'] || '');
  for (const ч of s.split(/[;\n]/)) {
    const m = ч.match(/^\s*([^:：]{1,60}?)\s*[:：]\s*([−–-]?\d{1,3})/);
    if (m && namesLikelySame(m[1], кому)) return parseInt(m[2].replace(/[−–]/, '-'), 10);
  }
  return null;
}
/** Шанс заметить, 5…95. */
export function шансЗаметить({ процент = null, стрессЧел = null, доверие: д = null } = {}) {
  let ш = Number.isFinite(процент) ? процент : 35;
  if (Number.isFinite(стрессЧел) && стрессЧел >= 80) ш += 10;
  if (Number.isFinite(д)) ш += д >= 60 ? 15 : д >= 30 ? 5 : 0;
  return Math.max(5, Math.min(95, Math.round(ш)));
}

