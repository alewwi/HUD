// hud-manager/units.js
//
// Формат даты и времени, единицы температуры и ветра — только для показа.
// Модель пишет как раньше: день.месяц.год, 24-часовое время, градусы Цельсия,
// ветер в чём придётся. По этим записям HUD считает месяц, праздники, луну,
// фазу суток, сезон, холод и жару. Здесь они переписываются в видимом тексте
// карточки на выбранный формат: «17.10.2024» → «2024/10/17», «21:40» →
// «9:40 PM», «+9°C» → «48°F», «5 м/с» → «18 км/ч». Атрибуты, данные и сам
// HUD в сообщении не трогаются.
//
// Длительности («05:12» у звонка, «0:42» у голосового) — не время суток: их
// помечает невидимый знак ДЛИТ (или класс *-dur / *timer у тега), и они
// остаются как есть.

let формат = 'dmy';
let единица = 'c';
let часы = '24';
let ветер = 'auto';

export const ФОРМАТЫ_ДАТЫ = ['dmy', 'ymd', 'mdy', 'iso', 'cjk'];
export const ЕДИНИЦЫ_ВЕТРА = ['auto', 'ms', 'kmh', 'mph'];
/** Невидимая метка перед длительностью: «⁠05:12» не станет «5:12 AM». */
export const ДЛИТ = '\u2060';

/** Настройки из settings: dateFormat, tempUnit, timeFormat, windUnit. */
export function задатьЕдиницы({ dateFormat, tempUnit, timeFormat, windUnit } = {}) {
  формат = ФОРМАТЫ_ДАТЫ.includes(dateFormat) ? dateFormat : 'dmy';
  единица = tempUnit === 'f' ? 'f' : 'c';
  часы = timeFormat === '12' ? '12' : '24';
  ветер = ЕДИНИЦЫ_ВЕТРА.includes(windUnit) ? windUnit : 'auto';
}
export const форматДаты = () => формат;
export const единицаТемпературы = () => единица;
export const форматВремени = () => часы;
export const единицаВетра = () => ветер;
const всёКакЕсть = () => формат === 'dmy' && единица === 'c' && часы === '24' && ветер === 'auto';

const дв = (n) => String(n).padStart(2, '0');

// --- Дата ---------------------------------------------------------------------
/** Дата {д, м, г (строкой, как написано)} в выбранном формате. */
export function датаПоФормату(д, м, г, ф = формат) {
  switch (ф) {
    case 'ymd': return `${г}/${дв(м)}/${дв(д)}`;
    case 'mdy': return `${дв(м)}/${дв(д)}/${г}`;
    case 'iso': return `${г}-${дв(м)}-${дв(д)}`;
    case 'cjk': return `${г}年${м}月${д}日`;
    default: return `${дв(д)}.${дв(м)}.${г}`;
  }
}

// День.месяц.год (только через точку: «05/06/2024» — американская это дата
// или европейская, не угадать) и ISO год-месяц-день. Соседние цифры и точки
// исключены: «1.2.3.4», «37.2» и версии не задеваются.
const ДМГ = /(?<![\d.,/])(\d{1,2})\.(\d{1,2})\.(\d{4}|\d{2})(?![\d.,/]?\d)/g;
const ГМД = /(?<![\d-])(\d{4})-(\d{1,2})-(\d{1,2})(?![\d-]?\d)/g;
function переписатьДаты(т) {
  if (формат === 'dmy') return т;
  return т
    .replace(ДМГ, (все, д, м, г) => (+д >= 1 && +д <= 31 && +м >= 1 && +м <= 12 ? датаПоФормату(+д, +м, г) : все))
    .replace(ГМД, (все, г, м, д) => (+д >= 1 && +д <= 31 && +м >= 1 && +м <= 12 ? датаПоФормату(+д, +м, г) : все));
}

// --- Время ----------------------------------------------------------------------
/** «21:40» → «9:40 PM» (при 12-часовом формате); остальное — как есть. */
export function время12(ч, м) {
  return `${(+ч % 12) || 12}:${м} ${+ч < 12 ? 'AM' : 'PM'}`;
}
// Время суток: ЧЧ:ММ с минутами из двух цифр, без секунд, не после метки
// длительности; уже написанное «9:40 PM» не трогаем. Одиночный ноль в часах
// («0:15») — длительность голосового или ролика: время суток так не пишут.
// «9:05 вечера», «9:05 in the evening» — уже двенадцатичасовое: не трогаем.
const ВРЕМЯ = /(?<![\d:\u2060])([01]\d|2[0-3]|[1-9]):([0-5]\d)(?![\d:])(?!\s?[AaPp]\.?\s?[Mm](?![\p{L}]))(?!\s*(?:утра|дня|вечера|ночи|in the (?:morning|afternoon|evening)|at night|o'clock))(?<!(?:上午|下午|早上|晚上)\s*\d{1,2}:\d\d)/gu;
function переписатьВремя(т) {
  if (часы !== '12' || !/:/.test(т)) return т;
  return т.replace(ВРЕМЯ, (все, ч, м) => время12(ч, м));
}

// --- Температура ------------------------------------------------------------------
/** Градусы Цельсия → строка в выбранной единице: «+9°» / «48°». С единицей — «+9°C» / «48°F». */
export function градусы(c, { сЕдиницей = false, дробь = false, плюс = true } = {}) {
  if (c === null || c === undefined || !Number.isFinite(+c)) return '';
  const v = единица === 'f' ? +c * 9 / 5 + 32 : +c;
  const число = дробь ? v.toFixed(1) : String(Math.round(v));
  const знак = плюс && единица === 'c' && v > 0 && !дробь ? '+' : '';
  return знак + число.replace('-', '−') + '°' + (сЕдиницей ? (единица === 'f' ? 'F' : 'C') : '');
}

// «+9°C», «-3 °C», «37,2°C», диапазон «+5…+8°C» / «5-8°C». Буква С — и латинская, и кириллическая.
const ЧИСЛО = '(?:([+\\-−–])\\s?)?(\\d+(?:[.,]\\d+)?)';
const ТИРЕ = '(…|\\.\\.\\.|–|—|-)';
const ДИАПАЗОН = new RegExp(`${ЧИСЛО}\\s?(?:°\\s?)?${ТИРЕ}\\s?${ЧИСЛО}(\\s?)°\\s?[CС](?![\\p{L}])`, 'gu');
const ОДНО = new RegExp(`${ЧИСЛО}(\\s?)°\\s?[CС](?![\\p{L}])`, 'gu');
function вФаренгейт(знак, число) {
  const c = (знак && знак !== '+' ? -1 : 1) * parseFloat(число.replace(',', '.'));
  const f = c * 9 / 5 + 32;
  const дробь = /[.,]/.test(число);
  return (дробь ? f.toFixed(1) : String(Math.round(f))).replace('-', '−');
}
function переписатьГрадусы(т) {
  if (единица !== 'f' || !/°/.test(т)) return т;
  return т
    // «54°F (12°C)» — Фаренгейт уже есть, скобка с Цельсием лишняя.
    .replace(/(\d\s?°\s?F)\s*\([^()]*°\s?[CС]\)/gu, '$1')
    // «19°C (66°F)» — то же наоборот: остаётся Фаренгейт из скобки.
    .replace(/(?:[+\-−–]\s?)?\d+(?:[.,]\d+)?\s?°\s?[CС]\s*\(\s*([^()]*?\d\s?°\s?F)\s*\)/gu, '$1')
    .replace(ДИАПАЗОН, (все, з1, ч1, тире, з2, ч2, пробел) => `${вФаренгейт(з1, ч1)}${тире}${вФаренгейт(з2, ч2)}${пробел}°F`)
    .replace(ОДНО, (все, з, ч, пробел) => `${вФаренгейт(з, ч)}${пробел}°F`);
}

// --- Ветер ------------------------------------------------------------------------
// Скорость в м/с, км/ч и милях в час (русские, английские и китайские записи).
// Подпись новой единицы — тем же письмом, что и исходная.
const В_МС = { ms: 1, kmh: 1 / 3.6, mph: 0.44704 };
const ЕД_ВЕТРА = '(м\\s?\\/\\s?с(?:ек)?|m\\s?\\/\\s?s|mps|米\\s?\\/\\s?秒|米每秒|км\\s?\\/\\s?ч|km\\s?\\/\\s?h|kph|kmh|公里\\s?\\/\\s?(?:小)?时|千米\\s?\\/\\s?(?:小)?时|mph|миль\\s?\\/\\s?ч|миль в час|英里\\s?\\/\\s?(?:小)?时)';
const ВЕТЕР = new RegExp(`(?<![\\d.,])(\\d+(?:[.,]\\d+)?)(?:\\s?${ТИРЕ}\\s?(\\d+(?:[.,]\\d+)?))?\\s?${ЕД_ВЕТРА}(?![\\p{L}])`, 'giu');
function видЕдиницы(ед) {
  const е = ед.toLowerCase();
  if (/^(?:м\s?\/|m\s?\/|mps|米)/.test(е)) return 'ms';
  if (/^(?:км|km|kph|公里|千米)/.test(е)) return 'kmh';
  return 'mph';
}
function подписьЕдиницы(вид, исходная) {
  const письмо = /[\u0400-\u04ff]/.test(исходная) ? 'ru' : /[\u4e00-\u9fff]/.test(исходная) ? 'zh' : 'en';
  return {
    ru: { ms: 'м/с', kmh: 'км/ч', mph: 'миль/ч' },
    zh: { ms: '米/秒', kmh: '公里/小时', mph: '英里/小时' },
    en: { ms: 'm/s', kmh: 'km/h', mph: 'mph' },
  }[письмо][вид];
}
function скорость(число, из, в) {
  const v = parseFloat(String(число).replace(',', '.')) * В_МС[из] / В_МС[в];
  return v < 10 && в === 'ms' && v % 1 ? v.toFixed(1).replace(/\.0$/, '') : String(Math.round(v));
}
function переписатьВетер(т) {
  if (ветер === 'auto') return т;
  return т.replace(ВЕТЕР, (все, ч1, тире, ч2, ед) => {
    const из = видЕдиницы(ед);
    if (из === ветер) return все;
    // Китайский пишет единицу вплотную к числу.
    const подпись = (/[一-鿿]/.test(ед) ? '' : ' ') + подписьЕдиницы(ветер, ед);
    return ч2 ? `${скорость(ч1, из, ветер)}${тире}${скорость(ч2, из, ветер)}${подпись}` : `${скорость(ч1, из, ветер)}${подпись}`;
  });
}

// --- Текст и разметка ---------------------------------------------------------------
/** Видимый текст в выбранных форматах. */
export function текстВФормате(т) {
  if (всёКакЕсть() || !т) return т;
  return переписатьВетер(переписатьГрадусы(переписатьВремя(переписатьДаты(String(т)))));
}

// Тег с длительностью или таймером: время в нём — не время суток.
const ТЕГ_ДЛИТЕЛЬНОСТИ = /\bclass="[^"]*(?:-dur\b|timer|voice-time)/;
/**
 * Разметка карточки: переписываются только текстовые куски между тегами,
 * атрибуты (data-*, title с исходником) и содержимое <style>/<script>/<textarea> — нет.
 */
export function htmlВФормате(html) {
  if (всёКакЕсть() || !html) return html;
  let внутри = '';
  return String(html).replace(/<(\/?)(style|script|textarea)\b[^>]*>|(<[^<>]*)>([^<]+)(?=<)/gi, (все, закр, тег, открыт, текст) => {
    if (тег) { внутри = закр ? '' : тег.toLowerCase(); return все; }
    if (внутри || !/\d/.test(текст)) return все;
    if (ТЕГ_ДЛИТЕЛЬНОСТИ.test(открыт)) {
      const былиЧасы = часы; часы = '24';
      try { return открыт + '>' + текстВФормате(текст); } finally { часы = былиЧасы; }
    }
    return открыт + '>' + текстВФормате(текст);
  });
}

// --- Обратно: введённое человеком → как пишет модель -----------------------------------
/**
 * Дата, введённая в любом из форматов, → «день.месяц.год» (правка даты сцены).
 * Остальной текст — как есть.
 */
export function датаВХранение(т, ф = формат) {
  let s = String(т ?? '');
  s = s.replace(/(?<!\d)(\d{2,4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日/g, (_, г, м, д) => `${дв(д)}.${дв(м)}.${г}`);
  s = s.replace(/(?<![\d-])(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})(?![\d-]?\d)/g, (все, г, м, д) => (+м <= 12 && +д <= 31 ? `${дв(д)}.${дв(м)}.${г}` : все));
  if (ф === 'mdy') s = s.replace(/(?<![\d/])(\d{1,2})\/(\d{1,2})\/(\d{4}|\d{2})(?![\d/]?\d)/g, (все, м, д, г) => (+м <= 12 && +д <= 31 ? `${дв(д)}.${дв(м)}.${г}` : все));
  else s = s.replace(/(?<![\d/])(\d{1,2})\/(\d{1,2})\/(\d{4}|\d{2})(?![\d/]?\d)/g, (все, д, м, г) => (+м <= 12 && +д <= 31 ? `${дв(д)}.${дв(м)}.${г}` : все));
  return s;
}

/** «9:40 PM», «12:05 am» → «21:40», «00:05» (правка времени сцены). */
export function времяВХранение(т) {
  return String(т ?? '').replace(/(?<![\d:])(\d{1,2}):([0-5]\d)\s?([AaPp])\.?\s?[Mm]\.?(?![\p{L}])/gu, (все, ч, м, п) => {
    if (+ч < 1 || +ч > 12) return все;
    const h = (+ч % 12) + (/[Pp]/.test(п) ? 12 : 0);
    return `${дв(h)}:${м}`;
  });
}
