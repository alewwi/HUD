// --- Свет --------------------------------------------------------------------
{
  const Li = await модуль('render/light.js');
  // Старая формула из index.js (до выноса) — эталон.
  const старый = (minutesOfDay, DAY_START, DAY_END) => {
    let p;
    if (minutesOfDay >= DAY_START && minutesOfDay <= DAY_END) p = (minutesOfDay - DAY_START) / (DAY_END - DAY_START);
    else p = (minutesOfDay > DAY_END ? (minutesOfDay - DAY_END) : (minutesOfDay + (1440 - DAY_END))) / (1440 - (DAY_END - DAY_START));
    const cx = 6 + p * 84, cy = 76 - Math.sin(p * Math.PI) * 60;
    const clamp = (v, min, max) => Math.min(max, Math.max(min, v));
    const smoothStep = (value, edge0, edge1) => value <= edge0 ? 0 : value >= edge1 ? 1 : (value - edge0) / (edge1 - edge0);
    return { p, cx, cy, cxm: cx < 50 ? 8 + (cx - 6) / 44 * 8 : 84 + (cx - 50) / 40 * 8,
      ночь: clamp(1 - smoothStep(minutesOfDay, DAY_START - 60, DAY_START + 120) + smoothStep(minutesOfDay, DAY_END - 30, DAY_END + 120), 0, 1),
      золото: clamp(1 - Math.abs(minutesOfDay - (DAY_END - 180)) / 90, 0, 1),
      закат: clamp(1 - Math.abs(minutesOfDay - (DAY_END - 120)) / 90, 0, 1),
      звёзды: clamp(1 - smoothStep(minutesOfDay, DAY_START - 30, DAY_START + 360) + smoothStep(minutesOfDay, DAY_END, DAY_END + 240), 0, 1) };
  };
  let расхождений = 0, пример = '';
  for (const [н, к] of [[360, 1200], [420, 1140], [300, 1290], [480, 990]]) {
    for (let м = 0; м < 1440; м++) {
      const а = старый(м, н, к), б = Li.вычислитьСвет({ минуты: м, началоДня: н, конецДня: к });
      for (const ключ of Object.keys(а)) if (а[ключ].toFixed(3) !== б[ключ].toFixed(3)) { расхождений++; if (!пример) пример = `${н}-${к} ${м} ${ключ}: ${а[ключ]} ≠ ${б[ключ]}`; }
    }
  }
  проверить('свет: вынесенная функция = старая формула на 4×1440 минутах до 3-го знака', расхождений === 0, пример);
  const утро = Li.вычислитьСвет({ минуты: 8 * 60 }), вечер = Li.вычислитьСвет({ минуты: 18 * 60 }), полдень = Li.вычислитьСвет({ минуты: 13 * 60 });
  проверить('свет: утром тень вправо, вечером влево', утро.dx > 0.3 && вечер.dx < -0.3, `${утро.dx} ${вечер.dx}`);
  проверить('свет: в полдень тень короче, чем утром', полдень.dy < утро.dy);
  проверить('свет: выключен — переменных нет', Li.переменныеСвета(утро, 'off') === '' && Li.переменныеСвета(null, 'full') === '');
  проверить('свет: «слегка» — 30% силы', /--light-dx:0\.\d+/.test(Li.переменныеСвета(утро, 'subtle')) && Math.abs(parseFloat(Li.переменныеСвета(утро, 'subtle').match(/--light-dx:([-\d.]+)/)[1]) - утро.dx * 0.3) < 0.002);
  проверить('свет: минуты из «22:40 | ночь»', Li.минутыИзВремени('22:40 | ночь') === 1360 && Li.минутыИзВремени('утро') === null);
  проверить('свет: index.js берёт функцию, а не свою копию', /вычислитьСвет\(\{ минуты: minutesOfDay/.test(css('index.js')) && !/const nightStrength = clamp\(/.test(css('index.js')));
}

