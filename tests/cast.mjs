globalThis.localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
const узел = () => ({ style: {}, dataset: {}, classList: { add() {}, remove() {}, toggle() {}, contains: () => false }, querySelector: () => null, querySelectorAll: () => [], setAttribute() {}, getAttribute: () => null });
globalThis.document = { createElement: узел, querySelector: () => null, querySelectorAll: () => [], documentElement: узел(), getElementById: () => null, body: узел() };
let ctx = { chatId: 'c1', name1: 'Юзер', name2: 'Анна', characterId: 0, characters: [{ name: 'Анна', avatar: 'anna.png', description: 'Анна — врач. Она любит мужа.' }], chat: [], chatMetadata: {} };
globalThis.SillyTavern = { getContext: () => ctx };
for (const k of ['info', 'debug', 'warn']) console[k] = () => {};
const м = (f) => import('file:///' + path.join(КОРЕНЬ, f).replace(/\\/g, '/') + '?v=' + ВЕРСИЯ);
const { settings } = await м('settings.js');
const { namesLikelySame } = await м('names.js');
const К = await м('cast.js');
const { скрытыеФактыЗачатия } = await м('render/conception.js');

let всего = 0, провалов = 0;
const проверить = (что, ок, подробно = '') => { всего++; if (!ок) { провалов++; console.log('✗', что, подробно); } else console.log('✓', что); };
const ключи = (о) => Object.keys(о || {}).join(',');

// --- Пол ---
const люди = [
  { 'Имя': 'Анна', 'Внешность': 'Ж, 165 см', 'Беременность': 'wk: 20; fa: Андрей', 'Цикл': 'phs: paused', 'Отношения': 'Андрей: муж, любит; Ян: брат, скучает' },
  { 'Имя': 'Андрей', 'Внешность': '182 см, широкие плечи', 'Беременность': 'wk: 20', 'Цикл': 'cyd: 4' },
  { 'Имя': 'Ян', 'Цикл': 'cyd: 9' },
  { 'Имя': 'Яна', 'Внешность': 'Ж, 160', 'Цикл': 'cyd: 9' },
  { 'Имя': 'Кай', 'Цикл': 'cyd: 2' },
  { 'Имя': 'Омар', 'Внешность': 'М, омега, 175', 'Беременность': 'wk: 8' },
  { 'Имя': 'Лиам', 'Роль': 'Сын соседей', 'Цикл': 'cyd: 2' },
];
проверить('метка «Ж» — женщина', К.полЧеловека(люди[0]) === 'f');
проверить('муж по чужим «Отношениям» — мужчина', К.полЧеловека(люди[1], { люди }) === 'm');
проверить('без примет — не понять', К.полЧеловека(люди[4], { люди }) === '');
проверить('роль «Сын…» — мужчина', К.полЧеловека(люди[6], { люди }) === 'm');
проверить('частое имя без других примет', К.полЧеловека({ 'Имя': 'Дмитрий' }) === 'm' && К.полЧеловека({ 'Имя': 'Ольга' }) === 'f' && К.полЧеловека({ 'Имя': 'Саша' }) === '');
проверить('код NSFW «pn» — мужчина', К.полЧеловека({ N: 'X', W: 'ar: 40; pn: эрекция' }) === 'm');
проверить('омегаверс — не трогаем', !К.безМатки(люди[5]));
// Память: метку назвали раньше — ход без метки помнит пол.
К.полЧеловека({ 'Имя': 'Кира-Ли', 'Внешность': 'М, 190' });
проверить('пол из прошлой метки в этом чате', К.полЧеловека({ 'Имя': 'Кира-Ли', 'Внешность': 'высокий' }) === 'm');
ctx = { ...ctx, chatId: 'c2' };
проверить('в другом чате память своя', К.полЧеловека({ 'Имя': 'Кира-Ли', 'Внешность': 'высокий' }) === '');
ctx = { ...ctx, chatId: 'c1' };
// Карточка: местоимения.
ctx.characters = [{ name: 'Рэн', avatar: 'r.png', description: 'He is a quiet man. His sister died. He keeps to himself, and his hands shake.' }];
ctx.name2 = 'Рэн';
проверить('пол по местоимениям карточки', К.полЧеловека({ 'Имя': 'Рэн' }) === 'm');
ctx.characters = [{ name: 'Анна', avatar: 'anna.png', description: 'Анна — врач. Она любит мужа.' }];
ctx.name2 = 'Анна';

// --- Слабые места ---
const поИмени = К.составДляПоказа({ characters: [{ 'Имя': 'Дмитрий', 'Цикл': 'cyd: 3', 'Беременность': 'wk: 12' }] }).characters[0];
проверить('мужчина только по имени: цикл убран, беременность не тронута', !('Цикл' in поИмени) && 'Беременность' in поИмени, ключи(поИмени));
const спор = [{ 'Имя': 'Ли', 'Роль': 'девушка из бара', 'Беременность': 'wk: 5' }, { 'Имя': 'Сэм', 'Отношения': 'Ли: брат, злится' }];
проверить('приметы спорят — не трогаем', 'Беременность' in К.составДляПоказа({ characters: спор }).characters[0]);
проверить('родство в скобках у имени', К.полЧеловека({ 'Имя': 'Тор' }, { люди: [{ 'Имя': 'Ида', 'Отношения': 'Тор (муж): любит' }] }) === 'm');
проверить('«М-образный шрам» — не метка пола', К.полЧеловека({ 'Имя': 'Нэй', 'Внешность': 'М-образный шрам на щеке' }) === '');
проверить('английская метка M/F', К.полЧеловека({ N: 'Q', Ap: 'F, 170 cm' }) === 'f' && К.полЧеловека({ N: 'Q2', Ap: 'M, 185 cm' }) === 'm');

// --- Ян и Яна ---
проверить('Иван/Ивана — падеж, пока Ивана не встречалась', namesLikelySame('Иван', 'Ивана'));
проверить('Ян/Яна до встречи — сливались', namesLikelySame('Ян', 'Яна'));
const показ = К.составДляПоказа({ characters: люди, user: { 'Внешность': 'М, 180', 'Цикл': 'cyd: 1', 'Беременность': 'wk: 3' } });
проверить('Ян/Яна в одном HUD — разные люди', !namesLikelySame('Ян', 'Яна') && !namesLikelySame('Яна', 'Ян'));
проверить('Евгений/Евгения — пара узнаётся', (() => { К.составДляПоказа({ characters: [{ 'Имя': 'Евгений' }, { 'Имя': 'Евгения' }] }); return !namesLikelySame('Евгений', 'Евгения'); })());
const по = (имя) => показ.characters.find(c => c['Имя'] === имя);
проверить('у мужа нет беременности и цикла', ключи(по('Андрей')) === 'Имя,Внешность', ключи(по('Андрей')));
проверить('у жены беременность осталась', 'Беременность' in по('Анна') && 'Цикл' in по('Анна'));
проверить('Ян — без цикла, Яна — с циклом', !('Цикл' in по('Ян')) && 'Цикл' in по('Яна'));
проверить('неизвестный пол — как написала модель', 'Цикл' in по('Кай'));
проверить('омега — беременность остаётся', 'Беременность' in по('Омар'));
проверить('игрок-мужчина — без цикла и беременности', ключи(показ.user) === 'Внешность');
проверить('исходные данные не тронуты', 'Беременность' in люди[1] && 'Цикл' in люди[2]);
const скрытое = {}; Object.defineProperty(скрытое, '__ход', { value: 5, enumerable: false });
const сПометкой = К.составДляПоказа({ characters: [Object.assign(скрытое, { 'Имя': 'Пётр', 'Внешность': 'М', 'Цикл': 'cyd: 1' })] });
проверить('неперечисляемые пометки сохраняются', сПометкой.characters[0].__ход === 5 && !('Цикл' in сПометкой.characters[0]));
const чистые = { characters: [{ 'Имя': 'Анна', 'Внешность': 'Ж' }] };
проверить('нечего менять — тот же объект', К.составДляПоказа(чистые) === чистые);

