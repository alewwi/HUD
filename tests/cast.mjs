settings.castMode = 'main';
проверить('только основные: одна Анна', К.составДляПоказа({ characters: люди }).characters.map(c => c['Имя']).join() === 'Анна');
settings.castExtra = 'Кай, Lyam';
проверить('и ещё из списка (и латиницей)', К.составДляПоказа({ characters: люди }).characters.map(c => c['Имя']).join() === 'Анна,Кай,Лиам');
settings.castExtra = '';
ctx = { ...ctx, name2: 'Город N' };
проверить('карточка-мир: остаётся первый', К.составДляПоказа({ characters: люди }).characters.map(c => c['Имя']).join() === 'Анна');
ctx = { ...ctx, name2: 'THE LANTERNS  Андрей' };
проверить('приставка карточки не мешает', К.составДляПоказа({ characters: люди }).characters.map(c => c['Имя']).join() === 'Андрей');
ctx = { ...ctx, groupId: 'g1', groups: [{ id: 'g1', members: ['a.png', 'b.png'] }], characters: [{ name: 'Яна', avatar: 'a.png' }, { name: 'Кай', avatar: 'b.png' }] };
проверить('группа: участники — основные', К.составДляПоказа({ characters: люди }).characters.map(c => c['Имя']).join() === 'Яна,Кай');
ctx = { chatId: 'c1', name1: 'Юзер', name2: 'Анна', characterId: 0, characters: [{ name: 'Анна', avatar: 'anna.png' }], chat: [], chatMetadata: {} };
