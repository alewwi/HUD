// hud-manager/tests/phone-feed.mjs
//
// Телефон: непрочитанное, уведомления, время и превью в списке чатов.
// Виды ошибок — из живой игры; имена, тексты, даты и часы выдуманы:
// — сообщение было «Unread», в следующих ходах модель пишет «Read», а перенос
//   с прошлых ходов держал первую строку: уведомление висело днями;
// — над старым «Unread» стоят прочитанные сообщения того же человека или ответ
//   владельца: чат открывали, значит, прочитано всё выше;
// — время уведомления бралось первым «чч:мм» строки, а оно бывает в тексте;
// — вчерашние сообщения в списке чатов подписывались голыми «19:05»;
// — черновик, который потом дописали и отправили, висел в строке ввода.
// node tests/phone-feed.mjs

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ВЕРСИЯ = JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, 'manifest.json'), 'utf8')).version;
globalThis.window = globalThis;
globalThis.localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
globalThis.sessionStorage = { getItem: () => null, setItem() {}, removeItem() {} };
const узел = () => { let t = ''; return { style: {}, dataset: {}, classList: { add() {}, remove() {}, toggle() {} }, set textContent(x) { t = String(x); }, get innerHTML() { return t; }, set innerHTML(x) { t = String(x); }, get value() { return t; }, querySelector: () => null, querySelectorAll: () => [], setAttribute() {}, getAttribute: () => null, appendChild() {}, append() {}, addEventListener() {}, remove() {} }; };
globalThis.document = { createElement: узел, querySelector: () => null, querySelectorAll: () => [], documentElement: узел(), body: узел(), getElementById: () => null };
globalThis.SillyTavern = { getContext: () => ({ chat: [], chatMetadata: {}, name1: 'Мари', name2: 'Дамиан' }) };
for (const k of ['info', 'debug', 'warn']) console[k] = () => {};
const модуль = (имя) => import('file:///' + path.join(КОРЕНЬ, имя).replace(/\\/g, '/') + '?v=' + ВЕРСИЯ);

let всего = 0, провалов = 0;
const проверить = (что, ок, подробно = '') => { всего++; if (!ок) { провалов++; console.log('✗', что, String(подробно).slice(0, 400)); } else console.log('✓', что); };

const { settings } = await модуль('settings.js');
settings.language = 'ru';
const F = await модуль('render/msg-feed.js');
const CO = await модуль('render/carryover.js');
const M = await модуль('render/messenger.js');
const PH = await модуль('render/phone.js');
const P = await модуль('hud-parser.js');
const текст = (h) => String(h).replace(/<svg[\s\S]*?<\/svg>/g, '').replace(/<[^>]+>/g, ' ').replace(/​/g, '').replace(/\s+/g, ' ').trim();

// --- непрочитанные -----------------------------------------------------------
const В = 'Дамиан Харт';
проверить('непрочитанные: чужое «Unread» после последнего прочитанного',
  JSON.stringify(F.непрочитанные(['Нора -> Дамиан Харт: привет | 09:00 | Read', 'Нора -> Дамиан Харт: ты где? | 09:30 | Unread'], В)) === '[1]');
проверить('непрочитанные: своё «Unread» (не прочёл собеседник) — не уведомление',
  F.непрочитанные(['Дамиан Харт -> Нора: еду | 09:40 | Unread'], В).length === 0);
проверить('непрочитанные: ответил в чат — прочитал всё выше',
  F.непрочитанные(['Нора -> Дамиан Харт: ты где? | 09:30 | Unread', 'Дамиан Харт -> Нора: еду | 09:40 | Delivered'], В).length === 0);
проверить('непрочитанные: черновик ответа ничего не читает',
  F.непрочитанные(['Нора -> Дамиан Харт: ты где? | 09:30 | Unread', 'Дамиан Харт -> Нора: еду | 09:40 | Draft'], В).length === 1);
проверить('непрочитанные: прочитанное ниже снимает старое «Unread» (висело неделю)',
  F.непрочитанные(['Коди -> Дамиан Харт: ключи у вахтёра | 03.04.2031, 11:20 | Unread', 'Коди -> Дамиан Харт: отчёт | 10.04.2031, 15:40 | Read', 'Коди -> Дамиан Харт: ещё | 10.04.2031, 18:05 | Unread'], В).join() === '2');
проверить('непрочитанные: слово «unread» в самом тексте — не пометка',
  F.непрочитанные(['Нора -> Дамиан Харт: статус unread висит | 09:30 | Read'], В).length === 0);
проверить('непрочитанные: «не прочитано» по-русски',
  F.непрочитанные(['Нора -> Дамиан Харт: ау | 09:30 | не прочитано'], В).length === 1);

// --- время в списке ----------------------------------------------------------
const msgs = ['Нора -> Дамиан Харт: вчера | 09.04.2031, 19:05 | Read', 'Нора -> Дамиан Харт: давно | 02.04.2031, 11:20 | Read', 'Нора -> Дамиан Харт: сегодня | 08:30 | Read'];
проверить('время в списке: вчерашнее — «Вчера»', F.времяВСписке(msgs, 0, 'Четверг, 10.04.2031') === 'Вчера', F.времяВСписке(msgs, 0, 'Четверг, 10.04.2031'));
проверить('время в списке: старое — датой', F.времяВСписке(msgs, 1, '10.04.2031') === '02.04');
проверить('время в списке: сегодняшнее и голые часы — часами', F.времяВСписке(msgs, 2, '10.04.2031') === '08:30' && F.времяВСписке(['Нора -> Д: а | 10.04.2031, 07:10 | Read'], 0, '10.04.2031') === '07:10');
проверить('время в уведомлении: «Вчера, 19:05»', F.времяВСписке(msgs, 0, '10.04.2031', { сЧасами: true }) === 'Вчера, 19:05');
проверить('время в списке: без даты сцены — одни часы', F.времяВСписке(msgs, 0, '') === '19:05');
проверить('время в списке: часы из текста не берутся', F.времяВСписке(['Коди -> Д: Встреча в 09:15, не опоздай | 06.03.2031, 10:20 | Unread'], 0, '06.03.2031') === '10:20');

// --- лента: черновик ---------------------------------------------------------
const сЧерновиком = ['Дамиан Харт -> Брайс: Ты где? | 05.03.2031, 08:10 | Draft', 'Дамиан Харт -> Брайс: Ты где? Жду у входа. | 05.03.2031, 08:14 | Read', 'Брайс -> Дамиан Харт: Уже еду. | 05.03.2031, 08:20 | Read'];
проверить('лента: отправленное после черновика его заменило — строка ввода пуста',
  F.собратьЛенту(сЧерновиком, { owner: В, сцена: '06.03.2031', черновикВПоле: true }).draft === '');
проверить('лента: свежий черновик — в строке ввода',
  F.собратьЛенту([...сЧерновиком, 'Дамиан Харт -> Брайс: Жду | 05.03.2031, 08:30 | Draft'], { owner: В, сцена: '06.03.2031', черновикВПоле: true }).draft === 'Жду');
проверить('лента: точка непрочитанного только у непрочитанного',
  (F.собратьЛенту(['Коди -> Дамиан Харт: старое | 11:20 | Unread', 'Коди -> Дамиан Харт: новее | 16:02 | Read', 'Коди -> Дамиан Харт: свежее | 16:10 | Unread'], { owner: В, сцена: '10.04.2031' }).html.match(/unread-dot/g) || []).length === 1);

// --- перенос: свежий статус --------------------------------------------------
проверить('перенос: статус из свежей строки, текст и день — из первой',
  CO.свежийСтатус('Нора -> Д: пока | 04.03.2031, 20:40 | Unread', 'Нора -> Д: пока | 20:40 | Read') === 'Нора -> Д: пока | 04.03.2031, 20:40 | Read');
проверить('перенос: свежая строка без статуса — старая как есть',
  CO.свежийСтатус('Нора -> Д: пока | 20:40 | Unread', 'Нора -> Д: пока | 20:40') === 'Нора -> Д: пока | 20:40 | Unread');
{
  const hud = (obj) => '[HUD]\n```json\n' + JSON.stringify(obj) + '\n```\n[/HUD]';
  const ход = (o) => ({ is_user: false, mes: hud(o) });
  const чат = [
    { is_user: true, mes: 'а' },
    ход({ sc: { Dt: '04.03.2031', T: '21:40' }, cm: { 'Нора': { ow: В, ms: ['Нора -> Дамиан Харт: Забрала посылку, оставлю у соседки. | 20:40 | Unread'] } } }),
    { is_user: true, mes: 'б' },
    ход({ sc: { Dt: '05.03.2031', T: '08:40' }, cm: { 'Нора': { ow: В, ms: ['Нора -> Дамиан Харт: Забрала посылку, оставлю у соседки. | 04.03.2031, 20:40 | Read'] } } }),
    { is_user: true, mes: 'в' },
    ход({ sc: { Dt: '06.03.2031', T: '09:40' }, cm: { 'Нора': { ow: В, ms: ['Нора -> Дамиан Харт: Купишь хлеба? | 09:30 | Unread'] } } }),
  ];
  const прежний = globalThis.SillyTavern;
  globalThis.SillyTavern = { getContext: () => ({ chat: чат, name1: 'Мари', name2: В }) };
  const итог = CO.mergeCarryOver(P.parseHUDComplex(чат[5].mes), { getAttribute: () => '5' });
  globalThis.SillyTavern = прежний;
  const сообщения = (итог.chatsMap && Object.values(итог.chatsMap)[0] || {}).messages || [];
  проверить('перенос: «Unread» прошлого хода стало «Read» — непрочитанное одно',
    сообщения.length === 2 && /\| Read$/.test(сообщения[0]) && F.непрочитанные(сообщения, В).length === 1, JSON.stringify(сообщения));
}

{
  const raw = '[Кирилл] Ты где? | 15:15 | Unread';
  const чаты = { Кирилл: { owner: В, messages: [raw] } };
  const тел = PH.buildPhoneTabsHTML(чаты, 'u', true, В, {}, '06.03.2031', '15:16', []);
  проверить('имя в скобках: отправитель, превью и уведомление', F.разобратьСообщение(raw).кто === 'Кирилл' && тел.includes('class="hud-msg-sender">Кирилл</span>') && тел.includes('Ты где?') && !тел.includes('[Кирилл]'));
  const Б = await модуль('block-edit.js');
  const поля = Б.разобратьСообщениеПравки(raw);
  проверить('редактор открывает имя и текст отдельно', поля.от === 'Кирилл' && поля.текст === 'Ты где?' && Б.собратьСообщение(поля) === 'Кирилл: Ты где? | 15:15 | Unread');
  проверить('служебные теги без имени остаются в тексте', ['[PHOTO: фото]', '[VOICE]', '[CALL: incoming]', '[BY: Лера] привет'].every(s => F.разобратьСообщение(s).текст === s));
}

// --- список чатов и уведомления ---------------------------------------------
{
  const чаты = {
    'Коди': { owner: В, messages: ['Коди -> Дамиан Харт: Встреча в 09:15, не опоздай. | 06.03.2031, 10:20 | Unread'] },
    'Нора': { owner: В, messages: ['Нора -> Дамиан Харт: Спокойной ночи. | 05.03.2031, 23:50 | Unread'] },
    'Брайс': { owner: В, messages: ['Брайс -> Дамиан Харт: Буду. | 06.03.2031, 08:00 | Unread'] },
    'Лея': { owner: В, messages: ['Лея -> Дамиан Харт: Привет | 06.03.2031, 07:00 | Read', 'Дамиан Харт -> Лея: Иду | 06.03.2031, 07:05 | Draft'] },
    'Сэм': { owner: В, messages: ['Сэм -> Дамиан Харт: [удалено] Зря написал | 06.03.2031, 06:00 | Read'] },
  };
  const список = текст(M.buildMessengerHTML(чаты, 'u', В, 'Четверг, 06.03.2031'));
  проверить('список: вчерашний чат подписан «Вчера»', /Нора Спокойной ночи\. Вчера 1/.test(список), список);
  проверить('список: черновик в превью — «Черновик:»', список.includes('Черновик: Иду'), список);
  проверить('список: удалённое в превью — «Сообщение удалено»', список.includes('Сообщение удалено') && !список.includes('Зря написал Сообщение'), список);
  settings.phoneNotifMax = 5;
  const тел = PH.buildPhoneTabsHTML(чаты, 'u', true, В, {}, 'Четверг, 06.03.2031', '10:25', []);
  const ув = [...тел.matchAll(/class="hud-phone-notif[ "][\s\S]*?hud-phone-notif-meta">\s*<em>([^<]*)<\/em>/g)].map(m => m[1]);
  проверить('уведомления: новые сверху с учётом дня, время сообщения, а не из текста', JSON.stringify(ув) === JSON.stringify(['10:20', '08:00', 'Вчера, 23:50']), JSON.stringify(ув));
  проверить('значок «Сообщения»: три непрочитанных', /data-phone-app="messages"[\s\S]*?hud-unread-badge">3</.test(тел));
}

// Шаблон промта «[Sender] -> [Recipient]: …», переписанный буквально: имя в
// скобках оставалось в тексте («[Кирилл] Ты где?» от Unknown), окно правки
// прятало его как незнакомый тег. Теги в начале текста — не имена.
{
  const MF = await модуль('render/msg-feed.js');
  const р = (s) => { const x = MF.разобратьСообщение(s); return x.кто + ' | ' + x.текст; };
  for (const [s, ждём] of [
    ['[Кирилл] -> [Алиса]: Ты где? | 15:15 | Unread', 'Кирилл | Ты где?'],
    ['[Кирилл]: Ты где? | 15:15', 'Кирилл | Ты где?'],
    ['[Кирилл] Ты где? | 15:15', 'Кирилл | Ты где?'],
    ['Кирилл -> [Алиса]: Ты где? | 15:15', 'Кирилл | Ты где?'],
    ['Кирилл: [PHOTO: селфи у зеркала] Ну как? | 15:15', 'Кирилл | [PHOTO: селфи у зеркала] Ну как?'],
    ['[VOICE_0:42] Перезвони | 15:15', 'Unknown | [VOICE_0:42] Перезвони'],
    ['Мама: Купи хлеб: срочно | 15:15', 'Мама | Купи хлеб: срочно'],
  ]) проверить('имя в скобках: ' + s, р(s) === ждём, р(s));
}

console.log(`\nпроверок: ${всего}, провалов: ${провалов}`);
