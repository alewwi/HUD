const ЦВЕТА = { k: '#000', w: '#fff', y: '#ffff00', b: '#0000a8', c: '#00a8a8', g: '#c0c0c0', d: '#808080', r: '#c00000', n: '#008000', m: '#a800a8', o: '#d08000', f: '#f0c090' };
const пиксели = (рисунок) => {
  const out = [];
  рисунок.trim().split('\n').forEach((строка, y) => {
    const s = строка.trim();
    for (let x = 0; x < s.length;) {
      let n = 1;
      while (s[x + n] === s[x]) n++;
      if (ЦВЕТА[s[x]]) out.push(`<rect x="${28 + x * 4}" y="${26 + y * 4}" width="${n * 4}" height="4" fill="${ЦВЕТА[s[x]]}"/>`);
      x += n;
    }
  });
  return `<g shape-rendering="crispEdges">${out.join('')}</g>`;
};
