// Окно вопросов о противоречиях (disputes.js): что написала модель, что
// считает HUD, почему HUD спрашивает. Ответ — «Верно у модели», «Верно у
// HUD» или своё значение прямо здесь: неделя, вес, сколько спал, когда ели.
// Ниже — недавние решения: передумали — «Снять решение», и вопрос вернётся,
// если расхождение ещё есть.

import { т } from './i18n.js?v=23.89.90';
import { открытыеСпоры, решённыеСпоры, решитьСпор, снятьРешение } from './disputes.js?v=23.89.90';
import { открытьОкноПравки } from './block-edit-ui.js?v=23.89.90';

const эл = (тег, класс = '', текст = '') => {
  const у = document.createElement(тег);
  if (класс) у.className = класс;
  if (текст) у.textContent = текст;
  return у;
};
const кнопка = (текст, класс, действие) => {
  const к = эл('button', класс, т(текст));
  к.type = 'button';
  к.addEventListener('click', (e) => { e.preventDefault(); e.stopPropagation(); действие(); });
  return к;
};

// Своё значение: проверка по виду основы. Ошибка — строкой, иначе значение.
function проверить(основа, сырое) {
  const s = String(сырое ?? '').trim();
  if (!s) return { ошибка: 'Введите значение.' };
  if (основа.вид === 'время') {
    const м = s.match(/^(\d{1,2})[:.](\d{2})$/);
    if (!м || +м[1] > 23 || +м[2] > 59) return { ошибка: 'Время — как ЧЧ:ММ, например 14:30.' };
    return { значение: `${м[1].padStart(2, '0')}:${м[2]}` };
  }
  if (основа.вид === 'число') {
    const ч = parseFloat(s.replace(',', '.'));
    if (!Number.isFinite(ч)) return { ошибка: 'Нужно число.' };
    if (Number.isFinite(основа.мин) && ч < основа.мин) return { ошибка: `Не меньше ${основа.мин}.` };
    if (Number.isFinite(основа.макс) && ч > основа.макс) return { ошибка: `Не больше ${основа.макс}.` };
    return { значение: Math.round(ч * 10) / 10 };
  }
  return { значение: s.replace(/[|;]/g, ',') };
}

function карточкаСпора(с, после) {
  const к = эл('div', 'hud-dsp-card');
  const шапка = эл('div', 'hud-dsp-head');
  шапка.append(эл('b', '', т(с.что || 'Расхождение')), с.кто ? эл('span', '', с.кто) : '');
  const сравнение = эл('div', 'hud-dsp-cmp');
  const сторона = (подпись, значение, класс) => { const д = эл('div', 'hud-dsp-side ' + класс); д.append(эл('small', '', т(подпись)), эл('span', '', значение)); return д; };
  сравнение.append(сторона('Модель пишет', с.модель, 'is-model'), сторона('HUD считает', с.hud, 'is-hud'));
  const почему = эл('p', 'hud-dsp-why');
  почему.append(эл('b', '', т('Почему спрашиваю:') + ' '), document.createTextNode(т(с.почему || '')));
  const кнопки = эл('div', 'hud-dsp-acts');
  const ответ = (решение, своё = null) => { if (решитьСпор(с.ключ, решение, своё)) после(); };
  кнопки.append(кнопка('Верно у модели', 'hud-be-btn', () => ответ('model')), кнопка('Верно у HUD', 'hud-be-btn', () => ответ('hud')));
  к.append(шапка, сравнение, почему, кнопки);
  if (с.основа) {
    const своё = эл('div', 'hud-dsp-own');
    const подпись = эл('label', 'hud-be-field');
    const поле = эл('input', 'hud-be-input');
    поле.type = 'text';
    if (с.основа.вид === 'число') поле.inputMode = 'decimal';
    if (с.основа.вид === 'время') поле.placeholder = 'ЧЧ:ММ';
    подпись.append(эл('span', 'hud-be-label', т('Своё значение: ') + т(с.основа.подпись || '')), поле);
    const ошибка = эл('small', 'hud-dsp-err');
    ошибка.hidden = true;
    const задать = () => {
      const п = проверить(с.основа, поле.value);
      if (п.ошибка) { ошибка.hidden = false; ошибка.textContent = т(п.ошибка); поле.focus(); return; }
      ответ('own', п.значение);
    };
    поле.addEventListener('keydown', (e) => { if (e.key === 'Enter') { e.preventDefault(); задать(); } });
    своё.append(подпись, кнопка('Задать', 'hud-be-btn is-main', задать), ошибка);
    к.append(своё);
  }
  return к;
}

const ИМЕНА_РЕШЕНИЙ = { model: 'верно у модели', hud: 'верно у HUD', own: 'своё значение' };

/** Окно вопросов. после() — перерисовать карточки, когда что-то решили. */
export function открытьСпоры(после = () => {}) {
  const форма = { узел: эл('div', 'hud-dsp'), взять: () => undefined };
  let окно = null;
  const собрать = () => {
    форма.узел.replaceChildren();
    const открытые = открытыеСпоры();
    if (!открытые.length) форма.узел.append(эл('p', 'hud-be-note', т('Открытых вопросов нет: всё, что HUD считает сам, сходится с ответом модели или уже решено.')));
    for (const с of открытые) форма.узел.append(карточкаСпора(с, () => { после(); собрать(); }));
    const решённые = решённыеСпоры().slice(0, 6);
    if (решённые.length) {
      const список = эл('details', 'hud-dsp-done');
      список.append(эл('summary', '', т('Недавние решения')));
      for (const р of решённые) {
        const ряд = эл('div', 'hud-dsp-row');
        const текст = `${т(р.что || '')}${р.кто ? ' · ' + р.кто : ''} — ${т(ИМЕНА_РЕШЕНИЙ[р.решение] || р.решение)}${р.решение === 'own' ? ': ' + р.своё : ''}`;
        ряд.append(эл('span', '', текст), кнопка('Снять решение', 'hud-be-del is-wide', () => { снятьРешение(р.ключ); после(); собрать(); }));
        список.append(ряд);
      }
      форма.узел.append(список);
    }
  };
  собрать();
  окно = открытьОкноПравки({
    заголовок: т('Расхождения с моделью'),
    пояснение: 'HUD сам считает срок, вес, сон и сытость. Где модель написала другое, он не исправляет молча, а спрашивает. Пока нет ответа, остаётся написанное моделью.',
    путь: [], значение: null, форма, сохранить: async () => {}, текстОтмены: 'Закрыть',
  });
  document.querySelector('.hud-be-overlay:last-of-type')?.classList.add('is-pick', 'is-disputes');
  return окно;
}
