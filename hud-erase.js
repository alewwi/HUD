const ключ = (v) => String(v ?? '').trim().toLowerCase().replace(/[ё]/g, 'е').replace(/[«»"'`.,;:!?()\[\]]/g, '').replace(/\s+/g, ' ');
export function тотПункт(а, б) {
  const x = ключ(а), y = ключ(б);
  if (!x || !y) return false;
  if (x === y) return true;
  const [короче, длиннее] = x.length < y.length ? [x, y] : [y, x];
  return короче.length >= 15 && длиннее.startsWith(короче);
}
// Секрет модель от хода к ходу слегка переписывает: тот же ключ — тот же секрет.
export function тотСекрет(а, б) {
  if (тотПункт(а, б)) return true;
  const к = ключСекрета(а);
  return !!к && к === ключСекрета(б);
}
