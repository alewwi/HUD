/** Убрать цель из HUD в кодах. true — что-то убрано. */
export function убратьИзHUD(hud, цель, убранное = null) {
  if (!объект(hud) || !цель) return false;
  let убрано = false;
  if (цель.вид === 'pregnancy') {
    const кто = String(цель.кто || '');
    const все = Array.isArray(hud.cs) ? hud.cs : объект(hud.cs) ? [hud.cs] : [];
    const записи = кто === 'user' ? [hud.us] : записиЧеловека(все, кто.replace(/^char:/, '').trim());
    for (const з of записи) {
      // Заглушка «empty» — не беременность: из-за неё блок не переписываем.
      if (!объект(з) || !('Prg' in з) || ПУСТО.test(String(з.Prg ?? '').trim())) continue;
      if (убранное) убранное.push({ поле: 'Prg', кому: з === hud.us ? 'user' : String(з.N || '').trim(), значение: з.Prg });
      delete з.Prg;
      убрано = true;
    }
    return убрано;
  }
  const список = СПИСКИ[цель.вид];
  if (!список || !объект(hud.me)) return false;
  const лишний = подходит(цель);
  for (const поле of список.поля) {
    const было = hud.me[поле];
    if (Array.isArray(было)) {
      const стало = было.filter(п => !лишний(п));
      if (убранное) было.forEach((п, место) => { if (лишний(п)) убранное.push({ поле, значение: п, место }); });
      if (стало.length !== было.length) { hud.me[поле] = стало; убрано = true; }
    } else if (typeof было === 'string') {
      // «Важное» модель иногда пишет одной строкой через «;».
      const части = было.split(';').map(s => s.trim()).filter(Boolean);
      const стало = части.filter(п => !лишний(п));
      if (убранное) части.forEach((п, место) => { if (лишний(п)) убранное.push({ поле, значение: п, место }); });
      if (стало.length !== части.length) { hud.me[поле] = стало.join('; '); убрано = true; }
    }
  }
  return убрано;
}

// Отступ — как был: иначе блоки, отличные только оформлением (правка ✎ и ответ
// модели), дали бы один текст, и возврат не отличил бы их.
function блокHUD(hud, прежний) {
  const отступ = ((прежний.match(/\{\r?\n( +)"/) || [])[1] || ' ').length;
  return '[HUD]\n```json\n' + JSON.stringify(hud, null, отступ) + '\n```\n[/HUD]';
}

/** Текст с блоками [HUD], из которых убрана цель. Нечего убирать — тот же текст. */
export function стеретьВТексте(текст, цель, заметить = null, убранное = null) {
  let s = String(текст ?? '');
  for (const б of hudБлоки(s).reverse()) {
    const hud = HUDвКодах(б.inner, { сПоворотом: true });
    if (!hud || !убратьИзHUD(hud, цель, убранное)) continue;
    const новый = блокHUD(hud, б.full);
    if (заметить) заметить(б.full, новый);
    s = s.slice(0, б.index) + новый + s.slice(б.index + б.length);
  }
  return s;
}

/**
 * Вставить убранное в последний блок текста: [{ поле, кому, значение, место }]
 * (кому — только у беременности). То, что в блоке уже есть, не дублируется.
 * вид — вид удаления. Нечего вставлять — тот же текст.
 */
export function вставитьВТекст(текст, вид, что) {
  const s = String(текст ?? '');
  const б = hudБлоки(s).at(-1);
  if (!б || !что.length) return s;
  const hud = HUDвКодах(б.inner, { сПоворотом: true });
  if (!hud) return s;
  let вставлено = false;
  for (const п of что) {
    if (вид === 'pregnancy') {
      const все = Array.isArray(hud.cs) ? hud.cs : объект(hud.cs) ? [hud.cs] : [];
      if (п.кому === 'user' && !объект(hud.us)) hud.us = {};
      const записи = п.кому === 'user' ? [hud.us] : записиЧеловека(все, п.кому);
      for (const з of записи) if (объект(з) && ПУСТО.test(String(з.Prg ?? '').trim())) { з.Prg = п.значение; вставлено = true; }
      continue;
    }
    const список = СПИСКИ[вид];
    if (пунктыHUD(hud, вид).some(т => ключ(т) === ключ(список.текст(п.значение)))) continue;
    if (!объект(hud.me)) hud.me = {};
    const поле = список.поля.find(к => к in hud.me) || п.поле;
    if (typeof hud.me[поле] === 'string') hud.me[поле] = hud.me[поле].split(';').map(x => x.trim()).filter(Boolean);
    if (!Array.isArray(hud.me[поле])) hud.me[поле] = [];
    hud.me[поле].splice(Math.min(п.место ?? Infinity, hud.me[поле].length), 0, п.значение);
    вставлено = true;
  }
  return вставлено ? s.slice(0, б.index) + блокHUD(hud, б.full) + s.slice(б.index + б.length) : s;
}

// --- Разница блоков --------------------------------------------------------------
// Больше такого произведения строк таблицу не считаем: середина уходит целиком.
const ПРЕДЕЛ_ТАБЛИЦЫ = 4e6;

/**
 * Как получить старый текст из нового: [[строка в новом, сколько убрать,
 * что вставить], …], от конца к началу. Проверяет сама себя: не сошлось —
 * один кусок с текстом целиком.
 */
export function разницаБлока(старый, новый) {
  const А = старый.split('\n'), Б = новый.split('\n');
  let начало = 0;
  while (начало < А.length && начало < Б.length && А[начало] === Б[начало]) начало++;
  let конец = 0;
  while (конец < А.length - начало && конец < Б.length - начало && А[А.length - 1 - конец] === Б[Б.length - 1 - конец]) конец++;
  const а = А.slice(начало, А.length - конец), б = Б.slice(начало, Б.length - конец);
  const куски = [];
  if (а.length * б.length > ПРЕДЕЛ_ТАБЛИЦЫ) куски.push([начало, б.length, а.join('\n')]);
  else {
    // Длина общей подпоследовательности с хвоста, потом проход с начала.
    const ш = б.length + 1;
    const т = new Uint32Array((а.length + 1) * ш);
    for (let i = а.length - 1; i >= 0; i--) for (let j = б.length - 1; j >= 0; j--) {
      т[i * ш + j] = а[i] === б[j] ? т[(i + 1) * ш + j + 1] + 1 : Math.max(т[(i + 1) * ш + j], т[i * ш + j + 1]);
    }
    let i = 0, j = 0;
    while (i < а.length || j < б.length) {
      if (i < а.length && j < б.length && а[i] === б[j]) { i++; j++; continue; }
      const от = j, вставка = [];
      while ((i < а.length || j < б.length) && !(i < а.length && j < б.length && а[i] === б[j])) {
        if (j >= б.length || (i < а.length && т[(i + 1) * ш + j] >= т[i * ш + j + 1])) вставка.push(а[i++]);
        else j++;
      }
      куски.push(вставка.length ? [начало + от, j - от, вставка.join('\n')] : [начало + от, j - от]);
    }
  }
  const итог = куски.reverse();
  return применитьРазницу(новый, итог) === старый ? итог : [[0, Б.length, старый]];
}
export function применитьРазницу(новый, разница) {
  const строки = новый.split('\n');
  for (const [от, сколько, вставка] of разница) строки.splice(от, сколько, ...(вставка === undefined ? [] : вставка.split('\n')));
  return строки.join('\n');
}

/**
 * Обратно: блоки, которые есть в прежние (ключ очищенного блока → разница),
 * встают на место. Блок поправили после удаления — ключ другой, он остаётся
 * как есть.
 */
export function вернутьВТексте(текст, прежние) {
  let s = String(текст ?? '');
  for (const б of hudБлоки(s).reverse()) {
    const разница = прежние.get(ключБлока(б.full));
    if (разница !== undefined) s = s.slice(0, б.index) + применитьРазницу(б.full, разница) + s.slice(б.index + б.length);
  }
  return s;
}

/** Выжимка летописи без цели; null — менять нечего. Беременности в летописи нет. */
export function выжимкаБез(выжимка, цель) {
  const вид = цель && цель.вид;
  const пам = выжимка && выжимка.memory;
  if ((вид !== 'secrets' && вид !== 'guns') || !пам || !Array.isArray(пам[вид])) return null;
  const лишний = подходит(цель);
  const стало = пам[вид].filter(п => !лишний(п));
  return стало.length === пам[вид].length ? null : { ...выжимка, memory: { ...пам, [вид]: стало } };
}

// Только блоки, где пункт может быть: разбор блока — самое дорогое здесь.
const норм = (s) => String(s ?? '').toLowerCase().replace(/ё/g, 'е');
function отборТекстов(цель) {
  if (цель.вид === 'pregnancy') return (т) => /prg|беременн|pregnan/i.test(т);
  // Первое значимое слово: оно есть и у короткой версии пункта, и у дописанной.
  const корни = (цель.тексты || []).map(т => {
    const слово = норм(СПИСКИ[цель.вид].текст(т)).split(/[^\p{L}\p{N}]+/u).find(w => w.length >= 4);
    return слово ? слово.slice(0, 6) : '';
  });
  if (!корни.length || корни.some(к => !к)) return () => true;
  return (т) => { const н = норм(т); return корни.some(к => н.includes(к)); };
}
const передышка = () => new Promise(r => setTimeout(r, 0));

/** Тексты пунктов вида в HUD в кодах. */
export function пунктыHUD(hud, вид) {
  const список = СПИСКИ[вид];
  if (!список || !объект(hud) || !объект(hud.me)) return [];
  const out = [];
  for (const поле of список.поля) {
    const v = hud.me[поле];
    const части = Array.isArray(v) ? v : typeof v === 'string' ? v.split(';') : [];
    for (const п of части) { const т = список.текст(п).trim(); if (т) out.push(т); }
  }
  return out;
}

// Версии «↶» лежат у сообщения и у каждого свайпа.
function версии(m) {
  const out = [];
  for (const e of [m && m.extra, ...(Array.isArray(m && m.swipe_info) ? m.swipe_info.map(и => и && и.extra) : [])]) {
    if (e && Array.isArray(e.hud_versions)) out.push(...e.hud_versions.filter(v => v && typeof v.hud === 'string'));
  }
  return out;
}

/**
 * Все формулировки, похожие на пункт: [{ текст, сообщений }]. Нажатый — первым,
 * дальше по числу сообщений. сообщений 0 — такой осталась только запись в
 * архиве (летописи). Чистый расчёт: чат не меняет.
 */
export async function собратьВарианты(чат, вид, текст, { разобрать = (т) => т, архив = [] } = {}) {
  const список = СПИСКИ[вид];
  const найдено = new Map();
  const разборы = new Map();   // свайп и display_text часто один и тот же блок
  const можетБыть = отборТекстов({ вид, тексты: [текст] });
  const заметить = (т, номер) => {
    if (!список.похож(т, текст)) return;
    const к = ключ(т);
    if (!найдено.has(к)) найдено.set(к, { текст: т, сообщения: new Set() });
    if (номер !== null) найдено.get(к).сообщения.add(номер);
  };
  const сообщения = Array.isArray(чат) ? чат : [];
  for (let номер = 0; номер < сообщения.length; номер++) {
    const m = сообщения[номер];
    if (!m || m.is_user) continue;
    if (номер % 8 === 0) await передышка();
    for (const т of [...ячейки(m).map(я => я.взять()), ...версии(m).map(в => в.hud)]) {
      const полный = разобрать(т);
      if (!можетБыть(полный)) continue;
      for (const б of hudБлоки(полный)) {
        if (!разборы.has(б.inner)) разборы.set(б.inner, пунктыHUD(HUDвКодах(б.inner, { сПоворотом: true }), вид));
        for (const п of разборы.get(б.inner)) заметить(п, номер);
      }
    }
  }
  for (const т of архив) заметить(т, null);
  if (!найдено.has(ключ(текст))) найдено.set(ключ(текст), { текст, сообщения: new Set() });
  const свой = ключ(текст);
  return [...найдено.entries()]
    .sort(([а, x], [б, y]) => (б === свой) - (а === свой) || y.сообщения.size - x.сообщения.size)
    .map(([, в]) => ({ текст: в.текст, сообщений: в.сообщения.size }));
}

/** Варианты пункта в открытом чате, с выгруженными блоками и архивом. */
export async function вариантыПункта(вид, текст) {
  const c = ctx();
  await подгрузитьЧат(c && c.chat);
  const архив = [];
  if (вид === 'guns' || вид === 'secrets') {
    for (const в of await выжимкиЛетописи()) {
      const пункты = в && в.memory && в.memory[вид];
      if (Array.isArray(пункты)) архив.push(...пункты.map(п => СПИСКИ[вид].текст(п)).filter(Boolean));
    }
  }
  return собратьВарианты(c && c.chat, вид, текст, { разобрать: развернутьHUD, архив });
}

