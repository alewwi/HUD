// hud-manager/hud-erase.js
//
// Удаление из HUD: беременность человека и пункты «Важного», «Ружей Чехова»
// и «Секретов» — так, будто их в HUD не было.
//
// HUD заново собирается из прошлых ходов: перенос списков, снимок модели,
// сводки старых ходов, архив. Поэтому правка одного сообщения не помогла бы —
// пункт вернулся бы из соседнего хода. Чистим всё, откуда он может прийти:
// mes, свайпы, display_text, версии «↶», выгруженные блоки, летопись и
// метаданные чата. Текст ответов не меняется: блоки [HUD] переписываются, а
// проза, рассуждения и [HUD_SUMMARY] в сообщениях остаются как есть.
//
// Опознание пунктов нечёткое (модель переписывает их из хода в ход), и цена
// ошибки — чужой пункт. Поэтому оно только предлагает: вариантыПункта()
// собирает все похожие формулировки, игрок видит их с галочками, а удаляются
// лишь отмеченные, по точному совпадению (цель.точно).
//
// Возвращается всё. Нетронутые блоки встают на место байт в байт, по разнице.
// В блок, который поправили или перегенерировали после удаления, разница уже не
// ляжет: туда пункт вставляется заново, остальные правки остаются. То же с
// последним HUD чата, чтобы пункт снова увидела модель.
//
// Вернуть можно любое удаление («↶» в шапке карточки). Журнал лежит в метаданных
// чата и хранит не блоки, а разницу построчно: около двух КБ на блок вместо
// восьмидесяти. Поэтому возврат не пишет отдельных файлов, едет вместе с чатом
// на другое устройство и не оставляет ничего после удаления расширения.
//
// Чат бывает на десятки мегабайт, а работает это и на телефоне: разбираем только
// блоки, где пункт может быть, одинаковые тексты — один раз, и отдаём управление
// странице, чтобы она не вставала.
//
// Здесь — логика. Кнопки и окно подтверждения — index.js, разметка кнопки —
// render/erase-button.js.

