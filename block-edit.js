/** Соседние блоки для переключателя в окне: поля того же человека, разделы того же раздела. */
export function соседиБлока(hud, путь) {
  const корень = путь[0];
  const база = корень === 'cs' || корень === 'bb' ? путь.slice(0, 2) : корень === 'us' || корень === 'sc' ? [корень] : корень === 'cm' ? [] : [корень];
  if (!база.length) return [];
  const узел = взять(hud, база);
  if (!объект(узел)) return Array.isArray(узел) ? узел.map((_, i) => [...база, i]) : [];
  return Object.keys(узел).filter(к => к !== 'N').map(к => [...база, к]);
}

/** Переименовать переписку в cm, сохранив порядок. false — пусто или имя занято. */
export function переименоватьПереписку(hud, старое, новое) {
  const имя = безЧерты(новое).replace(/\n+/g, ' ').trim();
  if (!объект(hud) || !объект(hud.cm) || !(старое in hud.cm) || !имя) return false;
  if (имя === старое) return true;
  if (Object.prototype.hasOwnProperty.call(hud.cm, имя)) return false;
  const новыйСписок = {};
  for (const [к, v] of Object.entries(hud.cm)) новыйСписок[к === старое ? имя : к] = v;
  hud.cm = новыйСписок;
  return true;
}
