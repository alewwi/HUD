/** Строка «Кто -> Кому: [теги] текст | время | статус» → поля окна. */
export function разобратьСообщениеПравки(сырое) {
  const м = {
    от: '', кому: '', текст: '', время: '', статус: '', статусКак: '', вид: 'text',
    голос: { длит: '' }, фото: { что: '' }, видео: { длит: '', что: '' },
    звонок: { куда: '', исход: 'answered', длит: '' }, опрос: { вопрос: '', варианты: [] },
    ответ: null, переслано: null, кем: null, прочее: [], сырое: String(сырое ?? ''),
  };
  let s = String(сырое ?? '').trim();
  const части = s.split('|');
  let тело = части.shift();
  // Хвост: время и статус. Текст с «|» внутри (модель ошиблась) — обратно в текст.
  const хвост = части.map(x => x.trim());
  if (хвост.length) {
    const последний = хвост[хвост.length - 1];
    const вид = видСтатуса(последний);
    // Незнакомая отметка («Delivered») — статус, только если перед ней время.
    if (вид && (вид !== 'other' || (хвост.length >= 2 && (ПОХОЖЕ_НА_ВРЕМЯ.test(хвост[хвост.length - 2]) || !хвост[хвост.length - 2])))) {
      м.статусКак = последний; м.статус = вид; хвост.pop();
    } else if (!последний) хвост.pop();
    if (хвост.length && ПОХОЖЕ_НА_ВРЕМЯ.test(хвост[хвост.length - 1])) м.время = хвост.pop();
    else if (хвост.length === 1 && !хвост[0]) хвост.pop();
    if (хвост.length) тело += ' / ' + хвост.join(' / ');
  }
  const кто = тело.match(/^([^:[\]]+?)(?:\s*(?:->|→)\s*([^:[\]]+?))?\s*:\s*([\s\S]*)$/);
  if (кто) { м.от = кто[1].trim(); м.кому = (кто[2] || '').trim(); тело = кто[3]; }
  тело = тело.trim();
  // Теги в начале — шапки и вид; незнакомые сохраняем как есть.
  for (let т = тело.match(ТЕГ); т; т = тело.match(ТЕГ)) {
    const внутри = т[1];
    let р;
    if ((р = внутри.match(/^(?:VOICE|ГОЛОС)_?(\d{1,2}:\d{2})?$/i))) { м.вид = 'voice'; м.голос.длит = р[1] || ''; }
    else if ((р = внутри.match(/^(?:PHOTO|ФОТО|IMG|СНИМОК)\s*:?\s*([\s\S]*)$/i))) { м.вид = 'photo'; м.фото.что = р[1].trim(); }
    else if ((р = внутри.match(/^(?:VIDEO|ВИДЕО|VID|РОЛИК)[ _]?(\d{1,2}:\d{2})?\s*:?\s*([\s\S]*)$/i))) { м.вид = 'video'; м.видео.длит = р[1] || ''; м.видео.что = р[2].trim(); }
    else if ((р = внутри.match(/^(?:CALL|ЗВОНОК)\s*:?\s*([\s\S]*)$/i))) {
      м.вид = 'call';
      const тело2 = р[1].toLowerCase();
      м.звонок.длит = (тело2.match(/\b(\d{1,2}:\d{2})\b/) || [])[1] || '';
      м.звонок.исход = /пропущ|missed|no answer|без ответа|\bmi\b/.test(тело2) ? 'missed' : /отклон|сброш|declined|rejected|отказ|\bdc\b/.test(тело2) ? 'declined' : 'answered';
      м.звонок.куда = /входящ|incoming|\bin\b/.test(тело2) ? 'in' : /исходящ|outgoing|\bout\b/.test(тело2) ? 'out' : '';
    } else if ((р = внутри.match(/^(?:POLL|ОПРОС|ГОЛОСОВАНИЕ)\s*:\s*([\s\S]*)$/i))) {
      м.вид = 'poll';
      const куски = р[1].split(/;;/).map(x => x.trim()).filter(Boolean);
      м.опрос.вопрос = куски.shift() || '';
      м.опрос.варианты = куски.map(к => { const з = к.indexOf('='); return з > -1 ? { текст: к.slice(0, з).trim(), кто: к.slice(з + 1).trim() } : { текст: к, кто: '' }; });
    } else if ((р = внутри.match(/^(?:REPLY|ОТВЕТ|RE)\s*:\s*([\s\S]*)$/i))) {
      const ч = р[1].indexOf('::');
      м.ответ = ч > -1 ? { кто: р[1].slice(0, ч).trim(), что: р[1].slice(ч + 2).trim() } : { кто: '', что: р[1].trim() };
    } else if ((р = внутри.match(/^(?:FWD|FORWARD|ПЕРЕСЛАНО)\s*:?\s*([\s\S]*)$/i))) м.переслано = р[1].trim();
    else if ((р = внутри.match(/^BY\s*:\s*([\s\S]*)$/i))) м.кем = р[1].trim();
    // Метка в тексте ([DRAFT], [удалено]) — пишется обратно меткой, если отметку не меняли.
    else if (/^(?:удалено|deleted?)$/i.test(внутри.trim())) { м.статус = м.статус || 'deleted'; м.статусТег = м.статусТег || внутри.trim(); }
    else if (/^(?:черновик|draft)$/i.test(внутри.trim())) { м.статус = м.статус || 'draft'; м.статусТег = м.статусТег || внутри.trim(); }
    else м.прочее.push(т[0].trim());
    тело = тело.slice(т[0].length);
  }
  м.текст = тело.trim();
  if (м.статус && !м.статусКак && !м.статусТег) м.статусКак = СЛОВО_СТАТУСА[м.статус] || '';
  return м;
}

/** Поля окна → строка, как её пишет модель. */
export function собратьСообщение(м) {
  const теги = [];
  const тегСтатуса = м.статусТег && м.статус && м.статус === видСтатуса(м.статусТег) && !м.статусКак ? `[${м.статусТег}]` : '';
  if (тегСтатуса) теги.push(тегСтатуса);
  if (м.кем && чисто(м.кем)) теги.push(`[BY: ${внутриТега(м.кем)}]`);
  if (м.переслано !== null && м.переслано !== undefined) теги.push(`[FWD: ${внутриТега(м.переслано)}]`);
  if (м.ответ && (чисто(м.ответ.что) || чисто(м.ответ.кто))) {
    const кто = внутриТега(м.ответ.кто).replace(/::/g, ':');
    теги.push(`[REPLY: ${кто ? кто + ' :: ' : ''}${внутриТега(м.ответ.что).replace(/::/g, ':')}]`);
  }
  const длит = (v) => { const д = String(v ?? '').trim().match(/^(\d{1,2}):(\d{1,2})$/); return д ? `${+д[1]}:${д[2].padStart(2, '0')}` : ''; };
  if (м.вид === 'voice') теги.push(`[VOICE${длит(м.голос.длит) ? '_' + длит(м.голос.длит) : ''}]`);
  else if (м.вид === 'photo') теги.push(`[PHOTO: ${внутриТега(м.фото.что)}]`);
  else if (м.вид === 'video') теги.push(`[VIDEO${длит(м.видео.длит) ? '_' + длит(м.видео.длит) : ''}: ${внутриТега(м.видео.что)}]`);
  else if (м.вид === 'call') {
    const з = м.звонок;
    const слова = [з.куда === 'in' ? 'incoming' : з.куда === 'out' ? 'outgoing' : '', з.исход || 'answered', з.исход === 'answered' ? длит(з.длит) : ''].filter(Boolean);
    теги.push(`[CALL: ${слова.join(', ')}]`);
  } else if (м.вид === 'poll') {
    const вопрос = внутриТега(м.опрос.вопрос).replace(/;;/g, ';').replace(/=/g, '-');
    const варианты = (м.опрос.варианты || []).filter(в => чисто(в.текст)).map(в => {
      const текст = внутриТега(в.текст).replace(/;;/g, ';').replace(/=/g, '-');
      const кто = внутриТега(в.кто).replace(/;;/g, ',').replace(/=/g, '-').split(/\s*[,;]\s*/).filter(Boolean).join(', ');
      return кто ? `${текст} = ${кто}` : текст;
    });
    теги.push(`[POLL: ${[вопрос || '?', ...варианты].join(' ;; ')}]`);
  }
  теги.push(...(м.прочее || []));
  const текст = безЧерты(м.текст).replace(/\n+/g, ' ');
  // Без отправителя модель пишет строку с телефона владельца ([BY: …] первым) —
  // так и оставляем, не выдумывая «Unknown».
  // Пробелы внутри имени не трогаем: «THE REGENTS  Tristan» с двумя — тоже имя карточки.
  const от = безЧерты(м.от).replace(/[:[\]]/g, ' ').replace(/\n+/g, ' ').trim();
  const кому = безЧерты(м.кому).replace(/[:[\]]/g, ' ').replace(/\n+/g, ' ').trim();
  const голова = от ? `${от}${кому ? ' -> ' + кому : ''}: ` : '';
  let строка = голова + [...теги, текст].filter(Boolean).join(' ');
  const время = безЧерты(м.время).replace(/\n+/g, ' ');
  // Статус пишем, как он был у модели, если игрок его не менял.
  const было = видСтатуса(м.статусКак);
  const статус = !м.статус || тегСтатуса ? '' : (было === м.статус && м.статусКак ? м.статусКак : СЛОВО_СТАТУСА[м.статус] || '');
  if (время || статус) строка += ` | ${время}`;
  if (статус) строка += ` | ${статус}`;
  return строка;
}

/* --- Какая форма у значения -------------------------------------------------- */

/**
 * Форма для окна: { вид, ... }. Виды:
 *  текст · метки{известные} · список{строкой} · части{подписи} · доверие ·
 *  сообщение · объект · записи (массив объектов).
 */
export function формаЗначения(путь, значение) {
  const корень = путь[0];
  const ключ = путь[путь.length - 1];
  const родитель = путь[путь.length - 2];
  if (Array.isArray(значение)) {
    const образец = значение.find(x => x !== null && x !== undefined);
    if (ключ === 'ms' && (корень === 'cm' || корень === 'tp')) return { вид: 'сообщения' };
    // Хоть одна запись-объект — весь список записями: объект в строку не превращаем.
    if (объект(образец) || значение.some(объект)) return { вид: 'записи' };
    const части = ЧАСТИ[`${корень}.${ключ}`];
    if (части && путь.length === 2) return { вид: 'список', строкой: false, пункт: { вид: 'части', подписи: части } };
    return { вид: 'список', строкой: false, пункт: { вид: 'текст' } };
  }
  if (объект(значение)) return { вид: 'объект' };
  // Строки.
  if ((родитель === 'ms') && (корень === 'cm' || корень === 'tp')) return { вид: 'сообщение' };
  if (typeof родитель === 'number' || путь.length === 3 && ЧАСТИ[`${корень}.${родитель}`]) {
    const части = ЧАСТИ[`${корень}.${путь[1]}`];
    if (части && путь.length === 3) return { вид: 'части', подписи: части };
  }
  // Эмоция записи дневника — выбором из тем листа, а не английским словом.
  if ((корень === 'dy' || корень === 'bd') && путь.length === 3 && ключ === 'md') return { вид: 'настроение', набор: корень };
  const человек = ЛЮДИ.has(корень) && путь.length === (корень === 'us' ? 2 : 3);
  if (человек && ключ === 'Tr') return { вид: 'доверие' };
  if (человек) {
    const метки = меткиКаталога(корень === 'bb' ? 'bb' : 'cs', ключ);
    if (метки) return { вид: 'метки', известные: метки };
    if (СПИСКИ_ЛЮДЕЙ.has(ключ) && String(значение ?? '').includes(';')) return { вид: 'список', строкой: true, пункт: { вид: 'текст' } };
  }
  // Свой стат вида «Список меток» (метки через «;») — по пунктам.
  if ((корень === 'cst' || родитель === 'Cst') && typeof значение === 'string' && поТочкеСЗапятой(значение).length > 1 && !/[.!?…]\s/.test(значение)) return { вид: 'список', строкой: true, пункт: { вид: 'текст' } };
  if (корень === 'pet' && ключ === 'lv') return { вид: 'метки', известные: [['sat', 'сытость'], ['eng', 'энергия'], ['cln', 'чистота'], ['joy', 'настроение']] };
  if (похожеНаМетки(значение)) return { вид: 'метки', известные: null };
  return { вид: 'текст', длинный: String(значение ?? '').length > 70 };
}

/* --- Блок по тексту на экране ---------------------------------------------- */

// Невидимые символы (defeatWI ставит их после первой буквы, чтобы лорбук не
// срабатывал на экранный текст) слово не режут.
const слова = (s) => new Set(String(s ?? '').replace(/[\u200B-\u200D\u2060\uFEFF\u00AD]/g, '').toLowerCase().replace(/ё/g, 'е').split(/[^\p{L}\p{N}]+/u).filter(w => w.length >= 3));

function листья(у, путь, out) {
  if (typeof у === 'string') { if (!пусто(у)) out.push({ путь, слова: слова(у) }); return; }
  if (Array.isArray(у)) { у.forEach((x, i) => листья(x, [...путь, i], out)); return; }
  // Имя человека — его опознание во всех ходах: по нажатию на имя его не правим.
  if (объект(у)) for (const [к, v] of Object.entries(у)) if (к !== 'N') листья(v, [...путь, к], out);
}

/** Путь блока, к которому относится лист: поле человека, раздел, запись, сообщение. */
export function блокЛиста(путь) {
  const [корень, второй] = путь;
  if (корень === 'cs' || корень === 'bb') return путь.slice(0, 3);
  if (корень === 'us' || корень === 'sc') return путь.slice(0, 2);
  if (корень === 'cm') return путь[2] === 'ms' && путь.length >= 4 ? путь.slice(0, 4) : путь.slice(0, 2);
  if (корень === 'tp') return путь[2] === 'ms' && путь.length >= 4 ? путь.slice(0, 4) : путь.slice(0, 2);
  if (['dy', 'bd', 'dr', 'pet', 'lt', 'ov', 'mw'].includes(корень) && typeof второй === 'number') return путь.slice(0, 2);
  return путь.slice(0, Math.min(2, путь.length));
}

/**
 * Где в HUD текст, на который нажали. корни — разделы, где искать (по
 * вкладке). null — не нашлось уверенно.
 */
export function путьПоТексту(hud, корни, текст) {
  const нажато = слова(текст);
  if (!нажато.size) return null;
  const все = [];
  // Корень — код раздела ('wd') или путь к записи (['cs', 2]).
  for (const к of корни) { const п = Array.isArray(к) ? к : [к]; const у = взять(hud, п); if (у !== undefined) листья(у, п, все); }
  let лучший = null;
  for (const л of все) {
    let общих = 0;
    for (const w of нажато) if (л.слова.has(w)) общих++;
    if (!общих) continue;
    const точность = общих / нажато.size;
    const полнота = общих / Math.max(1, л.слова.size);
    const счёт = общих * точность + полнота;
    if (!лучший || счёт > лучший.счёт) лучший = { путь: л.путь, счёт, общих, точность };
  }
  if (!лучший) return null;
  // Короткий текст — все слова должны совпасть; длинный — большая часть.
  const нужно = Math.min(3, нажато.size);
  if (лучший.общих < нужно || лучший.точность < (нажато.size <= 3 ? 1 : 0.55)) return null;
  return { лист: лучший.путь, блок: блокЛиста(лучший.путь) };
}

