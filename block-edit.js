function меткиКаталога(раздел, код) {
  const р = КАТАЛОГ.find(x => x.код === раздел);
  if (!р) return null;
  for (const г of р.группы) {
    if (г.код) continue;
    const п = г.поля.find(x => x[0] === код);
    if (п) return п[2] || null;
  }
  return null;
}
