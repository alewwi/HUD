/** Значение по пути ['cs', 0, 'Tr']; undefined — нет такого. */
export function взять(hud, путь) {
  let у = hud;
  for (const к of путь) {
    if (у === null || typeof у !== 'object') return undefined;
    у = у[к];
  }
  return у;
}
/** Положить значение по пути; недостающие разделы заводятся. false — некуда. */
export function положить(hud, путь, значение) {
  if (!объект(hud) || !путь.length) return false;
  let у = hud;
  for (let i = 0; i < путь.length - 1; i++) {
    const к = путь[i];
    if (у[к] === null || typeof у[к] !== 'object') {
      if (Array.isArray(у) && typeof к === 'number' && к >= у.length) return false;
      у[к] = typeof путь[i + 1] === 'number' ? [] : {};
    }
    у = у[к];
  }
  const последний = путь[путь.length - 1];
  if (Array.isArray(у) && (typeof последний !== 'number' || последний > у.length)) return false;
  у[последний] = значение;
  return true;
}
