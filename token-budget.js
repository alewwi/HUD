// Инструкция смешанная: правила по-английски, примеры по-русски. У BPE
// латиница идёт ~4 знака на токен, кириллица ~2,5, прочее (знаки, цифры,
// пробелы) ~3,2. Считаем по алфавитам, а не по длине — и всегда пишем «≈».
export function оценкаТокенов(текст) {
  const s = String(текст || '');
  if (!s) return 0;
  const кир = (s.match(/[Ѐ-ӿ]/g) || []).length;
  const лат = (s.match(/[A-Za-z]/g) || []).length;
  return Math.round(кир / 2.5 + лат / 4 + (s.length - кир - лат) / 3.2);
}

// Родной счётчик SillyTavern, если до него дотянуться (в разных версиях он
// лежит по-разному и бывает асинхронным). Не вышло — оценка.
export async function точноТокенов(текст) {
  try {
    const c = window.SillyTavern?.getContext?.();
    const f = c?.getTokenCountAsync || c?.getTokenCount;
    if (typeof f === 'function') {
      const n = await f.call(c, String(текст || ''));
      if (Number.isFinite(n) && n > 0) return n;
    }
  } catch (_) { /* нет счётчика — оценка */ }
  return оценкаТокенов(текст);
}

/**
 * Разбивка инструкции. собрать({ nsfw, бой }) → строка инструкции (обычно
 * buildDynamicPrompt). nsfw и бой — как пойдёт следующий запрос.
 * Возвращает { всего, разделы: [{ имя, ключ|опция, цена, когда?, выкл }], основа }.
 *
 * settings — живой объект, общий для всех модулей: раздел выключаем только
 * на время одной сборки и возвращаем в finally — упавшая сборка иначе
 * оставила бы у человека выключенный блок.
 * Разделы не аддитивны (часть текста меняется при выключении соседа: «мир»
 * пишется по-разному при включённой экономике и афише), поэтому сумма
 * разделов не равна целому — остаток честно показан как «основа».
 * Цена — именно выключения: человек выключает, чтобы сэкономить.
 */
export function бюджетИнструкции(собрать, { nsfw = false, бой = false } = {}, токены = оценкаТокенов) {
  const полный = собрать({ nsfw, бой });
  const всего = токены(полный);
  const разделы = [];
  for (const р of РАЗДЕЛЫ) {
    let цена = 0, когда = '';
    if (р.опция) {
      // Опция: сколько добавится, когда она включится (или стоит сейчас).
      const сейчасВкл = р.опция === 'nsfw' ? !!nsfw : !!бой;
      const с = собрать({ nsfw, бой, [р.опция]: true });
      const без = собрать({ nsfw, бой, [р.опция]: false });
      цена = токены(с) - токены(без);
      if (!сейчасВкл) когда = р.когда;
    } else {
      if (!(р.ключ in settings) || settings[р.ключ] === false) continue;
      const было = settings[р.ключ];
      let без;
      settings[р.ключ] = false;
      try { без = собрать({ nsfw, бой }); } finally { settings[р.ключ] = было; }
      цена = всего - токены(без);
    }
    if (цена > 0) разделы.push({ имя: р.имя, ключ: р.ключ, опция: р.опция, цена, когда, выкл: р.выкл || [р.ключ, false] });
  }
  разделы.sort((a, b) => b.цена - a.цена);
  const вСумме = разделы.filter(р => !р.когда).reduce((s, р) => s + р.цена, 0);
  return { всего, разделы, основа: Math.max(0, всего - вСумме) };
}

// Подпись набора настроек, от которых зависит инструкция: пока она та же,
// пересчёт не нужен (двадцать с лишним сборок — миллисекунды, но на каждый
// рендер карточки их делать незачем).
export function подписьБюджета(доп = {}) {
  const ключи = РАЗДЕЛЫ.map(р => р.ключ).filter(Boolean).concat(['era', 'nsfwPrompt', 'enableCombat', 'hudFillGaps', 'hudAdaptPrompt', 'phoneAppMessages', 'phoneAppContacts', 'phoneAppGallery', 'phoneAppNotes', 'phoneAppMaps', 'phoneAppSearch', 'phoneAppWallet', 'phoneAppCalendar', 'phoneAppHealth']);
  return JSON.stringify([ключи.map(к => settings[к]), доп]);
}

// Ответ HUD — фактическая длина блока [HUD] в последних ответах, медианой:
// не оценка, а то, что реально потратилось. Тяжёлый HUD дорог дважды — в
// запросе (снимком) и в ответе.
export function медианаОтвета(чат, сколько = 8, токены = оценкаТокенов) {
  const длины = [];
  for (let j = (Array.isArray(чат) ? чат.length : 0) - 1; j >= 0 && длины.length < сколько; j--) {
    const m = чат[j];
    if (!m || m.is_user || m.is_system) continue;
    const т = m.swipes && m.swipes[m.swipe_id] !== undefined ? m.swipes[m.swipe_id] : m.mes;
    const блок = extractHudBlock(String(т || ''));
    if (блок) длины.push(токены(блок));
  }
  if (!длины.length) return null;
  длины.sort((a, b) => a - b);
  const с = длины.length >> 1;
  return длины.length % 2 ? длины[с] : Math.round((длины[с - 1] + длины[с]) / 2);
}

// «4 100» → «≈4,1k» для чипа; в панели — полным числом.
export const коротко = (n) => !Number.isFinite(n) ? '…' : n >= 1000 ? (Math.round(n / 100) / 10).toString().replace('.', ',') + 'k' : String(Math.round(n));
export const числом = (n) => Number.isFinite(n) ? Math.round(n).toLocaleString('ru-RU') : '—';

const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

/**
 * Панель разбивки. итог — то, что собрал index.js (посчитатьБюджет):
 * { запрос, инструкция: бюджетИнструкции(), снимок, ответ, сейф, усиление, слабые }.
 * Число — первым, полоска рядом и не единственный носитель смысла.
 * «Выключить» прямо в строке: человек экономит, не уходя из чата.
 */
export function разметкаБюджета(итог) {
  if (!итог) return '<p class="hud-budget-note">Считаю…</p>';
  const и = итог.инструкция || { разделы: [], основа: 0, всего: 0 };
  const макс = Math.max(1, ...и.разделы.map(р => р.цена), и.основа || 0);
  const полоса = (n) => `<i class="hud-budget-bar" style="--w:${Math.max(2, Math.round(n / макс * 100))}%" aria-hidden="true"></i>`;
  const кнопка = (ключ, значение, подпись = 'выключить') => `<button type="button" class="hud-budget-off" data-key="${esc(ключ)}" data-value="${esc(JSON.stringify(значение))}">${подпись}</button>`;
  const строка = (имя, цена, доп = '', хвост = '') => `<li><span class="hud-budget-name">${esc(имя)}${доп ? `<small>${esc(доп)}</small>` : ''}</span><b class="hud-budget-num">${числом(цена)}</b>${полоса(цена)}${хвост}</li>`;
  // Обычный ответ целиком и перегенерация HUD — что уходит модели на самом деле.
  const ц = итог.ответ_целиком, р = итог.перегенерация;
  const целиком = ц ? `<div class="hud-budget-total"><span>Ответ целиком</span><b>≈${числом(ц.всего)}</b><small>HUD ≈${числом(итог.запрос)}${ц.таверна !== null ? ` · Таверна ≈${числом(ц.таверна)}: пресет, история,` : ' · '} карточка и персона ≈${числом(ц.карточка)}${ц.лорбук !== null ? ` · лорбук ≈${числом(ц.лорбук)}` : ''}${ц.точно ? '' : ' (истории и пресета пока нет — запроса не было)'}</small></div>` : '';
  const реген = р ? `<div class="hud-budget-total"><span>Перегенерация HUD</span><b>≈${числом(р.всего)}</b><small>история (${р.сообщений} сообщ.) ≈${числом(р.история)} · инструкция ≈${числом(р.инструкция)} · снимок ≈${числом(р.снимок)} · карточка и персона ≈${числом(р.карточка)}${р.лорбук ? ` · лорбуки HUD ≈${числом(р.лорбук)}` : ''}</small></div>` : '';
  const сверху = целиком + реген + `<p class="hud-budget-sum"><b>≈${числом(итог.запрос)}</b> — HUD в ответе: инструкция ≈${числом(и.всего)} · снимок ≈${числом(итог.снимок)}${итог.сейф ? ` · дописать ≈${числом(итог.сейф)}` : ''}${итог.усиление ? ` · усиления ≈${числом(итог.усиление)}` : ''}</p>`
    + `<p class="hud-budget-note">Ответ HUD ≈${итог.ответ === null ? '—' : числом(итог.ответ)} (медиана последних) — тяжёлый HUD дорог дважды: в запросе снимком и в ответе.</p>`;
  const строки = и.разделы.map(р => строка(р.имя, р.цена, р.когда, кнопка(р.выкл[0], р.выкл[1])))
    .concat(итог.усиление ? [строка('Усиления', итог.усиление, (итог.слабые || []).map(с => с.имя).join(', ') + ' — модель их часто пропускает', кнопка('hudAdaptPrompt', false))] : [])
    .concat(итог.сейф ? [строка('Дописать пропущенное', итог.сейф, 'сейф по прошлому HUD', кнопка('hudFillGaps', false))] : [])
    .concat([строка('Основа', и.основа, 'правила и схема, всегда')]);
  return сверху + `<ul class="hud-budget-list">${строки.join('')}</ul>`
    + `<p class="hud-budget-note">Числа приблизительные (≈): токенизатор модели на сервере может считать иначе. «Выключить» действует со следующего ответа; скрыть вкладку, не выключая блок, — в «Кастомизации».</p>`;
}
