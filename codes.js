// Полный ключ, если он уже есть, главнее кода: смешанный ответ не теряет
// значение, записанное полным названием.
function переименовать(узел, словарь) {
  for (const [код, ключ] of Object.entries(словарь)) {
    if (!Object.prototype.hasOwnProperty.call(узел, код)) continue;
    if (узел[ключ] === undefined || узел[ключ] === null) узел[ключ] = узел[код];
    delete узел[код];
  }
}
const каждому = (список, словарь) => {
  if (Array.isArray(список)) список.forEach(x => { if (объект(x)) переименовать(x, словарь); });
};

// Разворачивает коды ключей на месте. Вызывается до нормализации схемы,
// поэтому дальше код видит привычные названия.
export function развернутьКоды(к) {
  if (!объект(к)) return к;
  переименовать(к, КОРЕНЬ);
  const п = к.memory;
  if (объект(п)) {
    переименовать(п, ПАМЯТЬ);
    if (объект(п.mood)) {
      переименовать(п.mood, ДВОЕ);
      for (const кто of Object.keys(п.mood)) if (объект(п.mood[кто])) переименовать(п.mood[кто], НАСТРОЕНИЕ);
    }
    if (объект(п.route)) переименовать(п.route, ДВОЕ);
    каждому(п.secrets, СЕКРЕТ);
    if (Array.isArray(п.secrets)) п.secrets.forEach(с => { if (объект(с)) каждому(с.knows, ЗНАЮЩИЙ); });
  }
  if (объект(к.chatsMap)) {
    for (const переписка of Object.values(к.chatsMap)) if (объект(переписка)) переименовать(переписка, ПЕРЕПИСКА);
  }
  каждому(к.intercepts, ПЕРЕХВАТ);
  if (объект(к.phone)) {
    переименовать(к.phone, ТЕЛЕФОН);
    for (const [раздел, словарь] of Object.entries(ПОЛЯ_ТЕЛЕФОНА)) каждому(к.phone[раздел], словарь);
    if (объект(к.phone.wallet)) {
      переименовать(к.phone.wallet, КОШЕЛЁК);
      каждому(к.phone.wallet.transactions, ПЛАТЁЖ);
    }
  }
  каждому(к.diary, ЗАПИСЬ);
  каждому(к.bodyDiary, ЗАПИСЬ);
  каждому(к.dreams, СОН);
  // Один спутник объектом, а не списком — тоже спутник.
  if (объект(к.companions)) к.companions = [к.companions];
  каждому(к.companions, СПУТНИК);
  if (объект(к.world)) переименовать(к.world, МИР);
  return к;
}

// Обратно к кодам: полное имя → первый код словаря, тот, что просит промт.
// Нужно снимку последнего HUD — модели показывают её же короткий формат,
// в каком бы виде ход ни сохранился (кодами, длинными ключами, вперемешку).
const обратный = (словарь) => {
  const out = {};
  for (const [код, имя] of Object.entries(словарь)) if (!(имя in out)) out[имя] = код;
  return out;
};
const В_КОД = {
  корень: обратный(КОРЕНЬ), память: обратный(ПАМЯТЬ), двое: обратный(ДВОЕ), настроение: обратный(НАСТРОЕНИЕ),
  секрет: обратный(СЕКРЕТ), знающий: обратный(ЗНАЮЩИЙ), переписка: обратный(ПЕРЕПИСКА), перехват: обратный(ПЕРЕХВАТ),
  телефон: обратный(ТЕЛЕФОН), кошелёк: обратный(КОШЕЛЁК), платёж: обратный(ПЛАТЁЖ), запись: обратный(ЗАПИСЬ),
  сон: обратный(СОН), мир: обратный(МИР), спутник: обратный(СПУТНИК),
  поляТелефона: Object.fromEntries(Object.entries(ПОЛЯ_ТЕЛЕФОНА).map(([раздел, с]) => [раздел, обратный(с)])),
};

// Сворачивает ключи разделов в коды на месте. Ключи полей персонажа, игрока и
// сцены (Имя → N) сворачивает вызывающий: их словарь живёт в utils.js.
export function свернутьКоды(к) {
  if (!объект(к)) return к;
  развернутьКоды(к);
  const п = к.memory;
  if (объект(п)) {
    if (объект(п.mood)) {
      for (const кто of Object.keys(п.mood)) if (объект(п.mood[кто])) переименовать(п.mood[кто], В_КОД.настроение);
      переименовать(п.mood, В_КОД.двое);
    }
    if (объект(п.route)) переименовать(п.route, В_КОД.двое);
    if (Array.isArray(п.secrets)) п.secrets.forEach(с => { if (объект(с)) каждому(с.knows, В_КОД.знающий); });
    каждому(п.secrets, В_КОД.секрет);
    переименовать(п, В_КОД.память);
  }
  if (объект(к.chatsMap)) {
    for (const переписка of Object.values(к.chatsMap)) if (объект(переписка)) переименовать(переписка, В_КОД.переписка);
  }
  каждому(к.intercepts, В_КОД.перехват);
  if (объект(к.phone)) {
    for (const [раздел, словарь] of Object.entries(В_КОД.поляТелефона)) каждому(к.phone[раздел], словарь);
    if (объект(к.phone.wallet)) {
      каждому(к.phone.wallet.transactions, В_КОД.платёж);
      переименовать(к.phone.wallet, В_КОД.кошелёк);
    }
    переименовать(к.phone, В_КОД.телефон);
  }
  каждому(к.diary, В_КОД.запись);
  каждому(к.bodyDiary, В_КОД.запись);
  каждому(к.dreams, В_КОД.сон);
  каждому(к.companions, В_КОД.спутник);
  if (объект(к.world)) переименовать(к.world, В_КОД.мир);
  переименовать(к, В_КОД.корень);
  return к;
}

