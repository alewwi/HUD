function поСловарю(словарь, образцы, слово, запасной) {
  const сырое = String(слово ?? '').trim();
  const низ = сырое.toLowerCase();
  let ключ = словарь[низ] ? низ : ((образцы.find(([rx]) => rx.test(сырое)) || [])[1] || запасной);
  return { ключ, текст: словарь[низ] || сырое || (ключ ? словарь[ключ] : '') };
}
