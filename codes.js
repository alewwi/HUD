const найти = (словарь, слово) => словарь[String(слово ?? '').trim().toLowerCase()];
const или = (словарь) => (слово) => найти(словарь, слово) || String(слово ?? '');

// «mo | cl | +7°C | заметка» → «Утро | ясно | +7°C | заметка».
export function строкаПрогноза(строка) {
  const части = String(строка ?? '').split('|');
  if (части.length === 1) return найти(ПОГОДА, части[0]) || String(строка ?? '');
  части[0] = найти(ПЕРИОДЫ, части[0]) || части[0].trim();
  части[1] = найти(ПОГОДА, части[1]) || части[1].trim();
  return части.map(ч => ч.trim()).join(' | ');
}

// «ar | текст | gd» → «Овен | текст | удача».
export function строкаГороскопа(строка) {
  const части = String(строка ?? '').split('|');
  if (части.length === 1) return String(строка ?? '');
  части[0] = найти(ЗНАКИ, части[0]) || части[0].trim();
  if (части.length > 2) части[2] = найти(ТОН_ДНЯ, части[2]) || части[2].trim();
  return части.map(ч => ч.trim()).join(' | ');
}

// «14:30 - Кафе - ar» → «14:30 - Кафе - прибытие». Трогаем только последний
// кусок и только если это код: в названии места тоже бывает дефис.
export function строкаМаршрута(строка) {
  return String(строка ?? '').replace(/([-—–]\s*)([a-z]+)\s*$/i, (всё, тире, код) => {
    const слово = найти(ДВИЖЕНИЕ, код);
    return слово ? тире + слово : всё;
  });
}

// Статус в конце строки сообщения (| ur) и исход звонка внутри [CALL: …].
// Разворачиваем в прежние слова: переписка и уведомления ищут именно их.
export function строкаСообщения(строка) {
  return String(строка ?? '')
    .replace(/(\|\s*)(rd|ur|dl|df)\s*$/i, (всё, черта, код) => черта + СТАТУС_СООБЩЕНИЯ[код.toLowerCase()])
    .replace(/\[(CALL|ЗВОНОК)([^\]]*)\]/gi, (всё, тег, тело) =>
      '[' + тег + тело.replace(/\b(ans|an|dc|mi)\b/gi, код => ИСХОД_ЗВОНКА[код.toLowerCase()]) + ']');
}

