// hud-manager/hud-check.js
//
// Проверка полноты HUD после ответа модели.
//
// В длинном чате модель ленится: пропускает мысли персонажей, дневник,
// гороскоп — то, что пишется заново каждый ход. Проверяем только поля,
// которые схема требует КАЖДЫЙ ход без условий. Условные не трогаем: сны
// бывают только во сне, дневник тела — только в близости, скрытый подтекст
// честно бывает 'empty', комментариев может не быть вовсе. Ложная тревога
// здесь стоит лишнего запроса к модели, поэтому лучше промолчать.

import { settings } from './settings.js?v=23.90.1';
import { extractHudBlock } from './hud-block.js?v=23.90.1';
import { HUDвКодах, непусто } from './hud-snapshot.js?v=23.90.1';
import { противоречияБыта } from './render/life.js?v=23.90.1';
import { сжатыеПоля, лимитПоля } from './compact-fields.js?v=23.90.1';

const объект = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const МЕТКА = /<\s*new this turn\b[^>]*>/i;

// Заполнено ли поле: не пусто, не 'empty' и не переписанная метка снимка.
function заполнено(v) {
  if (Array.isArray(v)) return v.some(заполнено);
  if (объект(v)) return Object.values(v).some(заполнено);
  return непусто(v) && !МЕТКА.test(String(v));
}

/**
 * Чего не хватает в HUD сообщения. Пустой список — HUD полный.
 * Названия — для всплывающего сообщения игроку; с { дляМодели: true } —
 * английские, с кодами полей: эта строка уходит в инструкцию модели
 * (index.js, дописатьПропущенное), а в промте кириллицы быть не должно.
 */
export function чегоНеХватает(текстСообщения, { дляМодели = false } = {}) {
  const м = (ru, en, имя) => { const s = дляМодели ? en : ru; return имя === undefined ? s : `${s} (${имя})`; };
  const блок = extractHudBlock(String(текстСообщения || ''));
  if (!блок) return [м('весь HUD', 'the whole HUD')];
  const к = HUDвКодах(блок);
  if (!к) return [м('весь HUD (не разобрался)', 'the whole HUD (unparsable)')];

  const нет = [];
  // Блока персонажей нет вовсе — модель выдала обрывок: сцену и память, а
  // персонажей, игрока, телефон и остальное выкинула. Схема просит "cs"
  // каждый ход; честное «никого нет» — пустой список [], а не пропуск ключа.
  // Без этой проверки обрывок считался полным: мысли и дневник сверяются
  // только у тех, кто в cs.
  if (!Array.isArray(к.cs)) нет.push(м('персонажи (весь блок cs)', 'the whole "cs" block (characters) and the other blocks of the schema'));
  (Array.isArray(к.cs) ? к.cs : []).filter(объект).forEach(c => {
    const имя = непусто(c.N) ? String(c.N) : м('персонаж', 'character');
    if (!заполнено(c.Th)) нет.push(м('мысли', 'Th (thoughts)', имя));
    if (!заполнено(c.Ex)) нет.push(м('ожидание и реальность', 'Ex (expectation vs reality)', имя));
  });
  // Дневник пишут присутствующие. Никого в cs нет — {{char}} вне сцены, и
  // писать от его имени промт запрещает: пустой дневник тогда честный.
  if (settings.enableDiary && (Array.isArray(к.cs) ? к.cs : []).some(объект) && !заполнено(к.dy)) нет.push(м('дневник', 'dy (diary)'));
  // Дневник — настоящая запись, а не мысль или заметка: короче ~220 знаков
  // и меньше трёх предложений — это заметка. Порог мягкий, чтобы не гонять
  // модель из-за записи чуть короче просимой.
  // Сжатый дневник (compact-fields.js) короче сам по себе: порог — по его
  // размеру, иначе запись в 30 слов гоняла бы перегенерацию каждый ход.
  const сжатДневник = сжатыеПоля(settings).includes('dy.tx') ? лимитПоля(settings, 'dy.tx').w : 0;
  const знаков = сжатДневник ? Math.min(220, сжатДневник * 3) : 220;
  const предложений = сжатДневник ? Math.min(3, Math.max(2, Math.floor(сжатДневник / 20))) : 3;
  const короткая = (т) => { const s = String(т || '').replace(/~~.*?~~/g, '').trim(); return s.length < знаков && (s.match(/[.!?…]+(?=\s|$)/g) || []).length < предложений; };
  if (settings.enableDiary && Array.isArray(к.dy) && к.dy.some(з => объект(з) && заполнено(з.tx) && короткая(з.tx))) нет.push(м('дневник (слишком короткий)', 'dy (diary entry too short: write a real entry of several sentences)'));
  // «Мир раз в день» (hudWorldDaily, по умолчанию включено): гороскоп пишется
  // только в первом HUD нового дня, в остальных промт велит его пропускать —
  // требовать его каждый ход значило бы перегенерировать почти каждый ответ.
  if (settings.enableWorld && settings.enableHoroscope !== false && settings.hudWorldDaily === false && !заполнено(к.wd && к.wd.zd)) нет.push(м('гороскоп', 'wd.zd (horoscope)'));
  // Бой: раз блок есть, этап и участники обязательны, остальное — нет.
  if (settings.enableCombat !== false && объект(к.cb) && заполнено(к.cb)) {
    if (!заполнено(к.cb.st)) нет.push(м('этап боя', 'cb.st (combat stage)'));
    if (!заполнено(к.cb.pt)) нет.push(м('участники боя', 'cb.pt (combat participants)'));
  }
  return нет;
}

/**
 * Неполнота плюс противоречия с журналом быта (settings.hudConsistencyCheck,
 * по умолчанию выключено): «сытость 80, а не ели 9 ч», «баланс сдвинулся без
 * транзакций». Это не пропуск, а повод перепроверить — потому только по
 * настройке.
 */
export function проблемыОтвета(сообщения, id, текстСообщения) {
  const нет = чегоНеХватает(текстСообщения);
  // С вопросами о противоречиях (disputes.js) они решаются вопросом игроку, а не перегенерацией.
  if (settings.hudConsistencyCheck === true && settings.enableLife !== false && settings.askContradictions !== true) {
    try { нет.push(...противоречияБыта(сообщения, id)); } catch (_) { /* журнал не собрался — молчим */ }
  }
  return нет;
}

// Типы генерации, после которых HUD должен быть в ответе.
const ПРОВЕРЯЕМ = new Set(['normal', 'swipe', 'regenerate', 'continue', undefined, null, '']);

/**
 * Обработчик MESSAGE_RECEIVED. Зависимости приходят снаружи, чтобы проверку
 * можно было прогнать без SillyTavern и без настоящей генерации.
 *   чат()                 — массив сообщений чата;
 *   ключЧата()            — чем различать чаты;
 *   перегенерировать(id)  — запустить перегенерацию HUD; вернуть промис, true если запущена;
 *   сообщить(тип, заголовок, текст)
 */
export function создатьПроверкуПолноты({ чат, ключЧата = () => '', перегенерировать, сообщить = () => {} }) {
  const уже = new Set();
  let остановленоВ = 0;

  return {
    // Игрок сам нажал «стоп» — обрезанный ответ не чиним.
    остановлено() { остановленоВ = Date.now(); },

    async послеОтвета(messageId, type) {
      // A repair request replaces the backend cache and edits the last reply.
      const выбранныйРежим = settings.hudCompleteCheck || 'regen';
      const режим = settings.hudCacheStable && выбранныйРежим === 'regen' ? 'warn' : выбранныйРежим;
      if (режим === 'off' || !settings.autoInject) return 'выключено';
      if (!ПРОВЕРЯЕМ.has(type)) return 'не тот тип';
      if (Date.now() - остановленоВ < 5000) return 'остановлено';
      const сообщения = чат();
      const id = Number(messageId);
      const m = Array.isArray(сообщения) ? сообщения[id] : null;
      if (!m || m.is_user || m.is_system) return 'не ответ';
      const текст = m.swipes && m.swipes[m.swipe_id] !== undefined ? m.swipes[m.swipe_id] : m.mes;
      if (!String(текст || '').trim()) return 'пусто';

      const нет = проблемыОтвета(сообщения, id, текст);
      if (!нет.length) return 'полный';

      // Одна попытка на ответ: неполный результат перегенерации не зацикливаем.
      const ключ = `${ключЧата()}|${id}|${m.swipe_id ?? 0}`;
      if (уже.has(ключ)) return 'уже чинили';
      уже.add(ключ);

      const список = нет.slice(0, 4).join(', ') + (нет.length > 4 ? ` и ещё ${нет.length - 4}` : '');
      if (режим === 'warn') {
        сообщить('error', 'HUD неполный', `Модель пропустила: ${список}. Нажмите 🔄, чтобы перегенерировать HUD.`);
        return 'предупредили';
      }
      // Не «loading»: такое сообщение само не гаснет, а у перегенерации свой индикатор.
      сообщить('info', 'HUD неполный', `Модель пропустила: ${список}. Досоздаю HUD…`);
      const запущено = await перегенерировать(id);
      if (!запущено) {
        сообщить('error', 'HUD неполный', `Модель пропустила: ${список}. Перегенерировать сама не смогла — нажмите 🔄.`);
        return 'не запустилось';
      }
      const после = чат()[id];
      const текстПосле = после && (после.swipes && после.swipes[после.swipe_id] !== undefined ? после.swipes[после.swipe_id] : после.mes);
      const осталось = проблемыОтвета(чат(), id, текстПосле);
      if (осталось.length) сообщить('error', 'HUD всё ещё неполный', `Не хватает: ${осталось.slice(0, 4).join(', ')}. Можно нажать 🔄 ещё раз.`);
      return осталось.length ? 'починили не всё' : 'починили';
    },
  };
}
