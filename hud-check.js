// hud-manager/hud-check.js
//
// Проверка полноты HUD после ответа модели.
//
// В длинном чате модель ленится: пропускает мысли персонажей, дневник,
// гороскоп — то, что пишется заново каждый ход. Проверяем только поля,
// которые схема требует КАЖДЫЙ ход без условий. Условные не трогаем: сны
// бывают только во сне, дневник тела — только в близости, скрытый подтекст
// честно бывает 'empty', комментариев может не быть вовсе. Ложная тревога
// здесь стоит лишнего запроса к модели, поэтому лучше промолчать.

import { settings } from './settings.js?v=22.99.79';
import { extractHudBlock } from './hud-block.js?v=22.99.79';
import { HUDвКодах, непусто } from './hud-snapshot.js?v=22.99.79';

const объект = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const МЕТКА = /<\s*new this turn\b[^>]*>/i;

// Заполнено ли поле: не пусто, не 'empty' и не переписанная метка снимка.
function заполнено(v) {
  if (Array.isArray(v)) return v.some(заполнено);
  if (объект(v)) return Object.values(v).some(заполнено);
  return непусто(v) && !МЕТКА.test(String(v));
}

/**
 * Чего не хватает в HUD сообщения. Пустой список — HUD полный.
 * Названия — для всплывающего сообщения игроку.
 */
export function чегоНеХватает(текстСообщения) {
  const блок = extractHudBlock(String(текстСообщения || ''));
  if (!блок) return ['весь HUD'];
  const к = HUDвКодах(блок);
  if (!к) return ['весь HUD (не разобрался)'];

  const нет = [];
  (Array.isArray(к.cs) ? к.cs : []).filter(объект).forEach(c => {
    const имя = непусто(c.N) ? String(c.N) : 'персонаж';
    if (!заполнено(c.Th)) нет.push(`мысли (${имя})`);
    if (!заполнено(c.Ex)) нет.push(`ожидание и реальность (${имя})`);
  });
  if (settings.enableDiary && !заполнено(к.dy)) нет.push('дневник');
  if (settings.enableWorld && settings.enableHoroscope !== false && !заполнено(к.wd && к.wd.zd)) нет.push('гороскоп');
  return нет;
}

// Типы генерации, после которых HUD должен быть в ответе.
const ПРОВЕРЯЕМ = new Set(['normal', 'swipe', 'regenerate', 'continue', undefined, null, '']);

/**
 * Обработчик MESSAGE_RECEIVED. Зависимости приходят снаружи, чтобы проверку
 * можно было прогнать без SillyTavern и без настоящей генерации.
 *   чат()                 — массив сообщений чата;
 *   ключЧата()            — чем различать чаты;
 *   перегенерировать(id)  — запустить перегенерацию HUD; вернуть промис, true если запущена;
 *   сообщить(тип, заголовок, текст)
 */
export function создатьПроверкуПолноты({ чат, ключЧата = () => '', перегенерировать, сообщить = () => {} }) {
  const уже = new Set();
  let остановленоВ = 0;

  return {
    // Игрок сам нажал «стоп» — обрезанный ответ не чиним.
    остановлено() { остановленоВ = Date.now(); },

    async послеОтвета(messageId, type) {
      const режим = settings.hudCompleteCheck || 'regen';
      if (режим === 'off' || !settings.autoInject) return 'выключено';
      if (!ПРОВЕРЯЕМ.has(type)) return 'не тот тип';
      if (Date.now() - остановленоВ < 5000) return 'остановлено';
      const сообщения = чат();
      const id = Number(messageId);
      const m = Array.isArray(сообщения) ? сообщения[id] : null;
      if (!m || m.is_user || m.is_system) return 'не ответ';
      const текст = m.swipes && m.swipes[m.swipe_id] !== undefined ? m.swipes[m.swipe_id] : m.mes;
      if (!String(текст || '').trim()) return 'пусто';

      const нет = чегоНеХватает(текст);
      if (!нет.length) return 'полный';

      // Одна попытка на ответ: неполный результат перегенерации не зацикливаем.
      const ключ = `${ключЧата()}|${id}|${m.swipe_id ?? 0}`;
      if (уже.has(ключ)) return 'уже чинили';
      уже.add(ключ);

      const список = нет.slice(0, 4).join(', ') + (нет.length > 4 ? ` и ещё ${нет.length - 4}` : '');
      if (режим === 'warn') {
        сообщить('error', 'HUD неполный', `Модель пропустила: ${список}. Нажмите 🔄, чтобы перегенерировать HUD.`);
        return 'предупредили';
      }
      // Не «loading»: такое сообщение само не гаснет, а у перегенерации свой индикатор.
      сообщить('info', 'HUD неполный', `Модель пропустила: ${список}. Досоздаю HUD…`);
      const запущено = await перегенерировать(id);
      if (!запущено) {
        сообщить('error', 'HUD неполный', `Модель пропустила: ${список}. Перегенерировать сама не смогла — нажмите 🔄.`);
        return 'не запустилось';
      }
      const после = чат()[id];
      const текстПосле = после && (после.swipes && после.swipes[после.swipe_id] !== undefined ? после.swipes[после.swipe_id] : после.mes);
      const осталось = чегоНеХватает(текстПосле);
      if (осталось.length) сообщить('error', 'HUD всё ещё неполный', `Не хватает: ${осталось.slice(0, 4).join(', ')}. Можно нажать 🔄 ещё раз.`);
      return осталось.length ? 'починили не всё' : 'починили';
    },
  };
}
