// hud-manager/hud-block.js
//
// Поиск блока [HUD] в тексте сообщения. Одна регулярка на всё расширение:
// раньше она была скопирована в семь файлов, и копии начали расходиться.
// Тег узнаём и в виде HTML-сущностей (&lt;HUD&gt;, &#91;HUD&#93;) — так его
// отдаёт разметка сообщения. Незакрытый блок тянется до конца текста.
//
// Рассуждения модели — <plan>, <thinking>, <think> и родня — расширение не
// видит вовсе. Модель пишет там «в конце [HUD]...[/HUD]», и такое упоминание
// разбиралось как блок: карточка собиралась из мусора, а обрезка и сводка
// резали текст ответа. Поэтому все поиски идут по «маске»: внутри рассуждений
// каждый символ заменён невидимым, длина строки та же — позиции совпадений
// годятся для исходного текста без пересчёта.

const ОТКР = String.raw`(?:\[|&lt;|<|&#91;)\s*HUD\s*(?:\]|&gt;|>|&#93;)`;
const ЗАКР = String.raw`(?:\[|&lt;|<|&#91;)\s*(?:\/|&#47;|\\)\s*HUD\s*(?:\]|&gt;|>|&#93;)`;

// Модель упоминает метку в своём <plan>: «Final [HUD] json block». Старая
// регулярка брала это упоминание за начало блока и тянула его до настоящего
// [/HUD] — перегенерация вырезала вместе со старым HUD весь текст ответа.
// Поэтому внутри блока другой открывающей метки быть не может: закрывающая
// соединяется с ближайшей открывающей перед ней.
const БЕЗ_ОТКР = `(?:(?!${ОТКР})[\\s\\S])`;
// Незакрытым блоком считаем только метку, за которой сразу идут данные:
// код-блок, JSON или YAML с новой строки (в том числе в HTML-разметке).
// Одинокое упоминание «(OOC: в [HUD] дневник…)» до конца текста не тянется.
const НАЧАЛО_ДАННЫХ = String.raw`(?:\s*(?:<\/?(?:p|br|pre|code|span|div)\b[^>]*>\s*)*(?:\x60\x60\x60|\{|&#123;)|\s*\r?\n\s*[A-Za-z_]\w*\s*:)`;

// --- Рассуждения модели --------------------------------------------------------

/** Теги рассуждений: всё внутри них для расширения не существует. */
export const ТЕГИ_РАССУЖДЕНИЙ = ['plan', 'planning', 'thinking', 'think', 'thoughts', 'reasoning', 'analysis', 'scratchpad', 'reflection'];
const ИМЕНА = ТЕГИ_РАССУЖДЕНИЙ.join('|');
// И сырой тег, и заэкранированный разметкой (&lt;plan&gt;).
const ОТКР_РАССУЖДЕНИЙ = String.raw`(?:<|&lt;)\s*(${ИМЕНА})(?=[\s>&/])[^<>]*?(?:>|&gt;)`;
const ЗАКР_РАССУЖДЕНИЙ = (имя) => String.raw`(?:<|&lt;)\s*\/\s*${имя}\s*(?:>|&gt;)`;
// Невидимый разделитель: ни в метки, ни в пробелы, ни в данные HUD не входит.
const ЗАГЛУШКА = '⁣';

/**
 * Текст, в котором содержимое рассуждений (вместе с их тегами) заменено
 * невидимыми символами. Длина та же, код за кодом, — индексы совпадений
 * в маске верны и для исходного текста.
 * Незакрытое рассуждение (модель ещё пишет или забыла закрыть) глушим до
 * первой метки HUD, за которой сразу идут данные, — это уже сам блок, —
 * иначе до конца текста.
 */
export function маскаРассуждений(text) {
  const s = String(text ?? '');
  if (!/plan|think|thought|reason|analysis|scratchpad|reflection/i.test(s)) return s;
  const открыть = new RegExp(ОТКР_РАССУЖДЕНИЙ, 'gi');
  const куски = [];
  let позиция = 0, m;
  while ((m = открыть.exec(s)) !== null) {
    if (m.index < позиция) continue;
    const закрыть = new RegExp(ЗАКР_РАССУЖДЕНИЙ(m[1]), 'i');
    const после = m.index + m[0].length;
    const хвост = s.slice(после);
    const з = хвост.match(закрыть);
    let конец;
    if (з) конец = после + з.index + з[0].length;
    else {
      const данные = new RegExp(`${ОТКР}(?=${НАЧАЛО_ДАННЫХ})`, 'i');
      const д = хвост.match(данные);
      конец = д ? после + д.index : s.length;
    }
    куски.push([m.index, конец]);
    позиция = конец;
    открыть.lastIndex = Math.max(конец, m.index + 1);
  }
  if (!куски.length) return s;
  let out = '', было = 0;
  for (const [a, b] of куски) {
    out += s.slice(было, a) + ЗАГЛУШКА.repeat(b - a);
    было = b;
  }
  return out + s.slice(было);
}

// Регулярки отдаём новыми на каждый вызов: у глобальной lastIndex живёт
// между вызовами, и общий объект тихо пропускал совпадения.

/** Открывающий тег [HUD]. Сам по себе рассуждений не учитывает. */
export const hudOpenRe = (flags = 'i') => new RegExp(ОТКР, flags);

/** Закрывающий тег [/HUD]. Сам по себе рассуждений не учитывает. */
export const hudCloseRe = (flags = 'i') => new RegExp(ЗАКР, flags);

/** Весь блок от открывающего тега до закрывающего или до конца текста.
    inner — с группой содержимого между тегами. Рассуждений не учитывает:
    для поиска в тексте сообщения — hudБлоки() и функции ниже. */
export const hudBlockRe = (flags = 'i', inner = false) =>
  new RegExp(`${ОТКР}(?=${БЕЗ_ОТКР}*?${ЗАКР}|${НАЧАЛО_ДАННЫХ})${inner ? '(' : '(?:'}${БЕЗ_ОТКР}*?)(?:${ЗАКР}|$)`, flags);

/**
 * Все настоящие блоки HUD вне рассуждений.
 * [{ index, length, full, inner }] — full и inner вырезаны из исходного текста.
 */
export function hudБлоки(text) {
  const s = String(text ?? '');
  const маска = маскаРассуждений(s);
  const out = [];
  for (const m of маска.matchAll(new RegExp(hudBlockRe('gi', true).source, 'gid'))) {
    const [от, до] = m.indices[1];
    out.push({ index: m.index, length: m[0].length, full: s.slice(m.index, m.index + m[0].length), inner: s.slice(от, до) });
  }
  return out;
}

/** За меткой (хвост — текст сразу после неё) идут данные HUD? */
export function меткаСДанными(хвост) {
  return new RegExp(`^${НАЧАЛО_ДАННЫХ}`).test(String(хвост || ''));
}

/** В тексте есть настоящий блок HUD вне рассуждений? */
export function естьHudБлок(text) {
  return hudBlockRe('i').test(маскаРассуждений(text));
}

/** Первый блок [HUD]…[/HUD] вне рассуждений; пустая строка, если блока нет. */
export function extractHudBlock(text) {
  if (typeof text !== 'string') return '';
  const б = hudБлоки(text)[0];
  return б ? б.full : '';
}

/** Последний настоящий блок HUD вне рассуждений: { index, length } или null.
    Одинокое упоминание («except the [HUD] JSON block») и всё внутри <plan>
    блоком не считаются: раньше «Fix HUD (Cut & Regen)» резал от такого
    упоминания почти всё сообщение. */
export function последнийHudБлок(text) {
  const все = hudБлоки(text);
  const б = все[все.length - 1];
  return б ? { index: б.index, length: б.length } : null;
}

/** Где начинается последний настоящий HUD; -1, если настоящего блока нет. */
export function началоПоследнегоHud(text) {
  const блок = последнийHudБлок(text);
  return блок ? блок.index : -1;
}

/** Текст с блоками HUD (вне рассуждений), заменёнными на замену — строку
    или функцию (блок, номер) → строка. Рассуждения остаются как были. */
export function заменитьHudБлоки(text, замена = '') {
  const s = String(text ?? '');
  const блоки = hudБлоки(s);
  if (!блоки.length) return s;
  let out = '', было = 0;
  блоки.forEach((б, i) => {
    out += s.slice(было, б.index) + (typeof замена === 'function' ? замена(б, i) : замена);
    было = б.index + б.length;
  });
  return out + s.slice(было);
}
